// Naming and literal helpers shared by every emitter. Pure functions, no model access.

const RUST_KEYWORDS = new Set([
  "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if",
  "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self",
  "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
  "await", "dyn",
]);

/** `in_flight` / `VALIDATION_ERROR` / `Draft` -> `InFlight` / `ValidationError` / `Draft`. */
export function pascal(symbol: string): string {
  const parts = symbol.split(/[_\-\s]+/).filter(Boolean);
  const allUpper = symbol === symbol.toUpperCase();
  return parts
    .map((p) => {
      const w = allUpper ? p.toLowerCase() : p;
      return w.charAt(0).toUpperCase() + w.slice(1);
    })
    .join("");
}

/** `include-held` / `blockedBy` -> `include_held` / `blocked_by`. */
export function snake(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[-\s]+/g, "_")
    .toLowerCase();
}

/** A Rust field or variable identifier: snake case, raw-escaped when it is a keyword. */
export function ident(name: string): string {
  const s = snake(name);
  return RUST_KEYWORDS.has(s) ? `r#${s}` : s;
}

/** A Rust string literal for arbitrary text (escapes every control and non-ASCII-safe char). */
export function lit(text: string): string {
  let out = '"';
  for (const ch of text) {
    const c = ch.codePointAt(0) as number;
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (c < 0x20 || c === 0x7f) out += `\\u{${c.toString(16)}}`;
    else out += ch;
  }
  return out + '"';
}

