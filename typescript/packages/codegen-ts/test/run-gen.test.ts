describe("runGen — refuses to clobber hand-written files", () => {
  test("file without @generated header is left alone, status 'refused'", async () => {
    const loader = new FileMetaDataLoader();
    const result = await loader.loadFiles([join(FIXTURE_DIR, "single-entity.json")]);

    // Pre-place a hand-written Post.ts in outDir
    const handPath = join(tmp, "Post.ts");
    writeFileSync(handPath, "// I am a user wrote this\nexport const sacred = true;");

    const out = await runGen({
      config: defineConfig({
        outDir: tmp,
        extStyle: "none",
        dbImport: "~/server/db",
        dialect: "sqlite",
        generators: [entityFile(), queriesFile(), routesFile(), barrel()],
      }),
      metadata: result.root,
    });

    const postFile = out.files.find((f) => f.path.endsWith("Post.ts"));
    expect(postFile?.status).toBe("refused");
    expect(readFileSync(handPath, "utf-8")).toContain("sacred = true");
    expect(out.warnings.length).toBeGreaterThan(0);

    // Post.queries.ts should still be generated (its refusal is independent)
    expect(existsSync(join(tmp, "Post.queries.ts"))).toBe(true);
  });
});

// ---------------------------------------------------------------------------
// Helper: build a minimal in-memory MetaData root with one entity + long PK.
// Used for tests that need custom/untrusted names without going through the
// JSON parser (which might itself reject invalid names).
// ---------------------------------------------------------------------------
function makeRoot(pkg: string): MetaRoot {
  return metaRoot("root", pkg);
}

function makeEntity(name: string): MetaObject {
  const entity = metaObject(OBJECT_SUBTYPE_ENTITY, name);
  // id field (long)
  const id = metaField(FIELD_SUBTYPE_LONG, "id");
  entity.addChild(id);
  // title field (string)
  const title = metaField(FIELD_SUBTYPE_STRING, "title");
  entity.addChild(title);
  // primary identity
  const pk = meta(new TypeId(TYPE_IDENTITY, IDENTITY_SUBTYPE_PRIMARY), "primary");
  pk.setAttr(IDENTITY_ATTR_FIELDS, ["id"]);
  pk.setAttr(IDENTITY_ATTR_GENERATION, GENERATION_INCREMENT);
  entity.addChild(pk);
  return entity;
}

