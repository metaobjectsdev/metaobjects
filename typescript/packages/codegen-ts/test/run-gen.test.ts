describe("runGen — path-traversal guard (security)", () => {
  test("entity named '../evil' is skipped with a warning; normal entity still generates", async () => {
    const root = makeRoot("security-test");
    root.addChild(makeEntity("../evil"));
    root.addChild(makeEntity("Post"));

    const out = await runGen({
      config: defineConfig({
        outDir: tmp,
        extStyle: "none",
        dbImport: "~/server/db",
        dialect: "sqlite",
        generators: [entityFile(), barrel()],
      }),
      metadata: root,
    });

    // The warning must mention the unsafe name
    expect(out.warnings.some((w) => w.includes("unsafe name") && w.includes("../evil"))).toBe(true);

    // No file should be written for "../evil" — nothing outside tmp
    expect(existsSync(join(tmp, "../evil.ts"))).toBe(false);
    expect(existsSync(join(tmp, "..evil.ts"))).toBe(false);

    // Post should still be generated normally
    expect(existsSync(join(tmp, "Post.ts"))).toBe(true);

    // Barrel should only reference Post
    const barrelContent = readFileSync(join(tmp, "index.ts"), "utf-8");
    expect(barrelContent).toContain('export * from "./Post"');
    expect(barrelContent).not.toContain("evil");
  });
});

