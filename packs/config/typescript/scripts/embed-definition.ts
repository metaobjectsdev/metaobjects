#!/usr/bin/env bun
/**
 * Embed the pack's vocabulary definition (packs/config/metamodel/config.json) as
 * src/config-definition.embedded.ts, so the provider registers it wherever the pack's
 * own files are not on disk (a built or bundled install). The JSON is the source; the
 * test `definition.test.ts` fails when the embedded copy is stale.
 *
 *   bun run embed            # rewrite the embedded copy
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const DEFINITION_JSON = join(here, "..", "..", "metamodel", "config.json");
export const EMBEDDED_TS = join(here, "..", "src", "config-definition.embedded.ts");

export function renderEmbedded(json: string): string {
  const body = JSON.stringify(JSON.parse(json), null, 2);
  return [
    "// AUTO-GENERATED by packs/config/typescript/scripts/embed-definition.ts — DO NOT EDIT.",
    "// Source: packs/config/metamodel/config.json. Regenerate: bun run embed (in packs/config/typescript).",
    'import type { PackDefinition } from "./definition.js";',
    "",
    `export const CONFIG_DEFINITION: PackDefinition = ${body};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const next = renderEmbedded(readFileSync(DEFINITION_JSON, "utf8"));
  let current = "";
  try {
    current = readFileSync(EMBEDDED_TS, "utf8");
  } catch {
    // first run
  }
  if (current === next) console.log("config definition: embedded copy unchanged");
  else {
    writeFileSync(EMBEDDED_TS, next);
    console.log("config definition: wrote src/config-definition.embedded.ts");
  }
}
