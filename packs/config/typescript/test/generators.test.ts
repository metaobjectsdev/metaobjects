import { afterAll, describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { defineConfig, runGen, type Generator } from "@metaobjectsdev/codegen-ts";
import { entityFile } from "@metaobjectsdev/codegen-ts/generators";
import { envExampleFile, keyManifestFile, keysAxiTomlFile, renderKeysAxiToml } from "../src/index.js";
import { loadModel } from "./model.js";

const scratch = mkdtempSync(join(process.env.DEV_SCRATCH ?? tmpdir(), "pack-config-"));
afterAll(() => rmSync(scratch, { recursive: true, force: true }));

/** A dry run: every rendered file by its path relative to the output directory, nothing written. */
async function render(generators: Generator[], model?: unknown): Promise<Map<string, string>> {
  const out = join(scratch, "out");
  const res = await runGen({
    config: defineConfig({ outDir: out, extStyle: "none", dbImport: "../db", dialect: "sqlite", generators }),
    metadata: await loadModel(model),
    projectRoot: scratch,
    dryRun: true,
  });
  const files = new Map<string, string>();
  for (const [abs, content] of res.rendered ?? []) files.set(abs.slice(out.length + 1), content);
  return files;
}

const ENV_EXAMPLE = `# @generated by @metaobjectsdev/pack-config (env-example) — hand edits are kept by a three-way merge on regeneration; meta verify --codegen checks only the generated parts.
# Every setting the application reads. Secret settings are listed by name only.

# ── Database (acme::app::Database) ──
# The primary database.
# DATABASE_URL: string, required, secret: the value lives in the vault — Connection URL.
DATABASE_URL=
# DATABASE_USERNAME: string, required
DATABASE_USERNAME=
# DB_POOL_SIZE: int, optional
DB_POOL_SIZE=10

# ── LlmProvider (acme::app::LlmProvider) ──
# LLM_PROVIDER_API_KEY: string, required, secret: the value lives in the vault
LLM_PROVIDER_API_KEY=
# LLM_PROVIDER_MODEL: string, optional
LLM_PROVIDER_MODEL="a model name"
# LLM_PROVIDER_TRACE: boolean, optional
LLM_PROVIDER_TRACE=false

# ── Build (acme::app::Build) ──
# BUILD_COMMIT_SHA: string, optional, build-time
BUILD_COMMIT_SHA=
`;

const KEYS_AXI_TOML = `# @generated by @metaobjectsdev/pack-config (keys-axi-toml) — hand edits are kept by a three-way merge on regeneration; meta verify --codegen checks only the generated parts.
# From vault.infisical acme::app::keys.
backend = "infisical"
scope = "acme-app"
default_environment = "dev"

# dev
[environments.dev]
scope = "acme-app"

# production
[environments.prod]
scope = "acme-app-prod"
`;

describe("config pack generators", () => {
  test(".env.example lists every setting, secrets by name only", async () => {
    const files = await render([envExampleFile()]);
    expect([...files.keys()]).toEqual([".env.example"]);
    expect(files.get(".env.example")).toBe(ENV_EXAMPLE);
  });

  test("the key manifest names, types and flags every setting and lists the vault's scopes", async () => {
    const manifest = JSON.parse((await render([keyManifestFile()])).get("keys.manifest.json")!);
    expect(manifest.generatedBy).toBe("@metaobjectsdev/pack-config (key-manifest)");
    expect(manifest.settings.map((s: { envName: string }) => s.envName)).toEqual([
      "BUILD_COMMIT_SHA", "DATABASE_URL", "DATABASE_USERNAME", "DB_POOL_SIZE",
      "LLM_PROVIDER_API_KEY", "LLM_PROVIDER_MODEL", "LLM_PROVIDER_TRACE",
    ]);
    expect(manifest.settings.find((s: { envName: string }) => s.envName === "DATABASE_URL")).toEqual({
      envName: "DATABASE_URL", setting: "acme::app::Database.url", type: "string",
      required: true, secret: true, phase: "runtime", description: "Connection URL.",
    });
    expect(manifest.vaults).toEqual([{
      name: "keys", key: "acme::app::keys", product: "infisical", defaultScope: "dev",
      scopes: [{ name: "dev", project: "acme-app", env: "dev" }, { name: "production", project: "acme-app-prod", env: "prod" }],
    }]);
  });

  test(".keys-axi.toml maps each store environment to its project", async () => {
    const files = await render([keysAxiTomlFile()]);
    expect(files.get(".keys-axi.toml")).toBe(KEYS_AXI_TOML);
  });

  test(".keys-axi.toml without a default scope writes only the environments", () => {
    const toml = renderKeysAxiToml({ name: "k", key: "a::k", product: "infisical", scopes: [{ name: "qa env", project: 'p"q', env: "qa env" }] });
    expect(toml).toContain('backend = "infisical"\n\n# qa env\n[environments."qa env"]\nscope = "p\\"q"\n');
    expect(toml).not.toContain("default_environment");
  });

  test("a model with two vaults needs the one to write named", async () => {
    // A settings group too: runGen runs no generator for a root with no object at all.
    const twoVaults = { "metadata.root": { package: "acme::app", children: [
      { "object.settings": { name: "App", children: [{ "field.string": { name: "mode" } }] } },
      { "vault.infisical": { name: "a", children: [{ "scope.env": { name: "dev", "@project": "pa" } }] } },
      { "vault.infisical": { name: "b", children: [{ "scope.env": { name: "dev", "@project": "pb" } }] } },
    ] } };
    await expect(render([keysAxiTomlFile()], twoVaults)).rejects.toThrow(/declares 2 vaults/);
    expect((await render([keysAxiTomlFile({ vault: "b" })], twoVaults)).get(".keys-axi.toml")).toContain('scope = "pb"');
  });

  test("a model with no settings and no vault writes none of the files", async () => {
    const entityOnly = { "metadata.root": { package: "acme::app", children: [
      { "object.entity": { name: "Customer", children: [{ "field.long": { name: "id" } }, { "identity.primary": { name: "id", "@fields": "id" } }] } },
    ] } };
    expect((await render([envExampleFile(), keyManifestFile(), keysAxiTomlFile()], entityOnly)).size).toBe(0);
  });

  test("core's entity generator types a settings group as it does a value object: no table", async () => {
    const files = await render([entityFile()]);
    expect(files.get("Customer.ts")).toContain("Table(");
    const db = files.get("Database.ts")!;
    expect(db).toContain("export interface Database {");
    expect(db).not.toContain("Table(");
  });
});
