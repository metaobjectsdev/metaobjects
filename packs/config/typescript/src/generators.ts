/**
 * The config pack's generators. Each writes one whole-model file and stops: they talk to
 * no vault and no platform, and no value of a secret setting ever reaches their output
 * (the model holds none).
 *
 *  - `envExampleFile()`  `.env.example`: every setting's name, with its default when it is
 *                        not secret, and a comment line saying what it is.
 *  - `keyManifestFile()` `keys.manifest.json`: the same names, typed, plus each vault's
 *                        scopes. What a deploy or doctor script compares a vault and a
 *                        platform against.
 *  - `keysAxiTomlFile()` `.keys-axi.toml`: the Infisical vault's scope per environment, in
 *                        the file `keys-axi` reads, so `keys-axi run` needs no project flag.
 *
 * Paths are relative to the generator's target. These files belong at the project root,
 * so wire them to a target whose `outDir` is `"."` (README, "Wiring").
 */
import { GENERATED_EDIT_NOTE, type EmittedFile, type Generator, type GenContext } from "@metaobjectsdev/codegen-ts";
import type { MetaObject } from "@metaobjectsdev/metadata";
import { PHASE_BUILD, VAULT_SUBTYPE_INFISICAL } from "./constants.js";
import { ConfigModelError, misplacedSettingAttrs, readSettings, readVaults, type Setting, type Vault } from "./settings.js";

const PACKAGE = "@metaobjectsdev/pack-config";

export interface ConfigGeneratorOptions {
  /** The output path, relative to the target. */
  readonly path?: string;
  /** The named output target (`targets` in metaobjects.config.ts). Default: `"default"`. */
  readonly target?: string;
}

export interface KeysAxiTomlOptions extends ConfigGeneratorOptions {
  /** The vault to write, by name, when the model declares more than one. */
  readonly vault?: string;
}

function header(generator: string, comment: string): string {
  return `${comment} @generated by ${PACKAGE} (${generator}) — ${GENERATED_EDIT_NOTE}`;
}

/** The run's objects inside its `scope`. */
function scopedObjects(ctx: GenContext): MetaObject[] {
  return ctx.entities.filter(ctx.matches);
}

/** Text on one comment line. */
function oneLine(s: string): string {
  return s.replace(/\s+/g, " ").trim();
}

/** The root's vaults inside the run's scope (`scope` in the project config), as settings are. */
function vaultsInScope(ctx: GenContext): Vault[] {
  return readVaults(ctx.loadedRoot, (key) => ctx.select?.(key) ?? true);
}

/** Roots already checked for misplaced setting attributes: warn once per run, whichever generators run. */
const checked = new WeakSet<object>();

function generator(name: string, opts: ConfigGeneratorOptions, generate: (ctx: GenContext) => EmittedFile[]): Generator {
  return {
    name,
    ...(opts.target !== undefined ? { target: opts.target } : {}),
    generate(ctx) {
      if (!checked.has(ctx.loadedRoot)) {
        checked.add(ctx.loadedRoot);
        for (const w of misplacedSettingAttrs(scopedObjects(ctx))) ctx.warn(`${PACKAGE}: ${w}`);
      }
      return generate(ctx);
    },
  };
}

// ── .env.example ─────────────────────────────────────────────────────────────

/** A value as dotenv writes it: bare when that is unambiguous, else double-quoted. */
function dotenvValue(v: string): string {
  return /^[^\s"'#\\$`]*$/.test(v) ? v : `"${v.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/`/g, "\\`")}"`;
}

function describe(s: Setting): string {
  const facts = [s.type, s.required ? "required" : "optional"];
  if (s.secret) facts.push("secret: the value lives in the vault");
  if (s.phase === PHASE_BUILD) facts.push("build-time");
  const what = s.description === undefined ? "" : ` — ${oneLine(s.description)}`;
  return `# ${s.envName}: ${facts.join(", ")}${what}`;
}

export function renderEnvExample(ctx: GenContext): string | undefined {
  const groups = readSettings(scopedObjects(ctx)).filter((g) => g.settings.length > 0);
  if (groups.length === 0) return undefined;
  const lines = [
    header("env-example", "#"),
    "# Every setting the application reads. Secret settings are listed by name only.",
  ];
  for (const g of groups) {
    lines.push("", `# ── ${g.name} (${g.key}) ──`);
    if (g.description !== undefined) lines.push(`# ${oneLine(g.description)}`);
    for (const s of g.settings) lines.push(describe(s), `${s.envName}=${s.default === undefined ? "" : dotenvValue(s.default)}`);
  }
  return `${lines.join("\n")}\n`;
}

export function envExampleFile(opts: ConfigGeneratorOptions = {}): Generator {
  return generator("env-example", opts, (ctx) => {
    const content = renderEnvExample(ctx);
    return content === undefined ? [] : [{ path: opts.path ?? ".env.example", content }];
  });
}

// ── keys.manifest.json ──────────────────────────────────────────────────────

export function renderKeyManifest(ctx: GenContext): string | undefined {
  const settings = readSettings(scopedObjects(ctx)).flatMap((g) => g.settings);
  const vaults = vaultsInScope(ctx);
  if (settings.length === 0 && vaults.length === 0) return undefined;
  const manifest = {
    generatedBy: `${PACKAGE} (key-manifest)`,
    settings: [...settings].sort((a, b) => (a.envName < b.envName ? -1 : a.envName > b.envName ? 1 : 0)),
    vaults: vaults.map((v) => ({
      name: v.name,
      key: v.key,
      product: v.product,
      ...(v.defaultScope !== undefined ? { defaultScope: v.defaultScope.name } : {}),
      scopes: v.scopes,
    })),
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

export function keyManifestFile(opts: ConfigGeneratorOptions = {}): Generator {
  return generator("key-manifest", opts, (ctx) => {
    const content = renderKeyManifest(ctx);
    return content === undefined ? [] : [{ path: opts.path ?? "keys.manifest.json", content }];
  });
}

// ── .keys-axi.toml ──────────────────────────────────────────────────────────

/** A TOML basic string. */
function tomlString(v: string): string {
  return `"${v.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** A TOML key: bare when it may be, else quoted. */
function tomlKey(k: string): string {
  return /^[A-Za-z0-9_-]+$/.test(k) ? k : tomlString(k);
}

function pickVault(vaults: readonly Vault[], wanted: string | undefined): Vault | undefined {
  if (wanted !== undefined) {
    const v = vaults.find((x) => x.name === wanted || x.key === wanted);
    if (v === undefined) throw new ConfigModelError([`keys-axi-toml: no vault named "${wanted}" (the model declares: ${vaults.map((x) => x.key).join(", ") || "none"})`]);
    return v;
  }
  if (vaults.length > 1) {
    throw new ConfigModelError([`keys-axi-toml: the model declares ${vaults.length} vaults (${vaults.map((x) => x.key).join(", ")}); name one with keysAxiTomlFile({ vault })`]);
  }
  return vaults[0];
}

export function renderKeysAxiToml(vault: Vault): string {
  if (vault.product !== VAULT_SUBTYPE_INFISICAL) {
    throw new ConfigModelError([`keys-axi-toml: vault ${vault.key} is vault.${vault.product}; keys-axi reads only vault.${VAULT_SUBTYPE_INFISICAL} from this generator`]);
  }
  const lines = [header("keys-axi-toml", "#"), `# From vault.${vault.product} ${vault.key}.`, `backend = ${tomlString(vault.product)}`];
  if (vault.defaultScope !== undefined) {
    lines.push(`scope = ${tomlString(vault.defaultScope.project)}`, `default_environment = ${tomlString(vault.defaultScope.env)}`);
  }
  for (const s of vault.scopes) {
    lines.push("", `# ${s.name}`, `[environments.${tomlKey(s.env)}]`, `scope = ${tomlString(s.project)}`);
  }
  return `${lines.join("\n")}\n`;
}

export function keysAxiTomlFile(opts: KeysAxiTomlOptions = {}): Generator {
  return generator("keys-axi-toml", opts, (ctx) => {
    const vault = pickVault(vaultsInScope(ctx), opts.vault);
    if (vault === undefined) {
      ctx.warn("keys-axi-toml: the model declares no vault, so there is no .keys-axi.toml to write");
      return [];
    }
    return [{ path: opts.path ?? ".keys-axi.toml", content: renderKeysAxiToml(vault) }];
  });
}
