/**
 * The railway pack's generators. Each writes one file for the model's Railway project and
 * stops: none talks to Railway or to a vault, and no secret value reaches their output (the
 * model holds none).
 *
 *  - `railwayTsFile()`           `.railway/railway.ts`, Railway's Infrastructure as Code file.
 *  - `railwayUnexpressedFile()`  `deploy/unexpressed.md`, the facts that file cannot hold.
 *  - `railwaySyncSecretsScript()` `deploy/sync-secrets.sh`, vault → Railway at deploy (keys-axi).
 *  - `railwayDeployScript()`     `deploy/deploy.sh`, sync, plan, apply, check.
 *  - `railwayDoctorScript()`     `deploy/doctor.sh`, the model against the vault and Railway.
 *  - `railwayDeploySkill()`      `.claude/skills/deploy/SKILL.md`, how an agent deploys.
 *  - `railwayFiles()`            all six.
 *
 * Paths are relative to the generator's target; these files belong at the repository root,
 * so wire them to a target whose `outDir` is `"."` (README, "Wiring"). A model that deploys
 * nothing to Railway gets no files.
 */
import { GENERATED_EDIT_NOTE, type EmittedFile, type Generator, type GenContext } from "@metaobjectsdev/codegen-ts";
import {
  PATH_DEPLOY,
  PATH_DEPLOY_SKILL,
  PATH_DOCTOR,
  PATH_RAILWAY_TS,
  PATH_SYNC_SECRETS,
  PATH_UNEXPRESSED,
} from "./constants.js";
import { renderDeploy, renderDeploySkill, renderDoctor, renderSyncSecrets, renderUnexpressed } from "./files.js";
import { pickProject, readRailway, type RailwayProject, type ReadRailwayOptions } from "./model.js";
import { renderRailwayTs } from "./railway-ts.js";

const PACKAGE = "@metaobjectsdev/pack-railway";

export interface RailwayGeneratorOptions extends ReadRailwayOptions {
  /** The output path, relative to the target. */
  readonly path?: string;
  /** The named output target (`targets` in metaobjects.config.ts). Default: `"default"`. */
  readonly target?: string;
}

export function header(generator: string, comment: string): string {
  return `${comment} @generated by ${PACKAGE} (${generator}) — ${GENERATED_EDIT_NOTE}`;
}

/** The model read once per run and per options (a run shares one `entities` array). */
const cache = new WeakMap<object, Map<string, RailwayProject | undefined>>();

function projectFor(ctx: GenContext, opts: ReadRailwayOptions): RailwayProject | undefined {
  const k = JSON.stringify([opts.project ?? null, opts.partial ?? null]);
  let perRun = cache.get(ctx.entities);
  if (perRun === undefined) {
    perRun = new Map();
    cache.set(ctx.entities, perRun);
  }
  if (!perRun.has(k)) {
    const read: ReadRailwayOptions = {
      ...(opts.project !== undefined ? { project: opts.project } : {}),
      ...(opts.partial !== undefined ? { partial: opts.partial } : {}),
    };
    const projects = readRailway(ctx.loadedRoot, ctx.entities.filter(ctx.matches), (key) => ctx.select?.(key) ?? true, read);
    perRun.set(k, pickProject(projects));
  }
  return perRun.get(k);
}

function generator(
  name: string,
  defaultPath: string,
  opts: RailwayGeneratorOptions,
  render: (project: RailwayProject) => string,
): Generator {
  return {
    name,
    ...(opts.target !== undefined ? { target: opts.target } : {}),
    generate(ctx): EmittedFile[] {
      const project = projectFor(ctx, opts);
      return project === undefined ? [] : [{ path: opts.path ?? defaultPath, content: render(project) }];
    },
  };
}

export function railwayTsFile(opts: RailwayGeneratorOptions = {}): Generator {
  return generator("railway-ts", PATH_RAILWAY_TS, opts, (p) => renderRailwayTs(p, header("railway-ts", "//")));
}

export function railwayUnexpressedFile(opts: RailwayGeneratorOptions = {}): Generator {
  return generator("railway-unexpressed", PATH_UNEXPRESSED, opts, (p) => renderUnexpressed(p, header("railway-unexpressed", "<!--").concat(" -->")));
}

export function railwaySyncSecretsScript(opts: RailwayGeneratorOptions = {}): Generator {
  return generator("railway-sync-secrets", PATH_SYNC_SECRETS, opts, (p) => renderSyncSecrets(p, header("railway-sync-secrets", "#")));
}

export function railwayDeployScript(opts: RailwayGeneratorOptions = {}): Generator {
  return generator("railway-deploy", PATH_DEPLOY, opts, (p) => renderDeploy(p, header("railway-deploy", "#")));
}

export function railwayDoctorScript(opts: RailwayGeneratorOptions = {}): Generator {
  return generator("railway-doctor", PATH_DOCTOR, opts, (p) => renderDoctor(p, header("railway-doctor", "#")));
}

export function railwayDeploySkill(opts: RailwayGeneratorOptions = {}): Generator {
  return generator("railway-deploy-skill", PATH_DEPLOY_SKILL, opts, (p) => renderDeploySkill(p, header("railway-deploy-skill", "<!--").concat(" -->")));
}

/** All six generators with the same options (`path` is ignored: each keeps its own). */
export function railwayFiles(opts: Omit<RailwayGeneratorOptions, "path"> = {}): Generator[] {
  return [railwayTsFile(opts), railwayUnexpressedFile(opts), railwaySyncSecretsScript(opts), railwayDeployScript(opts), railwayDoctorScript(opts), railwayDeploySkill(opts)];
}
