/**
 * The cloudflare pack's generators. Each writes one file for the model's Cloudflare app and
 * stops: none talks to Cloudflare or to a vault, and no secret value reaches their output (the
 * model holds none).
 *
 *  - `wranglerConfigFile()`          `wrangler.jsonc`, the Worker's configuration (Workers only).
 *  - `cloudflareRunnerScript()`      `deploy/cloudflare/wrangler.sh`, wrangler as the narrow token.
 *  - `cloudflareDeployScript()`      `deploy/cloudflare/deploy.sh`, build, sync secrets, deploy.
 *  - `cloudflareSyncSecretsScript()` `deploy/cloudflare/sync-secrets.sh`, vault → Cloudflare.
 *  - `cloudflareDoctorScript()`      `deploy/cloudflare/doctor.sh`, the model against the vault and Cloudflare.
 *  - `cloudflareUnexpressedFile()`   `deploy/cloudflare/unexpressed.md`, the facts no file holds.
 *  - `cloudflareFiles()`             all six.
 *
 * Paths are relative to the generator's target; these files belong at the repository root, so
 * wire them to a target whose `outDir` is `"."` (README, "Wiring"). The scripts name each
 * other and the configuration by path, so every generator takes the same `paths`. A model that
 * deploys nothing to Cloudflare gets no files.
 */
import { GENERATED_EDIT_NOTE, type EmittedFile, type Generator, type GenContext } from "@metaobjectsdev/codegen-ts";
import {
  DEPLOYMENT_SUBTYPE_WORKER,
  PATH_DEPLOY,
  PATH_DOCTOR,
  PATH_SYNC_SECRETS,
  PATH_UNEXPRESSED,
  PATH_WRANGLER,
  PATH_WRANGLER_RUNNER,
  WRANGLER_VERSION,
} from "./constants.js";
import { renderDeploy, renderDoctor, renderRunner, renderSyncSecrets, renderUnexpressed, type CloudflarePaths } from "./files.js";
import { CloudflareModelError, readCloudflare, type CloudflareApp, type ReadCloudflareOptions } from "./model.js";
import { renderWrangler } from "./wrangler.js";

const PACKAGE = "@metaobjectsdev/pack-cloudflare";

export interface CloudflareGeneratorOptions extends ReadCloudflareOptions {
  /** The codegen target the files are written under (its `outDir` should be the repository root). */
  readonly target?: string;
  /** Where each file goes, relative to the target. Every generator must be given the same. */
  readonly paths?: Partial<Omit<CloudflarePaths, "wranglerVersion">>;
  /** The wrangler the scripts pin. Default: the version this pack was written against. */
  readonly wranglerVersion?: string;
}

function header(generator: string, comment: string): string {
  return `${comment} @generated by ${PACKAGE} (${generator}) — ${GENERATED_EDIT_NOTE}`;
}

function htmlHeader(generator: string): string {
  return `<!-- @generated by ${PACKAGE} (${generator}) — ${GENERATED_EDIT_NOTE} -->`;
}

export function resolvePaths(opts: CloudflareGeneratorOptions): CloudflarePaths {
  const p = opts.paths ?? {};
  return {
    config: p.config ?? PATH_WRANGLER,
    runner: p.runner ?? PATH_WRANGLER_RUNNER,
    deploy: p.deploy ?? PATH_DEPLOY,
    syncSecrets: p.syncSecrets ?? PATH_SYNC_SECRETS,
    doctor: p.doctor ?? PATH_DOCTOR,
    unexpressed: p.unexpressed ?? PATH_UNEXPRESSED,
    wranglerVersion: opts.wranglerVersion ?? WRANGLER_VERSION,
  };
}

/** The model read once per run and per options, a refusal included (a run shares one `entities` array). */
const cache = new WeakMap<object, Map<string, CloudflareApp | CloudflareModelError | undefined>>();

function appFor(ctx: GenContext, { app, topLevel }: ReadCloudflareOptions): CloudflareApp | undefined {
  const k = JSON.stringify([app ?? null, topLevel ?? null]);
  const perRun = cache.get(ctx.entities) ?? new Map<string, CloudflareApp | CloudflareModelError | undefined>();
  cache.set(ctx.entities, perRun);
  if (!perRun.has(k)) {
    const read = { ...(app !== undefined ? { app } : {}), ...(topLevel !== undefined ? { topLevel } : {}) };
    try {
      perRun.set(k, readCloudflare(ctx.loadedRoot, ctx.entities.filter(ctx.matches), (key) => ctx.select?.(key) ?? true, read));
    } catch (e) {
      if (!(e instanceof CloudflareModelError)) throw e;
      perRun.set(k, e);
    }
  }
  const got = perRun.get(k);
  if (got instanceof CloudflareModelError) throw got;
  return got;
}

function generator(
  name: string,
  opts: CloudflareGeneratorOptions,
  path: (paths: CloudflarePaths) => string,
  render: (app: CloudflareApp, paths: CloudflarePaths) => string | undefined,
): Generator {
  return {
    name,
    ...(opts.target !== undefined ? { target: opts.target } : {}),
    generate(ctx): EmittedFile[] {
      const app = appFor(ctx, opts);
      if (app === undefined) return [];
      const paths = resolvePaths(opts);
      const content = render(app, paths);
      return content === undefined ? [] : [{ path: path(paths), content }];
    },
  };
}

/** `wrangler.jsonc`. A Pages site has none: `wrangler pages deploy` takes its facts as arguments. */
export function wranglerConfigFile(opts: CloudflareGeneratorOptions = {}): Generator {
  return generator("wrangler-config", opts, (p) => p.config, (app, p) =>
    app.kind === DEPLOYMENT_SUBTYPE_WORKER ? renderWrangler(app, header("wrangler-config", "//"), p.config) : undefined,
  );
}

export function cloudflareRunnerScript(opts: CloudflareGeneratorOptions = {}): Generator {
  return generator("cloudflare-wrangler", opts, (p) => p.runner, (app, p) => renderRunner(app, header("cloudflare-wrangler", "#"), p));
}

export function cloudflareDeployScript(opts: CloudflareGeneratorOptions = {}): Generator {
  return generator("cloudflare-deploy", opts, (p) => p.deploy, (app, p) => renderDeploy(app, header("cloudflare-deploy", "#"), p));
}

export function cloudflareSyncSecretsScript(opts: CloudflareGeneratorOptions = {}): Generator {
  return generator("cloudflare-sync-secrets", opts, (p) => p.syncSecrets, (app, p) => renderSyncSecrets(app, header("cloudflare-sync-secrets", "#"), p));
}

export function cloudflareDoctorScript(opts: CloudflareGeneratorOptions = {}): Generator {
  return generator("cloudflare-doctor", opts, (p) => p.doctor, (app, p) => renderDoctor(app, header("cloudflare-doctor", "#"), p));
}

export function cloudflareUnexpressedFile(opts: CloudflareGeneratorOptions = {}): Generator {
  return generator("cloudflare-unexpressed", opts, (p) => p.unexpressed, (app, p) =>
    renderUnexpressed(app, htmlHeader("cloudflare-unexpressed"), p),
  );
}

/** All six generators with the same options. */
export function cloudflareFiles(opts: CloudflareGeneratorOptions = {}): Generator[] {
  return [
    wranglerConfigFile(opts),
    cloudflareRunnerScript(opts),
    cloudflareDeployScript(opts),
    cloudflareSyncSecretsScript(opts),
    cloudflareDoctorScript(opts),
    cloudflareUnexpressedFile(opts),
  ];
}
