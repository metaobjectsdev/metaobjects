// M2mFixture — shared schema-provisioning + seed for the FR-018 M:N api-contract
// lanes (reference + generated). The six tables (posts/tags/post_tags +
// people/follows/friendships) match the persistence-conformance canonical schema
// (literal column naming, composite-PK junctions). The seed is the multi-table
// m2m/seed.json (keyed by table name — distinct from the single-table author seed).

using System.Text.Json;        // JsonValueKind
using System.Text.Json.Nodes;  // JsonNode / JsonObject / JsonArray
using Npgsql;

namespace MetaObjects.IntegrationTests.Api;

internal static class M2mFixture
{
    // The six-table DDL, identical to fixtures/persistence-conformance/canonical/
    // schema.postgres.sql (the M:N slice). BIGINT GENERATED BY DEFAULT AS IDENTITY so
    // the seed can insert explicit ids; composite PKs on the three junction tables.
    public const string SchemaDdl = """
        CREATE TABLE "posts" (
          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
          "title" VARCHAR(200) NOT NULL,
          CONSTRAINT "posts_pkey" PRIMARY KEY ("id")
        );
        CREATE TABLE "tags" (
          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
          "name" VARCHAR(80) NOT NULL,
          CONSTRAINT "tags_pkey" PRIMARY KEY ("id")
        );
        CREATE TABLE "post_tags" (
          "postId" BIGINT NOT NULL,
          "tagId" BIGINT NOT NULL,
          CONSTRAINT "post_tags_pkey" PRIMARY KEY ("postId", "tagId")
        );
        CREATE TABLE "people" (
          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
          "name" VARCHAR(80) NOT NULL,
          CONSTRAINT "people_pkey" PRIMARY KEY ("id")
        );
        CREATE TABLE "follows" (
          "followerId" BIGINT NOT NULL,
          "followeeId" BIGINT NOT NULL,
          CONSTRAINT "follows_pkey" PRIMARY KEY ("followerId", "followeeId")
        );
        CREATE TABLE "friendships" (
          "personAId" BIGINT NOT NULL,
          "personBId" BIGINT NOT NULL,
          CONSTRAINT "friendships_pkey" PRIMARY KEY ("personAId", "personBId")
        );
        ALTER TABLE "post_tags" ADD CONSTRAINT "post_tags_postId_fk" FOREIGN KEY ("postId") REFERENCES "posts" ("id");
        ALTER TABLE "post_tags" ADD CONSTRAINT "post_tags_tagId_fk" FOREIGN KEY ("tagId") REFERENCES "tags" ("id");
        ALTER TABLE "follows" ADD CONSTRAINT "follows_followerId_fk" FOREIGN KEY ("followerId") REFERENCES "people" ("id");
        ALTER TABLE "follows" ADD CONSTRAINT "follows_followeeId_fk" FOREIGN KEY ("followeeId") REFERENCES "people" ("id");
        ALTER TABLE "friendships" ADD CONSTRAINT "friendships_personAId_fk" FOREIGN KEY ("personAId") REFERENCES "people" ("id");
        ALTER TABLE "friendships" ADD CONSTRAINT "friendships_personBId_fk" FOREIGN KEY ("personBId") REFERENCES "people" ("id");
        """;

    // Per-table column lists for the INSERTs (matches m2m/seed.json keys).
    private static readonly (string Table, string[] Cols)[] Tables =
    {
        ("posts",       new[] { "id", "title" }),
        ("tags",        new[] { "id", "name" }),
        ("post_tags",   new[] { "postId", "tagId" }),
        ("people",      new[] { "id", "name" }),
        ("follows",     new[] { "followerId", "followeeId" }),
        ("friendships", new[] { "personAId", "personBId" }),
    };

    /// <summary>Create the six tables on a fresh container.</summary>
    public static async Task ProvisionSchemaAsync(string connString)
    {
        await using var c = new NpgsqlConnection(connString);
        await c.OpenAsync();
        await using var cmd = c.CreateCommand();
        cmd.CommandText = SchemaDdl;
        await cmd.ExecuteNonQueryAsync();
    }

    /// <summary>
    /// Apply the multi-table m2m seed (m2m/seed.json) — explicit ids, in FK-safe
    /// order (base tables before junctions). Bumps the identity sequences on the two
    /// base tables so any later implicit insert is past the seeded max.
    /// </summary>
    public static async Task ApplySeedAsync(string connString, string seedPath)
    {
        var root = JsonNode.Parse(File.ReadAllText(seedPath)) as JsonObject
            ?? throw new InvalidOperationException($"{seedPath}: top-level must be an object");

        await using var c = new NpgsqlConnection(connString);
        await c.OpenAsync();

        foreach (var (table, cols) in Tables)
        {
            if (root[table] is not JsonArray rows) continue;
            foreach (var rowNode in rows)
            {
                if (rowNode is not JsonObject row) continue;
                var colList = string.Join(", ", cols.Select(c2 => "\"" + c2 + "\""));
                var paramList = string.Join(", ", cols.Select((_, i) => "@p" + i));
                await using var ins = c.CreateCommand();
                ins.CommandText = $"INSERT INTO \"{table}\" ({colList}) VALUES ({paramList})";
                for (int i = 0; i < cols.Length; i++)
                {
                    var v = row[cols[i]];
                    object? val = v is null ? DBNull.Value
                        : v.GetValueKind() == JsonValueKind.Number ? v.GetValue<long>()
                        : v.GetValue<string>();
                    ins.Parameters.AddWithValue("@p" + i, val ?? DBNull.Value);
                }
                await ins.ExecuteNonQueryAsync();
            }
        }

        foreach (var table in new[] { "posts", "tags", "people" })
        {
            await using var bump = c.CreateCommand();
            bump.CommandText =
                $"SELECT setval(pg_get_serial_sequence('{table}', 'id'), " +
                $"COALESCE((SELECT MAX(id) FROM \"{table}\"), 1))";
            await bump.ExecuteScalarAsync();
        }
    }
}
