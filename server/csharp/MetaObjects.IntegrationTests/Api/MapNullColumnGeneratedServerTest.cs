// MapNullColumnGeneratedServerTest — the field.map NULL-column read regression lane.
//
// A field.map column is NULLABLE by default (the TS-owned migration creates nullable
// jsonb; ADR-0015), and NULL cells there are ordinary cross-port state: a row written
// before the map was declared, by another port, or by raw SQL. The regression this
// lane locks: the generated map property once materialized as a NON-nullable
// Dictionary over that nullable column, so EF Core 8 skipped the shaper's IsDBNull
// check and EVERY read arm — get-by-id, list, and PATCH/PUT's FindAsync — crashed
// (InvalidCastException from the reader) on a single NULL-map row. The emission now
// follows the column (ObjectNavProperty's rule, not a new one): @required keeps the
// non-null dictionary + empty-dictionary initializer; a non-required map is a
// NULLABLE Dictionary with no initializer, so NULL reads back as null (never silently
// rewritten to {}), an absent map key on create persists NULL, and present-null on
// PATCH clears the column. A present {} stays a distinct empty map.
//
// Drives the REAL generated artifact — Entity + DbContext + FilterAllowlist + Routes
// output, Roslyn-compiled in-memory and hosted unmodified on Kestrel over Testcontainers
// Postgres (the JsonbGeneratedServerFactory pattern) — so the EF shaper itself, not a
// string match on the emission, is what runs. The seeded NULL-map row plays the role
// of the other-port / raw-SQL writer.
//
// Run on-demand (Docker required):
//   dotnet test server/csharp/MetaObjects.IntegrationTests/MetaObjects.IntegrationTests.csproj \
//     --filter "FullyQualifiedName~MapNullColumn"

