namespace MetaObjects.IntegrationTests.Api;

public sealed class MapNullColumnGeneratedServerTest
{
    private const string GeneratedNamespace = "MetaObjects.IntegrationTests.MapNullGenerated";

    // One scalar-valued nullable map (labels), one value-object-valued nullable map
    // (addresses), and one @required map (tags) so both nullability arms of the
    // emission are live in the same model.
    private const string Model = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.value": { "name": "Address", "children": [
        { "field.string": { "name": "street", "@required": true } }
      ]}},
      { "object.entity": { "name": "Customer", "children": [
        { "source.rdb": { "@table": "customers" } },
        { "field.long":   { "name": "id" } },
        { "field.string": { "name": "name", "@required": true } },
        { "field.map":    { "name": "labels", "@valueType": "string" } },
        { "field.map":    { "name": "addresses", "@objectRef": "Address" } },
        { "field.map":    { "name": "tags", "@valueType": "string", "@required": true } },
        { "identity.primary": { "@fields": "id" } }
      ]}}
    ]}}
    """;

    // Nullable-by-default jsonb map columns (what the TS-owned migration creates);
    // the @required map's column is NOT NULL. Row 1 carries NULL maps (the raw-SQL /
    // other-port writer); row 2 carries a PRESENT empty object — null and {} must
    // stay distinct on read.
    private const string SchemaDdl = """
        CREATE TABLE "customers" (
          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
          "name" VARCHAR(200) NOT NULL,
          "labels" jsonb,
          "addresses" jsonb,
          "tags" jsonb NOT NULL,
          CONSTRAINT "customers_pkey" PRIMARY KEY ("id")
        );
        """;

    private const string SeedDdl = """
        INSERT INTO "customers" ("id", "name", "labels", "addresses", "tags") VALUES
          (1, 'null-map row', NULL, NULL, '{"seed":"yes"}'::jsonb),
          (2, 'empty-map row', '{}'::jsonb, NULL, '{}'::jsonb);
        SELECT setval(pg_get_serial_sequence('customers', 'id'),
                      COALESCE((SELECT MAX(id) FROM "customers"), 1));
        """;

    [Fact]
    public async Task A_null_map_column_reads_lists_and_patches_cleanly()
    {
        await using var pg = await PostgresContainer.StartAsync();
        await ProvisionAsync(pg.ConnectionString);

        var (baseUrl, app) = await StartGeneratedServerAsync(pg);
        await using (app)
        {
            using var client = new HttpClient { BaseAddress = new Uri(baseUrl) };

            // GET by id over the NULL-map row: 200, maps surface as JSON null (the
            // regression: a non-nullable property made this 500 before the row was
            // ever touched).
            var row1 = await GetRowAsync(client, "/api/customers/1");
            Assert.Null(row1["labels"]);
            Assert.Null(row1["addresses"]);
            Assert.NotNull(row1["tags"]);

            // GET list is not poisoned by the NULL-map row, and null vs {} stay distinct.
            var rows = await GetListAsync(client, "/api/customers");
            Assert.Equal(2, rows.Count);
            var listRow1 = rows[0]!;
            var listRow2 = rows[1]!;
            Assert.Null(listRow1["labels"]);
            Assert.Empty((JsonObject)listRow2["labels"]!);

            // PATCH an unrelated field on the NULL-map row: the handler materializes the
            // row (FindAsync), merges, saves — all over the NULL maps (regression: 500).
            var patched = await PatchRowAsync(client, "/api/customers/1", new JsonObject { ["name"] = "renamed" });
            Assert.Equal("renamed", (string?)patched["name"]);

            // PATCH the map to a value, then back to present-null: the write path round-trips.
            await PatchRowAsync(client, "/api/customers/1", new JsonObject
            {
                ["labels"] = new JsonObject { ["x"] = "y" },
                ["addresses"] = new JsonObject
                {
                    ["hq"] = new JsonObject { ["street"] = "1 Main" },
                },
            });
            row1 = await GetRowAsync(client, "/api/customers/1");
            Assert.Equal("y", (string?)row1["labels"]!["x"]);
            Assert.Equal("1 Main", (string?)row1["addresses"]!["hq"]!["street"]);

            await PatchRowAsync(client, "/api/customers/1", new JsonObject { ["labels"] = null });
            row1 = await GetRowAsync(client, "/api/customers/1");
            Assert.Null(row1["labels"]);

            // Create WITHOUT the optional map keys: the absent value persists as NULL
            // (not a silent {}); the @required map is still honoured on the body.
            await PostExpectStatusAsync(client, "/api/customers",
                new JsonObject { ["name"] = "created", ["tags"] = new JsonObject { ["new"] = "row" } },
                expected: 201);
            JsonObject? created = null;
            foreach (var row in await GetListAsync(client, "/api/customers"))
            {
                if (row is JsonObject o && (string?)o["name"] == "created") created = o;
            }
            Assert.NotNull(created);
            Assert.Null(created!["labels"]);
            Assert.Equal("row", (string?)created!["tags"]!["new"]);
        }
    }

    // GET .../{id} — asserts 200 and returns the row object.
    private static async Task<JsonObject> GetRowAsync(HttpClient client, string path)
    {
        using var response = await client.GetAsync(path);
        var text = await response.Content.ReadAsStringAsync();
        if (!response.IsSuccessStatusCode)
            throw new XunitException($"GET {path} -> {(int)response.StatusCode}: {text}");
        return JsonNode.Parse(text) as JsonObject
            ?? throw new XunitException($"GET {path}: expected a JSON object, got: {text}");
    }

    // GET (list) — asserts 200 and returns the rows array.
    private static async Task<JsonArray> GetListAsync(HttpClient client, string path)
    {
        using var response = await client.GetAsync(path);
        var text = await response.Content.ReadAsStringAsync();
        if (!response.IsSuccessStatusCode)
            throw new XunitException($"GET {path} -> {(int)response.StatusCode}: {text}");
        return JsonNode.Parse(text) as JsonArray
            ?? throw new XunitException($"GET {path}: expected a JSON array, got: {text}");
    }

    private static async Task<JsonObject> PatchRowAsync(HttpClient client, string path, JsonObject body) =>
        await SendRowAsync(client, HttpMethod.Patch, path, body);

    private static async Task PostExpectStatusAsync(HttpClient client, string path, JsonObject body, int expected)
    {
        using var response = await client.PostAsync(path,
            new StringContent(body.ToJsonString(), Encoding.UTF8, "application/json"));
        var text = await response.Content.ReadAsStringAsync();
        if ((int)response.StatusCode != expected)
            throw new XunitException($"POST {path} -> {(int)response.StatusCode} (expected {expected}): {text}");
    }

    private static async Task<JsonObject> SendRowAsync(HttpClient client, HttpMethod method, string path, JsonObject body)
    {
        using var response = await client.SendAsync(new HttpRequestMessage(method, path)
        {
            Content = new StringContent(body.ToJsonString(), Encoding.UTF8, "application/json"),
        });
        var text = await response.Content.ReadAsStringAsync();
        if (!response.IsSuccessStatusCode)
            throw new XunitException($"{method} {path} -> {(int)response.StatusCode}: {text}");
        return JsonNode.Parse(text) as JsonObject
            ?? throw new XunitException($"{method} {path}: expected a JSON object, got: {text}");
    }

    private static async Task ProvisionAsync(string connString)
    {
        await using var c = new NpgsqlConnection(connString);
        await c.OpenAsync();
        await using var cmd = c.CreateCommand();
        cmd.CommandText = SchemaDdl + "\n" + SeedDdl;
        await cmd.ExecuteNonQueryAsync();
    }

    // Runs the real generators on the map model, Roslyn-compiles the emitted sources
    // in-memory, and hosts them on Kestrel against the container — the emitted
    // CustomerRoutes over the emitted AppDbContext is the artifact under test
    // (JsonbGeneratedServerFactory's pattern, inlined for this one-model lane).
    private static async Task<(string BaseUrl, WebApplication App)> StartGeneratedServerAsync(PostgresContainer pg)
    {
        var (assembly, routeEntities) = CompileGeneratedServer();
        var dbContextType = assembly.GetType($"{GeneratedNamespace}.AppDbContext")
            ?? throw new InvalidOperationException("generated AppDbContext type not found");

        int port = PickFreePort();
        string baseUrl = $"http://127.0.0.1:{port}";

        var builder = WebApplication.CreateBuilder();
        builder.WebHost.UseUrls(baseUrl);
        builder.Logging.ClearProviders();
        RegisterGeneratedDbContext(builder.Services, dbContextType, pg.ConnectionString);

        var app = builder.Build();
        foreach (var entity in routeEntities)
        {
            var routesType = assembly.GetType($"{GeneratedNamespace}.{entity}Routes");
            if (routesType is null) continue;
            var mapMethod = routesType.GetMethod($"Map{entity}Routes", BindingFlags.Public | BindingFlags.Static);
            mapMethod?.Invoke(null, new object[] { app, "/api" });
        }

        await app.StartAsync();
        return (baseUrl, app);
    }

    private static (Assembly Assembly, IReadOnlyList<string> RouteEntities) CompileGeneratedServer()
    {
        var loadResult = new MetaDataLoader().Load([new InMemoryStringSource(Model, id: "map-null.json")]);
        if (loadResult.Errors.Count != 0)
            throw new InvalidOperationException(
                "map model failed to load: " + string.Join("; ", loadResult.Errors.Select(e => e.ToString())));

        var routeEntities = loadResult.Root.Objects()
            .Where(o => o.IsEntity())
            .Select(o => CSharpNaming.Pascal(o.Name))
            .ToList();

        var ctx = new GenContext
        {
            Entities = loadResult.Root.Objects(),
            Root = loadResult.Root,
            Config = new GenConfig
            {
                OutDir = "/unused",
                Namespace = GeneratedNamespace,
                ColumnNamingStrategy = ColumnNamingStrategy.Literal,
                EmitAbstractShapes = false,
            },
        };

        var files = new EntityGenerator().Generate(ctx)
            .Concat(new DbContextGenerator().Generate(ctx))
            .Concat(new FilterAllowlistGenerator().Generate(ctx))
            .Concat(new RoutesGenerator().Generate(ctx))
            .ToList();

        var trees = files
            .Select(f => CSharpSyntaxTree.ParseText(f.Content, new CSharpParseOptions(LanguageVersion.CSharp12)))
            .ToArray();

        var comp = CSharpCompilation.Create(
            "mapnull_generated_" + Guid.NewGuid().ToString("N"),
            trees, BuildReferenceSet(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        using var ms = new MemoryStream();
        var emit = comp.Emit(ms);
        if (!emit.Success)
        {
            var errors = emit.Diagnostics
                .Where(d => d.Severity == DiagnosticSeverity.Error)
                .Select(d => $"{d.Id}: {d.GetMessage()}")
                .ToList();
            throw new InvalidOperationException(
                "generated map server failed to compile:\n  " + string.Join("\n  ", errors));
        }

        ms.Seek(0, SeekOrigin.Begin);
        return (Assembly.Load(ms.ToArray()), routeEntities);
    }

    private static List<MetadataReference> BuildReferenceSet()
    {
        var byFileName = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        var tpa = (string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ?? "";
        foreach (var path in tpa.Split(Path.PathSeparator))
            if (path.Length > 0 && path.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                byFileName[Path.GetFileName(path)] = path;

        var aspNetDir = Path.GetDirectoryName(typeof(WebApplication).Assembly.Location);
        if (aspNetDir is not null && Directory.Exists(aspNetDir))
            foreach (var dll in Directory.EnumerateFiles(aspNetDir, "*.dll"))
                byFileName[Path.GetFileName(dll)] = dll;

        return byFileName.Values
            .Select(loc => (MetadataReference)MetadataReference.CreateFromFile(loc))
            .ToList();
    }

    private static void RegisterGeneratedDbContext(
        IServiceCollection services, Type dbContextType, string connString)
    {
        var addDbContext = typeof(EntityFrameworkServiceCollectionExtensions)
            .GetMethods(BindingFlags.Public | BindingFlags.Static)
            .First(m => m.Name == "AddDbContext"
                        && m.IsGenericMethodDefinition
                        && m.GetGenericArguments().Length == 1
                        && m.GetParameters().Length == 4)
            .MakeGenericMethod(dbContextType);

        Action<DbContextOptionsBuilder> configure = opts => opts.UseNpgsql(connString);
        addDbContext.Invoke(null, new object?[]
        {
            services, configure, ServiceLifetime.Scoped, ServiceLifetime.Scoped,
        });
    }

    private static int PickFreePort()
    {
        var l = new System.Net.Sockets.TcpListener(System.Net.IPAddress.Loopback, 0);
        l.Start();
        int port = ((System.Net.IPEndPoint)l.LocalEndpoint).Port;
        l.Stop();
        return port;
    }
}
