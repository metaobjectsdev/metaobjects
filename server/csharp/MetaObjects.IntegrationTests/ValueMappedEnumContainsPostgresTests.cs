// ValueMappedEnumContainsPostgresTests — a parameterised `Contains` over a scalar value-mapped
// field.enum (@intValueMap or @stringValueMap), through the GENERATED entity + AppDbContext,
// compiled in memory and run against a real Postgres.
//
// The generated converter used to be the bare lambda pair handed to HasConversion(...), which EF
// types on the property's CLR type: ValueConverter<E?, int> for an OPTIONAL field. Npgsql EF 8
// cannot build the JSON collection reader for a parameterised collection over that converter, so
//
//     E?[] active = { E.LIVE };
//     db.Widgets.Where(w => active.Contains(w.Status)).Count();
//
// threw: InvalidOperationException ("When building an array mapping over 'Nullable`1', the
// JsonValueReaderWriter for element mapping ... is incorrect") on the EF 8.0.10 this project pins,
// MissingMethodException on JsonNullableStructCollectionReaderWriter`3[E?[], E?[], E] on later 8.0
// patches. The converter is now typed on the non-nullable enum. Required fields and string-stored
// enums are covered alongside, so each shape the converter takes is queried.
//
// Postgres needs METAOBJECTS_TEST_PG_URL (a fresh database is created and dropped) or Docker:
//   dotnet test server/csharp/MetaObjects.IntegrationTests/MetaObjects.IntegrationTests.csproj \
//     --filter "FullyQualifiedName~ValueMappedEnumContainsPostgresTests"

using System.Linq.Expressions;
using System.Reflection;
using MetaObjects.IntegrationTests.Runner;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using Xunit;

namespace MetaObjects.IntegrationTests;

public sealed class ValueMappedEnumContainsPostgresTests
{
    private const string Model = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.entity": { "name": "Widget", "children": [
        { "source.rdb": { "@table": "widgets" } },
        { "field.long": { "name": "id" } },
        { "field.enum": { "name": "status", "@values": ["DRAFT", "LIVE", "GONE"],
            "@intValueMap": { "DRAFT": 0, "LIVE": 5, "GONE": 9 } } },
        { "field.enum": { "name": "grade", "@required": true, "@values": ["LOW", "HIGH"],
            "@intValueMap": { "LOW": 1, "HIGH": 7 } } },
        { "field.enum": { "name": "phase", "@maxLength": 12, "@values": ["OPEN", "SHUT"],
            "@stringValueMap": { "OPEN": "open_v1", "SHUT": "shut_v1" } } },
        { "field.enum": { "name": "stage", "@required": true, "@maxLength": 10, "@values": ["NEW", "OLD"],
            "@stringValueMap": { "NEW": "new", "OLD": "old" } } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}}
    ]}}
    """;

    private const string Ddl = """
        CREATE TABLE "widgets" (
          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "status" INTEGER,
          "grade" INTEGER NOT NULL,
          "phase" VARCHAR(12),
          "stage" VARCHAR(10) NOT NULL
        );
        """;

    private static readonly Lazy<GeneratedEfModel> Gen = new(() => GeneratedEfModel.Compile(Model, "Acme.EnumContains"));

    private static object Member(string enumType, string member) => Gen.Value.Enum("Widget+" + enumType, member);

    private static Type EnumType(string enumType) => Gen.Value.Type("Widget+" + enumType);

    private static object Widget(string? status, string grade, string? phase, string stage) =>
        Gen.Value.New("Widget",
            ("Status", status is null ? null : Member("WidgetStatus", status)),
            ("Grade", Member("WidgetGrade", grade)),
            ("Phase", phase is null ? null : Member("WidgetPhase", phase)),
            ("Stage", Member("WidgetStage", stage)));

    [Fact]
    public async Task Postgres_runs_a_parameterised_Contains_over_each_value_mapped_enum_shape()
    {
        await using var pg = await PostgresContainer.StartAsync();
        await using (var conn = new NpgsqlConnection(pg.ConnectionString))
        {
            await conn.OpenAsync();
            await using var ddl = new NpgsqlCommand(Ddl, conn);
            await ddl.ExecuteNonQueryAsync();
        }

        using (var db = Gen.Value.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(Widget("DRAFT", "LOW", "OPEN", "NEW"));
            db.Add(Widget("LIVE", "HIGH", "SHUT", "OLD"));
            db.Add(Widget("GONE", "HIGH", "SHUT", "OLD"));
            db.Add(Widget(null, "LOW", null, "NEW"));
            db.SaveChanges();
        }

        // An optional value-mapped column reads NULL back as null, int-stored and string-stored alike:
        // EF never hands null to the typed converter, so it is neither refused nor read as a member.
        using (var db = Gen.Value.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var rows = GeneratedEfModel.All(db, Gen.Value.Type("Widget"));
            Assert.Equal(4, rows.Count);
            var unset = Assert.Single(rows, r => GeneratedEfModel.Get(r, "Status") is null);
            Assert.Null(GeneratedEfModel.Get(unset, "Phase"));
            Assert.Equal(Member("WidgetGrade", "LOW"), GeneratedEfModel.Get(unset, "Grade"));
            Assert.Equal(Member("WidgetStage", "NEW"), GeneratedEfModel.Get(unset, "Stage"));
            Assert.Single(rows, r => GeneratedEfModel.Get(r, "Phase") is null);
        }

        // Every shape is queried and every outcome reported together, so one failure does not hide
        // whether the others hold.
        var failures = new List<string>();
        void Expect(int expected, string property, string enumType, bool nullable, params object?[] members)
        {
            using var db = Gen.Value.NewContext(o => o.UseNpgsql(pg.ConnectionString));
            var label = $"{property} in [{string.Join(", ", members.Select(m => m?.ToString() ?? "null"))}]";
            try
            {
                var actual = CountIn(db, property, EnumType(enumType), nullable, members);
                if (actual != expected) failures.Add($"{label}: counted {actual}, expected {expected}");
            }
            catch (Exception e)
            {
                var inner = GeneratedEfModel.Chain(e).Last();
                failures.Add($"{label}: {inner.GetType().Name}: {inner.Message}");
            }
        }

        // Optional int-stored: the repro. Two of the three non-null rows match.
        Expect(2, "Status", "WidgetStatus", nullable: true, Member("WidgetStatus", "LIVE"), Member("WidgetStatus", "GONE"));
        // Optional string-stored.
        Expect(1, "Phase", "WidgetPhase", nullable: true, Member("WidgetPhase", "OPEN"));
        // A list holding null matches the row whose column is NULL, as well as the members listed.
        Expect(2, "Status", "WidgetStatus", nullable: true, null, Member("WidgetStatus", "LIVE"));
        Expect(2, "Phase", "WidgetPhase", nullable: true, null, Member("WidgetPhase", "OPEN"));
        // Required int-stored and string-stored.
        Expect(2, "Grade", "WidgetGrade", nullable: false, Member("WidgetGrade", "HIGH"));
        Expect(2, "Stage", "WidgetStage", nullable: false, Member("WidgetStage", "NEW"));

        Assert.True(failures.Count == 0, string.Join("\n", failures));
    }

    // `db.Set<Widget>().Where(w => active.Contains(w.<property>)).Count()`, with `active` a
    // CAPTURED array — a query parameter, not constants inlined into the SQL — typed as the
    // property is: E?[] for an optional field, E[] for a required one. A null member is a null
    // element of the E?[] list.
    private static int CountIn(DbContext db, string property, Type enumType, bool nullable, params object?[] members)
    {
        var elementType = nullable ? typeof(Nullable<>).MakeGenericType(enumType) : enumType;
        var active = Array.CreateInstance(elementType, members.Length);
        for (var i = 0; i < members.Length; i++) active.SetValue(members[i], i);
        return (int)typeof(ValueMappedEnumContainsPostgresTests)
            .GetMethod(nameof(CountInOf), BindingFlags.NonPublic | BindingFlags.Static)!
            .MakeGenericMethod(Gen.Value.Type("Widget"), elementType)
            .Invoke(null, [db, property, active])!;
    }

    private static int CountInOf<TEntity, TElement>(DbContext db, string property, TElement[] active)
        where TEntity : class
    {
        var w = Expression.Parameter(typeof(TEntity), "w");
        Expression<Func<TElement[]>> captured = () => active;
        var body = Expression.Call(typeof(Enumerable), nameof(Enumerable.Contains), [typeof(TElement)],
            captured.Body, Expression.Property(w, property));
        return db.Set<TEntity>().Where(Expression.Lambda<Func<TEntity, bool>>(body, w)).Count();
    }
}
