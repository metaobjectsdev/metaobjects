// IntBackedEnumArrayPersistenceTests — an int-backed field.enum ARRAY (@intValueMap inherited
// from a shared abstract enum, isArray on the consuming field) through the GENERATED entity +
// AppDbContext, compiled in memory and run against a real engine.
//
// What must hold, per element: the declared int is stored (never the member symbol, and never
// the C# ordinal — PUBLISHED is 5 here, its ordinal is 1), it reads back as its member, and a
// stored int the map does not describe throws rather than becoming some member, an empty
// array stays empty and a NULL array stays null. Covered on the three mappings that carry such
// a column: an entity column, a member of a flattened value object, and a read-only projection
// (view) column.
//
//   Postgres: native integer[] — the column type EF itself picks for the property is asserted
//             too, so the model and the DDL agree.
//   SQLite:   EF Core 8 keeps a primitive collection as JSON text — a JSON array of NUMBERS.
//
// The raw stored value is read with plain SQL, bypassing EF, so the assertions are on what the
// database holds rather than on what the reading code is willing to show back.
//
// Postgres needs METAOBJECTS_TEST_PG_URL (a fresh database is created and dropped) or Docker:
//   dotnet test server/csharp/MetaObjects.IntegrationTests/MetaObjects.IntegrationTests.csproj \
//     --filter "FullyQualifiedName~IntBackedEnumArrayPersistenceTests"

using System.Collections;
using System.Reflection;
using MetaObjects.Codegen;
using MetaObjects.Codegen.Generators;
using MetaObjects.IntegrationTests.Runner;
using MetaObjects.Loader;
using MetaObjects.Meta;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.Data.Sqlite;
