namespace MetaObjects.IntegrationTests;

public sealed class IntBackedEnumArrayPersistenceTests
{
    private const string Ns = "MetaObjects.IntegrationTests.IntEnumArrayGenerated";

    private const string Model = """
    { "metadata.root": { "package": "acme", "children": [
      { "field.enum": { "name": "Status", "abstract": true,
          "@values": ["DRAFT", "PUBLISHED", "ARCHIVED"],
          "@intValueMap": { "DRAFT": 0, "PUBLISHED": 5, "ARCHIVED": 9 } } },
      { "object.value": { "name": "Address", "children": [
        { "field.string": { "name": "street" } },
        { "field.enum":   { "name": "tags", "extends": "acme::Status", "isArray": true } }
      ]}},
      { "object.entity": { "name": "Doc", "children": [
        { "source.rdb": { "@table": "docs" } },
        { "field.long":   { "name": "id" } },
        { "field.string": { "name": "title" } },
        { "field.enum":   { "name": "current", "extends": "acme::Status" } },
        { "field.enum":   { "name": "history", "extends": "acme::Status", "isArray": true } },
        { "field.object": { "name": "home", "@objectRef": "Address", "@storage": "flattened" } },
        { "identity.primary": { "name": "pk", "@fields": "id", "@generation": "increment" } }
      ]}},
      { "object.projection": { "name": "DocHistory", "children": [
        { "source.rdb": { "@kind": "view", "@table": "v_doc_history" } },
        { "field.long":   { "name": "id" } },
        { "field.string": { "name": "title" } },
        { "field.enum":   { "name": "history", "extends": "acme::Status", "isArray": true } }
      ]}}
    ]}}
    """;

    private const string PgDdl = """
        CREATE TABLE "docs" (
          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          "title" TEXT,
          "current" INTEGER,
          "history" INTEGER[],
          "home_street" TEXT,
          "home_tags" INTEGER[]
        );
        CREATE VIEW "v_doc_history" AS SELECT "id", "title", "history" FROM "docs";
        """;

    private const string SqliteDdl = """
        CREATE TABLE "docs" (
          "id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
          "title" TEXT,
          "current" INTEGER,
          "history" TEXT,
          "home_street" TEXT,
          "home_tags" TEXT
        );
        CREATE VIEW "v_doc_history" AS SELECT "id", "title", "history" FROM "docs";
        """;

    private static readonly Lazy<Assembly> Generated = new(Compile);

    [Fact]
    public async Task Postgres_stores_each_element_as_its_declared_int_in_an_integer_array()
    {
        await using var pg = await PostgresContainer.StartAsync();
        await using (var conn = new NpgsqlConnection(pg.ConnectionString))
        {
            await conn.OpenAsync();
            await using var ddl = new NpgsqlCommand(PgDdl, conn);
            await ddl.ExecuteNonQueryAsync();
        }

        DbContext NewDb() => NewContext(o => o.UseNpgsql(pg.ConnectionString));

        // The column type EF ITSELF infers for the mapped property: integer[], the shape the
        // migration creates. A text[] or a json column here would be a model/DDL disagreement.
        using (var db = NewDb())
        {
            var doc = db.Model.FindEntityType(Type("Doc"))!;
            Assert.Equal("integer[]", doc.FindProperty("History")!.GetColumnType());
            Assert.Equal("integer", doc.FindProperty("Current")!.GetColumnType());
            var home = doc.FindNavigation("Home")!.TargetEntityType;
            Assert.Equal("integer[]", home.FindProperty("Tags")!.GetColumnType());
            Assert.Equal("home_tags", home.FindProperty("Tags")!.GetColumnName());
            var view = db.Model.FindEntityType(Type("DocHistory"))!;
            Assert.Equal("integer[]", view.FindProperty("History")!.GetColumnType());
        }

        InsertTwoDocs(NewDb);

        // RAW: what Postgres holds, read as text with the element type alongside.
        var raw = new List<(string Title, string? History, string? HomeTags, string? Type)>();
        await using (var conn = new NpgsqlConnection(pg.ConnectionString))
        {
            await conn.OpenAsync();
            await using var cmd = new NpgsqlCommand(
                """SELECT "title", "history"::text, "home_tags"::text, pg_typeof("history")::text FROM "docs" ORDER BY "id" """, conn);
            await using var r = await cmd.ExecuteReaderAsync();
            while (await r.ReadAsync())
                raw.Add((r.GetString(0), r.IsDBNull(1) ? null : r.GetString(1),
                    r.IsDBNull(2) ? null : r.GetString(2), r.GetString(3)));
        }
        Assert.Equal(("two", "{5,0}", "{9}", "integer[]"), raw[0]);
        Assert.Equal(("empty", "{}", "{}", "integer[]"), raw[1]);
        Assert.Equal(("null", null, null, "integer[]"), raw[2]);

        AssertReadsBackAsMembers(NewDb);

        // An int the map does not describe (7) throws on read, as the scalar column does.
        await using (var conn = new NpgsqlConnection(pg.ConnectionString))
        {
            await conn.OpenAsync();
            await using var cmd = new NpgsqlCommand(
                """INSERT INTO "docs" ("title", "history") VALUES ('bad', '{5,7}')""", conn);
            await cmd.ExecuteNonQueryAsync();
        }
        AssertUnmappedElementThrows(NewDb);
    }

    [Fact]
    public async Task Sqlite_stores_each_element_as_its_declared_int_in_a_json_array_of_numbers()
    {
        using var file = new SqliteTempDatabase("mo-ivm-array-");
        var cs = $"Data Source={file.FilePath}";
        await using (var conn = new SqliteConnection(cs))
        {
            await conn.OpenAsync();
            await using var ddl = conn.CreateCommand();
            ddl.CommandText = SqliteDdl;
            await ddl.ExecuteNonQueryAsync();
        }

        DbContext NewDb() => NewContext(o => o.UseSqlite(cs));

        InsertTwoDocs(NewDb);

        var raw = new List<(string Title, string? History, string? HomeTags)>();
        await using (var conn = new SqliteConnection(cs))
        {
            await conn.OpenAsync();
            await using var cmd = conn.CreateCommand();
            cmd.CommandText = """SELECT "title", "history", "home_tags" FROM "docs" ORDER BY "id" """;
            await using var r = await cmd.ExecuteReaderAsync();
            while (await r.ReadAsync())
                raw.Add((r.GetString(0), r.IsDBNull(1) ? null : r.GetString(1), r.IsDBNull(2) ? null : r.GetString(2)));
        }
        Assert.Equal(("two", "[5,0]", "[9]"), raw[0]);
        Assert.Equal(("empty", "[]", "[]"), raw[1]);
        Assert.Equal(("null", null, null), raw[2]);

        AssertReadsBackAsMembers(NewDb);

        await using (var conn = new SqliteConnection(cs))
        {
            await conn.OpenAsync();
            await using var cmd = conn.CreateCommand();
            cmd.CommandText = """INSERT INTO "docs" ("title", "history") VALUES ('bad', '[5,7]')""";
            await cmd.ExecuteNonQueryAsync();
        }
        AssertUnmappedElementThrows(NewDb);
    }

    // ── shared steps ──────────────────────────────────────────────────────────────

    private static void InsertTwoDocs(Func<DbContext> newDb)
    {
        using var db = newDb();
        db.Add(NewDoc("two", Statuses("PUBLISHED", "DRAFT"), Statuses("ARCHIVED"), current: "PUBLISHED"));
        db.Add(NewDoc("empty", Statuses(), Statuses(), current: null));
        db.Add(NewDoc("null", null, null, current: null));
        db.SaveChanges();
    }

    private static void AssertReadsBackAsMembers(Func<DbContext> newDb)
    {
        using var db = newDb();
        var docs = All(db, Type("Doc")).OrderBy(d => (long)Prop(d, "Id")!).ToList();
        Assert.Equal(new[] { "PUBLISHED", "DRAFT" }, Names(Prop(docs[0], "History")));
        Assert.Equal(new[] { "ARCHIVED" }, Names(Prop(Prop(docs[0], "Home")!, "Tags")));
        Assert.Equal("PUBLISHED", Prop(docs[0], "Current")!.ToString());
        Assert.Empty(Names(Prop(docs[1], "History"))!);
        Assert.Null(Prop(docs[2], "History"));
        Assert.Null(Prop(Prop(docs[2], "Home")!, "Tags"));

        var rows = All(db, Type("DocHistory")).ToDictionary(r => (string)Prop(r, "Title")!);
        Assert.Equal(new[] { "PUBLISHED", "DRAFT" }, Names(Prop(rows["two"], "History")));
        Assert.Empty(Names(Prop(rows["empty"], "History"))!);
        Assert.Null(Prop(rows["null"], "History"));
    }

    private static void AssertUnmappedElementThrows(Func<DbContext> newDb)
    {
        foreach (var type in new[] { "Doc", "DocHistory" })
        {
            using var db = newDb();
            var ex = Assert.ThrowsAny<Exception>(() => All(db, Type(type)).ToList());
            var chain = string.Join(" | ", Chain(ex).Select(e => e.Message));
            Assert.Contains("intValueMap", chain);
            Assert.Contains("7", chain);
        }
    }

    // ── reflection plumbing over the compiled generated assembly ─────────────────

    private static Type Type(string name) =>
        Generated.Value.GetType($"{Ns}.{name}") ?? throw new InvalidOperationException($"no generated type {name}");

    private static DbContext NewContext(Action<DbContextOptionsBuilder> configure)
    {
        var ctxType = Type("AppDbContext");
        var builder = (DbContextOptionsBuilder)Activator.CreateInstance(
            typeof(DbContextOptionsBuilder<>).MakeGenericType(ctxType))!;
        configure(builder);
        return (DbContext)Activator.CreateInstance(ctxType, builder.Options)!;
    }

    private static object NewDoc(string title, IList? history, IList? tags, string? current)
    {
        var doc = Activator.CreateInstance(Type("Doc"))!;
        Set(doc, "Title", title);
        Set(doc, "History", history);
        Set(doc, "Current", current is null ? null : Enum.Parse(Type("Status"), current));
        var home = Activator.CreateInstance(Type("Address"))!;
        Set(home, "Street", "1 Main");
        Set(home, "Tags", tags);
        Set(doc, "Home", home);
        return doc;
    }

    private static IList Statuses(params string[] members)
    {
        var list = (IList)Activator.CreateInstance(typeof(List<>).MakeGenericType(Type("Status")))!;
        foreach (var m in members) list.Add(Enum.Parse(Type("Status"), m));
        return list;
    }

    private static string[]? Names(object? list) =>
        list is null ? null : ((IEnumerable)list).Cast<object>().Select(o => o.ToString()!).ToArray();

    private static object? Prop(object o, string name) => o.GetType().GetProperty(name)!.GetValue(o);

    private static void Set(object o, string name, object? value)
    {
        var p = o.GetType().GetProperty(name)
            ?? throw new InvalidOperationException($"{o.GetType().Name} has no property {name}");
        p.SetValue(o, value);
    }

    private static IEnumerable<object> All(DbContext db, Type t) =>
        (IEnumerable<object>)typeof(IntBackedEnumArrayPersistenceTests)
            .GetMethod(nameof(AllOf), BindingFlags.NonPublic | BindingFlags.Static)!
            .MakeGenericMethod(t).Invoke(null, [db])!;

    private static List<object> AllOf<T>(DbContext db) where T : class =>
        db.Set<T>().AsNoTracking().AsEnumerable().Cast<object>().ToList();

    private static IEnumerable<Exception> Chain(Exception? e)
    {
        for (; e is not null; e = e.InnerException) yield return e;
    }

    private static Assembly Compile()
    {
        var load = new MetaDataLoader().Load([new InMemoryStringSource(Model, id: "ivm-array.json")]);
        if (load.Errors.Count != 0)
            throw new InvalidOperationException("model failed to load: " + string.Join("; ", load.Errors));

        var ctx = new GenContext
        {
            Entities = load.Root.Objects(),
            Root = load.Root,
            Config = new GenConfig
            {
                OutDir = "/unused",
                Namespace = Ns,
                ColumnNamingStrategy = ColumnNamingStrategy.Literal,
                EmitAbstractShapes = false,
            },
        };
        var trees = new EntityGenerator().Generate(ctx)
            .Concat(new DbContextGenerator().Generate(ctx))
            .Select(f => CSharpSyntaxTree.ParseText(f.Content, new CSharpParseOptions(LanguageVersion.CSharp12)))
            .ToArray();

        var refs = ((string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ?? "")
            .Split(Path.PathSeparator)
            .Where(p => p.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
            .Select(p => (MetadataReference)MetadataReference.CreateFromFile(p))
            .ToList();
        var comp = CSharpCompilation.Create("ivm_array_" + Guid.NewGuid().ToString("N"), trees, refs,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        using var ms = new MemoryStream();
        var emit = comp.Emit(ms);
        if (!emit.Success)
            throw new InvalidOperationException("generated code failed to compile:\n  " + string.Join("\n  ",
                emit.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).Select(d => $"{d.Id}: {d.GetMessage()}")));
        return Assembly.Load(ms.ToArray());
    }
}
