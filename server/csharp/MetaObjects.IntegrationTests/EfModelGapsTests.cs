        Assert.Equal(new object?[] { false, null, null, 0, 0m, "LOW", created.UtcDateTime }, row);

        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var p = Assert.Single(GeneratedEfModel.All(db, gen.Type("Preference")));
