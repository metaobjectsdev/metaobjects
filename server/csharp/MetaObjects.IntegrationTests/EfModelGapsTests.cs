// EF model gaps — facts the metadata declares that the generated AppDbContext must carry into
// the finalized EF model, and the runtime behaviour each one controls. Each test reads the real
// IModel built from the generated code, and the ones whose point is runtime behaviour write and
// read rows on a live Postgres.
//
// Postgres needs METAOBJECTS_TEST_PG_URL (a fresh database is created and dropped) or Docker:
//   dotnet test server/csharp/MetaObjects.IntegrationTests/MetaObjects.IntegrationTests.csproj \
//     --filter "FullyQualifiedName~EfModelGapsTests"

using MetaObjects.IntegrationTests.Runner;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Npgsql;
using Xunit;

namespace MetaObjects.IntegrationTests;

public sealed class EfModelGapsTests
{
    private static async Task Exec(string cs, string sql)
    {
        await using var conn = new NpgsqlConnection(cs);
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        await cmd.ExecuteNonQueryAsync();
    }

    private static async Task<List<object?[]>> Rows(string cs, string sql)
    {
        var rows = new List<object?[]>();
        await using var conn = new NpgsqlConnection(cs);
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        await using var r = await cmd.ExecuteReaderAsync();
        while (await r.ReadAsync())
        {
            var row = new object?[r.FieldCount];
            for (var i = 0; i < r.FieldCount; i++) row[i] = r.IsDBNull(i) ? null : r.GetValue(i);
            rows.Add(row);
        }
        return rows;
    }

    private static IEntityType EntityType(DbContext db, string name) =>
        Assert.Single(db.Model.GetEntityTypes(), t => t.ClrType.Name == name);

    // ── D10: identity.primary @generation: assigned ─────────────────────────────────────────

    private const string AssignedModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.entity": { "name": "Country", "children": [
        { "source.rdb": { "@table": "countries" } },
        { "field.long":   { "name": "id" } },
        { "field.string": { "name": "name" } },
        { "identity.primary": { "@fields": "id", "@generation": "assigned" } }
      ]}},
      { "object.entity": { "name": "Region", "children": [
        { "source.rdb": { "@table": "regions" } },
        { "field.long":   { "name": "id" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}}
    ]}}
    """;

    [Fact]
    public void An_assigned_key_is_never_generated_by_the_database()
    {
        var gen = GeneratedEfModel.Compile(AssignedModel, "Acme.Assigned");
        using var db = gen.ModelOnlyContext();
        Assert.Equal(ValueGenerated.Never, EntityType(db, "Country").FindProperty("Id")!.ValueGenerated);
        // An increment key keeps EF's convention: generated on add.
        Assert.Equal(ValueGenerated.OnAdd, EntityType(db, "Region").FindProperty("Id")!.ValueGenerated);
    }

    [Fact]
    public async Task An_assigned_key_is_sent_on_insert_even_when_it_is_zero()
    {
        var gen = GeneratedEfModel.Compile(AssignedModel, "Acme.Assigned");
        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "countries" ("id" BIGINT PRIMARY KEY, "name" TEXT);
            CREATE TABLE "regions" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
            """);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            // 0 is the CLR default: a generated-on-add key would leave it out of the INSERT and
            // the NOT NULL primary key, which has no default, would refuse the row.
            db.Add(gen.New("Country", ("Id", 0L), ("Name", "zero")));
            db.Add(gen.New("Country", ("Id", 42L), ("Name", "answer")));
            db.SaveChanges();
        }
        var rows = await Rows(pg.ConnectionString, """SELECT "id", "name" FROM "countries" ORDER BY "id" """);
        Assert.Equal(new object?[] { 0L, "zero" }, rows[0]);
        Assert.Equal(new object?[] { 42L, "answer" }, rows[1]);
    }

    // ── D12 + D16: identity.reference @constraintName, and a reference to a non-PK key ──────

    private const string ReferenceModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.entity": { "name": "Customer", "children": [
        { "source.rdb": { "@table": "customers" } },
        { "field.long": { "name": "id" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}},
      { "object.entity": { "name": "Warehouse", "children": [
        { "source.rdb": { "@table": "warehouses" } },
        { "field.long":   { "name": "id" } },
        { "field.string": { "name": "regionCode", "@required": true } },
        { "field.int":    { "name": "siteNo", "@required": true } },
        { "identity.primary":   { "@fields": "id", "@generation": "increment" } },
        { "identity.secondary": { "name": "site", "@fields": ["regionCode", "siteNo"], "@unique": true } }
      ]}},
      { "object.entity": { "name": "Shipment", "children": [
        { "source.rdb": { "@table": "shipments" } },
        { "field.long":   { "name": "id" } },
        { "field.long":   { "name": "customerId", "@required": true } },
        { "field.string": { "name": "regionCode", "@required": true } },
        { "field.int":    { "name": "siteNo", "@required": true } },
        { "identity.primary":   { "@fields": "id", "@generation": "increment" } },
        { "identity.reference": { "name": "refCustomer", "@fields": "customerId", "@references": "Customer",
            "@constraintName": "shipment_customer_fk" } },
        { "identity.reference": { "name": "refSite", "@fields": ["regionCode", "siteNo"],
            "@references": "Warehouse.regionCode,siteNo", "@constraintName": "shipment_site_fk" } }
      ]}}
    ]}}
    """;

    private static IForeignKey ForeignKey(IEntityType t, params string[] props) =>
        Assert.Single(t.GetForeignKeys(), fk => fk.Properties.Select(p => p.Name).SequenceEqual(props));

    [Fact]
    public void A_reference_carries_its_constraint_name_and_its_principal_key_into_the_model()
    {
        var gen = GeneratedEfModel.Compile(ReferenceModel, "Acme.References");
        using var db = gen.ModelOnlyContext();
        var shipment = EntityType(db, "Shipment");

        var customer = ForeignKey(shipment, "CustomerId");
        Assert.Equal("shipment_customer_fk", customer.GetConstraintName());
        Assert.True(customer.PrincipalKey.IsPrimaryKey());

        // The target fields are not Warehouse's primary key, so EF must pair the FK with them —
        // without HasPrincipalKey it pairs a two-column FK with the one-column PK and fails.
        var site = ForeignKey(shipment, "RegionCode", "SiteNo");
        Assert.Equal("shipment_site_fk", site.GetConstraintName());
        Assert.Equal(new[] { "RegionCode", "SiteNo" }, site.PrincipalKey.Properties.Select(p => p.Name));
    }

    [Fact]
    public async Task The_database_EF_creates_names_the_constraints_and_enforces_the_alternate_key()
    {
        var gen = GeneratedEfModel.Compile(ReferenceModel, "Acme.References");
        await using var pg = await PostgresContainer.StartAsync();
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
            db.Database.EnsureCreated();

        var names = (await Rows(pg.ConnectionString,
                "SELECT conname FROM pg_constraint WHERE contype = 'f' ORDER BY conname"))
            .Select(r => (string)r[0]!).ToList();
        Assert.Equal(new[] { "shipment_customer_fk", "shipment_site_fk" }, names);

        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(gen.New("Customer"));
            db.Add(gen.New("Warehouse", ("RegionCode", "NE"), ("SiteNo", 7)));
            db.SaveChanges();
            db.Add(gen.New("Shipment", ("CustomerId", 1L), ("RegionCode", "NE"), ("SiteNo", 7)));
            db.SaveChanges();
        }
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(gen.New("Shipment", ("CustomerId", 1L), ("RegionCode", "NE"), ("SiteNo", 8)));
            var ex = Assert.Throws<DbUpdateException>(() => db.SaveChanges());
            Assert.Contains("shipment_site_fk", ex.InnerException!.Message);
        }
    }

    // ── D21: a TPH discriminator typed by a SHARED enum ─────────────────────────────────────

    private const string SharedDiscriminatorModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "field.enum": { "name": "VehicleKind", "abstract": true, "@values": ["Car", "Van"] } },
      { "object.entity": { "name": "Vehicle", "@discriminator": "kind", "children": [
        { "source.rdb": { "@table": "vehicles" } },
        { "field.long": { "name": "id" } },
        { "field.enum": { "name": "kind", "extends": "acme::VehicleKind" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}},
      { "object.entity": { "name": "Car", "extends": "Vehicle", "@discriminatorValue": "Car", "children": [
        { "field.int": { "name": "seats" } }
      ]}},
      { "object.entity": { "name": "Van", "extends": "Vehicle", "@discriminatorValue": "Van", "children": [
        { "field.int": { "name": "payloadKg" } }
      ]}}
    ]}}
    """;

    [Fact]
    public async Task A_shared_enum_discriminator_maps_each_subtype_and_round_trips()
    {
        // The HasValue argument named the enum as nested in the base (Vehicle.VehicleKind.Car),
        // which a shared enum is not: the context did not compile.
        var gen = GeneratedEfModel.Compile(SharedDiscriminatorModel, "Acme.SharedDisc");
        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "vehicles" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "kind" TEXT NOT NULL, "seats" INTEGER, "payloadKg" INTEGER);
            """);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(gen.New("Car", ("Seats", 5)));
            db.Add(gen.New("Van", ("PayloadKg", 900)));
            db.SaveChanges();
        }
        var raw = await Rows(pg.ConnectionString, """SELECT "kind" FROM "vehicles" ORDER BY "id" """);
        Assert.Equal(new[] { "Car", "Van" }, raw.Select(r => (string)r[0]!));
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var types = GeneratedEfModel.All(db, gen.Type("Vehicle")).Select(v => v.GetType().Name).OrderBy(n => n);
            Assert.Equal(new[] { "Car", "Van" }, types);
        }
    }
}
