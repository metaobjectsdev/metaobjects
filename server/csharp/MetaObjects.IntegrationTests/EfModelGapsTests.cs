// EF model gaps — facts the metadata declares that the generated AppDbContext must carry into
// the finalized EF model, and the runtime behaviour each one controls. Each test reads the real
// IModel built from the generated code, and the ones whose point is runtime behaviour write and
// read rows on a live Postgres.
//
// Postgres needs METAOBJECTS_TEST_PG_URL (a fresh database is created and dropped) or Docker:
//   dotnet test server/csharp/MetaObjects.IntegrationTests/MetaObjects.IntegrationTests.csproj \
//     --filter "FullyQualifiedName~EfModelGapsTests"

using MetaObjects.IntegrationTests.Runner;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Npgsql;
using Xunit;

namespace MetaObjects.IntegrationTests;

public sealed class EfModelGapsTests
{
    private static async Task Exec(string cs, string sql)
    {
        await using var conn = new NpgsqlConnection(cs);
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        await cmd.ExecuteNonQueryAsync();
    }

    private static async Task<List<object?[]>> Rows(string cs, string sql)
    {
        var rows = new List<object?[]>();
        await using var conn = new NpgsqlConnection(cs);
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        await using var r = await cmd.ExecuteReaderAsync();
        while (await r.ReadAsync())
        {
            var row = new object?[r.FieldCount];
            for (var i = 0; i < r.FieldCount; i++) row[i] = r.IsDBNull(i) ? null : r.GetValue(i);
            rows.Add(row);
        }
        return rows;
    }

    private static IEntityType EntityType(DbContext db, string name) =>
        Assert.Single(db.Model.GetEntityTypes(), t => t.ClrType.Name == name);

    // ── D10: identity.primary @generation: assigned ─────────────────────────────────────────

    private const string AssignedModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.entity": { "name": "Country", "children": [
        { "source.rdb": { "@table": "countries" } },
        { "field.long":   { "name": "id" } },
        { "field.string": { "name": "name" } },
        { "identity.primary": { "@fields": "id", "@generation": "assigned" } }
      ]}},
      { "object.entity": { "name": "Region", "children": [
        { "source.rdb": { "@table": "regions" } },
        { "field.long":   { "name": "id" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}}
    ]}}
    """;

    [Fact]
    public void An_assigned_key_is_never_generated_by_the_database()
    {
        var gen = GeneratedEfModel.Compile(AssignedModel, "Acme.Assigned");
        using var db = gen.ModelOnlyContext();
        Assert.Equal(ValueGenerated.Never, EntityType(db, "Country").FindProperty("Id")!.ValueGenerated);
        // An increment key keeps EF's convention: generated on add.
        Assert.Equal(ValueGenerated.OnAdd, EntityType(db, "Region").FindProperty("Id")!.ValueGenerated);
    }

    [Fact]
    public async Task An_assigned_key_is_sent_on_insert_even_when_it_is_zero()
    {
        var gen = GeneratedEfModel.Compile(AssignedModel, "Acme.Assigned");
        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "countries" ("id" BIGINT PRIMARY KEY, "name" TEXT);
            CREATE TABLE "regions" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
            """);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            // 0 is the CLR default: a generated-on-add key would leave it out of the INSERT and
            // the NOT NULL primary key, which has no default, would refuse the row.
            db.Add(gen.New("Country", ("Id", 0L), ("Name", "zero")));
            db.Add(gen.New("Country", ("Id", 42L), ("Name", "answer")));
            db.SaveChanges();
        }
        var rows = await Rows(pg.ConnectionString, """SELECT "id", "name" FROM "countries" ORDER BY "id" """);
        Assert.Equal(new object?[] { 0L, "zero" }, rows[0]);
        Assert.Equal(new object?[] { 42L, "answer" }, rows[1]);
    }

    // ── D12 + D16: identity.reference @constraintName, and a reference to a non-PK key ──────

    private const string ReferenceModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.entity": { "name": "Customer", "children": [
        { "source.rdb": { "@table": "customers" } },
        { "field.long": { "name": "id" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}},
      { "object.entity": { "name": "Warehouse", "children": [
        { "source.rdb": { "@table": "warehouses" } },
        { "field.long":   { "name": "id" } },
        { "field.string": { "name": "regionCode", "@required": true } },
        { "field.int":    { "name": "siteNo", "@required": true } },
        { "identity.primary":   { "@fields": "id", "@generation": "increment" } },
        { "identity.secondary": { "name": "site", "@fields": ["regionCode", "siteNo"], "@unique": true } }
      ]}},
      { "object.entity": { "name": "Shipment", "children": [
        { "source.rdb": { "@table": "shipments" } },
        { "field.long":   { "name": "id" } },
        { "field.long":   { "name": "customerId", "@required": true } },
        { "field.string": { "name": "regionCode", "@required": true } },
        { "field.int":    { "name": "siteNo", "@required": true } },
        { "identity.primary":   { "@fields": "id", "@generation": "increment" } },
        { "identity.reference": { "name": "refCustomer", "@fields": "customerId", "@references": "Customer",
            "@constraintName": "shipment_customer_fk" } },
        { "identity.reference": { "name": "refSite", "@fields": ["regionCode", "siteNo"],
            "@references": "Warehouse.regionCode,siteNo", "@constraintName": "shipment_site_fk" } }
      ]}}
    ]}}
    """;

    private static IForeignKey ForeignKey(IEntityType t, params string[] props) =>
        Assert.Single(t.GetForeignKeys(), fk => fk.Properties.Select(p => p.Name).SequenceEqual(props));

    [Fact]
    public void A_reference_carries_its_constraint_name_and_its_principal_key_into_the_model()
    {
        var gen = GeneratedEfModel.Compile(ReferenceModel, "Acme.References");
        using var db = gen.ModelOnlyContext();
        var shipment = EntityType(db, "Shipment");

        var customer = ForeignKey(shipment, "CustomerId");
        Assert.Equal("shipment_customer_fk", customer.GetConstraintName());
        Assert.True(customer.PrincipalKey.IsPrimaryKey());

        // The target fields are not Warehouse's primary key, so EF must pair the FK with them —
        // without HasPrincipalKey it pairs a two-column FK with the one-column PK and fails.
        var site = ForeignKey(shipment, "RegionCode", "SiteNo");
        Assert.Equal("shipment_site_fk", site.GetConstraintName());
        Assert.Equal(new[] { "RegionCode", "SiteNo" }, site.PrincipalKey.Properties.Select(p => p.Name));
    }

    [Fact]
    public async Task The_database_EF_creates_names_the_constraints_and_enforces_the_alternate_key()
    {
        var gen = GeneratedEfModel.Compile(ReferenceModel, "Acme.References");
        await using var pg = await PostgresContainer.StartAsync();
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
            db.Database.EnsureCreated();

        var names = (await Rows(pg.ConnectionString,
                "SELECT conname FROM pg_constraint WHERE contype = 'f' ORDER BY conname"))
            .Select(r => (string)r[0]!).ToList();
        Assert.Equal(new[] { "shipment_customer_fk", "shipment_site_fk" }, names);

        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(gen.New("Customer"));
            db.Add(gen.New("Warehouse", ("RegionCode", "NE"), ("SiteNo", 7)));
            db.SaveChanges();
            db.Add(gen.New("Shipment", ("CustomerId", 1L), ("RegionCode", "NE"), ("SiteNo", 7)));
            db.SaveChanges();
        }
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(gen.New("Shipment", ("CustomerId", 1L), ("RegionCode", "NE"), ("SiteNo", 8)));
            var ex = Assert.Throws<DbUpdateException>(() => db.SaveChanges());
            Assert.Contains("shipment_site_fk", ex.InnerException!.Message);
        }
    }

    // ── D21: a TPH discriminator typed by a SHARED enum ─────────────────────────────────────

    private const string SharedDiscriminatorModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "field.enum": { "name": "VehicleKind", "abstract": true, "@values": ["Car", "Van"] } },
      { "object.entity": { "name": "Vehicle", "@discriminator": "kind", "children": [
        { "source.rdb": { "@table": "vehicles" } },
        { "field.long": { "name": "id" } },
        { "field.enum": { "name": "kind", "extends": "acme::VehicleKind" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}},
      { "object.entity": { "name": "Car", "extends": "Vehicle", "@discriminatorValue": "Car", "children": [
        { "field.int": { "name": "seats" } }
      ]}},
      { "object.entity": { "name": "Van", "extends": "Vehicle", "@discriminatorValue": "Van", "children": [
        { "field.int": { "name": "payloadKg" } }
      ]}}
    ]}}
    """;

    [Fact]
    public async Task A_shared_enum_discriminator_maps_each_subtype_and_round_trips()
    {
        // The HasValue argument named the enum as nested in the base (Vehicle.VehicleKind.Car),
        // which a shared enum is not: the context did not compile.
        var gen = GeneratedEfModel.Compile(SharedDiscriminatorModel, "Acme.SharedDisc");
        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "vehicles" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "kind" TEXT NOT NULL, "seats" INTEGER, "payloadKg" INTEGER);
            """);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(gen.New("Car", ("Seats", 5)));
            db.Add(gen.New("Van", ("PayloadKg", 900)));
            db.SaveChanges();
        }
        var raw = await Rows(pg.ConnectionString, """SELECT "kind" FROM "vehicles" ORDER BY "id" """);
        Assert.Equal(new[] { "Car", "Van" }, raw.Select(r => (string)r[0]!));
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var types = GeneratedEfModel.All(db, gen.Type("Vehicle")).Select(v => v.GetType().Name).OrderBy(n => n);
            Assert.Equal(new[] { "Car", "Van" }, types);
        }
    }

    // ── D23: a keyed projection ─────────────────────────────────────────────────────────────

    private const string KeyedProjectionModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.entity": { "name": "BaseRow", "abstract": true, "children": [
        { "field.long": { "name": "id" } },
        { "identity.primary": { "name": "pk", "@fields": "id", "@generation": "increment" } }
      ]}},
      { "object.entity": { "name": "Member", "extends": "BaseRow", "children": [
        { "source.rdb": { "@table": "members" } },
        { "field.string": { "name": "name" } }
      ]}},
      { "object.entity": { "name": "Badge", "children": [
        { "source.rdb": { "@table": "badges" } },
        { "field.long":   { "name": "memberId" } },
        { "field.string": { "name": "tag" } },
        { "identity.primary": { "name": "pk", "@fields": ["memberId", "tag"] } }
      ]}},
      { "object.projection": { "name": "MemberCard", "children": [
        { "source.rdb": { "@kind": "view", "@table": "v_member_cards" } },
        { "field.long":   { "name": "memberId", "extends": "BaseRow.id" } },
        { "field.string": { "name": "name", "extends": "Member.name" } },
        { "identity.primary": { "name": "pk", "extends": "BaseRow.pk" } }
      ]}},
      { "object.projection": { "name": "BadgeRow", "children": [
        { "source.rdb": { "@kind": "view", "@table": "v_badge_rows" } },
        { "field.long":   { "name": "holderId", "extends": "Badge.memberId" } },
        { "field.string": { "name": "tag", "extends": "Badge.tag" } },
        { "identity.primary": { "name": "pk", "extends": "Badge.pk" } }
      ]}},
      { "object.value": { "name": "StatArgs", "children": [ { "field.int": { "name": "days" } } ]}},
      { "object.projection": { "name": "MemberStat", "children": [
        { "source.rdb": { "@kind": "storedProc", "@proc": "fn_member_stats", "@parameterRef": "StatArgs" } },
        { "field.long": { "name": "memberId", "extends": "BaseRow.id" } },
        { "field.long": { "name": "visits" } },
        { "identity.primary": { "name": "pk", "extends": "BaseRow.pk" } }
      ]}}
    ]}}
    """;

    [Fact]
    public async Task A_keyed_projection_is_keyed_by_its_primary_identity_and_reads_back()
    {
        var gen = GeneratedEfModel.Compile(KeyedProjectionModel, "Acme.KeyedProjection");
        using (var model = gen.ModelOnlyContext())
        {
            Assert.Equal(new[] { "MemberId" },
                EntityType(model, "MemberCard").FindPrimaryKey()!.Properties.Select(p => p.Name));
            Assert.Equal(new[] { "HolderId", "Tag" },
                EntityType(model, "BadgeRow").FindPrimaryKey()!.Properties.Select(p => p.Name));
            // A stored-procedure projection is keyed the same way.
            Assert.Equal(new[] { "MemberId" },
                EntityType(model, "MemberStat").FindPrimaryKey()!.Properties.Select(p => p.Name));
        }

        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "members" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" TEXT);
            INSERT INTO "members" ("name") VALUES ('ada'), ('lin');
            CREATE VIEW "v_member_cards" AS SELECT "id" AS "memberId", "name" FROM "members";
            CREATE TABLE "badges" ("memberId" BIGINT, "tag" TEXT, PRIMARY KEY ("memberId", "tag"));
            INSERT INTO "badges" VALUES (1, 'gold'), (1, 'blue');
            CREATE VIEW "v_badge_rows" AS SELECT "memberId" AS "holderId", "tag" FROM "badges";
            """);
        using var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString));
        var cards = GeneratedEfModel.All(db, gen.Type("MemberCard"));
        Assert.Equal(new[] { "ada", "lin" }, cards.Select(c => (string)GeneratedEfModel.Get(c, "Name")!).OrderBy(n => n));
        Assert.Equal(2, GeneratedEfModel.All(db, gen.Type("BadgeRow")).Count);
    }

    // ── D11a: facets of fields inherited from an abstract base (EmitAbstractShapes) ──────────

    private const string AbstractBaseModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.entity": { "name": "AuditedRow", "abstract": true, "children": [
        { "field.string": { "name": "ledgerCode", "@maxLength": 12 } },
        { "field.string": { "name": "createdBy", "@maxLength": 200, "@column": "created_by" } },
        { "field.enum":   { "name": "origin", "@values": ["APP", "IMPORT"], "@column": "origin_kind" } },
        { "identity.primary": { "name": "pk", "@fields": "ledgerCode", "@generation": "assigned" } }
      ]}},
      { "object.entity": { "name": "Ledger", "extends": "AuditedRow", "children": [
        { "source.rdb": { "@table": "ledgers" } },
        { "field.string": { "name": "title", "@maxLength": 40 } }
      ]}}
    ]}}
    """;

    [Fact]
    public async Task Fields_inherited_from_an_abstract_shape_keep_their_key_column_and_length()
    {
        // With EmitAbstractShapes the inherited fields are declared on the abstract shape class,
        // which carries no EF attributes, so their key, column name and length never reached the
        // concrete entity's model.
        var gen = GeneratedEfModel.Compile(AbstractBaseModel, "Acme.AbstractBase",
            c => c with { EmitAbstractShapes = true });
        using (var model = gen.ModelOnlyContext())
        {
            var ledger = EntityType(model, "Ledger");
            Assert.Equal(new[] { "LedgerCode" }, ledger.FindPrimaryKey()!.Properties.Select(p => p.Name));
            var createdBy = ledger.FindProperty("CreatedBy")!;
            Assert.Equal(200, createdBy.GetMaxLength());
            Assert.Equal("created_by", createdBy.GetColumnName());
            Assert.Equal(12, ledger.FindProperty("LedgerCode")!.GetMaxLength());
            Assert.Equal("origin_kind", ledger.FindProperty("Origin")!.GetColumnName());
            Assert.Equal(40, ledger.FindProperty("Title")!.GetMaxLength());
        }

        await using var pg = await PostgresContainer.StartAsync();
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
            db.Database.EnsureCreated();
        var columns = await Rows(pg.ConnectionString, """
            SELECT column_name, character_maximum_length FROM information_schema.columns
            WHERE table_name = 'ledgers' ORDER BY column_name
            """);
        Assert.Contains(new object?[] { "created_by", 200 }, columns);
        Assert.Contains(new object?[] { "ledgerCode", 12 }, columns);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            db.Add(gen.New("Ledger", ("LedgerCode", "L-1"), ("CreatedBy", "ada"), ("Title", "first")));
            db.SaveChanges();
        }
        Assert.Single(await Rows(pg.ConnectionString, """SELECT "created_by" FROM "ledgers" WHERE "ledgerCode" = 'L-1' """));
    }

    // ── D06 + D07: a TPH subtype's own fields are configured ────────────────────────────────

    private const string TphOwnFieldsModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.value": { "name": "Address", "children": [
        { "field.string": { "name": "city" } },
        { "field.enum":   { "name": "kind", "@values": ["HOME", "WORK"] } }
      ]}},
      { "object.entity": { "name": "Party", "@discriminator": "kind", "children": [
        { "source.rdb": { "@table": "parties" } },
        { "field.long": { "name": "id" } },
        { "field.enum": { "name": "kind", "@values": ["Person", "Company"] } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}},
      { "object.entity": { "name": "Person", "extends": "Party", "@discriminatorValue": "Person", "children": [
        { "field.timestamp": { "name": "bornAt" } },
        { "field.object":    { "name": "home", "@objectRef": "Address" } },
        { "field.enum":      { "name": "tier", "@values": ["GOLD", "SILVER"] } }
      ]}},
      { "object.entity": { "name": "Company", "extends": "Party", "@discriminatorValue": "Company", "children": [
        { "field.decimal": { "name": "revenue", "@precision": 14, "@scale": 2 } },
        { "field.string":  { "name": "tickers", "isArray": true } },
        { "field.enum":    { "name": "size", "@values": ["S", "L"], "@intValueMap": { "S": 1, "L": 2 } } }
      ]}}
    ]}}
    """;

    [Fact]
    public async Task A_tph_subtypes_own_fields_get_their_column_configuration_and_round_trip()
    {
        var gen = GeneratedEfModel.Compile(TphOwnFieldsModel, "Acme.TphOwn");
        using (var model = gen.ModelOnlyContext())
        {
            var person = EntityType(model, "Person");
            // D07: without it EF falls back to `timestamp with time zone` only by accident of the
            // CLR type; the explicit column type is what the migration creates.
            Assert.Equal("timestamp with time zone", person.FindProperty("BornAt")!.GetColumnType());
            // D06: the value object is an owned JSON document, not a discovered navigation.
            var home = person.FindNavigation("Home")!;
            Assert.True(home.ForeignKey.IsOwnership);
            Assert.Equal("home", home.TargetEntityType.GetContainerColumnName());
            Assert.Equal(typeof(string), person.FindProperty("Tier")!.GetProviderClrType());
            var company = EntityType(model, "Company");
            Assert.Equal(14, company.FindProperty("Revenue")!.GetPrecision());
        }

        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "parties" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "kind" TEXT NOT NULL, "bornAt" TIMESTAMPTZ, "home" JSONB, "tier" TEXT,
              "revenue" NUMERIC(14,2), "tickers" TEXT[], "size" INTEGER);
            """);
        var born = new DateTimeOffset(1990, 5, 1, 8, 30, 0, TimeSpan.Zero);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var home = gen.New("Address", ("City", "Oslo"), ("Kind", gen.Enum("Address+AddressKind", "WORK")));
            db.Add(gen.New("Person", ("BornAt", born), ("Home", home), ("Tier", gen.Enum("Person+PersonTier", "GOLD"))));
            db.Add(gen.New("Company", ("Revenue", 1234.5m), ("Size", gen.Enum("Company+CompanySize", "L"))));
            db.SaveChanges();
        }
        var raw = await Rows(pg.ConnectionString, """SELECT "tier", "home"->>'kind', "revenue", "size" FROM "parties" ORDER BY "kind" DESC""");
        Assert.Equal(new object?[] { "GOLD", "WORK", null, null }, raw[0]);
        Assert.Equal(1234.50m, raw[1][2]);
        Assert.Equal(2, raw[1][3]);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var person = GeneratedEfModel.All(db, gen.Type("Party")).Single(p => p.GetType().Name == "Person");
            Assert.Equal(born, GeneratedEfModel.Get(person, "BornAt"));
            Assert.Equal("Oslo", GeneratedEfModel.Get(GeneratedEfModel.Get(person, "Home")!, "City"));
        }
    }
