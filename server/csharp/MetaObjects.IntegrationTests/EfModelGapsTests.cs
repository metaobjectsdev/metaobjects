        { "field.enum":      { "name": "tier", "@values": ["GOLD", "SILVER"] } }
      ]}},
      { "object.entity": { "name": "Company", "extends": "Party", "@discriminatorValue": "Company", "children": [
        { "field.decimal": { "name": "revenue", "@precision": 14, "@scale": 2 } },
        { "field.string":  { "name": "tickers", "isArray": true } },
        { "field.enum":    { "name": "size", "@values": ["S", "L"], "@intValueMap": { "S": 1, "L": 2 } } }
      ]}}
    ]}}
    """;

    [Fact]
    public async Task A_tph_subtypes_own_fields_get_their_column_configuration_and_round_trip()
    {
        var gen = GeneratedEfModel.Compile(TphOwnFieldsModel, "Acme.TphOwn");
        using (var model = gen.ModelOnlyContext())
        {
            var person = EntityType(model, "Person");
            // D07: without it EF falls back to `timestamp with time zone` only by accident of the
            // CLR type; the explicit column type is what the migration creates.
            Assert.Equal("timestamp with time zone", person.FindProperty("BornAt")!.GetColumnType());
            // D06: the value object is an owned JSON document, not a discovered navigation.
            var home = person.FindNavigation("Home")!;
            Assert.True(home.ForeignKey.IsOwnership);
            Assert.Equal("home", home.TargetEntityType.GetContainerColumnName());
            Assert.Equal(typeof(string), person.FindProperty("Tier")!.GetProviderClrType());
            var company = EntityType(model, "Company");
            Assert.Equal(14, company.FindProperty("Revenue")!.GetPrecision());
        }

        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "parties" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "kind" TEXT NOT NULL, "bornAt" TIMESTAMPTZ, "home" JSONB, "tier" TEXT,
              "revenue" NUMERIC(14,2), "tickers" TEXT[], "size" INTEGER);
            """);
        var born = new DateTimeOffset(1990, 5, 1, 8, 30, 0, TimeSpan.Zero);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var home = gen.New("Address", ("City", "Oslo"), ("Kind", gen.Enum("Address+AddressKind", "WORK")));
            db.Add(gen.New("Person", ("BornAt", born), ("Home", home), ("Tier", gen.Enum("Person+PersonTier", "GOLD"))));
            db.Add(gen.New("Company", ("Revenue", 1234.5m), ("Size", gen.Enum("Company+CompanySize", "L"))));
            db.SaveChanges();
        }
        var raw = await Rows(pg.ConnectionString, """SELECT "tier", "home"->>'kind', "revenue", "size" FROM "parties" ORDER BY "kind" DESC""");
        Assert.Equal(new object?[] { "GOLD", "WORK", null, null }, raw[0]);
        Assert.Equal(1234.50m, raw[1][2]);
        Assert.Equal(2, raw[1][3]);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
        {
            var person = GeneratedEfModel.All(db, gen.Type("Party")).Single(p => p.GetType().Name == "Person");
            Assert.Equal(born, GeneratedEfModel.Get(person, "BornAt"));
            Assert.Equal("Oslo", GeneratedEfModel.Get(GeneratedEfModel.Get(person, "Home")!, "City"));
        }
    }

    // ── D20(c): a value object nested inside a FLATTENED value object ───────────────────────

    private const string FlattenedNestedModel = """
    { "metadata.root": { "package": "acme", "children": [
      { "object.value": { "name": "GeoPoint", "children": [
        { "field.double": { "name": "lat" } },
        { "field.double": { "name": "lng" } },
        { "field.enum":   { "name": "datum", "@values": ["WGS84", "ETRS89"] } }
      ]}},
      { "object.value": { "name": "Address", "children": [
        { "field.string": { "name": "city" } },
        { "field.enum":   { "name": "kind", "@values": ["HOME", "WORK"] } },
        { "field.object": { "name": "geo", "@objectRef": "GeoPoint" } },
        { "field.object": { "name": "stops", "@objectRef": "GeoPoint", "isArray": true } }
      ]}},
      { "object.entity": { "name": "Delivery", "children": [
        { "source.rdb": { "@table": "deliveries" } },
        { "field.long":   { "name": "id" } },
        { "field.object": { "name": "shipTo", "@objectRef": "Address", "@storage": "flattened",
            "@flattenedColumnPrefix": "dest_" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } }
      ]}}
    ]}}
    """;

    [Fact]
    public async Task A_nested_value_object_in_a_flattened_owner_is_one_jsonb_value_and_every_member_is_named()
    {
        // EF Core 8 refuses a JSON column (ToJson) inside a table-split owned type, so the nested
        // value object is one jsonb property converted whole. Every flattened member, the scalar
        // enum included, is pinned to the column the migration creates under the custom prefix.
        var gen = GeneratedEfModel.Compile(FlattenedNestedModel, "Acme.FlatNested");
        using (var model = gen.ModelOnlyContext())
        {
            var shipTo = EntityType(model, "Delivery").FindNavigation("ShipTo")!.TargetEntityType;
            Assert.Equal("dest_city", shipTo.FindProperty("City")!.GetColumnName());
            Assert.Equal("dest_kind", shipTo.FindProperty("Kind")!.GetColumnName());
            Assert.Equal("dest_geo", shipTo.FindProperty("Geo")!.GetColumnName());
            Assert.Equal("jsonb", shipTo.FindProperty("Geo")!.GetColumnType());
            Assert.Equal("dest_stops", shipTo.FindProperty("Stops")!.GetColumnName());
        }

        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "deliveries" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "dest_city" TEXT, "dest_kind" TEXT, "dest_geo" JSONB, "dest_stops" JSONB);
            """);
        using (var db = gen.NewContext(o => o.UseNpgsql(pg.ConnectionString)))
