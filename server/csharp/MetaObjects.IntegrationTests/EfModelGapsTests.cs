    [Fact]
    public async Task A_shared_enum_discriminator_maps_each_subtype_and_round_trips()
    {
        // The HasValue argument named the enum as nested in the base (Vehicle.VehicleKind.Car),
        // which a shared enum is not: the context did not compile.
        var gen = GeneratedEfModel.Compile(SharedDiscriminatorModel, "Acme.SharedDisc");
        await using var pg = await PostgresContainer.StartAsync();
        await Exec(pg.ConnectionString, """
            CREATE TABLE "vehicles" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "kind" TEXT NOT NULL, "seats" INTEGER, "payloadKg" INTEGER);
            """);
