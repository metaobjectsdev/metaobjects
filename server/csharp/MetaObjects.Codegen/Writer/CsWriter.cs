// The C# dialect of the code writer (ADR-0063; contract: spec/code-writer.md).
//
// Adds what is specific to C#: the file header, `using` directives collected while the body is
// written and printed before it, XML doc comments, and the Allman brace block. The core it
// extends owns lines, blocks, blank lines and fit-or-break lists; a subclass overrides one step
// (OrderUsings, WriteHeader, WriteUsings) and keeps the rest.

namespace MetaObjects.Codegen.Writer;

/// <summary>How a <see cref="CsWriter"/> orders the <c>using</c> directives it collected.</summary>
public enum UsingOrder
{
    /// <summary>The order the generator named them, each once. What the reference generators wrote before
    /// the writer, so converting one changes no byte.</summary>
    AsWritten,
    /// <summary><c>System</c> namespaces first, then the rest, each group in code-unit order.</summary>
    Sorted,
}

/// <summary>
/// The writer a C# generator writes through. Four-space indent, 120 columns, a trailing comma in
/// broken lists. Not final: every method is public or protected.
/// </summary>
public class CsWriter : CodeWriter
{
    private readonly List<string> _header = [];
    private readonly List<string> _usings = [];
    private readonly Dictionary<string, string> _aliases = new(StringComparer.Ordinal);

    /// <summary>The order the <c>using</c> block prints in.</summary>
    public UsingOrder UsingOrder { get; init; } = UsingOrder.AsWritten;

    public CsWriter() : base(new CodeWriterOptions { Indent = "    ", Width = 120, TrailingComma = true }) { }

    public CsWriter(CodeWriterOptions options) : base(options) { }

    /// <summary>Lines that print first, before the <c>using</c> block: the generated-file marker,
    /// <c>#nullable enable</c>. Each line is written as given.</summary>
    public CsWriter Header(params string[] lines)
    {
        _header.AddRange(lines);
        return this;
    }

    /// <summary>The header every generated file starts with: the generated-file marker, the generator's
    /// name, and (unless <paramref name="nullable"/> is false) <c>#nullable enable</c>.</summary>
    public CsWriter GeneratedFileHeader(string generator, bool nullable = true)
    {
        Header("// <auto-generated/>", $"// Generated by MetaObjects {generator}. Do not edit by hand.");
        return nullable ? Header("#nullable enable") : this;
    }

    /// <summary>
    /// A statement that continues on the next lines, one level in: <c>using (w.Hanging()) { w.Line(".Select(x)"); }</c>
    /// after a line that is not finished. Writes nothing itself; the indent returns when the scope ends.
    /// </summary>
    public IDisposable Hanging()
    {
        Openers.Add(Out.Count > 0 ? Out[^1].Trim() : "");
        var depth = Openers.Count;
        return new HangingScope(() =>
        {
            if (Openers.Count != depth)
                throw new WriterException(WriterErrors.UnbalancedClose, "a hanging continuation ended while a block inside it is still open");
            Openers.RemoveAt(Openers.Count - 1);
        });
    }

    private sealed class HangingScope(Action onDispose) : IDisposable
    {
        private bool _done;
        public void Dispose() { if (_done) return; _done = true; onDispose(); }
    }

    /// <summary>Add <paramref name="type"/> to the base list of the declaration line just written:
    /// <c>, type</c> when it already has one, else <c> : type</c>.</summary>
    public CsWriter AddBaseType(string type)
    {
        var last = Out.Count - 1;
        if (last < 0) throw new InvalidOperationException("AddBaseType before any line was written");
        Out[last] += Out[last].Contains(" : ", StringComparison.Ordinal) ? ", " + type : " : " + type;
        return this;
    }

    /// <summary>Record <c>using ns;</c>. Naming the same namespace twice prints it once.</summary>
    public CsWriter Using(string ns) => AddUsing($"using {ns};");

    /// <summary>Record <c>using static type;</c>.</summary>
    public CsWriter UsingStatic(string type) => AddUsing($"using static {type};");

    /// <summary>Record <c>using alias = target;</c>. One alias naming two targets is
    /// <see cref="WriterErrors.ImportConflict"/>.</summary>
    public CsWriter UsingAlias(string alias, string target)
    {
        if (_aliases.TryGetValue(alias, out var seen))
        {
            if (seen != target)
                throw new WriterException(WriterErrors.ImportConflict, $"the alias {alias} names both {seen} and {target}");
            return this;
        }
        _aliases[alias] = target;
        return AddUsing($"using {alias} = {target};");
    }

    private CsWriter AddUsing(string directive)
    {
        if (!_usings.Contains(directive)) _usings.Add(directive);
        return this;
    }

    /// <summary>
    /// A block whose braces are on their own lines, the way C# is written:
    /// <c>using (w.Braced("public class A")) { ... }</c> writes <c>public class A</c>, <c>{</c>, the
    /// body, then <c>}</c>. Pass a different <paramref name="tail"/> for <c>};</c>.
    /// </summary>
    public IDisposable Braced(Piece head, string tail = "}")
    {
        Line(head);
        return Block("{", tail);
    }

    /// <summary>An XML doc <c>&lt;summary&gt;</c>: one <c>///</c> line per entry (a bare <c>///</c> for an empty one).
    /// The text is written as given, so it carries any XML escaping it needs.</summary>
    public CsWriter DocSummary(params string[] lines)
    {
        Line("/// <summary>");
        foreach (var l in lines) Line(l.Length == 0 ? "///" : "/// " + l);
        Line("/// </summary>");
        return this;
    }

    /// <summary>The <c>using</c> directives in print order. A subclass overrides this to order them its own way.</summary>
    protected virtual IReadOnlyList<string> OrderUsings(IReadOnlyList<string> asWritten) => UsingOrder switch
    {
        UsingOrder.Sorted => asWritten
            .OrderBy(u => IsSystem(Target(u)) ? 0 : 1)
            .ThenBy(Target, StringComparer.Ordinal)
            .ToList(),
        _ => asWritten,
    };

    /// <summary>What a directive names: <c>using A.B;</c> is <c>A.B</c>. Sorting compares this, so
    /// <c>System</c> comes before <c>System.Linq</c> although <c>.</c> sorts before <c>;</c>.</summary>
    private static string Target(string directive) => directive["using ".Length..^1];

    private static bool IsSystem(string target) =>
        target == "System" || target.StartsWith("System.", StringComparison.Ordinal);

    /// <summary>The header lines, as printed.</summary>
    protected virtual IEnumerable<string> WriteHeader() => _header;

    /// <summary>The <c>using</c> block, as printed.</summary>
    protected virtual IEnumerable<string> WriteUsings() => OrderUsings(_usings);

    protected override string Body()
    {
        var body = base.Body();
        var top = WriteHeader().Concat(WriteUsings()).ToList();
        if (top.Count == 0) return body;
        return body.Length == 0 ? string.Join('\n', top) : string.Join('\n', top) + "\n\n" + body;
    }
}
