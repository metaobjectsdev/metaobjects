// dbcontext-generator — emits a single EF Core DbContext exposing a DbSet per entity.

using System.Text;
using MetaObjects.Meta;

namespace MetaObjects.Codegen.Generators;

/// <summary>Generates one <c>AppDbContext</c> with a <c>DbSet&lt;T&gt;</c> per entity.</summary>
public sealed class DbContextGenerator : IGenerator
{
    public string Name => "dbcontext-generator";

    public IEnumerable<EmittedFile> Generate(GenContext ctx)
    {
        var entities = ctx.Entities.Where(e => e.IsEntity())
            .Select(e => CSharpNaming.Pascal(e.Name))
            .OrderBy(n => n, StringComparer.Ordinal)
            .ToList();
        if (entities.Count == 0) yield break;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by MetaObjects dbcontext-generator. Do not edit by hand.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using Microsoft.EntityFrameworkCore;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ctx.Config.Namespace};");
        sb.AppendLine();
        sb.AppendLine("public class AppDbContext : DbContext");
        sb.AppendLine("{");
        sb.AppendLine("    public AppDbContext(DbContextOptions<AppDbContext> options) : base(options) { }");
        sb.AppendLine();
        foreach (var name in entities)
            sb.AppendLine($"    public DbSet<{name}> {Pluralize(name)} {{ get; set; }} = default!;");
        sb.AppendLine("}");

        yield return new EmittedFile("AppDbContext.g.cs", sb.ToString());
    }

    // Cosmetic DbSet property pluralization (the table name comes from [Table]).
    private static string Pluralize(string name)
    {
        if (name.EndsWith("s", StringComparison.Ordinal) || name.EndsWith("x", StringComparison.Ordinal) ||
            name.EndsWith("z", StringComparison.Ordinal) || name.EndsWith("ch", StringComparison.Ordinal) ||
            name.EndsWith("sh", StringComparison.Ordinal))
            return name + "es";
        if (name.Length > 1 && name.EndsWith("y", StringComparison.Ordinal) && !"aeiou".Contains(name[^2]))
            return name[..^1] + "ies";
        return name + "s";
    }
}
