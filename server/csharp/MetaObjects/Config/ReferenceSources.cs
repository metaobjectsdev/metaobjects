// Reference sources: `{ "path": "replies", "reference": true }` in `.metaobjects/config.json`.
//
// Behavioral contract: server/typescript/packages/sdk/src/memory.ts `referenceNodesOf` and
// fixtures/reference-source-conformance/cases.json. The files load into the SAME root as every other
// source, so a `@responseRef`, `extends` or `@objectRef` resolves against them; a top-level node is a
// reference node only when EVERY file that declares it (an overlay included) is a reference file.

using MetaObjects.Meta;
using MetaObjects.Source;

namespace MetaObjects.Config;

public static class ReferenceSources
{
    /// <summary>
    /// The resolution keys of the top-level nodes only <paramref name="referenceFiles"/> declare. A
    /// <c>template.*</c> among them is refused (<see cref="ErrorCode.ERR_REFERENCE_SOURCE_TEMPLATE"/>): a
    /// reference source holds shapes another run generates, so a prompt there would have its parser and
    /// payload type generated by nobody. Returns the refusal in <paramref name="refusal"/>.
    /// </summary>
    public static IReadOnlySet<string> NodesOf(MetaRoot root, IReadOnlySet<string> referenceFiles, out MetaError? refusal)
    {
        refusal = null;
        var ids = referenceFiles.Select(Normalize).ToHashSet(StringComparer.Ordinal);
        var nodes = new HashSet<string>(StringComparer.Ordinal);
        // ADR-0039: own — the metadata root has no super chain, so its own children are its nodes.
        foreach (var node in root.OwnChildren())
        {
            var files = FilesOf(node.Source);
            if (files.Count == 0 || !files.All(f => ids.Contains(Normalize(f)))) continue;
            if (node.Type == MetaObjects.Shared.BaseTypes.TYPE_TEMPLATE)
            {
                refusal ??= new MetaError(
                    $"template \"{node.ResolutionKey()}\" is declared only in a reference source ({string.Join(", ", files)}). " +
                    "A reference source holds shapes another run generates; declare the prompt in one of the " +
                    "project's own sources, where its parser and payload are generated.",
                    ErrorCode.ERR_REFERENCE_SOURCE_TEMPLATE);
                continue;
            }
            nodes.Add(node.ResolutionKey());
        }
        return nodes;
    }

    /// <summary>Every file in a node's provenance, every overlay contributor included.</summary>
    private static IReadOnlyList<string> FilesOf(ErrorSource source) => source switch
    {
        MergedSource m => m.Files.Concat(m.Contributors.Select(c => c.File)).Distinct().ToList(),
        JsonSource j => j.Files,
        YamlSource y => y.Files,
        _ => [],
    };

    /// <summary>A source id may be a file URI or a path; compare them as full local paths.</summary>
    private static string Normalize(string id) =>
        Uri.TryCreate(id, UriKind.Absolute, out var uri) && uri.IsFile ? Path.GetFullPath(uri.LocalPath) : id;
}
