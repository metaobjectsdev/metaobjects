// G5, rc.20: a self-hosted runner that keeps no hash manifest (no GenConfig.GenStateDir) has
// nothing the manifest sweep can read, so a layout change (R39) left the old files behind.
// OrphanSweep.SweepMarked is its opt-in: after a run of the whole list, a file under the run's
// directories that carries the generated marker and that no generator emitted is deleted. A run
// that does not call it deletes nothing, as before.

using MetaObjects.Loader;
using MetaObjects.Meta;
using Xunit;

namespace MetaObjects.Codegen.Tests;

public sealed class OrphanSweepMarkedTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "mo-marked-" + Guid.NewGuid().ToString("N"));
    private string Out => Path.Combine(_root, "gen");

    public void Dispose() { try { Directory.Delete(_root, recursive: true); } catch { } }

    /// <summary>One file per value object, under its package directory when <paramref name="byPackage"/>.</summary>
    private sealed class PerValue(bool byPackage) : IGenerator
    {
        public string Name => "values";
        public IEnumerable<EmittedFile> Generate(GenContext ctx) =>
            ctx.Root.Objects().Select(o => new EmittedFile(
                (byPackage ? "acme/" : "") + $"{o.Name}.g.cs", $"// <auto-generated/>\npublic sealed class {o.Name} {{ }}\n"));
    }

    private static MetaRoot Root(params string[] values)
    {
        var children = string.Join(",", values.Select(v => $$"""{ "object.value": { "name": "{{v}}", "children": [ { "field.string": { "name": "x" } } ] } }"""));
        var r = new MetaDataLoader().Load([new InMemoryStringSource($$"""{ "metadata.root": { "package": "acme", "children": [ {{children}} ] } }""", id: "m.json")]);
        Assert.Empty(r.Errors);
        return r.Root;
    }

    private CodegenRunner.RunResult Run(MetaRoot root, bool byPackage, string? outDir = null) =>
        CodegenRunner.Run(new GenConfig { OutDir = outDir ?? Out, Namespace = "Acme" }, root, [new PerValue(byPackage)]);

    private string At(string rel) => Path.Combine(Out, rel);

    [Fact]
    public void A_layout_change_leaves_the_old_files_unless_the_runner_sweeps()
    {
        Run(Root("Alpha", "Beta"), byPackage: false);
        Assert.True(File.Exists(At("Alpha.g.cs")));

        // The layout moves every file; without the sweep the flat ones stay, as before.
        var moved = Run(Root("Alpha", "Beta"), byPackage: true);
        Assert.True(File.Exists(At("acme/Alpha.g.cs")));
        Assert.True(File.Exists(At("Alpha.g.cs")));

        var removed = OrphanSweep.SweepMarked([Out], moved.EmittedPaths);
        Assert.Equal([Path.GetFullPath(At("Alpha.g.cs")), Path.GetFullPath(At("Beta.g.cs"))], removed);
        Assert.False(File.Exists(At("Alpha.g.cs")));
        Assert.True(File.Exists(At("acme/Alpha.g.cs")));
        Assert.True(File.Exists(At("acme/Beta.g.cs")));
    }

    [Fact]
    public void A_file_without_the_marker_and_the_metaobjects_directory_are_never_touched()
    {
        Directory.CreateDirectory(At(".metaobjects"));
        File.WriteAllText(At(".metaobjects/state.g.cs"), "// <auto-generated/>\n");
        Directory.CreateDirectory(Out);
        File.WriteAllText(At("Handwritten.cs"), "public partial class Alpha { }\n");
        // The marker past the first lines is a mention, not a header.
        File.WriteAllText(At("Notes.cs"), "// one\n// two\n// three\n// four\n// five\n// six <auto-generated/>\n");
        var result = Run(Root("Alpha"), byPackage: false);

        Assert.Empty(OrphanSweep.SweepMarked([Out], result.EmittedPaths));
        Assert.True(File.Exists(At(".metaobjects/state.g.cs")));
        Assert.True(File.Exists(At("Handwritten.cs")));
        Assert.True(File.Exists(At("Notes.cs")));
        Assert.True(File.Exists(At("Alpha.g.cs")));
    }

    [Fact]
    public void A_runner_of_several_runs_sweeps_their_union()
    {
        // A second run's directory nested in the first: swept alone, the first would delete its files.
        var inner = Path.Combine(Out, "inner");
        var outer = Run(Root("Alpha"), byPackage: false);
        var nested = Run(Root("Beta"), byPackage: false, outDir: inner);
        File.WriteAllText(At("Stale.g.cs"), "// <auto-generated/>\n");

        var emitted = outer.EmittedPaths.Union(nested.EmittedPaths).ToHashSet(StringComparer.Ordinal);
        var removed = OrphanSweep.SweepMarked([Out, inner], emitted);
        Assert.Equal([Path.GetFullPath(At("Stale.g.cs"))], removed);
        Assert.True(File.Exists(Path.Combine(inner, "Beta.g.cs")));
        Assert.True(File.Exists(At("Alpha.g.cs")));
    }
}
