// The generator in docs/ports/csharp.md, "Write your own generator", compiled and run. If the
// document's example stops compiling or stops writing a file, this fails.

using MetaObjects.Loader;
using Xunit;

namespace MetaObjects.Codegen.Tests;

// --- the example, as the document shows it (codegen/generators/EntityList.cs) ---
public sealed class EntityListGenerator : IGenerator
{
    public string Name => "entity-list";

    public IEnumerable<EmittedFile> Generate(GenContext ctx)
    {
        var names = ctx.Entities.Select(e => e.Name).Order(StringComparer.Ordinal);
        yield return new EmittedFile("EntityList.g.cs",
            "// <auto-generated/>\npublic static class EntityList\n{\n" +
            "    public static readonly string[] Names = [" + string.Join(", ", names.Select(n => $"\"{n}\"")) + "];\n}\n");
    }
}

public sealed class GeneratorAuthoringExampleTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "meta-authoring-" + Guid.NewGuid().ToString("N"));
    public GeneratorAuthoringExampleTests() => Directory.CreateDirectory(_root);
    public void Dispose() { try { Directory.Delete(_root, recursive: true); } catch { } }

    [Fact]
    public void The_documented_generator_runs_and_writes_its_file()
    {
        var load = new MetaDataLoader().Load([new FileSource(CorpusPaths.FitnessMetadata)]);
        var outcome = CodegenCli.RunGen(load, Path.Combine(_root, "out"), "Acme", false, [new EntityListGenerator()], _root);

        Assert.True(outcome.Ok, string.Join("\n", outcome.LoadErrors));
        var text = File.ReadAllText(Path.Combine(_root, "out", "EntityList.g.cs"));
        Assert.Contains("public static class EntityList", text);
    }
}
