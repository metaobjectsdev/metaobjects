// `dotnet meta gen` deletes a file it wrote earlier and no longer generates.
//
// The rc.5 re-check found the gap in every port: renaming the value object Telemetry to
// TelemetryReading (or a release moving api-docs pages to another package) left the old file on
// disk, `verify --codegen` reported it as extra and said "regenerate", and regenerating never
// removed anything, so an agent following the remedy looped. The rule every port shares
// (OrphanSweep): an untouched file the manifest records and no generator emits is deleted and
// forgotten; an edited one is refused by name; a file the manifest does not record is never
// touched; a run narrowed by --generators sweeps nothing.

using System.Text.Json;
using MetaObjects.Meta;
using Xunit;

namespace MetaObjects.Codegen.Tests;

[Collection("Console")]
public sealed class OrphanSweepTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "mo-orphans-" + Guid.NewGuid().ToString("N"));
    private string Meta => Path.Combine(_root, "metaobjects");
    private string Out => Path.Combine(_root, "gen");
    private string Docs => Path.Combine(_root, "docs");
    private string ManifestPath => Path.Combine(_root, ".metaobjects", ".gen-state", ".hashes.json");

    public OrphanSweepTests() => Directory.CreateDirectory(Meta);
    public void Dispose() { try { Directory.Delete(_root, recursive: true); } catch { } }

    /// <summary>One file per value object, the shape of a value-object POCO generator.</summary>
    private sealed class PerValue : IGenerator
    {
        public string Name => "values";
        public IEnumerable<EmittedFile> Generate(GenContext ctx) =>
            ctx.Root.Objects().Where(o => o.SubType == "value")
                .Select(o => new EmittedFile($"{o.Name}.g.cs", $"// <auto-generated/>\npublic sealed class {o.Name} {{ }}\n"));
    }

    /// <summary>One page per object under its package, in a directory of its own, the shape of api-docs.</summary>
    private sealed class PerPackageDocs(string outDir) : IGenerator
    {
        public string Name => "pages";
        public string? OutDir => outDir;
        public IEnumerable<EmittedFile> Generate(GenContext ctx) =>
            ctx.Root.Objects().Select(o => new EmittedFile(
                $"{o.ResolutionKey().Replace("::", "/")}.md", $"# {o.Name}\n"));
    }

    private IReadOnlyList<IGenerator>? _suite;
    private IReadOnlyList<IGenerator> Suite => _suite ?? [new PerValue(), new PerPackageDocs(Docs)];

    private void Model(string package, params string[] values) =>
        File.WriteAllText(Path.Combine(Meta, "meta.acme.json"), JsonSerializer.Serialize(new Dictionary<string, object>
        {
            ["metadata.root"] = new Dictionary<string, object>
            {
                ["package"] = package,
                ["children"] = values.Select(v => new Dictionary<string, object>
                {
                    ["object.value"] = new Dictionary<string, object>
                    {
                        ["name"] = v,
                        ["children"] = new[] { new Dictionary<string, object> { ["field.string"] = new Dictionary<string, object> { ["name"] = "reading" } } },
                    },
                }).ToArray(),
            },
        }));

    private (int Code, string Out, string Err) Run(params string[] args)
    {
        var (prevOut, prevErr) = (Console.Out, Console.Error);
        var (o, e) = (new StringWriter(), new StringWriter());
        Console.SetOut(o);
        Console.SetError(e);
        try { return (CodegenCli.Run(args, Suite), o.ToString(), e.ToString()); }
        finally { Console.SetOut(prevOut); Console.SetError(prevErr); }
    }

    private (int Code, string Out, string Err) Gen(params string[] extra) => Run(["gen", Meta, "--out", Out, .. extra]);
    private (int Code, string Out, string Err) Verify() => Run("verify", "--codegen", Meta, "--out", Out);

    private Dictionary<string, string> Manifest() =>
        JsonSerializer.Deserialize<Dictionary<string, string>>(File.ReadAllText(ManifestPath))!;

    [Fact]
    public void A_renamed_value_object_is_deleted_and_verify_goes_green()
    {
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var old = Path.Combine(Out, "Telemetry.g.cs");
        Assert.True(File.Exists(old));

        Model("acme", "TelemetryReading");
        var drift = Verify();
        Assert.Equal(1, drift.Code);
        Assert.Contains("Telemetry.g.cs (committed but a fresh regen would not emit it; 'dotnet meta gen' deletes it)", drift.Err);
        Assert.Contains("Run 'dotnet meta gen' to regenerate", drift.Err);

        var gen = Gen();
        Assert.Equal(0, gen.Code);
        Assert.False(File.Exists(old));
        Assert.Contains("removed: Telemetry.g.cs", gen.Out);
        Assert.DoesNotContain(Manifest().Keys, k => k.EndsWith("Telemetry.g.cs", StringComparison.Ordinal));
        Assert.True(File.Exists(Path.Combine(Out, "TelemetryReading.g.cs")));

        Assert.Equal(0, Verify().Code);
    }

    [Fact]
    public void A_hand_edited_orphan_is_refused_and_verify_says_delete_it()
    {
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var old = Path.Combine(Out, "Telemetry.g.cs");
        File.AppendAllText(old, "// mine\n");

        Model("acme", "TelemetryReading");
        var gen = Gen();
        Assert.True(File.Exists(old));
        Assert.Contains("NOT deleted", gen.Err);
        Assert.Contains("gen/Telemetry.g.cs", gen.Err);
        // Still recorded, so the refusal repeats until someone resolves it.
        Assert.Contains(Manifest().Keys, k => k.EndsWith("Telemetry.g.cs", StringComparison.Ordinal));

        var drift = Verify();
        Assert.Equal(1, drift.Code);
        Assert.Contains("edited by hand", drift.Err);
        Assert.Contains("will NOT delete them", drift.Err);
        Assert.DoesNotContain("to regenerate", drift.Err);
    }

    [Fact]
    public void Pages_that_move_package_in_their_own_directory_leave_no_stale_copy()
    {
        Model("acme::iam", "Leg");
        Assert.Equal(0, Gen().Code);
        var before = Path.Combine(Docs, "acme", "iam", "Leg.md");
        Assert.True(File.Exists(before));

        Model("acme::ops", "Leg");
        Assert.Equal(0, Gen().Code);
        Assert.True(File.Exists(Path.Combine(Docs, "acme", "ops", "Leg.md")));
        Assert.False(File.Exists(before));
        Assert.Equal(0, Verify().Code);
    }

    [Fact]
    public void A_file_nobody_generated_is_never_touched_nor_convicted()
    {
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var mine = Path.Combine(Out, "Helpers.cs");
        File.WriteAllText(mine, "public static class Helpers { }\n");

        Assert.Equal(0, Verify().Code);
        Model("acme", "TelemetryReading");
        Assert.Equal(0, Gen().Code);
        Assert.True(File.Exists(mine));
        Assert.Equal(0, Verify().Code);
    }

    [Fact]
    public void A_generators_narrowed_run_deletes_nothing()
    {
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var page = Path.Combine(Docs, "acme", "Telemetry.md");
        var old = Path.Combine(Out, "Telemetry.g.cs");

        Model("acme", "TelemetryReading");
        Assert.Equal(0, Gen("--generators", "values").Code);
        Assert.True(File.Exists(old));
        Assert.True(File.Exists(page));
    }

    // handEdits: Keep (the default) refuses to replace or delete a hand edit; Overwrite replaces
    // it with fresh output, deletes the edited orphan, and names each file it discards.

    private void Overwriting() => _suite = [new PerValue().WithHandEdits(HandEdits.Overwrite)];

    [Fact]
    public void Keep_refuses_to_replace_an_edited_file()
    {
        _suite = [new PerValue()];
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var file = Path.Combine(Out, "Telemetry.g.cs");
        File.AppendAllText(file, "// mine\n");

        var gen = Gen();
        Assert.EndsWith("// mine\n", File.ReadAllText(file));
        Assert.Contains("Refused to overwrite", gen.Out + gen.Err);
        Assert.DoesNotContain("handEdits", gen.Out + gen.Err);
    }

    [Fact]
    public void Overwrite_replaces_an_edited_file_and_rebaselines_it()
    {
        Overwriting();
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var file = Path.Combine(Out, "Telemetry.g.cs");
        var fresh = File.ReadAllText(file);
        File.AppendAllText(file, "// mine\n");

        var drift = Verify();
        Assert.Equal(1, drift.Code);
        Assert.Contains("edited by hand; its generator sets handEdits: Overwrite", drift.Err);
        Assert.Contains("to regenerate", drift.Err);

        var gen = Gen();
        Assert.Equal(0, gen.Code);
        Assert.Equal(fresh, File.ReadAllText(file));
        Assert.Contains("overwrote hand-edited Telemetry.g.cs", gen.Out + gen.Err);
        var again = Gen();
        Assert.DoesNotContain("overwrote", again.Out + again.Err);
        Assert.Equal(0, Verify().Code);
    }

    [Fact]
    public void Overwrite_deletes_an_edited_orphan()
    {
        Overwriting();
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var old = Path.Combine(Out, "Telemetry.g.cs");
        File.AppendAllText(old, "// mine\n");

        Model("acme", "TelemetryReading");
        var drift = Verify();
        Assert.Equal(1, drift.Code);
        Assert.Contains("handEdits is Overwrite, so 'dotnet meta gen' deletes it", drift.Err);
        Assert.DoesNotContain("will NOT delete them", drift.Err);

        var gen = Gen();
        Assert.Equal(0, gen.Code);
        Assert.False(File.Exists(old));
        Assert.Contains("deleted hand-edited gen/Telemetry.g.cs", gen.Out + gen.Err);
        Assert.DoesNotContain(Manifest().Keys, k => k.EndsWith("Telemetry.g.cs", StringComparison.Ordinal));
        Assert.Equal(0, Verify().Code);
    }

    [Fact]
    public void Overwrite_never_replaces_a_file_gen_has_no_record_of_writing()
    {
        Overwriting();
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var file = Path.Combine(Out, "Telemetry.g.cs");
        File.WriteAllText(ManifestPath, "{}");
        File.WriteAllText(file, "// not generated\n");

        Gen();
        Assert.Equal("// not generated\n", File.ReadAllText(file));
    }

    [Fact]
    public void One_keep_entry_in_a_shared_directory_protects_its_edited_orphans()
    {
        _suite = [new PerValue().WithHandEdits(HandEdits.Overwrite), new PerPackageDocs(Out)];
        Model("acme", "Telemetry");
        Assert.Equal(0, Gen().Code);
        var old = Path.Combine(Out, "Telemetry.g.cs");
        File.AppendAllText(old, "// mine\n");

        Model("acme", "TelemetryReading");
        Gen();
        Assert.True(File.Exists(old));
    }
}
