// gen-api-contract-duration-schema.ts — (re)generate the committed duration sub-corpus schemas.
//
// Run: `bun run gen:duration-api-schema` (from this package). Pure metadata→SQL — no DB.
//
// Postgres and SQLite: `meta migrate`'s own output. MySQL: the adopter's hand-written table
// (ADR-0015), a duration held as a BIGINT count of microseconds as on SQLite.

import { join } from "node:path";

import type { MetaRoot } from "@metaobjectsdev/metadata";
import { generateCanonicalSchemaSql, writeArtifact } from "./canonical-schema.ts";
import { renderMysqlSchemaArtifact } from "./canonical-schema-mysql.ts";
import { loadMetadataFile } from "./load-metadata.ts";
import {
  API_CONTRACT_DURATION_DIR,
  API_CONTRACT_DURATION_MYSQL_SCHEMA_SQL_PATH,
  API_CONTRACT_DURATION_SCHEMA_SQL_PATH,
  API_CONTRACT_DURATION_SQLITE_SCHEMA_SQL_PATH,
} from "./paths.ts";

type Dialect = "postgres" | "sqlite" | "mysql";
const LABEL: Record<Dialect, string> = { postgres: "Postgres", sqlite: "SQLite", mysql: "MySQL 8.4" };

function header(dialect: Dialect): string {
  return [
    "-- @generated by @metaobjectsdev/integration-tests — DO NOT EDIT.",
    `-- api-contract duration sub-corpus schema (${LABEL[dialect]}, literal column naming).`,
    "-- Regenerate: `bun run gen:duration-api-schema` in server/typescript/packages/integration-tests.",
  ].join("\n");
}

const MYSQL_TABLES = [
  `CREATE TABLE \`timers\` (
  \`id\` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`label\` VARCHAR(16) NOT NULL,
  \`timeout\` BIGINT
)`,
];

async function schemaSql(root: MetaRoot, dialect: Dialect): Promise<string> {
  if (dialect === "mysql") return renderMysqlSchemaArtifact(header(dialect), MYSQL_TABLES, root);
  return generateCanonicalSchemaSql(root, { header: header(dialect), dialect });
}

async function main(): Promise<void> {
  const root = await loadMetadataFile(join(API_CONTRACT_DURATION_DIR, "meta.json"));
  writeArtifact(API_CONTRACT_DURATION_SCHEMA_SQL_PATH, await schemaSql(root, "postgres"));
  writeArtifact(API_CONTRACT_DURATION_SQLITE_SCHEMA_SQL_PATH, await schemaSql(root, "sqlite"));
  writeArtifact(API_CONTRACT_DURATION_MYSQL_SCHEMA_SQL_PATH, await schemaSql(root, "mysql"));
}

main().catch((err: unknown) => {
  // eslint-disable-next-line no-console
  console.error(err);
  process.exit(1);
});
