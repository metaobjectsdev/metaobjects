// api-contract-report-mysql-schema.ts — the MySQL counterpart of the report sub-corpus schema
// artifact (report/schema.mysql.sql).
//
// `meta migrate` does not own a MySQL schema (ADR-0015), so the TABLES are the adopter's
// hand-written DDL, in the LITERAL column spelling the other committed artifacts use
// (amountCents, issuedOn) — the spelling the C# generated lane maps. The VIEWS are not
// hand-written: each is `buildReportViews(root, { dialect: "mysql" })`, the one producer of
// report SQL, wrapped in the recipe's `CREATE VIEW`. Drift-checked by
// test/api-contract-report-corpus.test.ts.

import type { MetaRoot } from "@metaobjectsdev/metadata";

import { renderMysqlSchemaArtifact } from "./canonical-schema-mysql.ts";

const HEADER = [
  "-- @generated by @metaobjectsdev/integration-tests — DO NOT EDIT.",
  "-- api-contract report sub-corpus schema (MySQL 8.4, literal column naming).",
  "-- Tables: the adopter's hand-written DDL (meta migrate does not own MySQL, ADR-0015).",
  "-- Views: buildReportViews(root, { dialect: \"mysql\" }), produced by TypeScript.",
  "-- Regenerate: `bun run gen:report-api-schema` in server/typescript/packages/integration-tests.",
].join("\n");

/** The adopter's tables, parents first. */
const TABLES = [
  `CREATE TABLE \`invoices\` (
  \`id\` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`reference\` VARCHAR(40) NOT NULL,
  \`status\` VARCHAR(20) NOT NULL,
  \`amountCents\` BIGINT NOT NULL,
  \`issuedOn\` DATE NOT NULL
)`,
  `CREATE TABLE \`products\` (
  \`id\` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`name\` VARCHAR(200) NOT NULL
)`,
  `CREATE TABLE \`sales\` (
  \`id\` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`productId\` BIGINT NOT NULL,
  \`amountCents\` BIGINT NOT NULL,
  FOREIGN KEY (\`productId\`) REFERENCES \`products\` (\`id\`)
)`,
];

/** The bytes of report/schema.mysql.sql for a loaded report/meta.json. */
export function generateReportApiMysqlSchemaSql(root: MetaRoot): string {
  return renderMysqlSchemaArtifact(HEADER, TABLES, root);
}
