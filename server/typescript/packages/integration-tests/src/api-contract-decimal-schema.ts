// api-contract-decimal-schema.ts — the schema artifacts of the api-contract `decimal/` sub-corpus
// (ADR-0019 Amendment 1): one table, `entries`, and its report view `v_entry_totals`.
//
// Postgres and SQLite: `meta migrate`'s own output. MySQL: the adopter's hand-written table
// (ADR-0015) and the view `buildReportViews(root, { dialect: "mysql" })` lowers.

import type { MetaRoot } from "@metaobjectsdev/metadata";

import { generateCanonicalSchemaSql } from "./canonical-schema.ts";
import { renderMysqlSchemaArtifact } from "./canonical-schema-mysql.ts";

export type DecimalApiSchemaDialect = "postgres" | "sqlite" | "mysql";

const LABEL: Record<DecimalApiSchemaDialect, string> = { postgres: "Postgres", sqlite: "SQLite", mysql: "MySQL 8.4" };

function header(dialect: DecimalApiSchemaDialect): string {
  return [
    "-- @generated by @metaobjectsdev/integration-tests — DO NOT EDIT.",
    `-- api-contract decimal sub-corpus schema (${LABEL[dialect]}, literal column naming).`,
    "-- Regenerate: `bun run gen:decimal-api-schema` in server/typescript/packages/integration-tests.",
  ].join("\n");
}

const MYSQL_TABLES = [
  `CREATE TABLE \`entries\` (
  \`id\` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`bucket\` VARCHAR(8) NOT NULL,
  \`amount\` DECIMAL(28,10),
  \`flagged\` BOOLEAN NOT NULL
)`,
];

/** The bytes of decimal/schema.<dialect>.sql for a loaded decimal/meta.json. */
export async function generateDecimalApiSchemaSql(root: MetaRoot, dialect: DecimalApiSchemaDialect): Promise<string> {
  if (dialect === "mysql") return renderMysqlSchemaArtifact(header(dialect), MYSQL_TABLES, root);
  return generateCanonicalSchemaSql(root, { header: header(dialect), dialect });
}
