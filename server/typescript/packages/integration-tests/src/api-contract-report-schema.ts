// api-contract-report-schema.ts — the schema artifact of the api-contract `report/`
// sub-corpus. TypeScript is the only producer of view SQL (ADR-0015); the C# generated
// lane executes the committed file, and the seam lanes seed rows behind their seam.

import type { MetaRoot } from "@metaobjectsdev/metadata";

import { generateCanonicalSchemaSql } from "./canonical-schema.ts";

/** The dialects the report sub-corpus commits a schema artifact for (MySQL is the adopter's own DDL, ADR-0015). */
export type ReportApiSchemaDialect = "postgres" | "sqlite";

/** The header of the committed artifact for `dialect`. */
export function reportApiSchemaHeader(dialect: ReportApiSchemaDialect = "postgres"): string {
  return [
    "-- @generated by @metaobjectsdev/integration-tests — DO NOT EDIT.",
    `-- api-contract report sub-corpus schema (${dialect === "postgres" ? "Postgres" : "SQLite"}, literal column naming).`,
    "-- Produced by TypeScript from report/meta.json; the C# generated lane executes it.",
    "-- Regenerate: `bun run gen:report-api-schema` in this package.",
  ].join("\n");
}

/** The bytes of report/schema.<dialect>.sql for a loaded report/meta.json. */
export function generateReportApiSchemaSql(root: MetaRoot, dialect: ReportApiSchemaDialect = "postgres"): Promise<string> {
  return generateCanonicalSchemaSql(root, { header: reportApiSchemaHeader(dialect), dialect });
}
