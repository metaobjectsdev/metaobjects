// canonical-schema-mysql.ts — the MySQL counterpart of the canonical schema artifact.
//
// `meta migrate` does not own a MySQL schema (ADR-0015; `--dialect mysql` is refused), so the
// TABLES here are the adopter's hand-written DDL, exactly as docs/recipes/mysql.md tells an
// adopter to write them. The VIEWS are not hand-written: each is `buildReportViews(root,
// { dialect: "mysql" })`, the one producer of report SQL, wrapped in the recipe's
// `CREATE VIEW`. Only the tables the report scenarios read are declared (programs, weeks,
// assets) — the rest of the canonical model gates the entity runtime on Postgres.
//
// Committed as fixtures/persistence-conformance/canonical/schema.mysql.sql and drift-checked
// by test/schema-artifact.test.ts, so a port that runs the report scenarios on MySQL executes
// TypeScript's bytes instead of lowering a report itself.

import { buildReportViews } from "@metaobjectsdev/codegen-ts";
import type { MetaRoot } from "@metaobjectsdev/metadata";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { CANONICAL_COLUMN_NAMING } from "./canonical-schema.ts";
import { CANONICAL_DIR } from "./paths.ts";

export const CANONICAL_MYSQL_SCHEMA_SQL_PATH = resolve(CANONICAL_DIR, "schema.mysql.sql");

const HEADER = [
  "-- @generated by @metaobjectsdev/integration-tests — DO NOT EDIT.",
  "-- Canonical persistence-conformance schema (MySQL 8.4, literal column naming).",
  "-- Tables: the adopter's hand-written DDL (meta migrate does not own MySQL, ADR-0015).",
  "-- Views: buildReportViews(root, { dialect: \"mysql\" }), produced by TypeScript.",
  "-- Only the tables the report-* scenarios read are declared.",
  "-- Regenerate: `bun run gen:schema` in server/typescript/packages/integration-tests.",
].join("\n");

/** The adopter's tables, parents first. */
const TABLES = [
  `CREATE TABLE \`programs\` (
  \`id\` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`title\` VARCHAR(200) NOT NULL,
  \`priceCents\` BIGINT NOT NULL,
  \`status\` VARCHAR(9) NOT NULL,
  \`created_ts\` DATETIME(3) NOT NULL
)`,
  `CREATE TABLE \`weeks\` (
  \`id\` BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  \`programId\` BIGINT NOT NULL,
  \`label\` VARCHAR(80),
  \`durationMinutes\` INT NOT NULL,
  FOREIGN KEY (\`programId\`) REFERENCES \`programs\` (\`id\`)
)`,
  `CREATE TABLE \`assets\` (
  \`id\` VARCHAR(36) NOT NULL DEFAULT (UUID()) PRIMARY KEY,
  \`ownerId\` VARCHAR(36) NOT NULL,
  \`externalId\` VARCHAR(36),
  \`payload\` JSON,
  \`recordedAt\` DATETIME(3) NOT NULL,
  \`observedAt\` DATETIME(3) NOT NULL,
  \`asOfDate\` DATE NOT NULL,
  \`atTime\` TIME(3) NOT NULL
)`,
];

/** The bytes of schema.mysql.sql for a loaded canonical model. */
export function generateCanonicalMysqlSchemaSql(root: MetaRoot): string {
  const views = buildReportViews(root, { dialect: "mysql", columnNamingStrategy: CANONICAL_COLUMN_NAMING });
  const statements = [
    ...TABLES,
    ...views.map((v) => `CREATE VIEW \`${v.name}\` AS\n${v.sql}`),
  ];
  return `${HEADER}\n\n${statements.map((s) => `${s};`).join("\n\n")}\n`;
}

/** Read the committed MySQL schema artifact. */
export function readCanonicalMysqlSchemaSql(): string {
  return readFileSync(CANONICAL_MYSQL_SCHEMA_SQL_PATH, "utf8");
}
