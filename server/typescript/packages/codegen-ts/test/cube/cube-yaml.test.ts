const HEADER = "# @generated by @metaobjectsdev/codegen-ts — cube-model";

/** A TPH subtype cube: a `sql` SELECT in place of `sql_table`. */
function sqlCube(sql: string, over: Partial<CubeSpec> = {}): CubeSpec {
  const { sqlTable: _table, ...rest } = spec();
  return { ...rest, sql, ...over };
}

/** A cube with nothing in it but a name and a table; tests override what they exercise. */
function spec(over: Partial<CubeSpec> = {}): CubeSpec {
  return {
    name: "Thing",
    sqlTable: '"things"',
    joins: [],
    dimensions: [],
    measures: [],
    segments: [],
    preAggregations: [],
    ...over,
  };
}

function dim(over: Partial<CubeDimensionSpec> = {}): CubeDimensionSpec {
  return { name: "d", sql: '{CUBE}."d"', type: "string", ...over };
}

function measure(over: Partial<CubeMeasureSpec> = {}): CubeMeasureSpec {
  return { name: "m", sql: '{CUBE}."id"', type: "count", ...over };
}

function segment(over: Partial<CubeSegmentSpec> = {}): CubeSegmentSpec {
  return { name: "s", sql: '{CUBE}."d" = 1', ...over };
}

/** The lines of a rendered file after the two-line preamble, for tests that look at one section. */
function body(yaml: string): string {
  const prefix = `${HEADER}\ncubes:\n`;
  expect(yaml.startsWith(prefix)).toBe(true);
  return yaml.slice(prefix.length);
}

function refusal(fn: () => unknown): CubeModelError {
  try {
    fn();
  } catch (e) {
    if (e instanceof CubeModelError) return e;
    throw e;
  }
  throw new Error("expected a CubeModelError");
}

