describe("scalars", () => {
  test("a single quote in any sql or sql_table value is doubled", () => {
    const yaml = renderCubeYaml(
      spec({
        sqlTable: `"it's"`,
        joins: [{ name: "Other", relationship: "many_to_one", sql: `{CUBE}."k" = 'a''b'` }],
        dimensions: [dim({ sql: `'x'` })],
        measures: [measure({ sql: `'y'`, filters: [{ sql: `{CUBE}."k" = 'z'` }] })],
        segments: [segment({ sql: `{CUBE}."k" <> 'it''s'` })],
      }),
    );
    expect(yaml).toContain(`    sql_table: '"it''s"'\n`);
    expect(yaml).toContain(`        sql: '{CUBE}."k" = ''a''''b'''\n`);
    expect(yaml).toContain(`        sql: '''x'''\n`);
    expect(yaml).toContain(`        sql: '''y'''\n`);
    expect(yaml).toContain(`          - sql: '{CUBE}."k" = ''z'''\n`);
    expect(yaml).toContain(`        sql: '{CUBE}."k" <> ''it''''s'''\n`);
  });

  test("a SQL value Cube-escaped by the build stage is only YAML-quoted, never escaped again", () => {
    // Table G: a segment value a{b}c reaches Cube as 'a\{b\}c' inside its SQL literal.
    const yaml = renderCubeYaml(spec({ segments: [segment({ sql: `{CUBE}."d" = 'a\\{b\\}c'` })] }));
    expect(yaml).toContain(`        sql: '{CUBE}."d" = ''a\\{b\\}c'''\n`);
    // And a Jinja-wrapped literal keeps its raw block verbatim.
    const raw = renderCubeYaml(spec({ segments: [segment({ sql: `{CUBE}."d" = '{% raw %}{{y}} {% z %}{% endraw %}'` })] }));
    expect(raw).toContain(`        sql: '{CUBE}."d" = ''{% raw %}{{y}} {% z %}{% endraw %}'''\n`);
  });

  test("a backslash and a double quote in sql pass through unchanged in single quotes", () => {
    const yaml = renderCubeYaml(spec({ segments: [segment({ sql: `{CUBE}."d" LIKE 'a\\%'` })] }));
    expect(yaml).toContain(`        sql: '{CUBE}."d" LIKE ''a\\%'''\n`);
  });

  test("names that a YAML reader would take for a boolean or null are quoted, other names are plain", () => {
    const yaml = renderCubeYaml(
      spec({
        name: "null",
        joins: [{ name: "yes", relationship: "many_to_one", sql: "x" }],
        dimensions: [dim({ name: "on" }), dim({ name: "True_story" }), dim({ name: "false" })],
        segments: [segment({ name: "N" })],
        preAggregations: [{ name: "off", type: "rollup", measures: ["true"], dimensions: [], segments: [] }],
      }),
    );
    expect(yaml).toContain("  - name: 'null'\n");
    expect(yaml).toContain("      - name: 'yes'\n");
    expect(yaml).toContain("      - name: 'on'\n");
    expect(yaml).toContain("      - name: True_story\n");
    expect(yaml).toContain("      - name: 'false'\n");
    expect(yaml).toContain("      - name: 'N'\n");
    expect(yaml).toContain("      - name: 'off'\n");
    // Inside a CUBE.<member> reference the word is already a string.
    expect(yaml).toContain("measures: [CUBE.true]\n");
  });
});

describe("free text", () => {
  function title(text: string): string {
    const yaml = renderCubeYaml(spec({ title: text }));
    const line = body(yaml).split("\n").find((l) => l.startsWith("    title: "));
    if (line === undefined) throw new Error("no title line");
    return line.slice("    title: ".length);
  }

  test("title and description are double-quoted, JSON-style: quotes, backslashes and newlines are escaped", () => {
    expect(title(`He said "hi"\\ and\nleft`)).toBe('"He said \\"hi\\"\\\\ and\\nleft"');
  });

  test("a single quote needs no doubling in a double-quoted scalar", () => {
    expect(title("it's")).toBe('"it\'s"');
  });

  test("braces that Cube resolves only in sql are written as they are", () => {
    expect(title("Share of {weeks}, a{b}c")).toBe('"Share of {weeks}, a{b}c"');
  });

  test("{{ is wrapped in a raw block, inside the string", () => {
    expect(title("Value is {{x}}")).toBe('"{% raw %}Value is {{x}}{% endraw %}"');
  });

  test("{% is wrapped in a raw block, inside the string", () => {
    expect(title("Use {% x %} here")).toBe('"{% raw %}Use {% x %} here{% endraw %}"');
  });

  test("{# is wrapped in a raw block, inside the string", () => {
    expect(title("A {# comment #}")).toBe('"{% raw %}A {# comment #}{% endraw %}"');
  });

  test("a description is escaped the same way as a title, on a dimension, measure and segment too", () => {
    const yaml = renderCubeYaml(
      spec({
        description: "cube {{a}}",
        dimensions: [dim({ description: "dim {{b}}", title: "t\tab" })],
        measures: [measure({ description: "measure {{c}}" })],
        segments: [segment({ description: "segment {{d}}" })],
      }),
    );
    expect(yaml).toContain('    description: "{% raw %}cube {{a}}{% endraw %}"\n');
    expect(yaml).toContain('        description: "{% raw %}dim {{b}}{% endraw %}"\n');
    expect(yaml).toContain('        title: "t\\tab"\n');
    expect(yaml).toContain('        description: "{% raw %}measure {{c}}{% endraw %}"\n');
    expect(yaml).toContain('        description: "{% raw %}segment {{d}}{% endraw %}"\n');
  });

  test("characters a YAML reader may take for a line break are written as \\u escapes", () => {
    expect(title("a\u2028b\u2029c\u0085d")).toBe('"a\\u2028b\\u2029c\\u0085d"');
  });

  test("non-ASCII text passes through as it is", () => {
    expect(title("Café — naïve")).toBe('"Café — naïve"');
  });

  test("text containing endraw is refused, naming the cube", () => {
    const err = refusal(() => renderCubeYaml(spec({ description: "ends {% endraw %} early" })));
    expect(err.code).toBe(ERR_CUBE_UNESCAPABLE_LITERAL);
    expect(err.message.startsWith("ERR_CUBE_UNESCAPABLE_LITERAL: ")).toBe(true);
    expect(err.message).toContain("cube 'Thing'");
    expect(err.message).toContain("description");
    expect(err.message).toContain("endraw");
  });

  test("text containing endraw is refused on each member, naming the member", () => {
    const bad = "endraw";
    const cases: [CubeSpec, string][] = [
      [spec({ title: bad }), "cube 'Thing' title"],
      [spec({ dimensions: [dim({ name: "status", title: bad })] }), "dimension 'status' title"],
      [spec({ dimensions: [dim({ name: "status", description: bad })] }), "dimension 'status' description"],
      [spec({ measures: [measure({ name: "n", title: bad })] }), "measure 'n' title"],
      [spec({ measures: [measure({ name: "n", description: bad })] }), "measure 'n' description"],
      [spec({ segments: [segment({ name: "open", title: bad })] }), "segment 'open' title"],
      [spec({ segments: [segment({ name: "open", description: bad })] }), "segment 'open' description"],
    ];
    for (const [cube, where] of cases) {
      const err = refusal(() => renderCubeYaml(cube));
      expect(err.code).toBe(ERR_CUBE_UNESCAPABLE_LITERAL);
      expect(err.message).toContain("cube 'Thing'");
      expect(err.message).toContain(where);
    }
  });
});

describe("a SQL value a single-quoted scalar cannot carry", () => {
  // SQL reaches the YAML from a string `@filter` value, so any character is legal model data. A
  // single-quoted scalar folds a line break and cannot hold a control character; such a value is
  // written double-quoted (JSON escapes), and nothing is refused or altered.
  const cases: [string, string, string][] = [
    ["a line feed", "\n", "\\n"],
    ["a carriage return", "\r", "\\r"],
    ["a tab", "\t", "\\t"],
    ["NUL", "\u0000", "\\u0000"],
    ["U+0001", "\u0001", "\\u0001"],
    ["U+001F", "\u001f", "\\u001f"],
    ["DEL", "\u007f", "\\u007f"],
    ["NEL (U+0085)", "\u0085", "\\u0085"],
    ["U+009F", "\u009f", "\\u009f"],
    ["the line separator (U+2028)", "\u2028", "\\u2028"],
    ["the paragraph separator (U+2029)", "\u2029", "\\u2029"],
    ["the byte-order mark (U+FEFF)", "\ufeff", "\\ufeff"],
  ];

  for (const [what, ch, escaped] of cases) {
    test(`${what} makes the value a double-quoted scalar with the character escaped`, () => {
      const yaml = renderCubeYaml(spec({ segments: [segment({ sql: `a${ch}b` })] }));
      expect(yaml).toContain(`        sql: "a${escaped}b"\n`);
      // The raw character is not in the file at all.
      expect(/[\u0000-\u0009\u000b-\u001f\u007f-\u009f\u2028\u2029\ufeff]/.test(yaml)).toBe(false);
    });
  }

  test("quotes and backslashes in such a value are escaped as JSON escapes them, braces are left", () => {
    const yaml = renderCubeYaml(spec({ segments: [segment({ sql: `{CUBE}."d" = 'a\\{b\\}c'\n` })] }));
    expect(yaml).toContain('        sql: "{CUBE}.\\"d\\" = \'a\\\\{b\\\\}c\'\\n"\n');
  });

  test("each place a sql value is written takes one, and the file keeps its shape", () => {
    const sql = "a\nb";
    const cubes: CubeSpec[] = [
      spec({ sqlTable: sql }),
      sqlCube(sql),
      spec({ joins: [{ name: "O", relationship: "many_to_one", sql }] }),
      spec({ dimensions: [dim({ sql })] }),
      spec({ measures: [measure({ sql })] }),
      spec({ measures: [measure({ filters: [{ sql }] })] }),
      spec({ segments: [segment({ sql })] }),
    ];
    for (const cube of cubes) {
      const yaml = renderCubeYaml(cube);
      expect(yaml).toContain('"a\\nb"');
      expect(yaml).not.toContain("\n\n");
    }
  });

  test("a value with none of those characters stays single-quoted", () => {
    expect(renderCubeYaml(spec({ segments: [segment({ sql: "é — ü" })] }))).toContain("        sql: 'é — ü'\n");
  });
});

// ---------------------------------------------------------------------------
// A parse oracle: Bun's YAML parser reads back exactly what the spec holds
// ---------------------------------------------------------------------------

type Json = Record<string, unknown>;

/** Free text as the parser should hand it back: Jinja-safe, as the renderer wraps it. */
function freeText(text: string | undefined): string | undefined {
  return text !== undefined && /\{[{%#]/.test(text) ? `{% raw %}${text}{% endraw %}` : text;
}

function refs(members: readonly string[]): string[] | undefined {
  return members.length === 0 ? undefined : members.map((m) => `CUBE.${m}`);
}

function each<T>(items: readonly T[], f: (item: T) => Json): Json[] | undefined {
  return items.length === 0 ? undefined : items.map(f);
}

function docs(node: { public?: boolean; title?: string; description?: string }): Json {
  return { public: node.public, title: freeText(node.title), description: freeText(node.description) };
}

/** The value the parser must produce for a cube, written from the spec independently of the renderer. */
function expectedCube(c: CubeSpec): Json {
  return {
    name: c.name,
    sql_table: c.sqlTable,
    sql: c.sql,
    ...docs(c),
    joins: each(c.joins, (j) => ({ name: j.name, relationship: j.relationship, sql: j.sql })),
    dimensions: each(c.dimensions, (d) => ({
      name: d.name,
      sql: d.sql,
      type: d.type,
      primary_key: d.primaryKey,
      ...docs(d),
      meta: d.meta !== undefined && d.meta.grains.length > 0 ? { grains: [...d.meta.grains] } : undefined,
    })),
    measures: each(c.measures, (m) => ({
      name: m.name,
      sql: m.sql,
      type: m.type,
      filters: each(m.filters ?? [], (f) => ({ sql: f.sql })),
      ...docs(m),
    })),
    segments: each(c.segments, (s) => ({ name: s.name, sql: s.sql, ...docs(s) })),
    pre_aggregations: each(c.preAggregations, (r) => ({
      name: r.name,
      type: "rollup",
      measures: refs(r.measures),
      dimensions: refs(r.dimensions),
      segments: refs(r.segments),
      time_dimension: r.timeDimension === undefined ? undefined : `CUBE.${r.timeDimension}`,
      granularity: r.granularity,
      time_dimensions: each(r.timeDimensions ?? [], (t) => ({ dimension: `CUBE.${t.dimension}`, granularity: t.granularity })),
    })),
  };
}

function parsed(c: CubeSpec): unknown {
  return YAML.parse(renderCubeYaml(c));
}

describe("parse oracle", () => {
  test("the three canonical cubes parse to the model's values", async () => {
    const model = await canonicalModel();
    expect(model.cubes.map((c) => c.name)).toEqual(["Program", "Week", "Asset"]);
    for (const c of model.cubes) expect(parsed(c)).toEqual({ cubes: [expectedCube(c)] });
  });

  test("quotes, braces, Cube escapes and a Jinja raw block in sql survive", () => {
    const c = spec({
      sqlTable: `"it's"`,
      joins: [{ name: "Other", relationship: "many_to_one", sql: `{CUBE}."k" = {Other}."k" AND {CUBE}."s" = 'a''b'` }],
      dimensions: [dim({ sql: `'q'` }), dim({ name: "e", sql: `CAST({CUBE}."x" AS TEXT)` })],
      measures: [measure({ sql: `'y'`, filters: [{ sql: `{CUBE}."k" = 'a\\{b\\}c'` }] })],
      segments: [
        segment({ sql: `{CUBE}."d" = '{% raw %}{{y}} {% z %} {# c #}{% endraw %}'` }),
        segment({ name: "like", sql: `{CUBE}."d" LIKE 'a\\%' AND {CUBE}."e" = "x"` }),
      ],
    });
    expect(parsed(c)).toEqual({ cubes: [expectedCube(c)] });
  });

  test("a TPH subtype's sql parses to its SELECT", () => {
    const c = sqlCube(`SELECT * FROM "animals" WHERE "kind" = 'DOG'`, { name: "Dog", public: false });
    expect(parsed(c)).toEqual({ cubes: [expectedCube(c)] });
  });

  for (const [what, ch] of [
    ["a line break", "\n"],
    ["a carriage return", "\r\n"],
    ["a tab", "\t"],
    ["a control character", "\u0001"],
    ["NUL", "\u0000"],
    ["DEL", "\u007f"],
    ["a C1 control", "\u0085"],
    ["a line separator", "\u2028"],
    ["a paragraph separator", "\u2029"],
    ["a byte-order mark", "\ufeff"],
  ] as const) {
    test(`${what} in a filter value parses back untouched, at every sql site`, () => {
      const sql = `{CUBE}."d" = 'x${ch}y'`;
      const c = spec({
        sqlTable: sql,
        joins: [{ name: "O", relationship: "one_to_many", sql }],
        dimensions: [dim({ sql })],
        measures: [measure({ sql, filters: [{ sql }] })],
        segments: [segment({ sql })],
      });
      expect(parsed(c)).toEqual({ cubes: [expectedCube(c)] });
      expect(parsed(sqlCube(sql))).toEqual({ cubes: [expectedCube(sqlCube(sql))] });
    });
  }

  test("free text parses back: quotes, backslashes, newlines, Jinja openers, braces, separators, non-ASCII", () => {
    const text = `He said "hi" \\ it's\n{{x}} {% y %} {# z #} a{b}c \u2028 \u0085 café — ü`;
    const c = spec({
      title: text,
      description: "plain {braces} only",
      dimensions: [dim({ title: "{{a}}", description: "t\tab" })],
      measures: [measure({ title: "{% b %}", description: "{# c #}" })],
      segments: [segment({ title: "it's", description: `say "hi"` })],
    });
    expect(parsed(c)).toEqual({ cubes: [expectedCube(c)] });
    const cube = (parsed(c) as { cubes: Json[] }).cubes[0];
    expect(cube?.["title"]).toBe(`{% raw %}${text}{% endraw %}`);
    expect(cube?.["description"]).toBe("plain {braces} only");
  });

  test("names a YAML reader takes for a boolean or null parse back as strings", () => {
    const words = ["true", "false", "null", "yes", "no", "on", "off", "y", "n", "Yes", "NULL", "TRUE", "N"];
    const c = spec({
      name: "null",
      joins: [{ name: "yes", relationship: "many_to_one", sql: "x" }],
      dimensions: words.map((name) => dim({ name })),
      measures: [measure({ name: "off" })],
      segments: [segment({ name: "no" })],
      preAggregations: [{ name: "n", type: "rollup", measures: ["true", "off"], dimensions: ["null"], segments: ["no"] }],
    });
    expect(parsed(c)).toEqual({ cubes: [expectedCube(c)] });
    const dims = ((parsed(c) as { cubes: Json[] }).cubes[0]?.["dimensions"] ?? []) as Json[];
    expect(dims.map((d) => d["name"])).toEqual(words);
  });

  test("the three rollup time forms and every optional key parse back", () => {
    const c = spec({
      public: true,
      title: "Things",
      description: "Described.",
      joins: [{ name: "Other", relationship: "one_to_one", sql: `{CUBE}."id" = {Other}."id"` }],
      dimensions: [
        dim({ name: "id", type: "number", primaryKey: true, public: false, title: "Id", description: "The key." }),
        dim({ name: "at", type: "time", sql: `{CUBE}."at"`, meta: { grains: ["hour", "day", "week"] } }),
        dim({ name: "on2", type: "boolean", primaryKey: false, meta: { grains: [] } }),
      ],
      measures: [
        measure({ name: "n", type: "count_distinct", filters: [{ sql: `{CUBE}."x" > 1` }], public: false, title: "N", description: "D" }),
      ],
      segments: [segment({ name: "s", public: true, title: "S", description: "SD" })],
      preAggregations: [
        { name: "one", type: "rollup", measures: ["n"], dimensions: ["id"], segments: ["s"], timeDimension: "at", granularity: "day" },
        {
          name: "two", type: "rollup", measures: ["n"], dimensions: [], segments: [],
          timeDimensions: [{ dimension: "at", granularity: "hour" }, { dimension: "at", granularity: "week" }],
        },
        { name: "none", type: "rollup", measures: ["n"], dimensions: ["id"], segments: [] },
      ],
    });
    expect(parsed(c)).toEqual({ cubes: [expectedCube(c)] });
  });
});

