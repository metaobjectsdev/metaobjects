const CANONICAL = resolve(
  import.meta.dir, "..", "..", "..", "..", "..", "..",
  "fixtures", "persistence-conformance", "canonical", "meta.fitness.json",
);

async function canonicalModel(): Promise<CubeModel> {
  const result = await loadUris([pathToFileURL(CANONICAL).href]);
  expect(result.errors.map((e) => e.message)).toEqual([]);
  return buildCubeModel(result.root, { dialect: "postgres", columnNamingStrategy: "literal" });
}

describe("Table H — the canonical model's three files", () => {
  function render(model: CubeModel, name: string): string {
    const hit = model.cubes.find((c) => c.name === name);
    if (hit === undefined) throw new Error(`no cube ${name} in [${model.cubes.map((c) => c.name).join(", ")}]`);
    return renderCubeYaml(hit);
  }

  test("Program.yml", async () => {
    expect(render(await canonicalModel(), "Program")).toBe(PROGRAM_YML);
  });

  test("Week.yml", async () => {
    expect(render(await canonicalModel(), "Week")).toBe(WEEK_YML);
  });

  test("Asset.yml", async () => {
    expect(render(await canonicalModel(), "Asset")).toBe(ASSET_YML);
  });

  test("rendering twice gives the same bytes", async () => {
    const model = await canonicalModel();
    expect(render(model, "Week")).toBe(render(model, "Week"));
  });
});

