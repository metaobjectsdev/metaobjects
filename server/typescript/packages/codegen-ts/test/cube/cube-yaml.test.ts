describe("a rollup's three time forms", () => {
  function rollup(r: CubeRollupSpec): string {
    // Everything under the `pre_aggregations:` key, found by its text and not by a line count.
    const lines = renderCubeYaml(spec({ preAggregations: [r] })).split("\n");
    const at = lines.indexOf("    pre_aggregations:");
    expect(at).toBeGreaterThan(-1);
    return lines.slice(at + 1, -1).join("\n");
  }

  test("one time dimension: time_dimension and granularity, CUBE.-prefixed members in flow lists", () => {
    expect(
      rollup({
        name: "ByMonth", type: "rollup", measures: ["a", "b"], dimensions: ["x", "y"], segments: ["s"],
        timeDimension: "createdAt", granularity: "month",
      }),
    ).toBe(
      [
        "      - name: ByMonth",
        "        type: rollup",
        "        measures: [CUBE.a, CUBE.b]",
        "        dimensions: [CUBE.x, CUBE.y]",
        "        segments: [CUBE.s]",
        "        time_dimension: CUBE.createdAt",
        "        granularity: month",
      ].join("\n"),
    );
  });

  test("several time dimensions: a time_dimensions block list of dimension and granularity", () => {
    expect(
      rollup({
        name: "Activity", type: "rollup", measures: ["a"], dimensions: [], segments: [],
        timeDimensions: [
          { dimension: "recordedAt", granularity: "hour" },
          { dimension: "asOfDate", granularity: "week" },
        ],
      }),
    ).toBe(
      [
        "      - name: Activity",
        "        type: rollup",
        "        measures: [CUBE.a]",
        "        time_dimensions:",
        "          - dimension: CUBE.recordedAt",
        "            granularity: hour",
        "          - dimension: CUBE.asOfDate",
        "            granularity: week",
      ].join("\n"),
    );
  });

  test("no time dimension: no time keys at all", () => {
    expect(
      rollup({ name: "Totals", type: "rollup", measures: ["a"], dimensions: ["x"], segments: [] }),
    ).toBe(
      ["      - name: Totals", "        type: rollup", "        measures: [CUBE.a]", "        dimensions: [CUBE.x]"].join("\n"),
    );
  });
});

