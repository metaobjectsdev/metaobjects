describe("scalars", () => {
  test("a single quote in any sql or sql_table value is doubled", () => {
    const yaml = renderCubeYaml(
      spec({
        sqlTable: `"it's"`,
        joins: [{ name: "Other", relationship: "many_to_one", sql: `{CUBE}."k" = 'a''b'` }],
        dimensions: [dim({ sql: `'x'` })],
        measures: [measure({ sql: `'y'`, filters: [{ sql: `{CUBE}."k" = 'z'` }] })],
        segments: [segment({ sql: `{CUBE}."k" <> 'it''s'` })],
      }),
    );
    expect(yaml).toContain(`    sql_table: '"it''s"'\n`);
    expect(yaml).toContain(`        sql: '{CUBE}."k" = ''a''''b'''\n`);
    expect(yaml).toContain(`        sql: '''x'''\n`);
    expect(yaml).toContain(`        sql: '''y'''\n`);
    expect(yaml).toContain(`          - sql: '{CUBE}."k" = ''z'''\n`);
    expect(yaml).toContain(`        sql: '{CUBE}."k" <> ''it''''s'''\n`);
  });

  test("a SQL value Cube-escaped by the build stage is only YAML-quoted, never escaped again", () => {
    // Table G: a segment value a{b}c reaches Cube as 'a\{b\}c' inside its SQL literal.
    const yaml = renderCubeYaml(spec({ segments: [segment({ sql: `{CUBE}."d" = 'a\\{b\\}c'` })] }));
    expect(yaml).toContain(`        sql: '{CUBE}."d" = ''a\\{b\\}c'''\n`);
    // And a Jinja-wrapped literal keeps its raw block verbatim.
    const raw = renderCubeYaml(spec({ segments: [segment({ sql: `{CUBE}."d" = '{% raw %}{{y}} {% z %}{% endraw %}'` })] }));
    expect(raw).toContain(`        sql: '{CUBE}."d" = ''{% raw %}{{y}} {% z %}{% endraw %}'''\n`);
  });

  test("a backslash and a double quote in sql pass through unchanged in single quotes", () => {
    const yaml = renderCubeYaml(spec({ segments: [segment({ sql: `{CUBE}."d" LIKE 'a\\%'` })] }));
    expect(yaml).toContain(`        sql: '{CUBE}."d" LIKE ''a\\%'''\n`);
  });

  test("names that a YAML reader would take for a boolean or null are quoted, other names are plain", () => {
    const yaml = renderCubeYaml(
      spec({
        name: "null",
        joins: [{ name: "yes", relationship: "many_to_one", sql: "x" }],
        dimensions: [dim({ name: "on" }), dim({ name: "True_story" }), dim({ name: "false" })],
        segments: [segment({ name: "N" })],
        preAggregations: [{ name: "off", type: "rollup", measures: ["true"], dimensions: [], segments: [] }],
      }),
    );
    expect(yaml).toContain("  - name: 'null'\n");
    expect(yaml).toContain("      - name: 'yes'\n");
    expect(yaml).toContain("      - name: 'on'\n");
    expect(yaml).toContain("      - name: True_story\n");
    expect(yaml).toContain("      - name: 'false'\n");
    expect(yaml).toContain("      - name: 'N'\n");
    expect(yaml).toContain("      - name: 'off'\n");
    // Inside a CUBE.<member> reference the word is already a string.
    expect(yaml).toContain("measures: [CUBE.true]\n");
  });
});

describe("free text", () => {
  function title(text: string): string {
    const yaml = renderCubeYaml(spec({ title: text }));
    const line = body(yaml).split("\n").find((l) => l.startsWith("    title: "));
    if (line === undefined) throw new Error("no title line");
    return line.slice("    title: ".length);
  }

  test("title and description are double-quoted, JSON-style: quotes, backslashes and newlines are escaped", () => {
    expect(title(`He said "hi"\\ and\nleft`)).toBe('"He said \\"hi\\"\\\\ and\\nleft"');
  });

  test("a single quote needs no doubling in a double-quoted scalar", () => {
    expect(title("it's")).toBe('"it\'s"');
  });

  test("braces that Cube resolves only in sql are written as they are", () => {
    expect(title("Share of {weeks}, a{b}c")).toBe('"Share of {weeks}, a{b}c"');
  });

  test("{{ is wrapped in a raw block, inside the string", () => {
    expect(title("Value is {{x}}")).toBe('"{% raw %}Value is {{x}}{% endraw %}"');
  });

  test("{% is wrapped in a raw block, inside the string", () => {
    expect(title("Use {% x %} here")).toBe('"{% raw %}Use {% x %} here{% endraw %}"');
  });

  test("{# is wrapped in a raw block, inside the string", () => {
    expect(title("A {# comment #}")).toBe('"{% raw %}A {# comment #}{% endraw %}"');
  });

  test("a description is escaped the same way as a title, on a dimension, measure and segment too", () => {
    const yaml = renderCubeYaml(
      spec({
        description: "cube {{a}}",
        dimensions: [dim({ description: "dim {{b}}", title: "t\tab" })],
        measures: [measure({ description: "measure {{c}}" })],
        segments: [segment({ description: "segment {{d}}" })],
      }),
    );
    expect(yaml).toContain('    description: "{% raw %}cube {{a}}{% endraw %}"\n');
    expect(yaml).toContain('        description: "{% raw %}dim {{b}}{% endraw %}"\n');
    expect(yaml).toContain('        title: "t\\tab"\n');
    expect(yaml).toContain('        description: "{% raw %}measure {{c}}{% endraw %}"\n');
    expect(yaml).toContain('        description: "{% raw %}segment {{d}}{% endraw %}"\n');
  });

  test("characters a YAML reader may take for a line break are written as \\u escapes", () => {
    expect(title("a\u2028b\u2029c\u0085d")).toBe('"a\\u2028b\\u2029c\\u0085d"');
  });

  test("non-ASCII text passes through as it is", () => {
    expect(title("Café — naïve")).toBe('"Café — naïve"');
  });

  test("text containing endraw is refused, naming the cube", () => {
    const err = refusal(() => renderCubeYaml(spec({ description: "ends {% endraw %} early" })));
    expect(err.code).toBe(ERR_CUBE_UNESCAPABLE_LITERAL);
    expect(err.message.startsWith("ERR_CUBE_UNESCAPABLE_LITERAL: ")).toBe(true);
    expect(err.message).toContain("cube 'Thing'");
    expect(err.message).toContain("description");
    expect(err.message).toContain("endraw");
  });

  test("text containing endraw is refused on each member, naming the member", () => {
    const bad = "endraw";
    const cases: [CubeSpec, string][] = [
      [spec({ title: bad }), "cube 'Thing' title"],
      [spec({ dimensions: [dim({ name: "status", title: bad })] }), "dimension 'status' title"],
      [spec({ dimensions: [dim({ name: "status", description: bad })] }), "dimension 'status' description"],
      [spec({ measures: [measure({ name: "n", title: bad })] }), "measure 'n' title"],
      [spec({ measures: [measure({ name: "n", description: bad })] }), "measure 'n' description"],
      [spec({ segments: [segment({ name: "open", title: bad })] }), "segment 'open' title"],
      [spec({ segments: [segment({ name: "open", description: bad })] }), "segment 'open' description"],
    ];
    for (const [cube, where] of cases) {
      const err = refusal(() => renderCubeYaml(cube));
      expect(err.code).toBe(ERR_CUBE_UNESCAPABLE_LITERAL);
      expect(err.message).toContain("cube 'Thing'");
      expect(err.message).toContain(where);
    }
  });
});

describe("a SQL value that cannot be one line", () => {
  test("a newline in a sql value is refused, naming the cube and the member", () => {
    const err = refusal(() => renderCubeYaml(spec({ measures: [measure({ name: "n", sql: "a\nb" })] })));
    expect(err.code).toBe(ERR_CUBE_UNESCAPABLE_LITERAL);
    expect(err.message).toContain("cube 'Thing'");
    expect(err.message).toContain("measure 'n'");
    expect(err.message).toContain("line break");
  });

  test("a carriage return is a line break too", () => {
    expect(() => renderCubeYaml(spec({ sqlTable: "a\rb" }))).toThrow(CubeModelError);
  });

  test("each place a sql value is written is checked", () => {
    const cases: CubeSpec[] = [
      spec({ sqlTable: "a\nb" }),
      sqlCube("a\nb"),
      spec({ joins: [{ name: "O", relationship: "many_to_one", sql: "a\nb" }] }),
      spec({ dimensions: [dim({ sql: "a\nb" })] }),
      spec({ measures: [measure({ filters: [{ sql: "a\nb" }] })] }),
      spec({ segments: [segment({ sql: "a\nb" })] }),
    ];
    for (const cube of cases) expect(() => renderCubeYaml(cube)).toThrow(CubeModelError);
  });
});

// ---------------------------------------------------------------------------
// Bytes: line endings, the trailing newline, no trailing spaces
// ---------------------------------------------------------------------------

describe("the bytes", () => {
  const rich = spec({
    public: false,
    title: "Things — all of them",
    description: "Has {{braces}}\nand a second line.",
    joins: [{ name: "Other", relationship: "many_to_one", sql: `{CUBE}."oid" = {Other}."id"` }],
    dimensions: [
      dim({ name: "id", primaryKey: true, type: "number", sql: '{CUBE}."id"' }),
      dim({ name: "at", type: "time", sql: '{CUBE}."at"', meta: { grains: ["day", "week"] } }),
    ],
    measures: [measure({ filters: [{ sql: `{CUBE}."k" = 'v'` }] })],
    segments: [segment()],
    preAggregations: [
      {
        name: "Daily", type: "rollup", measures: ["m"], dimensions: ["d"], segments: ["s"],
        timeDimensions: [
          { dimension: "at", granularity: "day" },
          { dimension: "at", granularity: "week" },
        ],
      },
    ],
  });

  test("LF line endings only", () => {
    expect(renderCubeYaml(rich)).not.toContain("\r");
  });

  test("exactly one trailing newline", () => {
    const yaml = renderCubeYaml(rich);
    expect(yaml.endsWith("\n")).toBe(true);
    expect(yaml.endsWith("\n\n")).toBe(false);
  });

  test("no line ends in a space or tab", () => {
    expect(/[ \t]$/m.test(renderCubeYaml(rich))).toBe(false);
  });

  test("no blank lines", () => {
    expect(renderCubeYaml(rich)).not.toContain("\n\n");
  });

  test("indentation is two spaces per level, never a tab", () => {
    const yaml = renderCubeYaml(rich);
    expect(yaml).not.toContain("\t");
    for (const line of yaml.split("\n")) expect((line.length - line.trimStart().length) % 2).toBe(0);
  });
});
