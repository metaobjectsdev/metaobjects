// FR-044 Plan 4, Task 10 — renderCubeViewYaml, the deterministic Cube YAML for one view (a served
// report with `@spine`). The same scalar rules as renderCubeYaml (cube-yaml.ts): names plain
// unless a YAML reader would take them for a boolean or null, free text escaped for Cube and Jinja
// and written as a JSON string, block lists, two-space indent, LF, one trailing newline. Every
// expected text below is written out by hand.

import { YAML } from "bun";
import { describe, test, expect } from "bun:test";
import { CubeModelError, ERR_CUBE_UNESCAPABLE_LITERAL } from "../../src/cube/cube-errors.js";
import type { CubeViewSpec } from "../../src/cube/cube-model-spec.js";
import { renderCubeViewYaml } from "../../src/cube/cube-yaml.js";

const HEADER = "# @generated by @metaobjectsdev/codegen-ts — cube-model";

const roster: CubeViewSpec = {
  name: "ProgramRoster",
  cubes: [
    { joinPath: "Program", includes: [{ name: "id", alias: "programKey" }, { name: "title", alias: "programTitle" }] },
    { joinPath: "Program.ProgramRosterFacts", includes: [{ name: "weeks" }, { name: "totalMinutesOrZero" }] },
  ],
};

describe("renderCubeViewYaml", () => {
  test("a view: its name, then each join path and the members it includes there", () => {
    expect(renderCubeViewYaml(roster)).toBe(
      [
        HEADER,
        "views:",
        "  - name: ProgramRoster",
        "    cubes:",
        "      - join_path: Program",
        "        includes:",
        "          - name: id",
        "            alias: programKey",
        "          - name: title",
        "            alias: programTitle",
        "      - join_path: Program.ProgramRosterFacts",
        "        includes:",
        "          - name: weeks",
        "          - name: totalMinutesOrZero",
        "",
      ].join("\n"),
    );
  });

  test("the view's docs, and an include's docs and grains", () => {
    const yaml = renderCubeViewYaml({
      name: "ProgramsByMonth",
      title: "Programs by month",
      description: "Every {program}.",
      cubes: [
        {
          joinPath: "Program",
          includes: [
            { name: "createdAt", alias: "created", title: "Created", description: "When it was {{made}}.", meta: { grains: ["month", "year"] } },
          ],
        },
        { joinPath: "Program.ProgramsByMonthFacts", includes: [{ name: "weeks" }] },
      ],
    });
    expect(yaml).toBe(
      [
        HEADER,
        "views:",
        "  - name: ProgramsByMonth",
        '    title: "Programs by month"',
        '    description: "Every \\\\{program\\\\}."',
        "    cubes:",
        "      - join_path: Program",
        "        includes:",
        "          - name: createdAt",
        "            alias: created",
        '            title: "Created"',
        '            description: "{% raw %}When it was \\\\{\\\\{made\\\\}\\\\}.{% endraw %}"',
        "            meta:",
        "              grains: [month, year]",
        "      - join_path: Program.ProgramsByMonthFacts",
        "        includes:",
        "          - name: weeks",
        "",
      ].join("\n"),
    );
    // What a YAML reader hands Cube: the escapes are Cube's, not YAML's.
    const parsed = YAML.parse(yaml) as { views: Array<{ description: string; cubes: Array<{ includes: Array<{ meta?: unknown }> }> }> };
    expect(parsed.views[0]!.description).toBe("Every \\{program\\}.");
    expect(parsed.views[0]!.cubes[0]!.includes[0]!.meta).toEqual({ grains: ["month", "year"] });
  });

  test("a name a YAML reader would take for a boolean is quoted, wherever it stands", () => {
    const yaml = renderCubeViewYaml({
      name: "Yes",
      cubes: [{ joinPath: "No", includes: [{ name: "on", alias: "off" }] }],
    });
    expect(yaml).toContain("  - name: 'Yes'\n");
    expect(yaml).toContain("      - join_path: 'No'\n");
    expect(yaml).toContain("          - name: 'on'\n            alias: 'off'\n");
    const parsed = YAML.parse(yaml) as { views: Array<{ name: unknown; cubes: Array<{ join_path: unknown; includes: Array<{ name: unknown; alias: unknown }> }> }> };
    expect(parsed.views[0]!.name).toBe("Yes");
    expect(parsed.views[0]!.cubes[0]!.join_path).toBe("No");
    expect(parsed.views[0]!.cubes[0]!.includes[0]).toEqual({ name: "on", alias: "off" });
  });

  test("raw-wrapped text holding endraw is refused, naming the view and the include", () => {
    let err: unknown;
    try {
      renderCubeViewYaml({
        ...roster,
        cubes: [{ joinPath: "Program", includes: [{ name: "id", alias: "programKey", description: "{% endraw %}" }] }],
      });
    } catch (e) {
      err = e;
    }
    expect(err).toBeInstanceOf(CubeModelError);
    expect((err as CubeModelError).code).toBe(ERR_CUBE_UNESCAPABLE_LITERAL);
    expect((err as CubeModelError).message).toContain("view 'ProgramRoster' member 'programKey' description");
  });

  test("LF line endings, one trailing newline, no trailing spaces", () => {
    const yaml = renderCubeViewYaml(roster);
    expect(yaml.includes("\r")).toBe(false);
    expect(yaml.endsWith("\n") && !yaml.endsWith("\n\n")).toBe(true);
    expect(yaml.split("\n").some((l) => l !== l.trimEnd())).toBe(false);
  });
});
