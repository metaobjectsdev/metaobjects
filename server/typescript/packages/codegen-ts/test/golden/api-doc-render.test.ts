describe("renderEntityApiPage — human per-unit page", () => {
  test("byte-exact: sections per present kind, signatures, ordered", async () => {
    const { model } = await loadModel();
    const out = renderEntityApiPage(unit(model, "Product"), provider);
    expect(out).toBe(EXPECTED_PRODUCT_PAGE);
  });

  test("sections appear in canonical order (Model → … → Validation)", async () => {
    const { model } = await loadModel();
    const out = renderEntityApiPage(unit(model, "Product"), provider);
    const order = ["## Model", "## Data access", "## REST", "## Validation"].map((h) =>
      out.indexOf(h),
    );
    expect(order.every((i) => i >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  test("a fuller example, when present, renders as a fenced ```ts block", () => {
    // Examples are optional on ApiSymbol; the template emits a fenced block only
    // when present. Hand-build a unit carrying one to gate that path byte-exact.
    const synthetic: ApiUnitDoc = {
      node: "Widget",
      nodeKind: "entity",
      symbols: [
        {
          name: "makeWidget",
          kind: "data-access",
          signature: "makeWidget(): Widget",
          usage: "Build one.",
          example: "const w = makeWidget();\nconsole.log(w);",
        },
      ],
    };
    const out = renderEntityApiPage(synthetic, provider);
    expect(out).toBe(
      `<!-- @generated by @metaobjectsdev/codegen-ts — DO NOT EDIT. -->

# Widget API

## Data access

### \`makeWidget(): Widget\`

Build one.

\`\`\`ts
const w = makeWidget();
console.log(w);
\`\`\`
`,
    );
  });
});

