describe("one ApiModel feeds every form (no duplicate derivation)", () => {
  test("entity page, index, and agent form all render from the SAME buildApiModel result", async () => {
    const { model } = await loadModel();
    // A single model object drives all three renderers without rebuilding.
    const page = renderEntityApiPage(unit(model, "Product"), provider);
    const index = renderApiIndex(model, "flat", provider);
    const agent = renderAgentApi(model, provider);
    expect(page).toBe(EXPECTED_PRODUCT_PAGE);
    expect(index).toBe(EXPECTED_INDEX_FLAT);
    expect(agent).toBe(EXPECTED_AGENT);
  });
});
