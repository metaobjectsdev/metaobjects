const EXPECTED_AGENT = `<!-- @generated by @metaobjectsdev/codegen-ts — DO NOT EDIT. -->

# Agent API Reference

Generated API reference for this project; call these exactly as written.

## Product
- \`interface Product\` — The typed shape of a Product row, generated from its metadata.
- \`findProductById(db: Db, id: number): Promise<Product | null>\` — Fetch a single Product by its primary key; null when not found.
- \`listProducts(db: Db, opts?: { limit?: number; offset?: number }): Promise<Product[]>\` — List Product rows with optional limit/offset paging.
- \`createProduct(db: Db, data: unknown): Promise<Product>\` — Validate (via ProductInsertSchema) and insert a new Product.
- \`updateProduct(db: Db, id: number, data: unknown): Promise<Product | null>\` — Partially update an existing Product by primary key; null when not found.
- \`deleteProductById(db: Db, id: number): Promise<boolean>\` — Delete a Product by primary key; true when a row was removed.
- \`ProductInsertSchema: ZodType\` — Zod schema validating the body of a create<Product> / POST request (auto-generated PKs excluded).
- \`ProductUpdateSchema: ZodType\` — Zod schema validating the body of an update / PATCH request (all fields optional).
- \`GET /products\` — List Product (supports filter/sort/paging query params).
- \`GET /products/:id\` — Fetch a single Product by id (404 when not found).
- \`POST /products\` — Create a Product (body validated by ProductInsertSchema).
- \`PATCH /products/:id\` — Partially update a Product by id (body validated by ProductUpdateSchema).
- \`DELETE /products/:id\` — Delete a Product by id.

## SummaryVO
- \`interface SummaryVO\` — The typed shape of a SummaryVO row, generated from its metadata.

## ProductSummary
- \`extractProductSummary(root: MetaRoot, text: string): SummaryVO\` — Parse dirty LLM json text into a strict, fully-typed SummaryVO graph.
- \`extractLenientProductSummary(root: MetaRoot, text: string): ExtractionResult<ProductSummaryExtracted>\` — Never-throwing extract; inspect report for lost/defaulted fields.
- \`renderProductSummary(payload: SummaryVO, provider: Provider): string\` — Render the ProductSummary document from a typed SummaryVO payload.
`;

describe("renderAgentApi — condensed agent/LLM form", () => {
  test("byte-exact: one compact line per symbol, grouped by unit, no prose/examples", async () => {
    const { model } = await loadModel();
    const out = renderAgentApi(model, provider);
    expect(out).toBe(EXPECTED_AGENT);
  });

  test("NO prose/examples leak in — no fenced code blocks, every symbol on its own bullet", async () => {
    const { model } = await loadModel();
    const out = renderAgentApi(model, provider);
    expect(out).not.toContain("```"); // no example fences
    expect(out).not.toContain("### "); // no per-symbol headings (that's the human page)
    // Exactly one bullet line per symbol across the whole model.
    const totalSymbols = model.units.reduce((n, u) => n + u.symbols.length, 0);
    const bulletLines = out.split("\n").filter((l) => l.startsWith("- `")).length;
    expect(bulletLines).toBe(totalSymbols);
  });

  test("condensation guarantee: agent form stays under the per-symbol byte budget", async () => {
    const { model } = await loadModel();
    const out = renderAgentApi(model, provider);
    const totalSymbols = model.units.reduce((n, u) => n + u.symbols.length, 0);
    // Budget: a generous per-symbol line bound + a small fixed header allowance.
    // The agent form is one line per symbol, so bytes scale ~linearly with the
    // symbol count; this bounds it well under the prose pages.
    const BUDGET = 256 * totalSymbols + 512;
    expect(out.length).toBeLessThan(BUDGET);
    // And materially SMALLER than the sum of the human pages it condenses.
    const humanBytes = model.units.reduce(
      (n, u) => n + renderEntityApiPage(u, provider).length,
      0,
    );
    expect(out.length).toBeLessThan(humanBytes);
  });
});

