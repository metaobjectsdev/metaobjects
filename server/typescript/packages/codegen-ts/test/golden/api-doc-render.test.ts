const EXPECTED_INDEX_FLAT = `<!-- @generated by @metaobjectsdev/codegen-ts — DO NOT EDIT. -->

# API Reference

Generated public API surface, one page per entity and output template.

## Entities

- [Product](./Product.md) — model, 5 data access, 5 REST, 2 validation (13 symbols)
- [SummaryVO](./SummaryVO.md) — model (1 symbol)

## Templates

- [ProductSummary](./ProductSummary.md) — 2 extractor, render (3 symbols)
`;

describe("renderApiIndex — consolidated human index", () => {
  test("byte-exact: grouped entity vs template, per-unit summary + symbol count", async () => {
    const { model } = await loadModel();
    const out = renderApiIndex(model, "flat", provider);
    expect(out).toBe(EXPECTED_INDEX_FLAT);
  });

  test("flat-layout links resolve to ./<node>.md", async () => {
    const { model } = await loadModel();
    const out = renderApiIndex(model, "flat", provider);
    expect(out).toContain("(./Product.md)");
    expect(out).toContain("(./SummaryVO.md)");
    expect(out).toContain("(./ProductSummary.md)");
  });

  test("package-layout links fold under the package path (./acme/shop/<node>.md)", async () => {
    const { model } = await loadModel();
    const out = renderApiIndex(model, "package", provider);
    expect(out).toContain("(./acme/shop/Product.md)");
    expect(out).toContain("(./acme/shop/SummaryVO.md)");
    expect(out).toContain("(./acme/shop/ProductSummary.md)");
    // No bare flat link leaked through in package layout.
    expect(out).not.toContain("(./Product.md)");
  });

  test("singular/plural symbol-count grammar", async () => {
    const { model } = await loadModel();
    const out = renderApiIndex(model, "flat", provider);
    expect(out).toContain("(1 symbol)"); // SummaryVO — exactly one
    expect(out).toContain("(13 symbols)"); // Product — many
  });
});

