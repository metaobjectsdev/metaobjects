// api-doc-render — BYTE-EXACT golden tests for the two documentation FORMS the
// ApiModel feeds: the per-unit HUMAN reference page + the consolidated HUMAN
// index + the condensed AGENT/LLM form. All three render through the SHARED
// render() Mustache engine against the canonical templates under templates/api/
// (resolved via the framework provider — same mechanism as docs-file.ts).
//
// One ApiModel feeds all three forms (no duplicate derivation). The agent form
// is asserted to stay under a per-symbol byte budget — the condensation
// guarantee. Index links are asserted to resolve in BOTH flat and package
// layout via the collision-safe docPageHref helper.

import { describe, test, expect } from "bun:test";
import { MetaDataLoader, InMemoryStringSource } from "@metaobjectsdev/metadata";
import { buildApiModel, type ApiModel, type ApiUnitDoc } from "../../src/generators/api-model.js";
import {
  renderEntityApiPage,
  renderApiIndex,
  renderAgentApi,
} from "../../src/generators/api-doc-render.js";
import { frameworkTemplatesProvider } from "../../src/render-engine/framework-provider.js";

// A multi-entity model (a CRUD entity + a value object) plus a template unit —
// exercises every section kind (model / data-access / rest / validation /
// extractor / render) across the entity vs template grouping.
const CHILDREN = [
  {
    "object.entity": {
      name: "Product",
      children: [
        { "field.long": { name: "id" } },
        { "field.string": { name: "name" } },
        { "identity.primary": { "@fields": "id", "@generation": "increment" } },
        { "source.rdb": { "@table": "products" } },
      ],
    },
  },
  {
    "object.value": {
      name: "SummaryVO",
      children: [{ "field.string": { name: "headline", "@required": true } }],
    },
  },
  {
    "template.output": {
      name: "ProductSummary",
      "@kind": "document",
      "@payloadRef": "SummaryVO",
      "@textRef": "out/product-summary",
      "@format": "json",
    },
  },
];

async function loadModel(): Promise<{ model: ApiModel; root: Awaited<ReturnType<MetaDataLoader["load"]>>["root"] }> {
  const res = await new MetaDataLoader().load([
    new InMemoryStringSource(
      JSON.stringify({ "metadata.root": { package: "acme::shop", children: CHILDREN } }),
      { id: "meta.json", format: "json" },
    ),
  ]);
  expect(res.errors).toEqual([]);
  const root = res.root;
  return { model: buildApiModel(root, { loadedRoot: root }), root };
}

function unit(model: ApiModel, node: string): ApiUnitDoc {
  const u = model.units.find((x) => x.node === node);
  if (!u) throw new Error(`no unit ${node}`);
  return u;
}

const provider = frameworkTemplatesProvider;

