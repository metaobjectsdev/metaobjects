// Item 4: skip-existing strategy E2E test
// ---------------------------------------------------------------------------
describe("runGen — mergeStrategy: 'skip-existing'", () => {
  test("existing generated files are skipped; new entities still written", async () => {
    const loader = new MetaDataLoader();
    const result = await loader.load([new FileSource(join(FIXTURE_DIR, "single-entity.json"))]);
    expect(result.errors).toEqual([]);

    const baseConfig = defineConfig({
      outDir: tmp,
      extStyle: "none",
      dbImport: "~/server/db",
      dialect: "sqlite",
      generators: [entityFile(), queriesFile(), barrel()],
    });

    // First run: overwrite strategy produces new files
    const run1 = await runGen({
      config: baseConfig,
      metadata: result.root,
      mergeStrategy: "overwrite",
    });
    expect(run1.files.every((f) => f.status === "new")).toBe(true);

    // Modify Post.ts slightly (append a comment) — still has @generated header
    const postPath = join(tmp, "Post.ts");
    const original = readFileSync(postPath, "utf-8");
    writeFileSync(postPath, original + "\n// user tweak");

    // Second run: skip-existing — Post.ts should be skipped, content unchanged
    const run2 = await runGen({
      config: baseConfig,
      metadata: result.root,
      mergeStrategy: "skip-existing",
    });

    const postResult = run2.files.find((f) => f.path.endsWith("Post.ts"));
    expect(postResult?.status).toBe("skipped");

    // Content must be unchanged (our tweak comment is still there)
    const afterRun2 = readFileSync(postPath, "utf-8");
    expect(afterRun2).toContain("// user tweak");

    // All other files also skipped (they all have @generated headers)
    for (const f of run2.files) {
      expect(f.status).toBe("skipped");
    }

    // Now add a NEW entity to the root — it should still be written
    const root2 = makeRoot("test");
    // Copy the Post entity from result
    const postEntity = result.root.ownChildren().find((c) => c.name === "Post")!;
    root2.addChild(postEntity);
    root2.addChild(makeEntity("Comment"));

    const run3 = await runGen({
      config: baseConfig,
      metadata: root2,
      mergeStrategy: "skip-existing",
    });

    const commentResult = run3.files.find((f) => f.path.endsWith("Comment.ts"));
    expect(commentResult?.status).toBe("new");

    const postResult3 = run3.files.find((f) => f.path.endsWith("Post.ts"));
    expect(postResult3?.status).toBe("skipped");
  });
});

