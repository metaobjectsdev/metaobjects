let tmp: string;
beforeEach(() => { tmp = mkdtempSync(join(tmpdir(), "codegen-run-gen-")); });
afterEach(() => { rmSync(tmp, { recursive: true, force: true }); });

const FIXTURE_DIR = resolve(import.meta.dir, "fixtures");

describe("runGen — single entity, SQLite", () => {
  test("emits Post.ts, Post.queries.ts, and index.ts in outDir", async () => {
    const loader = new MetaDataLoader();
    const result = await loader.load([new FileSource(join(FIXTURE_DIR, "single-entity.json"))]);
    expect(result.errors).toEqual([]);

    const out = await runGen({
      config: defineConfig({
        outDir: tmp,
        extStyle: "none",
        dbImport: "~/server/db",
        dialect: "sqlite",
        generators: [entityFile(), queriesFile(), routesFile(), barrel()],
      }),
      metadata: result.root,
    });

    // dbImport is set; no warning expected
    expect(out.warnings).toEqual([]);
    const files = readdirSync(tmp);
    expect(files).toContain("Post.ts");
    expect(files).toContain("Post.queries.ts");
    expect(files).toContain("index.ts");

    const postContent = readFileSync(join(tmp, "Post.ts"), "utf-8");
    expect(postContent).toContain("@generated by @metaobjectsdev/codegen-ts");
    expect(postContent).toContain("sqliteTable");
    expect(postContent).toContain("PostInsertSchema");
    expect(postContent).toContain("InferSelectModel");

    const queriesContent = readFileSync(join(tmp, "Post.queries.ts"), "utf-8");
    expect(queriesContent).toContain("@generated by @metaobjectsdev/codegen-ts");
    // FR2 / ADR-0008: queries-file no longer imports a runtime `db` from
    // <dbImport>; it emits a dialect-correct `type Db = ...` alias instead and
    // every CRUD helper takes `db: Db` as its first parameter.
    expect(queriesContent).not.toContain("~/server/db");
    expect(queriesContent).toContain("type Db = BaseSQLiteDatabase");
    expect(queriesContent).toContain("findPostById");
    expect(queriesContent).toContain("createPost");

    const barrelContent = readFileSync(join(tmp, "index.ts"), "utf-8");
    expect(barrelContent).toContain('export * from "./Post"');
    // barrel does NOT re-export from Post.queries.js
    expect(barrelContent).not.toContain("queries");
  });
});

