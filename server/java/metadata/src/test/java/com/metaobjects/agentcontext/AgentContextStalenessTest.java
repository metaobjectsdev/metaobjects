package com.metaobjects.agentcontext;

import org.junit.Test;

import java.util.List;
import java.util.Map;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

/**
 * Unit coverage for the pure agent-context staleness decision — mirrors the TS
 * reference {@code agentContextStaleness}
 * ({@code server/typescript/packages/sdk/src/agent-context/scaffold.ts}):
 *
 * <ul>
 *   <li>no manifest → {@code null} (nothing scaffolded here, nothing to nudge);</li>
 *   <li>{@code generatedBy} EQUALS current → {@code null} (in sync; exact-equality
 *       on purpose, NOT a semver compare — any drift nudges);</li>
 *   <li>{@code generatedBy} DIFFERS → a one-line nudge naming both versions and the
 *       Node CLI refresh command {@code npx meta agent-docs --server java};</li>
 *   <li>{@code generatedBy} ABSENT (legacy manifest) → a nudge with "an older
 *       MetaObjects" as the from-version.</li>
 * </ul>
 *
 * <p>Advisory only — the production method never throws and never blocks.
 */
public class AgentContextStalenessTest {

    // ---- across version lines (the JVM's actual situation) ---------------------
    //
    // Every fixture ABOVE uses a `7.x` generatedBy, and that shape CANNOT OCCUR: the manifest
    // is written only by the Node CLI, which stamps an npm version. Those cases pin the pure
    // function's contract and are correct as such — but they are also why nobody noticed that
    // the JVM was comparing `7.24.1` against `0.24.1` on every build and nudging forever.
    // These cases use the shape production actually produces.

    @Test
    public void sameRelease_acrossLines_isNotStale() {
        assertNull("npm-stamped 0.24.1 vs Maven 7.24.1 is the SAME release — must not nudge",
                AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.24.1"), "7.24.1"));
    }

    @Test
    public void differentRelease_acrossLines_nudgesNamingBothRealVersions() {
        String msg = AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.23.1"), "7.24.1");
        assertNotNull("a real release gap must still nudge", msg);
        // The message names the REAL versions, not the stripped coordinates — a reader has to
        // recognise what is installed and what is on disk.
        assertTrue("should name the stamped version", msg.contains("0.23.1"));
        assertTrue("should name the installed version", msg.contains("7.24.1"));
    }

    @Test
    public void prereleaseDrift_acrossLines_stillNudges() {
        // The pure contract's exact-equality property survives the coordinate reduction:
        // 24.1-rc.1 != 24.1, so an RC-scaffolded context against a final release still nudges.
        assertNotNull(AgentContextScaffold.stalenessAcrossVersionLines(
                manifest("0.24.1-rc.1"), "7.24.1"));
    }

    @Test
    public void absentGeneratedBy_acrossLines_stillNudges() {
        assertNotNull("a legacy manifest with no stamp must not read as in-sync",
                AgentContextScaffold.stalenessAcrossVersionLines(manifest(null), "7.24.1"));
    }

    @Test
    public void nullManifest_acrossLines_isNotStale() {
        assertNull(AgentContextScaffold.stalenessAcrossVersionLines(null, "7.24.1"));
    }

    @Test
    public void releaseCoordinate_stripsOnlyTheLeadingMajor() {
        assertEquals("24.1", AgentContextScaffold.releaseCoordinate("7.24.1"));
        assertEquals("24.1", AgentContextScaffold.releaseCoordinate("0.24.1"));
        assertEquals("24.1-rc.1", AgentContextScaffold.releaseCoordinate("0.24.1-rc.1"));
        // No dot: returned unchanged, so a sentinel cannot accidentally match a real version.
        assertEquals("unknown", AgentContextScaffold.releaseCoordinate("unknown"));
    }

    private static AgentContextScaffold.Manifest manifest(String generatedBy) {
        return new AgentContextScaffold.Manifest(
                1, generatedBy, List.of("java"), List.of("react"), Map.of());
    }

    @Test
    public void noManifestIsNull() {
        assertNull(AgentContextScaffold.staleness(null, "7.2.1"));
    }

    @Test
    public void inSyncIsNull() {
        assertNull(AgentContextScaffold.staleness(manifest("7.2.1"), "7.2.1"));
    }

    @Test
    public void differingVersionNudgesNamingBoth() {
        String msg = AgentContextScaffold.staleness(manifest("7.1.0"), "7.2.1");
        assertEquals(
                "MetaObjects agent context was generated by 7.1.0; you're on 7.2.1. "
                        + "Run 'npx meta agent-docs --server java' to refresh the .claude/skills docs.",
                msg);
    }

    @Test
    public void absentGeneratedByNudgesAsOlder() {
        String msg = AgentContextScaffold.staleness(manifest(null), "7.2.1");
        assertTrue("should name the current version", msg.contains("7.2.1"));
        assertTrue("should describe an older MetaObjects",
                msg.contains("an older MetaObjects"));
        assertTrue("should name the agent-docs refresh goal",
                msg.contains("npx meta agent-docs --server java"));
    }

    // ── the context is AHEAD of the install (publish-what-changed, docs/RELEASING.md) ──
    // A registry publishes only when it has a changed product file, so the JVM legitimately
    // sits behind npm — and `meta agent-docs` (npm, canonical for every port) stamps the
    // NEWER version. Nudging there is #347's shape: the remedy re-stamps the same newer
    // version, so the advisory can never be satisfied and fires forever on a correct setup.
    @Test
    public void contextFromNewerReleaseIsSilent() {
        assertNull(AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.24.7"), "7.24.4"));
    }

    @Test
    public void contextNewerOnlyInPatchIsSilent() {
        assertNull(AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.24.5"), "7.24.4"));
    }

    @Test
    public void contextOlderThanInstallStillNudges() {
        String msg = AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.24.4"), "7.24.7");
        assertNotNull("an older context is what the advisory exists for", msg);
        assertTrue(msg.contains("0.24.4"));
        assertTrue(msg.contains("7.24.7"));
    }

    @Test
    public void matchingCoordinateAcrossLinesStaysSilent() {
        assertNull(AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.24.4"), "7.24.4"));
    }

    // The suppression is deliberately narrow: anything not orderable as a plain release
    // still nudges, preserving the documented "ANY drift nudges" property.
    @Test
    public void prereleaseContextStillNudges() {
        assertNotNull(AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.24.5-rc.1"), "7.24.4"));
    }

    @Test
    public void buildMetadataStillNudges() {
        assertNotNull(AgentContextScaffold.stalenessAcrossVersionLines(manifest("0.24.5+abc"), "7.24.4"));
    }

    @Test
    public void unknownInstalledVersionNeverAssertsInSync() {
        assertNotNull(AgentContextScaffold.stalenessAcrossVersionLines(
                manifest("0.24.7"), AgentContextScaffold.UNKNOWN_VERSION));
    }

    @Test
    public void nonNumericVersionStillNudges() {
        assertNotNull(AgentContextScaffold.stalenessAcrossVersionLines(manifest("dev"), "7.24.4"));
    }

    @Test
    public void legacyManifestWithoutGeneratedByStillNudgesAcrossLines() {
        assertNotNull(AgentContextScaffold.stalenessAcrossVersionLines(manifest(null), "7.24.4"));
    }
}
