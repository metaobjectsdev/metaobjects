package com.metaobjects.agentcontext;

import java.io.InputStream;
import java.util.List;
import java.util.Map;
import java.util.Properties;

/**
 * Sidecar manifest and staleness advisor for the agent-context writer.
 *
 * <p>Scaffold planning has moved to the {@code meta} CLI
 * ({@code npx meta agent-docs --server java}). This class retains the READ-ONLY
 * staleness advisory ({@link #staleness}/{@link #installedVersion}) called by
 * {@code AbstractMetaDataMojo.warnIfAgentContextStale()}.
 */
public final class AgentContextScaffold {

    /** Consumer-relative path of the sidecar manifest that tracks scaffolded files. */
    public static final String MANIFEST_PATH = ".metaobjects/.agent-context.json";

    /**
     * Safe fallback when the installed version can't be resolved from the classpath
     * (mirrors the TS reference's {@code "0.0.0"} fallback). Compares unequal to any
     * real stamped version, so a real {@code generatedBy} always wins the equality
     * check — the nudge stays advisory, never spuriously asserting "in sync".
     */
    public static final String UNKNOWN_VERSION = "0.0.0";

    /** Maven group of the artifact carrying this class — used to find {@code pom.properties}. */
    private static final String MAVEN_GROUP_ID = "com.metaobjects";
    /** Maven artifact carrying this class — used to find {@code pom.properties}. */
    private static final String MAVEN_ARTIFACT_ID = "metaobjects-metadata";

    private AgentContextScaffold() {
    }

    /**
     * Tracks what the assembler last wrote, so re-runs can detect hand-edits.
     *
     * <p>{@code generatedBy} is the MetaObjects version that last scaffolded this agent
     * context. It is stamped so {@code gen}/{@code verify} can nudge a re-scaffold when
     * the installed version moves ahead (the skills/docs ship with the artifact, so an
     * upgrade can leave the copied-in context stale). It may be {@code null} for
     * back-compat with manifests written before version tracking existed (and for
     * cross-read manifests written by another port). Serialized as {@code "generatedBy"}
     * — the SAME key as the TS reference — so a polyglot repo can cross-read it.
     */
    public record Manifest(int version, String generatedBy, List<String> servers,
                           List<String> clients, Map<String, String> files) {
    }

    /**
     * A one-line nudge if the scaffolded agent context predates the installed MetaObjects
     * (so {@code gen}/{@code verify} can remind the user to refresh the skills after an
     * upgrade), or {@code null} when there is nothing to say — no agent context
     * scaffolded, or it is in sync.
     *
     * <p>Pure + advisory: never throws, never blocks, never writes. Direct port of the TS
     * {@code agentContextStaleness}. The equality check is EXACT on purpose — any drift
     * (including a prerelease/build-metadata difference) nudges, because a re-scaffold is
     * cheap + idempotent. Don't "fix" this into a semver compare.
     *
     * @param manifest       the parsed prior manifest, or {@code null} if none on disk.
     * @param currentVersion the installed MetaObjects version (see {@link #installedVersion()}).
     * @return the nudge message, or {@code null} when nothing needs saying.
     */
    public static String staleness(Manifest manifest, String currentVersion) {
        if (manifest == null) {
            return null; // no agent context here → nothing to nudge
        }
        if (currentVersion.equals(manifest.generatedBy())) {
            return null; // in sync
        }
        String from = manifest.generatedBy() != null ? manifest.generatedBy() : "an older MetaObjects";
        return "MetaObjects agent context was generated by " + from + "; you're on "
                + currentVersion + ". Run 'npx meta agent-docs --server java' to refresh "
                + "the .claude/skills docs.";
    }

    /**
     * The comparable coordinate of a version — everything after the leading major.
     *
     * <p>{@code "7.24.1"} and {@code "0.24.1"} both yield {@code "24.1"}. Returns the input
     * unchanged when there is no {@code '.'}, so a malformed or sentinel value never becomes
     * something that accidentally matches.
     */
    static String releaseCoordinate(String version) {
        if (version == null) {
            return null;
        }
        int dot = version.indexOf('.');
        return dot < 0 ? version : version.substring(dot + 1);
    }

    /**
     * {@link #staleness} for a consumer whose installed version sits on a DIFFERENT VERSION
     * LINE from the one that stamped the manifest.
     *
     * <p>This exists because of a fact peculiar to the JVM. The manifest is always stamped by
     * the Node CLI — {@code meta agent-docs} is the canonical scaffolder for every port and the
     * others redirect to it — so {@code generatedBy} is always an npm version ({@code 0.24.1}).
     * The JVM's {@link #installedVersion()} reads the Maven artifact version ({@code 7.24.1}),
     * which carries a historical major of {@code 7} by design. Exact equality between those two
     * is false and always will be, so the plain {@link #staleness} nudged on EVERY build, in
     * perpetuity, including when the context was perfectly in sync. An advisory that cries wolf
     * in the inner loop gets tuned out, and then it is not there for the upgrade it exists for.
     *
     * <p>The fix is in the COORDINATE, not in the comparison: both sides are reduced to the
     * release they name and the equality stays EXACT, so every property {@link #staleness}'s
     * contract defends — prerelease and build-metadata drift still nudging — is preserved. Do
     * not instead relax {@link #staleness} into a semver compare; its javadoc forbids that, and
     * it is right.
     *
     * <p>The four registries NO LONGER share a {@code minor.patch}. Under publish-what-changed
     * (docs/RELEASING.md) a registry publishes only when it has a changed product file, so a
     * port legitimately sits behind npm — and this method's premise, which used to read
     * <em>"correct while the four registries share a minor.patch … a CONVENTION rather than a
     * gate"</em>, is now false BY DESIGN rather than by accident. Both of its failure modes
     * became live: a JVM install at {@code 7.24.4} whose context was scaffolded by npm
     * {@code 0.24.7} reduced to {@code 24.4} vs {@code 24.7} and nudged forever (the remedy
     * re-stamps {@code 0.24.7}, so the advisory could never be satisfied — #347's exact shape),
     * while a JVM sitting at {@code 24.4} across several npm releases reported in-sync across a
     * real gap.
     *
     * <p>{@link #contextIsAheadOfInstall} closes the first, which is the one this rule created:
     * a context stamped by a STRICTLY NEWER release is not stale and must stay silent. The
     * second is narrowed but not closed — equal coordinates still assert in-sync, and only
     * hashing the shipped context could settle it, which this artifact cannot do because the
     * JVM ships no agent-context content (npm {@code meta agent-docs} is the canonical
     * scaffolder for every port).
     *
     * @param manifest       the parsed prior manifest, or {@code null} if none on disk.
     * @param currentVersion the installed version, on this port's own line.
     * @return the nudge message naming BOTH real versions, or {@code null} when in sync.
     */
    public static String stalenessAcrossVersionLines(Manifest manifest, String currentVersion) {
        if (manifest == null) {
            return null;
        }
        String stamped = releaseCoordinate(manifest.generatedBy());
        // A null/absent generatedBy is legacy and must still nudge — delegate, which says so.
        if (stamped != null && stamped.equals(releaseCoordinate(currentVersion))) {
            return null;
        }
        if (contextIsAheadOfInstall(manifest.generatedBy(), currentVersion)) {
            return null;
        }
        // Message construction lives in ONE place; this only decides whether to ask for it.
        // The delegate cannot return null here: the coordinates differ, so the versions do.
        return staleness(manifest, currentVersion);
    }

    /**
     * Ordered release coordinate {@code [minor, patch]}, or {@code null} when not orderable.
     *
     * <p>The MAJOR is deliberately dropped — it is a per-registry constant, not information:
     * npm/PyPI/NuGet ship {@code 0.<m>.<p>} and Maven Central the same {@code <m>.<p>} on its
     * historical major {@code 7}, so minor.patch IS the shared release coordinate. This is the
     * same reduction {@link #releaseCoordinate} makes for equality, parsed for ordering.
     *
     * <p>{@code null} means "not orderable, so nudge", and deliberately covers prereleases
     * ({@code 0.24.5-rc.1}), build metadata ({@code 0.24.5+abc}) and {@link #UNKNOWN_VERSION}.
     * Each must keep nudging: an RC-scaffolded context against a final release is still worth
     * refreshing, and an unresolved install must never assert "in sync".
     */
    static int[] releaseSeries(String version) {
        if (version == null) {
            return null;
        }
        String v = version.trim();
        if (UNKNOWN_VERSION.equals(v)) {
            return null;
        }
        String[] parts = v.split("\\.", -1);
        if (parts.length != 3) {
            return null;
        }
        for (String p : parts) {
            if (p.isEmpty()) {
                return null;
            }
            for (int i = 0; i < p.length(); i++) {
                if (p.charAt(i) < '0' || p.charAt(i) > '9') {
                    return null;
                }
            }
        }
        try {
            return new int[] { Integer.parseInt(parts[1]), Integer.parseInt(parts[2]) };
        } catch (NumberFormatException e) {
            return null;
        }
    }

    /**
     * True when the manifest was stamped by a release STRICTLY NEWER than the install.
     *
     * <p>The one exemption from "any drift nudges". See
     * {@link #stalenessAcrossVersionLines} for why publish-what-changed makes it necessary.
     *
     * <p>KNOWN BOUND, stated rather than hidden: ordering on minor.patch assumes both versions
     * sit in the same release SERIES. That holds for every release to date and after the
     * 1.0/8.0 cut, but not ACROSS it — there a {@code 0.24.x} context against a {@code 1.0.0}
     * install reads as "ahead" and the nudge is suppressed once. A missed advisory, never a
     * wrong action, and re-scaffolding at 1.0 is part of that cut anyway.
     */
    static boolean contextIsAheadOfInstall(String generatedBy, String currentVersion) {
        int[] stamped = releaseSeries(generatedBy);
        int[] installed = releaseSeries(currentVersion);
        if (stamped == null || installed == null) {
            return false; // not orderable → nudge
        }
        return stamped[0] > installed[0] || (stamped[0] == installed[0] && stamped[1] > installed[1]);
    }

    /**
     * The installed MetaObjects version, resolved the idiomatic Maven way: read
     * {@code /META-INF/maven/com.metaobjects/metaobjects-metadata/pom.properties} from the
     * classpath (Maven stamps this into the built jar). Falls back to
     * {@link #UNKNOWN_VERSION} when it can't be resolved (e.g. running from an exploded
     * classes dir in a test/IDE) — mirroring the TS reference's {@code "0.0.0"} fallback.
     * Never throws.
     *
     * @return the installed version, or {@link #UNKNOWN_VERSION}.
     */
    public static String installedVersion() {
        String resource = "/META-INF/maven/" + MAVEN_GROUP_ID + "/" + MAVEN_ARTIFACT_ID
                + "/pom.properties";
        try (InputStream in = AgentContextScaffold.class.getResourceAsStream(resource)) {
            if (in == null) {
                return UNKNOWN_VERSION;
            }
            Properties props = new Properties();
            props.load(in);
            String v = props.getProperty("version");
            return (v == null || v.isBlank()) ? UNKNOWN_VERSION : v.trim();
        } catch (Exception e) {
            return UNKNOWN_VERSION;
        }
    }
}
