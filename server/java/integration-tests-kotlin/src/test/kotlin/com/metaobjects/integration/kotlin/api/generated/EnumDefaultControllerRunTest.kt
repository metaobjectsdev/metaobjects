/**
 * An enum's `@default` is what an untouched record stores. The C# port stored the first member
 * here: its entity started at the CLR default, not at `@default`. The Kotlin create body is the
 * generated data class, and the generated insert writes every column it carries, so the data
 * class must start a field it was not sent at `@default` — a nullable one at null would be written
 * as an explicit NULL, which the column default never sees, and a required one with no ctor
 * default fails to bind at all.
 *
 * Three backings, each required and nullable: string-stored, an int map with a 0 member (0 is not
 * the default), an int map with no 0 member. The table carries the column defaults `meta migrate`
 * writes for this metadata. Generate → compile → H2 (PostgreSQL mode) → POST over MockMvc, as
 * [EnumFilterControllerRunTest] does.
 */
@OptIn(org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi::class)
class EnumDefaultControllerRunTest {

    private val mapper: ObjectMapper = ObjectMapper().registerKotlinModule()

    private val fixture = """{
      "metadata.root": { "package": "acme::setting", "children": [
        { "object.entity": { "name": "Setting", "children": [
            { "source.rdb":   { "@table": "settings" } },
            { "field.long":   { "name": "id" } },
            { "field.string": { "name": "title", "@required": true, "@maxLength": 40 } },
            { "field.enum": { "name": "mode", "@values": ["AUTO", "MANUAL"], "@required": true, "@default": "MANUAL" } },
            { "field.enum": { "name": "optMode", "@values": ["AUTO", "MANUAL"], "@default": "MANUAL" } },
            { "field.enum": { "name": "rank", "@values": ["LOW", "HIGH"], "@intValueMap": { "LOW": 0, "HIGH": 1 },
                "@required": true, "@default": "HIGH" } },
            { "field.enum": { "name": "optRank", "@values": ["LOW", "HIGH"], "@intValueMap": { "LOW": 0, "HIGH": 1 },
                "@default": "HIGH" } },
            { "field.enum": { "name": "band", "@values": ["LOW", "HIGH"], "@intValueMap": { "LOW": 1, "HIGH": 2 },
                "@required": true, "@default": "HIGH" } },
            { "field.enum": { "name": "optBand", "@values": ["LOW", "HIGH"], "@intValueMap": { "LOW": 1, "HIGH": 2 },
                "@default": "HIGH" } },
            { "identity.primary": { "@fields": "id", "@generation": "increment" } }
        ] } }
      ] }
    }""".trimIndent()

    // The DDL meta migrate writes for the fixture: this port's snake_case columns (unquoted, as
    // Exposed addresses them; `rank` is a keyword it quotes), and the column defaults.
    private val ddl = """
        CREATE TABLE settings (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(40) NOT NULL,
          mode TEXT NOT NULL DEFAULT 'MANUAL', opt_mode TEXT DEFAULT 'MANUAL',
          "rank" INTEGER NOT NULL DEFAULT 1, opt_rank INTEGER DEFAULT 1,
          band INTEGER NOT NULL DEFAULT 2, opt_band INTEGER DEFAULT 2)
    """.trimIndent()

    private val columns = listOf("mode", "opt_mode", "\"rank\"", "opt_rank", "band", "opt_band")

    @Test
    fun `a create that sends no enum stores each @default`() = withSettingController("enum_default") { post, raw ->
        val (status, body) = post(mapOf("title" to "omitted"))
        assertEquals(201, status, "POST -> $body")
        assertEquals(listOf<Any?>("MANUAL", "MANUAL", 1, 1, 2, 2), raw("omitted"))
    }

    @Test
    fun `an explicit first member and an explicit null are stored as sent`() = withSettingController("enum_set") { post, raw ->
        val (status, body) = post(mapOf("title" to "set", "mode" to "AUTO", "optMode" to null, "rank" to "LOW",
            "optRank" to null, "band" to "LOW", "optBand" to null))
        assertEquals(201, status, "POST -> $body")
        assertEquals(listOf<Any?>("AUTO", null, 0, null, 1, null), raw("set"))
    }

    private fun withSettingController(
        dbName: String,
        block: (post: (Map<String, Any?>) -> Pair<Int, String>, raw: (String) -> List<Any?>) -> Unit,
    ) {
        val outDir = Files.createTempDirectory("enum-default-")
        try {
            val loader = loadString("enum-default", fixture)
            assertEquals(emptyList(), loader.getErrors().map { it.message }, "fixture must load cleanly")
            for (g in listOf(KotlinEntityGenerator(), KotlinExposedTableGenerator(), KotlinFilterAllowlistGenerator(),
                KotlinSpringControllerGenerator())) {
                g.setArgs(mapOf("outputDir" to outDir.toString()))
                g.execute(loader)
            }
            val sources = Files.walk(outDir).filter { it.isRegularFile() }
                .map { SourceFile.kotlin(outDir.relativize(it).toString().replace('/', '_'), it.readText()) }
                .toList()
            val result = KotlinCompilation().apply {
                this.sources = sources
                inheritClassPath = true
                messageOutputStream = System.out
            }.compile()
            assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode, "generated code failed to compile:\n${result.messages}")

            val db = Database.connect("jdbc:h2:mem:$dbName;DB_CLOSE_DELAY=-1;MODE=PostgreSQL", driver = "org.h2.Driver")
            transaction(db) { exec(ddl) }

            val controller = result.classLoader.loadClass("acme.setting.SettingController")
                .getDeclaredConstructor(ObjectMapper::class.java, jakarta.validation.Validator::class.java)
                .newInstance(mapper, jakarta.validation.Validation.buildDefaultValidatorFactory().validator)
            val converter = MappingJackson2HttpMessageConverter().apply { objectMapper = mapper }
            val mvc = MockMvcBuilders.standaloneSetup(controller).setMessageConverters(converter).build()

            fun post(body: Map<String, Any?>): Pair<Int, String> {
                val res = mvc.perform(request(HttpMethod.POST, URI.create("/api/settings"))
                    .contentType(MediaType.APPLICATION_JSON).content(mapper.writeValueAsString(body))).andReturn().response
                return res.status to res.getContentAsString(StandardCharsets.UTF_8)
            }
            fun raw(title: String): List<Any?> = transaction(db) {
                exec("SELECT ${columns.joinToString(", ")} FROM settings WHERE title = '$title'") { rs ->
                    rs.next()
                    columns.indices.map { i -> rs.getObject(i + 1) }
                }!!
            }
            block(::post, ::raw)
        } finally {
            outDir.toFile().deleteRecursively()
        }
    }
}
