package com.metaobjects.integration.kotlin.api.generated

import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.module.kotlin.registerKotlinModule
import com.metaobjects.generator.kotlin.KotlinEntityGenerator
import com.metaobjects.generator.kotlin.KotlinExposedTableGenerator
import com.metaobjects.generator.kotlin.KotlinFilterAllowlistGenerator
import com.metaobjects.generator.kotlin.KotlinRelationsGenerator
import com.metaobjects.generator.kotlin.KotlinSpringControllerGenerator
import com.metaobjects.metadata.ktx.loadString
import com.tschuchort.compiletesting.KotlinCompilation
import com.tschuchort.compiletesting.SourceFile
import org.jetbrains.exposed.sql.Database
import org.jetbrains.exposed.sql.transactions.transaction
import org.springframework.http.HttpMethod
import org.springframework.http.MediaType
import org.springframework.http.converter.json.MappingJackson2HttpMessageConverter
import org.springframework.test.web.servlet.setup.MockMvcBuilders
import org.springframework.test.web.servlet.request.MockMvcRequestBuilders.request
import java.net.URI
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import kotlin.io.path.isRegularFile
import kotlin.io.path.readText
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * uuid-PK regression: the generated by-id surface must derive its key type from the
 * entity's `identity.primary` field. Before the fix a `field.uuid` PK
 * (`@generation: uuid`) produced Kotlin that DID NOT COMPILE:
 *
 *  - controller: `@PathVariable id: Long` then `pkField eq id` against the Exposed
 *    `Column<UUID>` — a type error at every by-id route (get/update/delete);
 *  - Exposed table: any relationship pointing at the uuid-PK entity emitted
 *    `long("author_id").references(AuthorTable.id)` — `Column<Long>.references(Column<UUID>)`
 *    fails typecheck, breaking the whole generated module;
 *  - relations: the helper param was derived (UUID) but `java.util.UUID` was never
 *    imported — unresolved reference.
 *
 * This drives the GENERATED artifacts through the same generate→compile→load→seed→HTTP
 * pattern as [EnumFilterControllerRunTest] (MockMvc over H2 in PostgreSQL mode), proving
 * a uuid-keyed entity with relationships compiles AND serves by-id requests: GET 200/404,
 * PATCH, DELETE, and an FR-009 `filter[id][eq]=<uuid>` round-trip (the uuid value
 * coercer). Mirrors the C# port, where `RoutesGenerator` derives the PK scalar via
 * `CSharpNaming.ScalarFor` and `Guid` binds correctly.
 */
@OptIn(org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi::class)
class UuidPkControllerRunTest {

    private val mapper: ObjectMapper = ObjectMapper().registerKotlinModule()

    /**
     * uuid-PK Author with BOTH FK shapes against it: Post declares a to-one composition
     * (declared FK `author_id` on posts) and Author declares a to-many composition to
     * Comment (inferred inverse FK `author_id` on comments) — each must be a uuid column.
     */
    private val fixture = """{
      "metadata.root": { "package": "acme::demo", "children": [
        { "object.entity": { "name": "Author", "children": [
            { "source.rdb":   { "@table": "authors" } },
            { "field.uuid":   { "name": "id", "@filterable": true } },
            { "field.string": { "name": "name", "@required": true, "@maxLength": 80, "@filterable": true } },
            { "relationship.composition": { "name": "comments", "@objectRef": "Comment", "@cardinality": "many" } },
            { "identity.primary": { "@fields": "id", "@generation": "uuid" } }
        ] } },
        { "object.entity": { "name": "Post", "children": [
            { "source.rdb":   { "@table": "posts" } },
            { "field.long":   { "name": "id" } },
            { "field.string": { "name": "title", "@required": true, "@maxLength": 200 } },
            { "relationship.composition": { "name": "author", "@objectRef": "Author" } },
            { "identity.primary": { "@fields": "id", "@generation": "increment" } }
        ] } },
        { "object.entity": { "name": "Comment", "children": [
            { "source.rdb":   { "@table": "comments" } },
            { "field.long":   { "name": "id" } },
            { "field.string": { "name": "body", "@required": true, "@maxLength": 400 } },
            { "identity.primary": { "@fields": "id", "@generation": "increment" } }
        ] } }
      ] }
    }""".trimIndent()

    @Test
    fun `uuid-PK entity with relationships compiles and serves by-id requests`() {
        val outDir = Files.createTempDirectory("uuid-pk-")
        try {
            val loader = loadString("uuid-pk", fixture)
            for (g in listOf(
                KotlinEntityGenerator(),
                KotlinExposedTableGenerator(),
                KotlinFilterAllowlistGenerator(),
                KotlinRelationsGenerator(),
                KotlinSpringControllerGenerator(),
            )) {
                g.setArgs(mapOf("outputDir" to outDir.toString()))
                g.execute(loader)
            }

            // 1. COMPILE gate — before the fix this failed with
            //    `Column<Long>.references(Column<UUID>)` (PostTable/CommentTable) and
            //    `pkField eq id` Long-vs-UUID type errors (AuthorController).
            val sources = Files.walk(outDir).filter { it.isRegularFile() }
                .map { SourceFile.kotlin(outDir.relativize(it).toString().replace('/', '_'), it.readText()) }
                .toList()
            val result = KotlinCompilation().apply {
                this.sources = sources
                inheritClassPath = true
                messageOutputStream = System.out
            }.compile()
            assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode,
                "generated uuid-PK artifacts failed to compile:\n${result.messages}")

            // 2. RUN gate — H2 (PostgreSQL mode) + MockMvc against the compiled controller.
            val cl = result.classLoader
            val controllerClass = cl.loadClass("acme.demo.AuthorController")

            val db = Database.connect(
                "jdbc:h2:mem:uuid_pk;DB_CLOSE_DELAY=-1;MODE=PostgreSQL", driver = "org.h2.Driver")
            val aliceId = "123e4567-e89b-12d3-a456-426614174000"
            val ghostId = "00000000-0000-0000-0000-000000000999"
            // `name` must be created quoted-lowercase: Exposed quotes it in generated SQL
            // (it is a keyword in some dialects), and H2 uppercases unquoted identifiers.
            transaction(db) {
                exec("""CREATE TABLE authors (id uuid PRIMARY KEY, "name" varchar(80) NOT NULL)""")
                exec("""INSERT INTO authors (id, "name") VALUES ('$aliceId', 'Alice')""")
            }

            val controller = controllerClass.getDeclaredConstructor().newInstance()
            val converter = MappingJackson2HttpMessageConverter().apply { objectMapper = mapper }
            val mvc = MockMvcBuilders.standaloneSetup(controller).setMessageConverters(converter).build()

            fun exchange(method: String, path: String, body: Any?): Pair<Int, String> {
                val builder = request(HttpMethod.valueOf(method), URI.create(path))
                if (body != null) builder.contentType(MediaType.APPLICATION_JSON).content(mapper.writeValueAsString(body))
                val res = mvc.perform(builder).andReturn().response
                return res.status to res.getContentAsString(StandardCharsets.UTF_8)
            }

            // GET by uuid id — 200 with the row (Spring binds the UUID path variable).
            val (getStatus, getBody) = exchange("GET", "/api/authors/$aliceId", null)
            assertEquals(200, getStatus, "GET by uuid id -> $getBody")
            assertTrue("\"Alice\"" in getBody, "expected Alice in body; saw $getBody")

            // GET a different uuid — 404 envelope (not a 400 binding failure).
            val (missStatus, missBody) = exchange("GET", "/api/authors/$ghostId", null)
            assertEquals(404, missStatus, "GET unknown uuid -> $missBody")

            // FR-009 filter round-trip on the uuid PK (eq) — the uuid value coercer.
            val (filterStatus, filterBody) = exchange("GET", "/api/authors?filter[id][eq]=$aliceId", null)
            assertEquals(200, filterStatus, "filter[id][eq] -> $filterBody")
            assertTrue("\"Alice\"" in filterBody, "expected Alice from uuid filter; saw $filterBody")

            // PATCH by uuid id — update binds + writes.
            val (patchStatus, patchBody) = exchange(
                "PATCH", "/api/authors/$aliceId", mapOf("name" to "Alice Updated"))
            assertEquals(200, patchStatus, "PATCH by uuid id -> $patchBody")
            assertTrue("\"Alice Updated\"" in patchBody, "expected updated name; saw $patchBody")

            // DELETE by uuid id — 204, then the row is gone.
            val (delStatus, _) = exchange("DELETE", "/api/authors/$aliceId", null)
            assertEquals(204, delStatus, "DELETE by uuid id")
            val (goneStatus, _) = exchange("GET", "/api/authors/$aliceId", null)
            assertEquals(404, goneStatus, "GET after DELETE")
        } finally {
            outDir.toFile().deleteRecursively()
        }
    }
}
