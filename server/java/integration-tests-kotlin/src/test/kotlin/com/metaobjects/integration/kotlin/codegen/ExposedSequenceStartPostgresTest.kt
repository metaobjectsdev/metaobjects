package com.metaobjects.integration.kotlin.codegen

import com.metaobjects.generator.kotlin.KotlinExposedTableGenerator
import com.metaobjects.integration.kotlin.PostgresContainer
import com.metaobjects.metadata.ktx.loadString
import com.tschuchort.compiletesting.KotlinCompilation
import com.tschuchort.compiletesting.SourceFile
import org.jetbrains.exposed.sql.Column
import org.jetbrains.exposed.sql.Database
import org.jetbrains.exposed.sql.SchemaUtils
import org.jetbrains.exposed.sql.Table
import org.jetbrains.exposed.sql.insert
import org.jetbrains.exposed.sql.selectAll
import org.jetbrains.exposed.sql.transactions.transaction
import java.nio.file.Files
import kotlin.io.path.isRegularFile
import kotlin.io.path.readText
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * #544, live: a generated Exposed table whose `identity.primary` declares `@sequenceStart: 1000`
 * begins its key at 1000 when `SchemaUtils.create` makes the schema on Postgres. Forward-only, so
 * there is no changed-start case here: Exposed output has no migration path.
 *
 * Second half: the same generated table over the shape the TypeScript migrate engine creates
 * (`GENERATED BY DEFAULT AS IDENTITY`) still gets a database-assigned id on insert, so declaring a
 * start does not break a schema Exposed did not create.
 */
@OptIn(org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi::class)
class ExposedSequenceStartPostgresTest {

    private val model = """{
      "metadata.root": { "package": "acme::demo", "children": [
        { "object.entity": { "name": "Ticket", "children": [
            { "field.long":   { "name": "id" } },
            { "field.string": { "name": "title", "@maxLength": 100 } },
            { "source.rdb":   { "@table": "tickets" } },
            { "identity.primary": { "name": "pk", "@fields": ["id"], "@generation": "increment", "@sequenceStart": 1000 } }
        ] } }
      ] }
    }""".trimIndent()

    private fun generatedTable(): Table {
        val outDir = Files.createTempDirectory("seq-start-")
        try {
            val gen = KotlinExposedTableGenerator()
            gen.setArgs(mapOf("outputDir" to outDir.toString()))
            gen.execute(loadString("seq-start", model))
            val sources = Files.walk(outDir).filter { it.isRegularFile() && it.toString().endsWith(".kt") }
                .toList().map { SourceFile.kotlin(it.fileName.toString(), it.readText()) }
            val result = KotlinCompilation().apply {
                this.sources = sources
                inheritClassPath = true
            }.compile()
            assertEquals(KotlinCompilation.ExitCode.OK, result.exitCode, result.messages)
            val cls = result.classLoader.loadClass("acme.demo.TicketTable")
            return cls.getField("INSTANCE").get(null) as Table
        } finally {
            outDir.toFile().deleteRecursively()
        }
    }

    @Suppress("UNCHECKED_CAST")
    private fun insertAndReadId(db: Database, table: Table): Long = transaction(db) {
        val title = table.columns.first { it.name == "title" } as Column<String>
        val id = table.columns.first { it.name == "id" } as Column<Long>
        table.insert { it[title] = "first" }
        table.selectAll().map { it[id] }.min()
    }

    @Test
    fun `SchemaUtils create begins the key at the declared start`() {
        PostgresContainer().use { pg ->
            val db = Database.connect(pg.jdbcUrl, driver = "org.postgresql.Driver", user = pg.username, password = pg.password)
            val table = generatedTable()
            transaction(db) { SchemaUtils.create(table) }
            assertEquals(1000L, insertAndReadId(db, table))
        }
    }

    @Test
    fun `a schema the migrate engine created keeps assigning ids on insert`() {
        PostgresContainer().use { pg ->
            val db = Database.connect(pg.jdbcUrl, driver = "org.postgresql.Driver", user = pg.username, password = pg.password)
            val table = generatedTable()
            transaction(db) {
                exec("CREATE TABLE tickets (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title varchar(100) NOT NULL)")
            }
            // The identity column's own sequence is tickets_id_seq, the name the generated table draws from.
            assertEquals(1L, insertAndReadId(db, table))
        }
    }
}
