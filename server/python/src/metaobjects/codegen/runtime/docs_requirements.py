"""The requirements pages' builders: the ledger rows and the page data of ``requirements.md``,
``requirements.toon`` and ``agent/requirements.md``.

Mirrors the TypeScript ``requirements-view.ts``, ``requirements-markdown.ts``,
``requirements-toon.ts`` and ``agent-requirements-page.ts``. Every page is a shared Mustache
template (``templates/requirements/`` and ``templates/agent/``) fed the data built here; the
builder makes every decision (heading depth, which title survives, the fact bar, the
demotion of the embedded ledger, every table cell, TOON quoting) and the template only lays
the lines out. The rows and the data are pinned by ``fixtures/docs-page-conformance/``.

Rows and page data are plain dicts, so they compare as JSON values against the corpus. A
value the TypeScript leaves ``undefined`` is an ABSENT key here, as it is in the JSON.

``notes`` is deliberately not a row field: ``documentation.json`` charters it internal-only,
and a renderer cannot leak a field the projection never carries.
"""
from __future__ import annotations

import re
from typing import Any, Callable

from metaobjects.codegen.requirement_walk import walk_requirements
from metaobjects.documentation.doc_constants import DOC_ATTR_DESCRIPTION, DOC_ATTR_TITLE
from metaobjects.meta.core.requirement.requirement_constants import (
    REQUIREMENT_ATTR_COUNTEREXAMPLE,
    REQUIREMENT_ATTR_STATEMENT,
)
from metaobjects.meta.meta_data import MetaData

#: The shared template refs (``<group>/<file>``, resolved by a provider).
REQUIREMENTS_PAGE_REF = "requirements/requirements.md"
REQUIREMENTS_TOON_REF = "requirements/requirements.toon"
AGENT_REQUIREMENTS_PAGE_REF = "agent/requirements.md"

#: The marker the pinned page data carries. It is part of the shared contract (the corpus
#: pins it byte for byte in the page data and the pages), so every port writes this exact line.
GENERATED_MARKER = "<!-- @generated by @metaobjectsdev/codegen-ts — DO NOT EDIT. -->"

#: The TOON row's columns. ORDER is the wire contract.
REQUIREMENTS_TOON_FIELDS = ("path", "subType", "level", "status", "disposition", "claims", "statement")

# --- rows -----------------------------------------------------------------------------


def _string_attr(node: MetaData, name: str) -> str | None:
    """A resolving string attr; "declared but empty" is absent."""
    raw = node.get_meta_attr(name)
    return raw if isinstance(raw, str) and raw != "" else None


def requirement_rows(
    root: MetaData, in_ledger: Callable[[str], bool] | None = None
) -> list[dict[str, Any]]:
    """Every ``requirement.*`` node in the project's ledger, nested ones included, as render-ready
    rows in declaration order. Projects over :func:`walk_requirements`, never re-walks. ``[]`` for a
    model declaring none, which is what lets the surface write nothing."""
    rows: list[dict[str, Any]] = []
    for walked in walk_requirements(root, in_ledger):
        node, view = walked.node, walked.view
        row: dict[str, Any] = {"path": view.path, "depth": view.path.count(".")}
        title = _string_attr(node, DOC_ATTR_TITLE)
        if title is not None:
            row["title"] = title
        row["subType"] = view.sub_type
        if view.level is not None:
            row["level"] = view.level
        if view.status is not None:
            row["status"] = view.status
        disposition = node.disposition()
        if disposition is not None:
            row["disposition"] = disposition
        row["trackedBy"] = list(node.tracked_by())
        for key, attr in (
            ("statement", REQUIREMENT_ATTR_STATEMENT),
            ("counterexample", REQUIREMENT_ATTR_COUNTEREXAMPLE),
            ("description", DOC_ATTR_DESCRIPTION),
        ):
            value = _string_attr(node, attr)
            if value is not None:
                row[key] = value
        row["implementedBy"] = list(node.implemented_by())
        row["claimedConcerns"] = list(dict.fromkeys(t.concern for t in walked.targets))
        rows.append(row)
    return rows


# --- requirements.md ------------------------------------------------------------------


def _heading(depth: int) -> str:
    """``##`` for a root-level requirement, deepening with nesting; ``#`` is the page title."""
    return "#" * min(depth + 2, 6)


def _normalize(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", text.lower())


def _title_restates_leaf(path: str, title: str) -> bool:
    """True when the title says nothing the path's LEAF segment does not already say."""
    return _normalize(path[path.rfind(".") + 1 :]) == _normalize(title)


def _heading_line(row: dict[str, Any]) -> str:
    title = re.sub(r"\s+", " ", row.get("title", "")).strip()
    label = "" if title == "" or _title_restates_leaf(row["path"], title) else f" — {title}"
    return f"{_heading(row['depth'])} {row['path']}{label}"


def _facts(row: dict[str, Any]) -> str:
    parts = [f"`{row['subType']}`"]
    if "level" in row:
        parts.append(f"**L{row['level']}**")
    if "status" in row:
        parts.append(f"status: `{row['status']}`")
    if "disposition" in row:
        parts.append(f"disposition: `{row['disposition']}`")
    if row["trackedBy"]:
        parts.append(f"tracked: {', '.join(row['trackedBy'])}")
    return " · ".join(parts)


def _demote(text: str) -> str:
    """One extra ``#`` on every line that starts a heading, capped at h6."""
    return re.sub(
        r"^(#{1,6}) ", lambda m: "#" * min(len(m.group(1)) + 1, 6) + " ", text, flags=re.MULTILINE
    )


def _entry(row: dict[str, Any], embedded: bool) -> dict[str, Any]:
    line: Callable[[str], str] = _demote if embedded else (lambda text: text)
    entry: dict[str, Any] = {"heading": line(_heading_line(row)), "facts": line(_facts(row))}
    if "statement" in row:
        entry["statement"] = line(row["statement"])
    if "counterexample" in row:
        entry["counterexample"] = line(f"**Counterexample:** {row['counterexample']}")
    if "description" in row:
        entry["description"] = line(row["description"])
    if row["implementedBy"]:
        refs = ", ".join(f"`{c}`" for c in row["implementedBy"])
        entry["implementedBy"] = line(f"**Implemented by:** {refs}")
    return entry


def requirements_ledger_data(rows: list[dict[str, Any]], embedded: bool = False) -> dict[str, Any]:
    """What ``requirements/requirements.md.mustache`` renders. ``embedded`` is the ledger as a
    section of a larger page: no ``# Requirements`` title, every heading one level down."""
    return {
        "embedded": embedded,
        "count": len(rows),
        "plural": "" if len(rows) == 1 else "s",
        "entries": [_entry(r, embedded) for r in rows],
    }


# --- requirements.toon ----------------------------------------------------------------

_NUMERIC_LIKE = re.compile(r"-?[0-9]+(?:\.[0-9]+)?(?:e[+-]?[0-9]+)?", re.IGNORECASE)
_LEADING_ZERO = re.compile(r"0[0-9]+")
_TOON_UNSAFE = re.compile(r'[:"\\\[\]{},\x00-\x1f]')


def toon_cell(value: str | int) -> str:
    """One cell as TOON writes it in a comma-delimited row: a number bare, a string bare when
    safe and quoted (with TOON's escapes) when it is empty, padded, numeric- or literal-looking,
    or carries a delimiter, a colon, a quote, a bracket, a leading ``-`` or a control character."""
    if isinstance(value, int):
        return str(value)
    safe = (
        value != ""
        and value == value.strip()
        and value not in ("true", "false", "null")
        and not _NUMERIC_LIKE.fullmatch(value)
        and not _LEADING_ZERO.fullmatch(value)
        and not _TOON_UNSAFE.search(value)
        and not value.startswith("-")
    )
    if safe:
        return value
    out = ['"']
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def requirements_toon_data(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """What ``requirements/requirements.toon.mustache`` renders: every cell a finished literal."""
    return {
        "count": len(rows),
        "fields": "{" + ",".join(REQUIREMENTS_TOON_FIELDS) + "}",
        "rows": [
            {
                "line": ",".join(
                    toon_cell(cell)
                    for cell in (
                        r["path"],
                        r["subType"],
                        r.get("level", ""),
                        r.get("status", ""),
                        r.get("disposition", ""),
                        " ".join(r["implementedBy"]),
                        r.get("statement", ""),
                    )
                )
            }
            for r in rows
        ],
    }


# --- agent/requirements.md ------------------------------------------------------------


def _node_address(node: MetaData) -> str:
    """The ROOT-level node's resolution key, then the child-name path down to *node*. A claimed
    field has a bare name, so the owner is part of the address."""
    segments: list[str] = []
    cur: MetaData | None = node
    while cur is not None:
        parent = cur.parent
        if parent is None or parent.parent is None:
            segments.append(cur.resolution_key())
            break
        segments.append(cur.name)
        cur = parent
    return ".".join(reversed(segments))


def build_node_index(
    root: MetaData, in_ledger: Callable[[str], bool] | None = None
) -> list[dict[str, Any]]:
    """Invert the walk: claimed node -> the requirements that claim it, sorted by address."""
    by_address: dict[str, dict[str, Any]] = {}
    for walked in walk_requirements(root, in_ledger):
        statement = walked.node.get_meta_attr(REQUIREMENT_ATTR_STATEMENT)
        for target in walked.targets:
            address = _node_address(target.node)
            entry = by_address.setdefault(
                address, {"address": address, "concern": target.concern, "claims": []}
            )
            entry["claims"].append(
                {
                    "path": walked.view.path,
                    "subType": walked.view.sub_type,
                    "level": walked.view.level,
                    "status": walked.view.status,
                    "statement": statement if isinstance(statement, str) and statement != "" else None,
                }
            )
    return sorted(by_address.values(), key=lambda e: e["address"])


def md_cell(text: str) -> str:
    return text.replace("|", "\\|")


def one_line(text: str) -> str:
    """Collapse to one line: a newline would end the table row."""
    return re.sub(r"\s+", " ", text).strip()


def agent_requirements_page_data(
    root: MetaData,
    in_ledger: Callable[[str], bool] | None,
    render_ledger: Callable[[dict[str, Any]], str],
) -> dict[str, Any] | None:
    """The data ``agent/requirements.md.mustache`` renders, or ``None`` for a model declaring no
    requirements (no page). *render_ledger* renders the ``requirements`` template from ledger
    data, so the embedded ledger is that page's own template and cannot disagree with it."""
    rows = requirement_rows(root, in_ledger)
    if not rows:
        return None
    index = build_node_index(root, in_ledger)
    stated: dict[str, dict[str, str]] = {}
    for entry in index:
        for c in entry["claims"]:
            if c["statement"] is not None:
                stated[c["path"]] = {"subType": c["subType"], "statement": c["statement"]}
    statements = [
        {"path": path, "subType": info["subType"], "statement": md_cell(one_line(info["statement"]))}
        for path, info in sorted(stated.items())
    ]

    def claims_cell(entry: dict[str, Any]) -> str:
        cells = []
        for c in entry["claims"]:
            level = "" if c["level"] is None else f" L{c['level']}"
            status = "" if c["status"] is None else f" ({c['status']})"
            cells.append(f"`{c['path']}`{level}{status}")
        return "<br>".join(cells)

    return {
        "generatedMarker": GENERATED_MARKER,
        "hasNodeIndex": len(index) > 0,
        "nodeIndex": [
            {"address": e["address"], "concern": e["concern"], "claims": claims_cell(e)} for e in index
        ],
        "hasStatements": len(statements) > 0,
        "statements": statements,
        # The embedded ledger drops its own H1, demotes every heading one level, and loses its
        # trailing line breaks (the agent template supplies the page's last one).
        "ledger": render_ledger(requirements_ledger_data(rows, embedded=True)).rstrip("\n"),
    }
