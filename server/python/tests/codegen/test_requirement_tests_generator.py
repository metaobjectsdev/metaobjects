def test_a_renderer_hook_replaces_one_test_and_receives_the_digest(tmp_path: Path) -> None:
    seen: list[RequirementTestArgs] = []

    def renderer(args: RequirementTestArgs) -> RenderedTest | None:
        seen.append(args)
        if args.identity.path != "Orders.Recorded":
            return None
        return RenderedTest(imports=(), source=f"def test_custom():\n    assert {args.identity.digest!r}\n")

    files, _ = generate(_load_corpus_case("worked-example"), tmp_path, renderer=renderer)
    source = files["requirements/test_acme_shop_requirements.py"]
    assert "def test_custom():" in source and "def test_req_acme_shop_Orders_Recorded__object_entity" not in source
    assert "def test_req_acme_shop_Orders_Refunded():" in source  # the hook returned None: default kept
    recorded = next(a for a in seen if a.identity.path == "Orders.Recorded")
    assert recorded.identity.digest == "2714aa3925a47959aa5e48ae39d80ed203fd4e2caa046a90aab9e04691d9881a"
    assert recorded.statement == "An order is recorded when it is placed."
    assert recorded.counterexample == "A placed order has no row."
    assert recorded.targets == (("Order", "object.entity"),)
    assert (recorded.disposition, recorded.tracked_by) == (None, ())


