def test_the_generated_tests_run_one_passes_one_has_no_witness_one_asserts_one_is_skipped(
    tmp_path: Path,
) -> None:
    files, _ = generate(_four_outcomes_root(), tmp_path, witness_module="req_witnesses")
    _write_project(
        tmp_path,
        files,
        witnesses=(
            "def req_acme_shop_Passes__object_entity():\n    return None\n\n\n"
            "def req_acme_shop_Asserts__object_entity():\n    assert 1 == 2, 'the witness itself says no'\n"
        ),
    )
    out = _pytest(tmp_path)
    assert "PASSED gen/requirements/test_acme_shop_requirements.py::test_req_acme_shop_Passes__object_entity" in out
    # -rA names a skip by file and line, not by test: the reason is what identifies it.
    assert "SKIPPED [1] gen/requirements/test_acme_shop_requirements.py:" in out
    assert "planned - not built yet" in out
    assert "FAILED gen/requirements/test_acme_shop_requirements.py::test_req_acme_shop_Missing__object_entity" in out
    assert (
        "unimplemented requirement: acme::shop::Missing [object.entity] - write req_witnesses."
        "req_acme_shop_Missing__object_entity() so that it fails when: S fails."
    ) in out
    assert "FAILED gen/requirements/test_acme_shop_requirements.py::test_req_acme_shop_Asserts__object_entity" in out
    assert "the witness itself says no" in out
    assert "2 failed, 1 passed, 1 skipped" in out


