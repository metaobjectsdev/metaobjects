_ENTITY = """
    - object.entity:
        name: Order
        children:
          - field.uuid: { name: id }
          - identity.primary: { name: pk, fields: [id] }
"""


def _load_corpus_case(name: str) -> Any:
    files = sorted((CORPUS / name / "input").iterdir(), key=lambda p: p.name)
    result = MetaDataLoader(strict=True).load([FileSource(p) for p in files])
    assert [str(e) for e in result.errors] == []
    return result.root


def _load_yaml(*documents: str) -> Any:
    result = MetaDataLoader(strict=True).load(
        [InMemoryStringSource(d, format=MetaDataFormat.YAML) for d in documents]
    )
    assert [str(e) for e in result.errors] == []
    return result.root


def _doc(requirements: str, package: str | None = "acme::shop") -> str:
    head = f"metadata:\n  package: {package}\n  children:" if package else "metadata:\n  children:"
    return head + _ENTITY + requirements


def _requirement(name: str, status: str = "live", *, statement: str = "S holds.", counter: str = "S fails.",
                 implemented_by: str = "[Order]", extra: str = "") -> str:
    impl = "" if implemented_by == "" else f"        implementedBy: {implemented_by}\n"
    return (
        f"    - requirement.functional:\n"
        f"        name: {name}\n"
        f"        level: 4\n"
        f"        status: {status}\n"
        f"        statement: {statement}\n"
        f"        counterexample: {counter}\n"
        f"{impl}{extra}"
    )


def generate(root: Any, tmp_path: Path, **options: Any) -> tuple[dict[str, str], list[str]]:
    """Run the generator through the real runner. Returns ({relative path: content}, warnings)."""
    out = tmp_path / "gen"
    result = run_gen(
        GenConfig(out_dir=str(out)), root, generators=[requirement_tests(**options)]
    )
    files = {
        str(Path(full).relative_to(out)): Path(full).read_text(encoding="utf-8")
        for full, _status in result.files
        if not full.endswith("__init__.py")
    }
    return files, result.warnings


