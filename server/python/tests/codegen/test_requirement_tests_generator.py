_AWKWARD = {
    "quotes": 'the GM sees a player\'s "secret" notes',
    "backslash": "a raw C:\\Users path and a trailing backslash\\",
    "newline": "line one\nline two",
    "triple": 'ends with """ and \'\'\' and */ and # and {x}',
}


@pytest.mark.parametrize("label", sorted(_AWKWARD))
def test_prose_that_would_break_a_string_or_a_comment_still_parses_and_the_failure_message_carries_it(
    tmp_path: Path, label: str
) -> None:
    prose = _AWKWARD[label]
    block = "|\n          " + prose.replace("\n", "\n          ")
    root = _load_yaml(
        _doc(_requirement("Probe", statement=block, counter=block, implemented_by="[Order]"))
    )
    files, _ = generate(root, tmp_path)
    source = files["requirements/test_acme_shop_requirements.py"]
    tree = ast.parse(source, feature_version=(3, 9))
    # The counterexample reaches the failure message as the third argument of _run, unaltered
    # (a YAML block scalar keeps one trailing newline).
    literals = [n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)]
    assert prose + "\n" in literals
    # …and the statement sits in the comments, one marker per line, `*/` broken.
    lines = source.splitlines()
    for line in prose.split("\n"):
        assert ("# " + line.replace("*/", "* /")).rstrip() in lines


def _write_project(tmp_path: Path, files: dict[str, str], *, witnesses: str | None) -> None:
    for rel, content in files.items():
        target = tmp_path / "gen" / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    if witnesses is not None:
        (tmp_path / "req_witnesses.py").write_text(witnesses, encoding="utf-8")


def _pytest(tmp_path: Path) -> str:
    done = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-rA", "-p", "no:cacheprovider", "--no-header", "gen"],
        cwd=tmp_path,
        env={"PYTHONPATH": str(tmp_path), "PATH": "/usr/bin:/bin", "PYTHONDONTWRITEBYTECODE": "1"},
        capture_output=True,
        text=True,
    )
    return done.stdout + done.stderr


