def test_a_carriage_return_in_a_counterexample_is_escaped_the_file_parses_and_the_message_carries_it(
    tmp_path: Path, separator: str
) -> None:
    # A double-quoted YAML scalar, so the carriage return is a real character in the value.
    counter = f'"first{separator}second"'
    root = _load_yaml(_doc(_requirement("Probe", counter=counter)))
    files, _ = generate(root, tmp_path, witness_module="req_witnesses")
    source = files["requirements/test_acme_shop_requirements.py"]
    assert "\r" not in source  # a raw carriage return would end the line inside the literal
    tree = ast.parse(source, feature_version=(3, 9))
    expected = "first" + separator.encode().decode("unicode_escape") + "second"
    literals = [n.value for n in ast.walk(tree) if isinstance(n, ast.Constant)]
    assert expected in literals  # the literal holds the exact characters, escaped in the file
    _write_project(tmp_path, files, witnesses="")
    out = _pytest(tmp_path)
    assert "unimplemented requirement:" in out and "so that it fails when: first" in out


