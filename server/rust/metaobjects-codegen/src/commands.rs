//! The `commands` generator: command-line commands over the generated client, one crate per
//! package.
//!
//! A tool that talks to a model's API needs the same commands for every entity: list it,
//! show one row, create, change, delete. They are derivable from the model, so they are
//! generated. For the package `acme::billing` the generator writes:
//!
//! ```text
//! <out>/acme_billing_cli/Cargo.toml     the crate (clap, the package's client and model crates)
//! <out>/acme_billing_cli/src/lib.rs     `Command`, one group per served entity, and `run`
//! <out>/acme_billing_cli/src/<type>.rs  one entity: its `<Name>Command` and its `run`
//! <out>/meta_cli/                       what every command crate uses to build a body and a query
//! ```
//!
//! A crate exports a `clap` `Subcommand` and an asynchronous `run`, and no `main`: the
//! binary, its name, where the API's address comes from and how an answer is printed are the
//! application's. Mounted under a package name, the commands read
//! `app <package> <entity> <verb>`:
//!
//! - `list` takes `--filter field:op=value` (repeatable), `--sort field[:asc|desc]`,
//!   `--limit`, `--offset` and `--count`, checked against the same allowlists the typed
//!   client is built from;
//! - `get <id>`, `update <id>` and `delete <id>` exist when the entity has a single key of
//!   text or a whole number; a view-backed entity has no `create`, `update` or `delete`;
//! - `create` and `update` take the body as `--json` (a JSON object, or `-` for standard
//!   input) and one flag per scalar member, a flag winning over the body. The finished body
//!   is read as the model's create or patch type and held to its `validate()` before
//!   anything is sent, and a member the model does not declare is refused, not dropped;
//! - a many-to-many relationship is a command named after it: `app shop post tags 7`.
//!
//! This generator runs with `entity` and `client`: the crates it writes name theirs.
//!
//! No other port ships this generator. It is recorded as a deliberate difference in the
//! generator registry (`fixtures/generator-registry-conformance/`) and in ADR-0065.

use std::collections::BTreeSet;

use metaobjects_codegen::emitted::COMMAND_HELPERS_RS;
use metaobjects_codegen::generator::{EmittedFile, GenContext, GenError, Generator};
use metaobjects_codegen::names::{literal, pascal, snake};
use metaobjects_codegen::plan::{
    CLI_CRATE, CLI_SUFFIX, CLIENT_CRATE, CLIENT_SUFFIX, CratePlan, FieldPlan, Kind, Plan, Presence,
    Route, SUPPORT_CRATE, StructPlan, Ty,
};
use metaobjects_codegen::writer::{
    CodeWriter, Manifest, RUSTFMT_TOML, file, fixed, item, list, padded, piece, sibling_dep,
    toml_string,
};

/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects commands generator. Do not edit: change the model and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects commands generator. Do not edit: change the model and run `cargo meta gen`.";

/// The commands generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct CommandsGenerator;

impl Generator for CommandsGenerator {
    fn name(&self) -> &str {
        "commands"
    }

    fn identity(&self) -> String {
        format!("commands:{FORMAT}")
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl CommandsParts for CommandsGenerator {}

/// The pieces of the commands generator's output, one method each (ADR-0063 item 7). Each
/// default is the shipped piece: implement this for a generator of your own, override the
/// piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape). An override can call the
/// shipped piece, a public function of this module with the same name. Not a stability
/// contract: the methods may change in a minor release, and the CHANGELOG says when.
pub trait CommandsParts {
    /// Every file: one command crate per package with a served entity, then the helper
    /// crate when there is any.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// The helper crate's files.
    fn helper_crate(&self) -> Vec<EmittedFile> {
        helper_crate()
    }

    /// A command crate's `Cargo.toml`, with a dependency on each crate in `deps`.
    fn manifest(&self, name: &str, c: &CratePlan, deps: &[&str]) -> String {
        cargo_toml(name, c, deps)
    }

    /// A command crate's `src/lib.rs`: its modules and the `Command` and `run` over them.
    /// Each group is a module, its entity's type name and its route path.
    fn lib_file(
        &self,
        package: &str,
        groups: &[(String, String, String)],
    ) -> Result<String, GenError> {
        lib_file(package, groups)
    }

    /// One served entity's file: its subcommands and how each runs.
    fn entity_file(
        &self,
        s: &StructPlan,
        route: &Route,
        model_crate: &str,
        client_crate: &str,
    ) -> Result<String, GenError> {
        entity_file(s, route, model_crate, client_crate)
    }
}

/// The shipped [`CommandsParts::render`], through `parts`.
pub fn render<P: CommandsParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let plan = Plan::of(ctx)?;
    let selected = plan.selected_crates(ctx.entities)?;
    let mut files = Vec::new();
    for (cname, c) in &plan.crates {
        if selected.as_ref().is_some_and(|sel| !sel.contains(cname)) {
            continue;
        }
        command_crate(parts, &plan, cname, c, &mut files)?;
    }
    if !files.is_empty() {
        files.extend(parts.helper_crate());
    }
    Ok(files)
}

// ---- the helper crate ------------------------------------------------------------------

/// The crate of helpers the command crates share. It is generated, so the output depends on
/// nothing from MetaObjects.
pub fn helper_crate() -> Vec<EmittedFile> {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, CLI_CRATE);
    m.entry(
        "description",
        &toml_string("What the generated MetaObjects command crates build a request with."),
    );
    m.blank().table("dependencies");
    m.entry("serde", &toml_string("1"));
    m.entry("serde_json", &toml_string("1"));
    m.entry(CLIENT_CRATE, &sibling_dep(CLIENT_CRATE));
    m.entry(SUPPORT_CRATE, &sibling_dep(SUPPORT_CRATE));
    let manifest = m.finish();
    let file = |name: &str, text: String| EmittedFile::new(format!("{CLI_CRATE}/{name}"), text);
    vec![
        file("Cargo.toml", manifest),
        file("rustfmt.toml", RUSTFMT_TOML.to_string()),
        file("src/lib.rs", fixed(BANNER, COMMAND_HELPERS_RS)),
    ]
}

// ---- one command crate -----------------------------------------------------------------

fn command_crate<P: CommandsParts + ?Sized>(
    parts: &P,
    plan: &Plan,
    cname: &str,
    c: &CratePlan,
    files: &mut Vec<EmittedFile>,
) -> Result<(), GenError> {
    let served: Vec<&StructPlan> = plan.served(c).collect();
    if served.is_empty() {
        return Ok(());
    }
    let name = format!("{cname}{CLI_SUFFIX}");
    let client_crate = format!("{cname}{CLIENT_SUFFIX}");
    let mut groups: Vec<(String, String, String)> = Vec::new();
    for s in &served {
        let route = s.route.as_ref().expect("a served entity has a route");
        groups.push((s.module(), s.type_name.clone(), route.path.clone()));
        let text = parts.entity_file(s, route, cname, &client_crate)?;
        files.push(EmittedFile::new(
            format!("{name}/src/{}.rs", s.module()),
            text,
        ));
    }
    groups.sort();
    let manifest = parts.manifest(&name, c, &[cname, &client_crate]);
    files.push(EmittedFile::new(format!("{name}/Cargo.toml"), manifest));
    files.push(EmittedFile::new(
        format!("{name}/rustfmt.toml"),
        RUSTFMT_TOML.to_string(),
    ));
    files.push(EmittedFile::new(
        format!("{name}/src/lib.rs"),
        parts.lib_file(&c.package, &groups)?,
    ));
    Ok(())
}

/// The shipped [`CommandsParts::manifest`].
pub fn cargo_toml(name: &str, c: &CratePlan, deps: &[&str]) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "Commands over the REST API of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    m.entry("clap", r#"{ version = "4", features = ["derive"] }"#);
    m.entry("serde_json", &toml_string("1"));
    for dep in [CLI_CRATE, CLIENT_CRATE]
        .into_iter()
        .chain(deps.iter().copied())
    {
        m.entry(dep, &sibling_dep(dep));
    }
    m.finish()
}

/// A match arm with one expression for a body: on one line when it fits, and in a block
/// when it does not, which is where rustfmt puts it.
fn arm(w: &mut CodeWriter, pattern: &str, body: &str) {
    let one_line = format!("{pattern} => {body},");
    if w.fits(&one_line) {
        w.line(one_line);
    } else {
        w.block(format!("{pattern} => {{"), |w| {
            w.line(body);
        });
    }
}

/// The shipped [`CommandsParts::lib_file`].
pub fn lib_file(package: &str, groups: &[(String, String, String)]) -> Result<String, GenError> {
    let mut w = CodeWriter::new();
    if package.is_empty() {
        w.line("//! Commands over the REST API of the MetaObjects model that declares no package.");
    } else {
        w.line(format!(
            "//! Commands over the REST API of the MetaObjects package `{package}`."
        ));
    }
    w.line("//!");
    w.line("//! Mount `Command` in your own `clap` parser and hand what it parsed to `run`.");
    w.blank();
    for (module, _, _) in groups {
        w.line(format!("mod {module};"));
    }
    w.blank();
    for (module, type_name, _) in groups {
        w.line(format!("pub use {module}::{type_name}Command;"));
    }
    let head = w.finish()?;
    let what = if package.is_empty() {
        "What to do with the model.".to_string()
    } else {
        format!("What to do in the `{package}` package.")
    };
    let command = item(|w| {
        w.prose(&what);
        w.line("#[derive(Debug, clap::Subcommand)]");
        w.block("pub enum Command {", |w| {
            for (_, type_name, path) in groups {
                w.prose(&format!("Work with `{path}`."));
                w.line("#[command(subcommand)]");
                w.line(format!("{type_name}({type_name}Command),"));
            }
        });
    })?;
    let run = item(|w| {
        w.prose("Runs one command against the API. Returns what the server answered, as JSON.");
        let head = piece![
            "pub async fn run",
            list(
                "(",
                [
                    "command: Command".to_string(),
                    format!("client: &{CLIENT_CRATE}::Client")
                ],
                ")"
            ),
            format!(" -> {CLI_CRATE}::Answer {{")
        ];
        w.block(head, |w| {
            w.block("match command {", |w| {
                for (module, type_name, _) in groups {
                    arm(
                        w,
                        &format!("Command::{type_name}(command)"),
                        &format!("{module}::run(command, client).await"),
                    );
                }
            });
        });
    })?;
    Ok(file(BANNER, &[head, command, run]))
}

// ---- one entity ------------------------------------------------------------------------

/// The names a `run` arm uses itself, which a flag's binding must not take.
const LOCALS: &[&str] = &["api", "body", "client", "command", "found", "json", "query"];

/// The flags clap or the command already has, so a member of that name has none.
const RESERVED_FLAGS: &[&str] = &["help", "json"];

/// One member a command sets from a flag.
struct Flag<'a> {
    field: &'a FieldPlan,
    /// The type of the flag's value: `Option<T>`, or `Vec<T>` for an array.
    ty: String,
    /// The name the flag's value is bound to in `run`.
    binding: String,
}

/// The flags of a create (`patch` false) or an update (`patch` true): one per scalar member
/// of the body. A nested value, a map, and a member whose name a flag already has are set
/// through `--json` only.
fn flags(s: &StructPlan, patch: bool, has_id: bool) -> Vec<Flag<'_>> {
    let mut out = Vec::new();
    for f in &s.fields {
        let carried = if patch {
            f.patch
        } else {
            f.create != Presence::Absent
        };
        let bare = f.bare_ident();
        if !carried
            || matches!(f.kind, Kind::Object | Kind::Map)
            || RESERVED_FLAGS.contains(&bare)
            || (has_id && bare == "id")
        {
            continue;
        }
        let value = render_prim(&f.ty);
        let ty = if f.array {
            format!("Vec<{value}>")
        } else {
            format!("Option<{value}>")
        };
        let mut binding = f.ident.clone();
        while LOCALS.contains(&binding.as_str()) || (has_id && binding == "id") {
            binding = format!("{}_flag", binding.strip_prefix("r#").unwrap_or(&binding));
        }
        out.push(Flag {
            field: f,
            ty,
            binding,
        });
    }
    out
}

fn body_variant(w: &mut CodeWriter, doc: &str, name: &str, flags: &[Flag<'_>]) {
    w.prose(doc);
    w.block_with(format!("{name} {{"), "},", |w| {
        w.prose(
            "The body as a JSON object, or `-` to read it from standard input. A flag sets its member over the body's.",
        );
        w.line("#[arg(long, value_name = \"JSON\")]");
        w.line("json: Option<String>,");
        for flag in flags {
            let f = flag.field;
            match f.doc.as_deref().and_then(|d| d.lines().next()) {
                Some(doc) => w.prose(&format!("Sets `{}`: {doc}", f.wire)),
                None => w.prose(&format!("Sets `{}`.", f.wire)),
            };
            w.line("#[arg(long)]");
            w.line(format!("{}: {},", f.ident, flag.ty));
        }
    });
}

/// The pattern of a body command's arm, each flag bound to a name `run` does not use itself.
fn body_pattern(has_id: bool, flags: &[Flag<'_>]) -> Vec<String> {
    let mut bound = Vec::new();
    if has_id {
        bound.push("id".to_string());
    }
    bound.push("json".to_string());
    for flag in flags {
        if flag.binding == flag.field.ident {
            bound.push(flag.binding.clone());
        } else {
            bound.push(format!("{}: {}", flag.field.ident, flag.binding));
        }
    }
    bound
}

fn body_statements(w: &mut CodeWriter, flags: &[Flag<'_>], body_type: &str) {
    w.line(format!(
        "let mut body = {CLI_CRATE}::body(json.as_deref())?;"
    ));
    w.line(format!("{CLI_CRATE}::known(&body, MEMBERS)?;"));
    for flag in flags {
        let function = if flag.field.array { "put_all" } else { "put" };
        w.line(list(
            &format!("{CLI_CRATE}::{function}("),
            [
                "&mut body".to_string(),
                literal(&flag.field.wire),
                flag.binding.clone(),
            ],
            ")?;",
        ));
    }
    w.assign(
        &format!("let body: {body_type} ="),
        format!("{CLI_CRATE}::decode(body)?;"),
    );
    w.line(format!("{CLI_CRATE}::check(body.validate())?;"));
}

/// The shipped [`CommandsParts::entity_file`].
pub fn entity_file(
    s: &StructPlan,
    route: &Route,
    model_crate: &str,
    client_crate: &str,
) -> Result<String, GenError> {
    let command = format!("{}Command", s.type_name);
    let key = route.key.map(|k| &s.fields[k]);
    let id_line = key.map(|f| {
        let ty = render_prim(&f.ty);
        format!("id: {ty},")
    });
    // How `run` hands the key to the client: text is borrowed, a number is copied.
    let id_arg = match key {
        Some(f) if f.ty == Ty::Str => "&id",
        _ => "id",
    };
    let id_doc = key.map(|f| format!("The row's `{}`.", f.wire));
    let writes = !route.read_only;
    let create_flags = if writes {
        flags(s, false, false)
    } else {
        Vec::new()
    };
    let update_flags = if writes && key.is_some() {
        flags(s, true, true)
    } else {
        Vec::new()
    };
    let mut seen = BTreeSet::new();
    // (variant, command name, relation, client method)
    let related: Vec<(String, String, String, String)> = route
        .traversals
        .iter()
        .filter(|_| key.is_some())
        .filter_map(|t| {
            let variant = format!("Related{}", pascal(&t.name));
            if !seen.insert(variant.clone()) {
                return None;
            }
            let mut name = snake(&t.name).replace('_', "-");
            if FIXED_VERBS.contains(&name.as_str()) {
                name.push_str("-of");
            }
            Some((
                variant,
                name,
                t.name.clone(),
                format!("{}_of", snake(&t.name)),
            ))
        })
        .collect();
    let filter_names: Vec<&str> = s.filterable().map(|f| f.wire.as_str()).collect();
    let sort_names: Vec<&str> = s.sortable().map(|f| f.wire.as_str()).collect();
    let listed = |names: &[&str]| {
        if names.is_empty() {
            "none".to_string()
        } else {
            names.join(", ")
        }
    };

    let id_field = |w: &mut CodeWriter| {
        if let (Some(doc), Some(line)) = (&id_doc, &id_line) {
            w.prose(doc);
            w.line(line);
        }
    };
    let declaration = item(|w| {
        w.prose(&format!("What to do with `{}`.", route.path));
        w.line("#[derive(Debug, clap::Subcommand)]");
        w.block(format!("pub enum {command} {{"), |w| {
            w.prose("List rows.");
            w.block_with("List {", "},", |w| {
                w.prose(&format!(
                    "Keep the rows that pass a test, written `field:op=value` (`field=value` means `eq`). Repeat it to add tests. Fields: {}.",
                    listed(&filter_names)
                ));
                w.line("#[arg(long, value_name = \"FIELD:OP=VALUE\")]");
                w.line("filter: Vec<String>,");
                w.prose(&format!(
                    "Sort by a field: `field`, `field:asc` or `field:desc`. Fields: {}.",
                    listed(&sort_names)
                ));
                w.line("#[arg(long, value_name = \"FIELD[:asc|desc]\")]");
                w.line("sort: Option<String>,");
                w.prose("Return at most this many rows.");
                w.line("#[arg(long)]");
                w.line("limit: Option<u64>,");
                w.prose("Skip this many rows.");
                w.line("#[arg(long)]");
                w.line("offset: Option<u64>,");
                w.prose("Also report how many rows the tests match in all.");
                w.line("#[arg(long)]");
                w.line("count: bool,");
            });
            if key.is_some() {
                w.prose("Show one row.");
                w.block_with("Get {", "},", id_field);
            }
            if writes {
                body_variant(w, "Create a row.", "Create", &create_flags);
            }
            if writes && key.is_some() {
                w.prose("Change one row: only the members given.");
                w.block_with("Update {", "},", |w| {
                    id_field(w);
                    w.prose(
                        "The change as a JSON object, or `-` to read it from standard input. A flag sets its member over the body's; a member set to `null` here is cleared.",
                    );
                    w.line("#[arg(long, value_name = \"JSON\")]");
                    w.line("json: Option<String>,");
                    for flag in &update_flags {
                        w.prose(&format!("Sets `{}`.", flag.field.wire));
                        w.line("#[arg(long)]");
                        w.line(format!("{}: {},", flag.field.ident, flag.ty));
                    }
                });
                w.prose("Delete one row.");
                w.block_with("Delete {", "},", id_field);
            }
            for (variant, name, relation, _) in &related {
                w.prose(&format!("List the `{relation}` of one row."));
                w.line(format!("#[command(name = {})]", literal(name)));
                w.block_with(format!("{variant} {{"), "},", id_field);
            }
        });
    })?;

    let members = item(|w| {
        w.prose("Every member the model declares on this entity, by its name on the wire.");
        let names = s.fields.iter().map(|f| literal(&f.wire));
        w.assign("const MEMBERS: &[&str] =", list("&[", names, "];"));
    })?;

    let api = format!("{client_crate}::{}", s.client_name());
    let query = format!("{client_crate}::{}", s.query_name());
    let run = item(|w| {
        w.prose("Runs one command against the API. Returns what the server answered, as JSON.");
        let head = piece![
            "pub async fn run",
            list(
                "(",
                [
                    format!("command: {command}"),
                    format!("client: &{CLIENT_CRATE}::Client")
                ],
                ")"
            ),
            format!(" -> {CLI_CRATE}::Answer {{")
        ];
        w.block(head, |w| {
            w.assign("let api =", format!("{api}::new(client);"));
            w.block("match command {", |w| {
                w.block(
                    format!("{command}::List {{ filter, sort, limit, offset, count }} => {{"),
                    |w| {
                        w.line(format!("let mut query = {CLIENT_CRATE}::Query::new();"));
                        w.line(list(
                            &format!("{CLI_CRATE}::filters("),
                            [
                                "&mut query".to_string(),
                                "&filter".to_string(),
                                format!("{query}::FILTERS"),
                            ],
                            ")?;",
                        ));
                        w.line(list(
                            &format!("{CLI_CRATE}::sort("),
                            [
                                "&mut query".to_string(),
                                "sort.as_deref()".to_string(),
                                format!("{query}::SORTS"),
                            ],
                            ")?;",
                        ));
                        w.line(format!("{CLI_CRATE}::window(&mut query, limit, offset);"));
                        w.assign("let query =", format!("{query}::raw(query);"));
                        w.block("if count {", |w| {
                            w.line("let found = api.page(&query).await?;");
                            w.line(format!("return {CLI_CRATE}::answer(&found);"));
                        });
                        w.line("let found = api.list(&query).await?;");
                        w.line(format!("{CLI_CRATE}::answer(&found)"));
                    },
                );
                if key.is_some() {
                    w.block(format!("{command}::Get {{ id }} => {{"), |w| {
                        w.line(format!("let found = api.get({id_arg}).await?;"));
                        w.line(format!("{CLI_CRATE}::answer(&found)"));
                    });
                }
                if writes {
                    let pattern = body_pattern(false, &create_flags);
                    let head = padded(&format!("{command}::Create {{"), pattern, "} => {");
                    w.block(head, |w| {
                        let body_type = format!("{model_crate}::{}", s.create_name());
                        body_statements(w, &create_flags, &body_type);
                        w.line("let found = api.create(&body).await?;");
                        w.line(format!("{CLI_CRATE}::answer(&found)"));
                    });
                }
                if writes && key.is_some() {
                    let pattern = body_pattern(true, &update_flags);
                    let head = padded(&format!("{command}::Update {{"), pattern, "} => {");
                    w.block(head, |w| {
                        let body_type = format!("{model_crate}::{}", s.patch_name());
                        body_statements(w, &update_flags, &body_type);
                        w.line(format!("let found = api.update({id_arg}, &body).await?;"));
                        w.line(format!("{CLI_CRATE}::answer(&found)"));
                    });
                    w.block(format!("{command}::Delete {{ id }} => {{"), |w| {
                        w.line(format!("api.delete({id_arg}).await?;"));
                        w.line("Ok(serde_json::Value::Null)");
                    });
                }
                for (variant, _, _, method) in &related {
                    w.block(format!("{command}::{variant} {{ id }} => {{"), |w| {
                        w.line(format!("let found = api.{method}({id_arg}).await?;"));
                        w.line(format!("{CLI_CRATE}::answer(&found)"));
                    });
                }
            });
        });
    })?;
    let mut items = vec![declaration];
    if writes {
        items.push(members);
    }
    items.push(run);
    Ok(file(BANNER, &items))
}

/// The verbs a generated command already owns; a traversal named like one gets `-of`.
const FIXED_VERBS: &[&str] = &["list", "get", "create", "update", "delete", "help"];

/// A whole-number key's type.
fn render_prim(ty: &Ty) -> String {
    match ty {
        Ty::Prim(p) => (*p).to_string(),
        _ => "String".to_string(),
    }
}
