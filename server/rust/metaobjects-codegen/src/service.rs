/// How a file names the things its bodies use.
struct Names {
    /// The store module: `store` in an entity's file, the module's own name elsewhere.
    store: String,
    /// The row type: `Row` in an entity's file, its path elsewhere.
    row: String,
    /// The entity's rules module and the alias the file names it by.
    rules: Option<(String, String)>,
}

impl Names {
    /// `path` (a rules crate path) through the file's alias.
    fn rules_path(&self, path: &str) -> String {
        match &self.rules {
            Some((full, alias)) => path.replacen(full.as_str(), alias, 1),
            None => path.to_string(),
        }
    }
}

/// A method body: statements and blocks, which [`Body::write`] lays out through the writer.
#[derive(Default)]
struct Body(Vec<Stmt>);

enum Stmt {
    Line(String),
    Block {
        head: String,
        body: Body,
        tail: String,
    },
}

impl Body {
    fn line(&mut self, text: impl Into<String>) -> &mut Self {
        self.0.push(Stmt::Line(text.into()));
        self
    }

    /// `head`, the statements `build` adds one level in, then `tail`.
    fn block(
        &mut self,
        head: impl Into<String>,
        tail: &str,
        build: impl FnOnce(&mut Body),
    ) -> &mut Self {
        let mut body = Body::default();
        build(&mut body);
        self.0.push(Stmt::Block {
            head: head.into(),
            body,
            tail: tail.to_string(),
        });
        self
    }

    fn append(&mut self, other: Body) -> &mut Self {
        self.0.extend(other.0);
        self
    }

    fn write(&self, w: &mut CodeWriter) {
        for s in &self.0 {
            match s {
                Stmt::Line(text) => {
                    w.line(text.as_str());
                }
                Stmt::Block { head, body, tail } => {
                    w.block_with(head.as_str(), tail.as_str(), |w| body.write(w));
                }
            }
        }
    }
}

/// The `impl` block a file holds its methods in, as one item.
fn impl_block(s: &ServicePackage, body: impl FnOnce(&mut CodeWriter)) -> String {
    let params = s.generics();
    item(|w| {
        w.where_block(
            format!("impl<{params}> crate::{}<{params}>", s.service),
            &s.bounds(),
            body,
        );
    })
    .expect("an impl block closes every block")
}

/// `pub async fn <name>(&self, <params>) -> Result<<ret>, ServiceError> { <body> }`.
fn method(w: &mut CodeWriter, doc: &str, name: &str, params: &[String], ret: &str, body: &Body) {
    w.blank();
    w.prose(doc);
    let mut all = vec!["&self".to_string()];
    all.extend(params.iter().cloned());
    let head = piece![
        format!("pub async fn {name}"),
        list("(", all, ")"),
        format!(" -> Result<{ret}, ServiceError> {{")
    ];
    w.block(head, |w| body.write(w));
}

/// A write and its `_in` twin: the write opens a transaction and runs the twin in it.
fn write_pair(
    w: &mut CodeWriter,
    doc: &str,
    name: &str,
    params: &[String],
    ret: &str,
    body: &Body,
) {
    let outer: Vec<String> = params
        .iter()
        .map(|p| p.trim_start_matches("mut ").to_string())
        .collect();
    let args: Vec<String> = outer
        .iter()
        .map(|p| p.split(':').next().unwrap_or("").trim().to_string())
        .collect();
    let mut begin = Body::default();
    begin
        .line("let mut tx = self.db.begin().await?;")
        .line(format!(
            "let out = self.{name}_in(&mut *tx, {}).await;",
            args.join(", ")
        ))
        .line("meta_service::finish::<D, _>(tx, out).await");
    method(
        w,
        &format!("{doc} In one transaction."),
        name,
        &outer,
        ret,
        &begin,
    );
    let mut inner = vec!["conn: &mut D::Conn".to_string()];
    inner.extend(params.iter().cloned());
    method(
        w,
        &format!("`{name}` on `conn`, inside the caller's transaction."),
        &format!("{name}_in"),
        &inner,
        ret,
        body,
    );
}

/// The permission point: refuse unless the policy allows.
fn permission_check(
    s: &ServicePackage,
    permission: Option<&String>,
    row: bool,
    input: bool,
) -> Body {
    let mut b = Body::default();
    let Some(p) = permission else {
        b.line("// It is @public: no permission point.");
        return b;
    };
    let rules = s.rules.as_deref().unwrap_or_default();
    if row {
        b.line("let row_json = meta_service::json(&current);");
    }
    if input {
        b.line("let input_json = meta_service::json(&input);");
    }
    b.line(format!(
        "let seen = ({}, {});",
        if row { "Some(&row_json)" } else { "None" },
        if input { "Some(&input_json)" } else { "None" },
    ))
    .line(format!("let permission = {rules}::Permission::{p};"))
    .line("let allowed = self.policy.allows(permission, actor, seen.0, seen.1, &mut *conn);")
    .block("if !allowed.await? {", "}", |b| {
        b.line("return Err(ServiceError::Forbidden);");
    });
    b
}

/// The const a move's `@condition` is written in.
fn condition_const(operation: &str, m: &ServiceMove) -> String {
    format!(
        "{}_{}_CONDITION",
        snake(operation).to_uppercase(),
        snake(&m.name).to_uppercase()
    )
}

/// The consts of the conditions of `moves`.
fn condition_items(operation: &str, moves: &[&ServiceMove]) -> Vec<String> {
    moves
        .iter()
        .filter_map(|m| {
            let c = m.condition.as_ref()?;
            Some(
                item(|w| {
                    w.prose(&format!("The `@condition` of `{}`, as JSON.", m.name));
                    w.line(format!(
                        "const {}: &str = {};",
                        condition_const(operation, m),
                        raw_literal(c)
                    ));
                })
                .expect("a const opens no block"),
            )
        })
        .collect()
}

/// The guarded update of `m` and the transition event; `current` is the loaded row.
fn make_move(n: &Names, e: &ServiceEntity, m: &ServiceMove, operation: &str) -> Body {
    let condition = match &m.condition {
        Some(_) => format!("Some({})", condition_const(operation, m)),
        None => "None".to_string(),
    };
    let field = literal(&m.field);
    let mut b = Body::default();
    b.line(format!("let condition = {condition};"))
        .line("let (from, to) = (t.from(), t.to());")
        .line(format!(
            "let m = meta_service::Move {{ field: {field}, from, to, condition }};"
        ))
        .line(format!(
            "meta_service::make_move(&mut *conn, &{}::TABLE, &id, &m).await?;",
            n.store
        ))
        .line("let mut event = WriteEvent::new(WriteKind::Transition, actor);")
        .line(format!(
            "event.entity = Some({});",
            literal(&e.store.object)
        ))
        .line("event.key = Some(meta_service::json(&id));")
        .line(format!("event.operation = Some({});", literal(operation)))
        .line(format!("event.lifecycle = Some({field});"))
        .line(format!("event.transition = Some({});", literal(&m.name)))
        .line(format!(
            "event.from = Some(meta_service::state_name(&current.{}));",
            m.ident
        ))
        .line("event.to = Some(meta_service::state_name(&m.to));")
        .line("self.events.on_write(&event, &mut *conn).await?;");
    b
}

/// `r#"..."#` text that holds `text` as written.
fn raw_literal(text: &str) -> String {
    let mut hashes = String::from("#");
    while text.contains(&format!("\"{hashes}")) {
        hashes.push('#');
    }
    format!("r{hashes}\"{text}\"{hashes}")
}

/// Load the row `id` names into `current`: under a row lock for a write.
fn load(n: &Names, lock: bool) -> Body {
    let read = if lock {
        format!(
            "meta_store::get_for_update(&mut *conn, &{}::TABLE, id)",
            n.store
        )
    } else {
        format!("{}::get(&mut *conn, id)", n.store)
    };
    let mut b = Body::default();
    b.line(format!("let current = {read}.await?;"))
        .line(format!(
            "let current: {} = current.ok_or(ServiceError::NotFound)?;",
            n.row
        ));
    b
}

/// Read the row `id` names back into `row`.
fn read_back(n: &Names) -> Body {
    let mut b = Body::default();
    b.line(format!(
        "let row = {}::get(&mut *conn, id).await?;",
        n.store
    ))
    .line("let row = row.ok_or(ServiceError::NotFound)?;");
    b
}

fn write_event(kind: &str, e: &ServiceEntity, row: &str, previous: Option<&str>) -> Body {
    let mut b = Body::default();
    b.line(format!(
        "let mut event = WriteEvent::new(WriteKind::{kind}, actor);"
    ))
    .line(format!(
        "event.entity = Some({});",
        literal(&e.store.object)
    ));
    if let Some(k) = e.store.key_ident.as_deref() {
        b.line(format!("event.key = Some(meta_service::json(&{row}.{k}));"));
    }
    b.line(format!("event.row = Some(meta_service::json(&{row}));"));
    if let Some(p) = previous {
        b.line(format!("event.previous = Some(meta_service::json(&{p}));"));
    }
    b.line("self.events.on_write(&event, &mut *conn).await?;");
    b
}

const CX: &str = "let cx = Cx { conn: &mut *conn, actor };";

/// A lifecycle field named in a patch must name the state the row is in.
fn state_managed(l: &ServiceLifecycle) -> Body {
    let mut b = Body::default();
    b.line("// A lifecycle moves only through its transitions (ADR-0066 §6): naming the state")
        .line("// the row is in is no move.")
        .block(
            format!("if let Some(state) = patch.{}.take() {{", l.ident),
            "}",
            |b| {
                b.block(format!("if state != current.{} {{", l.ident), "}", |b| {
                    b.line("return Err(ServiceError::StateManaged);");
                });
            },
        );
    b
}

/// The `@autoSet` stamps `of`, into `target` (`input` or `patch`).
fn stamps(of: &[&ServiceStamp], target: &str, comment: &str) -> Body {
    let mut b = Body::default();
    if of.is_empty() {
        return b;
    }
    b.line(comment);
    for local in [false, true] {
        if of.iter().any(|t| t.local_time == local) {
            b.line(format!(
                "let {} = meta_service::now({local});",
                if local { "local_now" } else { "now" }
            ));
        }
    }
    for t in of {
        let v = format!("{}.clone()", if t.local_time { "local_now" } else { "now" });
        let (create, patch) = (target == "input", target == "patch");
        let v = match (create && t.create_optional, patch) {
            (true, _) => format!("Some({v})"),
            (_, true) if t.patch_optional => format!("Some(Some({v}))"),
            (_, true) => format!("Some({v})"),
            _ => v,
        };
        b.line(format!("{target}.{} = {v};", t.ident));
    }
    b
}

/// The `use` lines and type aliases at the top of a file.
fn header(w: &mut CodeWriter, service: &[&str], uses: &[String], aliases: &[(String, String)]) {
    w.use_list("meta_service", service);
    for u in uses {
        w.line(format!("use {u};"));
    }
    if !aliases.is_empty() {
        w.blank();
    }
    for (name, path) in aliases {
        w.line(format!("type {name} = {path};"));
    }
}

/// The shipped [`ServiceParts::entity_file`].
pub fn entity_file(s: &ServicePackage, e: &ServiceEntity) -> String {
    let st = &e.store;
    let m = &st.module;
    let stem = &s.stem;
    let n = Names {
        store: "store".to_string(),
        row: "Row".to_string(),
        rules: e.rules_module.clone().map(|r| (r, "rules".to_string())),
    };
    let mut items = Vec::new();
    let mut head = CodeWriter::new();
    let mut service = vec!["Page", "ServiceError"];
    if e.writable() {
        service = vec!["Cx", "Page", "ServiceError", "WriteEvent", "WriteKind"];
    }
    let mut aliases = vec![("Row".to_string(), st.row.clone())];
    if e.writable() {
        aliases.push(("Create".to_string(), st.create.clone()));
        if st.key.is_some() {
            aliases.push(("Patch".to_string(), st.patch.clone()));
        }
    }
    let mut uses = vec![format!("{} as store", e.store_module)];
    if let Some(r) = &e.rules_module {
        uses.push(format!("{r} as rules"));
    }
    header(&mut head, &service, &uses, &aliases);
    items.push(head.finish().expect("a header opens no block"));
    for c in &e.commands {
        items.extend(condition_items(&c.operation, &[&c.transition]));
    }
    let limit = match s.pagination {
        Some((default, max)) => {
            format!("meta_service::page_limit(query.limit, {default}, Some({max}))?")
        }
        None => {
            "meta_service::page_limit(query.limit, meta_service::DEFAULT_LIMIT, None)?".to_string()
        }
    };
    let page_doc = match s.pagination {
        Some((default, max)) => {
            format!("{default} rows when it names no limit, `limit_too_large` above {max}")
        }
        None => "50 rows when it names no limit".to_string(),
    };
    items.push(impl_block(s, |w| {
        let mut list = Body::default();
        list.line("let mut c = self.db.read().await?;")
            .line("let mut query = query.clone();")
            .line(format!("let limit = {limit};"))
            .line("query.limit = Some(limit);");
        if let Some((k, _)) = st.key.as_ref() {
            list.block("if query.sort.is_empty() {", "}", |b| {
                b.line(format!(
                    "query.sort.push(meta_store::Sort {{ field: {}.to_string(), descending: false }});",
                    literal(k)
                ));
            });
        }
        list.line("let rows = store::list(&mut *c, &query).await?;")
            .block("let total = match with_count {", "};", |b| {
                b.line("true => Some(store::count(&mut *c, query.filter.as_ref()).await?),")
                    .line("false => None,");
            })
            .line("Ok(Page { rows, total })");
        method(
            w,
            &format!("A page of `{}` rows: the filter, sort and page of `query` ({page_doc}), ordered by the key when it names no sort; with the count of the rows the filter selects when `with_count`.", st.object),
            &format!("list_{m}"),
            &["query: &meta_store::Query".to_string(), "with_count: bool".to_string()],
            "Page<Row>",
            &list,
        );
        let Some((_, key_ty)) = st.key.as_ref() else {
            if e.writable() {
                create(w, s, e, &n);
            }
            return;
        };
        let id = format!("id: {key_ty}");
        let mut get = Body::default();
        get.line("let mut c = self.db.read().await?;")
            .line("store::get(&mut *c, id).await?.ok_or(ServiceError::NotFound)");
        method(
            w,
            &format!("The `{}` row `id` names: `not_found` when there is none.", st.object),
            &format!("get_{m}"),
            std::slice::from_ref(&id),
            "Row",
            &get,
        );
        for t in &st.traversals {
            let mut b = Body::default();
            b.line("let mut c = self.db.read().await?;")
                .line(format!("Ok(store::{}(&mut *c, id).await?)", t.function));
            method(
                w,
                &format!("The rows `{}` relates to the `{}` row `id` names, in no order.", t.relation, st.object),
                &format!("{}_{m}", t.function),
                std::slice::from_ref(&id),
                &format!("Vec<{}>", t.target_row),
                &b,
            );
        }
        if !e.writable() {
            return;
        }
        create(w, s, e, &n);
        let managed: Vec<&ServiceLifecycle> = e.lifecycles.iter().filter(|l| l.patch).collect();
        let updated: Vec<&ServiceStamp> =
            e.stamps.iter().filter(|t| t.on_update && t.patch).collect();
        let variant = e.variant();
        let mut update = load(&n, true);
        update
            .line(CX)
            .line(format!(
                "let before = crate::{stem}Before::Update{variant} {{ patch: &mut patch, current: &current }};"
            ))
            .line("self.hooks.before(before, cx).await?;")
            .append(stamps(&updated, "patch", "// @autoSet: onUpdate, whatever the caller sent (ADR-0045)."))
            .line("meta_service::validated(patch.validate())?;");
        for l in managed {
            update.append(state_managed(l));
        }
        update
            .line("let row = store::update(&mut *conn, id, &patch).await?;")
            .line("let row = row.ok_or(ServiceError::NotFound)?;")
            .line(CX)
            .line(format!(
                "let after = crate::{stem}After::Update{variant} {{ row: &row, previous: &current }};"
            ))
            .line("self.hooks.after(after, cx).await?;")
            .append(write_event("Update", e, "row", Some("current")))
            .line("Ok(row)");
        write_pair(
            w,
            &format!("Update the `{}` row `id` names with `patch`: load it under a row lock (`not_found`), the before hook, validate it, write it, the after hook and the event hook.", st.object),
            &format!("update_{m}"),
            &["actor: Option<&A>".to_string(), id.clone(), "mut patch: Patch".to_string()],
            "Row",
            &update,
        );
        let mut delete = load(&n, true);
        delete
            .line(CX)
            .line(format!("let before = crate::{stem}Before::Delete{variant}(&current);"))
            .line("self.hooks.before(before, cx).await?;")
            .line("store::delete(&mut *conn, id).await?;")
            .line(CX)
            .line(format!("let after = crate::{stem}After::Delete{variant}(&current);"))
            .line("self.hooks.after(after, cx).await?;")
            .append(write_event("Delete", e, "current", None))
            .line("Ok(())");
        write_pair(
            w,
            &format!("Delete the `{}` row `id` names: load it under a row lock (`not_found`), the before hook, the delete, the after hook and the event hook.", st.object),
            &format!("delete_{m}"),
            &["actor: Option<&A>".to_string(), id.clone()],
            "()",
            &delete,
        );
        for c in &e.commands {
            let t = &c.transition;
            let mut b = load(&n, true);
            b.append(permission_check(s, c.permission.as_ref(), true, false))
                .line(format!("let t = {};", n.rules_path(&t.path)))
                .block(
                    format!("if !meta_service::in_state(&current.{}, t.from()) {{", t.ident),
                    "}",
                    |b| {
                        b.line("return Err(ServiceError::InvalidTransition);");
                    },
                )
                .append(make_move(&n, e, t, &c.operation))
                .append(read_back(&n))
                .line("Ok(row)");
            write_pair(
                w,
                &format!("The `{}` move of the `{}` row `id` names (ADR-0066 §2), in ADR-0066 §6's order: load it under a row lock (`not_found`), the permission point (`forbidden`), the state (`invalid_transition`), the guarded update (`invalid_transition`, or `transition_condition_failed` when its condition fails), the event hook. Answers the row written.", t.name, st.object),
                &c.function,
                &["actor: Option<&A>".to_string(), id.clone()],
                "Row",
                &b,
            );
        }
    }));
    file(BANNER, &items)
}

fn create(w: &mut CodeWriter, s: &ServicePackage, e: &ServiceEntity, n: &Names) {
    let st = &e.store;
    let m = &st.module;
    let stem = &s.stem;
    let variant = e.variant();
    let all: Vec<&ServiceStamp> = e.stamps.iter().collect();
    let mut b = Body::default();
    b.line(CX)
        .line(format!(
            "let before = crate::{stem}Before::Create{variant}(&mut input);"
        ))
        .line("self.hooks.before(before, cx).await?;")
        .append(stamps(
            &all,
            "input",
            "// @autoSet: the service stamps these, whatever the caller sent (ADR-0045).",
        ))
        .line("meta_service::validated(input.validate())?;");
    if s.create_initial {
        for l in &e.lifecycles {
            let given = match l.create {
                Presence::Absent => continue,
                Presence::Optional => format!(
                    "input.{}.is_some_and(|s| s != {}::INITIAL)",
                    l.ident,
                    n.rules_path(&l.module)
                ),
                Presence::Required => {
                    format!("input.{} != {}::INITIAL", l.ident, n.rules_path(&l.module))
                }
            };
            b.line(format!(
                "// rules.lifecycle.create is \"initial\": a create starts `{}` in its initial state.",
                l.field
            ))
            .block(format!("if {given} {{"), "}", |b| {
                b.line("return Err(ServiceError::StateManaged);");
            });
        }
    }
    b.line("let row = store::create(&mut *conn, &input).await?;")
        .line(CX)
        .line(format!(
            "let after = crate::{stem}After::Create{variant}(&row);"
        ))
        .line("self.hooks.after(after, cx).await?;")
        .append(write_event("Create", e, "row", None))
        .line("Ok(row)");
    write_pair(
        w,
        &format!(
            "Create a `{}`: the before hook (it may replace the input or refuse), validate it, insert it, the after hook and the event hook. Answers the row written.",
            st.object
        ),
        &format!("create_{m}"),
        &[
            "actor: Option<&A>".to_string(),
            "mut input: Create".to_string(),
        ],
        "Row",
        &b,
    );
}

/// The shipped [`ServiceParts::operations_file`].
pub fn operations_file(s: &ServicePackage) -> String {
    let contract = s.contract.as_deref().unwrap_or_default();
    let mut items = Vec::new();
    let mut head = CodeWriter::new();
    let targets: BTreeSet<usize> = s
        .operations
        .iter()
        .filter_map(|o| o.target.filter(|_| o.keyed))
        .collect();
    let mut uses = vec![format!("{} as contract", contract)];
    for i in &targets {
        let e = &s.entities[*i];
        uses.push(e.store_module.clone());
        if let (Some(r), true) = (
            &e.rules_module,
            s.operations
                .iter()
                .any(|o| o.target == Some(*i) && !o.moves.is_empty()),
        ) {
            uses.push(format!("{r} as {}_rules", e.store.module));
        }
    }
    let any_move = s.operations.iter().any(|o| o.command());
    let service: &[&str] = if any_move {
        &["BodyError", "Cx", "ServiceError", "WriteEvent", "WriteKind"]
    } else {
        &["BodyError", "Cx", "ServiceError"]
    };
    header(&mut head, service, &uses, &[]);
    items.push(head.finish().expect("a header opens no block"));
    for o in &s.operations {
        let moves: Vec<&ServiceMove> = o.moves.iter().collect();
        items.extend(condition_items(&o.names.name, &moves));
    }
    items.push(impl_block(s, |w| {
        for o in &s.operations {
            operation(w, s, o);
        }
    }));
    file(BANNER, &items)
}

fn operation(w: &mut CodeWriter, s: &ServicePackage, o: &ServiceOperation) {
    let target = o.target.map(|i| &s.entities[i]);
    let n = Names {
        store: target.map(|e| e.store.module.clone()).unwrap_or_default(),
        row: target.map(|e| e.store.row.clone()).unwrap_or_default(),
        rules: target.and_then(|e| {
            e.rules_module
                .clone()
                .map(|r| (r, format!("{}_rules", e.store.module)))
        }),
    };
    let mut params = vec!["actor: Option<&A>".to_string()];
    if o.keyed {
        let (_, ty) = target
            .and_then(|e| e.store.key.as_ref())
            .expect("a keyed operation has a key");
        params.push(format!("id: {ty}"));
    }
    if o.has_input {
        let mutable = if o.input_key.is_some() { "mut " } else { "" };
        params.push(format!("{mutable}input: contract::{}Input", o.stem));
    }
    if o.many && !o.command() {
        params.push("query: &meta_store::Query".to_string());
    }
    let mut body = Body::default();
    if !o.command() {
        body.line("let mut c = self.db.read().await?;")
            .line("let conn = &mut *c;");
    }
    if o.keyed {
        body.append(load(&n, o.command()));
    }
    if let Some((ident, optional)) = &o.input_key {
        let key = target
            .and_then(|e| e.store.key_ident.clone())
            .unwrap_or_default();
        let text_key = target
            .and_then(|e| e.store.key.as_ref())
            .is_some_and(|(_, ty)| ty == "&str");
        let clone = if text_key { ".clone()" } else { "" };
        let value = if *optional {
            format!("Some(current.{key}{clone})")
        } else {
            format!("current.{key}{clone}")
        };
        body.line("// The input borrows the key the call names.")
            .line(format!("input.{ident} = {value};"));
    }
    if o.has_input {
        body.line("meta_service::validated(input.validate())?;");
    }
    body.append(permission_check(
        s,
        o.permission.as_ref(),
        o.keyed,
        o.has_input,
    ));
    if !o.moves.is_empty() {
        for m in &o.moves {
            body.line(format!(
                "let move_{} = {};",
                snake(&m.name),
                n.rules_path(&m.path)
            ));
        }
        body.block("let movable = [", "];", |b| {
            for m in &o.moves {
                b.line(format!(
                    "meta_service::in_state(&current.{}, move_{}.from()),",
                    m.ident,
                    snake(&m.name)
                ));
            }
        })
        .block("if !movable.contains(&true) {", "}", |b| {
            b.line("return Err(ServiceError::InvalidTransition);");
        });
    }
    let mut args = Vec::new();
    if o.has_input {
        args.push("&input");
    }
    if o.keyed {
        args.push("&current");
    }
    if o.many && !o.command() {
        args.push("query");
    }
    args.push("cx");
    let bound = if o.command() && o.output_is_row && o.moves.is_empty() {
        "_outcome"
    } else {
        "outcome"
    };
    body.line(CX)
        .line(format!(
            "let {bound} = self.bodies.{}({}).await;",
            o.function,
            args.join(", ")
        ))
        .line(format!(
            "let {bound} = {bound}.map_err(BodyError::into_service)?;"
        ));
    let name = literal(&o.names.name);
    if o.command() {
        let entity = target.map_or("None".to_string(), |e| {
            format!("Some({})", literal(&e.store.object))
        });
        let command_event = || {
            let mut b = Body::default();
            b.line("let mut event = WriteEvent::new(WriteKind::Command, actor);")
                .line(format!("event.entity = {entity};"));
            if o.keyed {
                b.line("event.key = Some(meta_service::json(&id));");
            }
            b.line(format!("event.operation = Some({name});"))
                .line("self.events.on_write(&event, &mut *conn).await?;");
            b
        };
        let both = o.has_output && !o.output_is_row;
        if o.moves.is_empty() {
            body.append(command_event());
        } else {
            let e = target.expect("a move has a target");
            let on = if both {
                "outcome.transition"
            } else {
                "outcome"
            };
            body.block(format!("match {on} {{"), "}", |b| {
                for m in &o.moves {
                    b.block(
                        format!(
                            "crate::{}Move::{} => {{",
                            o.stem,
                            type_ident(&pascal(&m.name))
                        ),
                        "}",
                        |b| {
                            b.line(format!("let t = move_{};", snake(&m.name)))
                                .append(make_move(&n, e, m, &o.names.name));
                        },
                    );
                }
                b.block(format!("crate::{}Move::None => {{", o.stem), "}", |b| {
                    b.append(command_event());
                });
            });
        }
        if o.output_is_row {
            body.append(read_back(&n)).line("Ok(row)");
        } else if o.moves.is_empty() {
            // The body's answer is the output (or `()`).
            body.line("Ok(outcome)");
        } else if both {
            body.line("Ok(outcome.output)");
        } else {
            // The body's answer was only the move.
            body.line("Ok(())");
        }
    } else {
        body.line("Ok(outcome)");
    }
    let kind = if o.command() { "command" } else { "query" };
    let doc = format!(
        "`{}` (a {kind}), in ADR-0066 §6's order: {}.",
        o.names.name,
        steps(o).join(", ")
    );
    let ret = answer(s, o);
    if o.command() {
        write_pair(w, &doc, &o.function, &params, &ret, &body);
    } else {
        method(
            w,
            &format!("{doc} On a read connection, opening no transaction."),
            &o.function,
            &params,
            &ret,
            &body,
        );
    }
}

fn steps(o: &ServiceOperation) -> Vec<&'static str> {
    let mut s = Vec::new();
    if o.keyed {
        s.push(if o.command() {
            "load the row under a row lock (`not_found`)"
        } else {
            "read the row (`not_found`)"
        });
    }
    if o.has_input {
        s.push("validate the input");
    }
    s.push(if o.permission.is_some() {
        "the permission point (`forbidden`)"
    } else {
        "no permission point (it is `@public`)"
    });
    if !o.moves.is_empty() {
        s.push("the state (`invalid_transition`)");
    }
    s.push("the body");
    if !o.moves.is_empty() {
        s.push("the guarded update");
    }
    if o.command() {
        s.push("the event hook");
    }
    s
}
