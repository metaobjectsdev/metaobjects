/// `path` as lib.rs names it: through its `model` and `contract` aliases.
fn short(s: &ServicePackage, path: &str) -> String {
    let mut out = path.replace(&format!("{}::", s.model), "model::");
    if let Some(c) = &s.contract {
        out = out.replace(&format!("{c}::"), "contract::");
    }
    out
}

/// `fn <name><'a>(&'a self, <params>) -> impl Future<Output = <out>> + Send + 'a`, a trait
/// method; `default` is the body of one the trait implements, else it ends in `;`.
fn trait_method(
    w: &mut CodeWriter,
    doc: &str,
    name: &str,
    params: &[String],
    out: &str,
    default: Option<&str>,
) {
    w.blank();
    w.prose(doc);
    let mut all = vec!["&'a self".to_string()];
    all.extend(params.iter().cloned());
    let ret = format!(" -> impl Future<Output = {out}> + Send + 'a");
    match default {
        None => {
            w.line(piece![
                format!("fn {name}<'a>"),
                list("(", all, ")"),
                format!("{ret};")
            ]);
        }
        Some(body) => {
            let head = piece![
                format!("fn {name}<'a>"),
                list("(", all.clone(), ")"),
                format!("{ret} {{")
            ];
            // rustfmt moves the brace to a line of its own when the broken signature's last
            // line and ` {` pass the width less the item's indent (its `rewrite_fn` budget).
            let one_line = w.fits(&format!("fn {name}<'a>({}){ret} {{", all.join(", ")));
            if !one_line
                && !w.fits(&format!("{RUST_INDENT}){ret} {{"))
                && w.fits(&format!("){ret}"))
            {
                w.line(piece![format!("fn {name}<'a>"), list("(", all, ")"), ret]);
                w.block("{", |w| {
                    w.line(body);
                });
            } else {
                w.block(head, |w| {
                    w.line(body);
                });
            }
        }
    }
}

/// The shipped [`ServiceParts::lib_file`].
pub fn lib_file(s: &ServicePackage) -> String {
    let stem = &s.stem;
    let svc = &s.service;
    let err = format!("{stem}Error");
    let label = if s.package.is_empty() {
        "the MetaObjects model that declares no package".to_string()
    } else {
        format!("the MetaObjects package `{}`", s.package)
    };
    let mut items = Vec::new();
    let mut head = CodeWriter::new();
    head.line(format!(
        "//! The service layer of {label} (ADR-0067 layer 4)."
    ));
    head.line("//!");
    head.line(format!(
        "//! [`{svc}`] runs each operation over the store crate, a write in one transaction,"
    ));
    head.line(
        "//! calling the hand-written pieces it is built with at their points: the policy, the",
    );
    head.line("//! bodies, the hooks and the event hook.");
    head.blank();
    let mut modules: Vec<&str> = s.entities.iter().map(|e| e.store.module.as_str()).collect();
    if !s.operations.is_empty() {
        modules.push("operations");
    }
    modules.sort_unstable();
    for m in modules {
        head.line(format!("mod {m};"));
    }
    head.blank();
    head.line("use std::future::Future;");
    head.blank();
    head.line(format!("use {} as model;", s.model));
    if let Some(c) = &s.contract {
        head.line(format!("use {c} as contract;"));
    }
    head.blank();
    head.line(
        "pub use meta_service::{BodyError, Cx, Db, Page, ServiceError, WriteEvent, WriteKind};",
    );
    items.push(head.finish().expect("a header opens no block"));
    let one =
        |build: &dyn Fn(&mut CodeWriter)| item(|w| build(w)).expect("an item closes every block");
    items.push(one(&|w| {
        w.prose("What every operation of the package answers an error with.");
        w.line(format!("pub type {err} = ServiceError;"));
    }));
    let conn = "C: meta_store::Conn + ?Sized";
    if s.has_policy {
        let rules = s.rules.as_deref().unwrap_or_default();
        items.push(one(&|w| {
            w.prose(
                "The policy: whether the actor may pass a permission point, given the loaded row and the validated input as JSON. Asked before anything is written; a refusal is 403 `forbidden`. Who holds a permission is data, so the answer is the application's.",
            );
            w.block(format!("pub trait {stem}Policy<A, {conn}>: Send + Sync {{"), |w| {
                trait_method(
                    w,
                    "Whether `actor` may pass the point that asks about `permission`.",
                    "allows",
                    &[
                        format!("permission: {rules}::Permission"),
                        "actor: Option<&'a A>".to_string(),
                        "row: Option<&'a serde_json::Value>".to_string(),
                        "input: Option<&'a serde_json::Value>".to_string(),
                        "conn: &'a mut C".to_string(),
                    ],
                    &format!("Result<bool, {err}>"),
                    None,
                );
            });
        }));
    }
    if s.has_bodies() {
        for o in &s.operations {
            if !o.moves.is_empty() {
                let moves = format!("{}Move", o.stem);
                items.push(one(&|w| {
                    w.prose(&format!(
                        "The move the body of `{}` chose (`@transitions`), or none.",
                        o.names.name
                    ));
                    w.line("#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
                    w.block(format!("pub enum {moves} {{"), |w| {
                        for m in &o.moves {
                            w.line(format!("{},", type_ident(&pascal(&m.name))));
                        }
                        w.line("None,");
                    });
                }));
                if o.has_output && !o.output_is_row {
                    items.push(one(&|w| {
                        w.prose(&format!(
                            "What the body of `{}` returns: its move and its output.",
                            o.names.name
                        ));
                        w.line("#[derive(Debug, Clone)]");
                        w.block(format!("pub struct {}Outcome {{", o.stem), |w| {
                            w.line(format!("pub transition: {moves},"));
                            w.line(format!("pub output: contract::{}Output,", o.stem));
                        });
                    }));
                }
            }
            items.push(one(&|w| {
                w.prose(&format!("What the body of `{}` answers.", o.names.name));
                w.assign(
                    &format!("pub type {}Answer =", o.stem),
                    format!(
                        "Result<{}, BodyError<contract::{}BusinessError>>;",
                        short(s, &body_output(s, o)),
                        o.stem
                    ),
                );
            }));
        }
        items.push(one(&|w| {
            w.prose(
                "The bodies of the package's declared operations (ADR-0066 §1): what each does, between the checks the service makes before it and the guarded update and the event hook after. A body runs on the operation's connection, inside its transaction for a command.",
            );
            w.block(format!("pub trait {stem}Bodies<A, {conn}>: Send + Sync {{"), |w| {
                for o in &s.operations {
                    let mut params = Vec::new();
                    if o.has_input {
                        params.push(format!("input: &'a contract::{}Input", o.stem));
                    }
                    if o.keyed {
                        let e = &s.entities[o.target.expect("a keyed operation has a target")];
                        params.push(format!("row: &'a {}", short(s, &e.store.row)));
                    }
                    if o.many && !o.command() {
                        params.push("query: &'a meta_store::Query".to_string());
                    }
                    params.push("cx: Cx<'a, A, C>".to_string());
                    let kind = if o.command() { "command" } else { "query" };
                    trait_method(
                        w,
                        &format!("The body of `{}` (a {kind}).", o.names.name),
                        &o.function,
                        &params,
                        &format!("{}Answer", o.stem),
                        None,
                    );
                }
            });
        }));
    }
    let writable: Vec<&ServiceEntity> = s.entities.iter().filter(|e| e.writable()).collect();
    if !writable.is_empty() {
        let variants = |w: &mut CodeWriter, after: bool| {
            // (the tuple variant, or the struct variant's name and fields), in model order.
            let mut list: Vec<(String, Vec<String>)> = Vec::new();
            for e in &writable {
                let row = short(s, &e.store.row);
                let ty = e.variant();
                list.push((
                    if after {
                        format!("Create{ty}(&'a {row}),")
                    } else {
                        format!("Create{ty}(&'a mut {}),", short(s, &e.store.create))
                    },
                    Vec::new(),
                ));
                if e.store.key.is_none() {
                    continue;
                }
                let fields = if after {
                    vec![format!("row: &'a {row}"), format!("previous: &'a {row}")]
                } else {
                    vec![
                        format!("patch: &'a mut {}", short(s, &e.store.patch)),
                        format!("current: &'a {row}"),
                    ]
                };
                list.push((format!("Update{ty}"), fields));
                list.push((format!("Delete{ty}(&'a {row}),"), Vec::new()));
            }
            // rustfmt breaks every struct variant of an enum once one of them does not fit.
            let one_line =
                |name: &str, fields: &[String]| format!("{name} {{ {} }},", fields.join(", "));
            let broken = list
                .iter()
                .any(|(name, fields)| !fields.is_empty() && !w.fits(&one_line(name, fields)));
            for (name, fields) in &list {
                if fields.is_empty() {
                    w.line(name.as_str());
                } else if broken {
                    w.block_with(format!("{name} {{"), "},", |w| {
                        for f in fields {
                            w.line(format!("{f},"));
                        }
                    });
                } else {
                    w.line(one_line(name, fields));
                }
            }
        };
        items.push(one(&|w| {
            w.prose(
                "A derived write, as its before hook is told of it: the input or patch to write, which the hook may change, and the row an update or a delete starts from.",
            );
            w.block(format!("pub enum {stem}Before<'a> {{"), |w| {
                variants(w, false);
            });
        }));
        items.push(one(&|w| {
            w.prose(
                "A derived write, as its after hook is told of it: the row written, the row before an update, and the row a delete removed.",
            );
            w.block(format!("pub enum {stem}After<'a> {{"), |w| {
                variants(w, true);
            });
        }));
    }
    items.push(one(&|w| {
        w.prose(
            "The hooks around each derived write, in its transaction: the before hook may change the input or patch or refuse, the after hook may refuse, and a refusal undoes the write. Each does nothing unless implemented; `()` implements neither.",
        );
        w.block(format!("pub trait {stem}Hooks<A, {conn}>: Send + Sync {{"), |w| {
            if writable.is_empty() {
                return;
            }
            let cx = "_cx: Cx<'a, A, C>".to_string();
            let ok = format!("Result<(), {err}>");
            trait_method(w, "Before a create, an update or a delete, after the row is loaded and before it is validated.", "before",
                &[format!("_write: {stem}Before<'a>"), cx.clone()], &ok, Some("async { Ok(()) }"));
            trait_method(w, "After a create, an update or a delete, before the event hook.", "after",
                &[format!("_write: {stem}After<'a>"), cx], &ok, Some("async { Ok(()) }"));
        });
    }));
    items.push(one(&|w| {
        w.line(format!(
            "impl<A: Sync, {conn}> {stem}Hooks<A, C> for () {{}}"
        ));
    }));
    items.push(one(&|w| {
        w.prose(
            "The event hook: told of every write last, inside its transaction, so a refusal undoes the write. `()` is the one that does nothing.",
        );
        w.block(format!("pub trait {stem}Events<A, {conn}>: Send + Sync {{"), |w| {
            trait_method(w, "One write.", "on_write",
                &["_event: &'a WriteEvent<'a, A>".to_string(), "_conn: &'a mut C".to_string()],
                &format!("Result<(), {err}>"), Some("async { Ok(()) }"));
        });
    }));
    items.push(one(&|w| {
        w.line(format!(
            "impl<A: Sync, {conn}> {stem}Events<A, C> for () {{}}"
        ));
    }));

    // The service type.
    let base: Vec<&str> = s
        .params()
        .into_iter()
        .filter(|p| *p != "H" && *p != "E")
        .collect();
    let base = base.join(", ");
    let params = s.generics();
    let mut fields = vec!["db"];
    if s.has_policy {
        fields.push("policy");
    }
    if s.has_bodies() {
        fields.push("bodies");
    }
    items.push(one(&|w| {
        w.prose(&format!(
            "The service of {label}: `D` the store, `A` the actor{}{}, `H` the hooks and `E` the event hook.",
            if s.has_policy { ", `P` the policy" } else { "" },
            if s.has_bodies() { ", `B` the bodies" } else { "" },
        ));
        w.block(format!("pub struct {svc}<{base}, H = (), E = ()> {{"), |w| {
            for (f, t) in [("db", "D"), ("policy", "P"), ("bodies", "B"), ("hooks", "H"), ("events", "E")] {
                if f == "db" || f == "hooks" || f == "events" || fields.contains(&f) {
                    w.line(format!("pub {f}: {t},"));
                }
            }
            w.line("actor: std::marker::PhantomData<fn(&A)>,");
        });
    }));
    let ctor: Vec<String> = fields
        .iter()
        .map(|f| format!("{f}: {}", f[..1].to_uppercase()))
        .collect();
    items.push(one(&|w| {
        w.block(format!("impl<{base}> {svc}<{base}> {{"), |w| {
            w.prose("A service with no hooks and no event hook.");
            w.block(
                piece!["pub fn new", list("(", ctor.clone(), ")"), " -> Self {"],
                |w| {
                    let mut lit: Vec<String> = fields.iter().map(|f| (*f).to_string()).collect();
                    lit.extend([
                        "hooks: ()".to_string(),
                        "events: ()".to_string(),
                        "actor: std::marker::PhantomData".to_string(),
                    ]);
                    w.line(piece![format!("{svc} "), padded("{", lit, "}")]);
                },
            );
        });
    }));
    items.push(one(&|w| {
        w.block(format!("impl<{params}> {svc}<{params}> {{"), |w| {
            for (what, other, ty) in [
                ("hooks", "hooks", params.replacen(", H, E", ", H2, E", 1)),
                (
                    "event hook",
                    "events",
                    params.replacen(", H, E", ", H, E2", 1),
                ),
            ] {
                let g = if other == "hooks" { "H2" } else { "E2" };
                let mut lit: Vec<String> =
                    fields.iter().map(|f| format!("{f}: self.{f}")).collect();
                for f in ["hooks", "events"] {
                    lit.push(if f == other {
                        f.to_string()
                    } else {
                        format!("{f}: self.{f}")
                    });
                }
                lit.push("actor: std::marker::PhantomData".to_string());
                w.blank();
                w.prose(&format!("The service with these {what}."));
                w.block(
                    format!("pub fn with_{other}<{g}>(self, {other}: {g}) -> {svc}<{ty}> {{"),
                    |w| {
                        w.line(piece![format!("{svc} "), padded("{", lit, "}")]);
                    },
                );
            }
        });
    }));
    // An alias nothing names would be an unused import.
    let rest = items[1..].concat();
    if !rest.contains("model::") {
        items[0] = items[0].replace(&format!("use {} as model;\n", s.model), "");
    }
    file(BANNER, &items)
}

/// What a declared operation's body returns.
fn body_output(s: &ServicePackage, o: &ServiceOperation) -> String {
    let contract = s.contract.as_deref().unwrap_or_default();
    let output = format!("{contract}::{}Output", o.stem);
    if !o.moves.is_empty() {
        return if o.has_output && !o.output_is_row {
            format!("crate::{}Outcome", o.stem)
        } else {
            format!("crate::{}Move", o.stem)
        };
    }
    if o.has_output && !o.output_is_row {
        output
    } else if o.command() {
        "()".to_string()
    } else {
        "serde_json::Value".to_string()
    }
}

/// What a declared operation answers.
fn answer(s: &ServicePackage, o: &ServiceOperation) -> String {
    let contract = s.contract.as_deref().unwrap_or_default();
    if o.output_is_row {
        return s.entities[o.target.expect("a row output has a target")]
            .store
            .row
            .clone();
    }
    if o.has_output {
        return format!("{contract}::{}Output", o.stem);
    }
    if o.command() {
        "()".to_string()
    } else {
        "serde_json::Value".to_string()
    }
}

