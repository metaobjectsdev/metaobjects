//! The `service` generator: the service layer (ADR-0067 layer 4), one crate per package, over
//! the `repository` generator's data access.
//!
//! For the package `acme::purchasing` it writes:
//!
//! ```text
//! <out>/acme_purchasing_service/Cargo.toml       the crate
//! <out>/acme_purchasing_service/src/lib.rs       PurchasingService, its traits and its error
//! <out>/acme_purchasing_service/src/<type>.rs    one entity's operations
//! <out>/acme_purchasing_service/src/operations.rs the package's declared operations
//! <out>/meta_service/                            what every service crate shares
//! ```
//!
//! `PurchasingService<D, A, ...>` holds the store (`D`, a `meta_service::Db`: an
//! `sqlx::PgPool` or `sqlx::SqlitePool`) and the hand-written pieces it calls, each a generated
//! trait: `PurchasingPolicy` (asked at every permission point, when the package has one),
//! `PurchasingBodies` (a body per declared operation, when it declares one), `PurchasingHooks`
//! (before and after each derived write) and `PurchasingEvents` (told of every write). The actor
//! is the type parameter `A`, passed through untouched to each of them. `()` is the hooks and
//! the events that do nothing.
//!
//! Per stored entity: `list_<type>` and `get_<type>` (a page, and one row by key), and for one
//! that is written `create_<type>`, `update_<type>` and `delete_<type>`; per many-to-many
//! relationship `<relation>_of_<type>`; per transition that derives a command (ADR-0066 §2,
//! under `rules.lifecycle.commands`) `<transition>_<type>`. Per declared operation, its name in
//! snake case. Every write runs in one transaction, and has an `_in` twin that runs on a
//! caller's connection, inside the caller's transaction. A write checks in ADR-0066 §6's order:
//! load the row under a row lock (`not_found`), the permission point (`forbidden`), the state
//! (`invalid_transition`), the body, the guarded update, the event hook. A create starts each
//! lifecycle in its initial state under `rules.lifecycle.create: initial`, and a generic update
//! never moves one (`state_managed`). Every operation answers `Result<T, <Type>Error>`; a
//! refusal anywhere rolls the whole transaction back.
//!
//! It names the model crate's types (`entity`), the rules crate's names (`rules-names`), the
//! contract crate's operation shapes (`contract-types`) and the store crate's functions
//! (`repository`), so it runs with those four.

