//! The `output-prompt` generator: the output-format fragment of each responding prompt, one
//! crate per package.
//!
//! A `template.prompt` that declares `@responseRef` asks for an answer shaped like that value
//! object (ADR-0052). The fragment is the part of the prompt that says so: "produce your
//! answer like this", as a field guide, an inline skeleton or a filled example
//! (`@promptStyle`: `guide`, `inline`, `exampleOnly`), in the reply's syntax
//! (`@responseFormat`: `json` or `xml`, ADR-0053). For the package `acme::ai` the generator
//! writes:
//!
//! ```text
//! <out>/acme_ai_formats/Cargo.toml         the crate (metaobjects-render)
//! <out>/acme_ai_formats/src/lib.rs         one `mod` per prompt and a `pub use` of its functions
//! <out>/acme_ai_formats/src/<prompt>.rs    one prompt: its fragment and its descriptor
//! ```
//!
//! Each prompt gets `render_<name>_format(overrides) -> String` and the descriptor it renders,
//! `<name>_format_spec()`: every field of the response object with its kind, whether it is
//! required, enum members and their `@enumDoc`, `@example` and `@instruction`. A nested
//! object is named with its kind and taught no deeper, as in every port. The fragment's root
//! is the response object's name, the same root the generated parser looks for.

use std::collections::{BTreeMap, BTreeSet};

use metaobjects::node::{NodeId, Tree};
use metaobjects::validate::util::ObjectIndex;
use metaobjects_codegen::generator::{EmittedFile, GenContext, GenError, Generator};
use metaobjects_codegen::inbound::{
    inbound_templates, output_format_spec, prompt_style, reply_format, response_object,
};
use metaobjects_codegen::names::{crate_name, field_ident, literal, snake};
use metaobjects_codegen::plan::Plan;
use metaobjects_codegen::render::extract::Format;
use metaobjects_codegen::render::prompt::{OutputFormatSpec, PromptField, PromptStyle};
use metaobjects_codegen::writer::{
    CodeWriter, Manifest, Piece, RUSTFMT_TOML, file, item, list, padded, toml_string,
};

/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects output-prompt generator. Do not edit: change the model and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects output-prompt generator. Do not edit: change the model and run `cargo meta gen`.";

/// The suffix of the fragment crate of a package: `shop`'s fragments are in `shop_formats`.
pub const FORMATS_SUFFIX: &str = "_formats";

const RENDER_CRATE: &str = "metaobjects-render";
/// The version requirement the generated crate names `metaobjects-render` by.
const RENDER_VERSION: &str = metaobjects_codegen::render::REQUIREMENT;

/// The output-prompt generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct OutputPromptGenerator;

impl Generator for OutputPromptGenerator {
    fn name(&self) -> &str {
        "output-prompt"
    }

    fn identity(&self) -> String {
        format!("output-prompt:{FORMAT}")
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl OutputPromptParts for OutputPromptGenerator {}

/// The pieces of the output-prompt generator's output, one method each (ADR-0063 item 7). Each
/// default is the shipped piece: implement this for a generator of your own, override the
/// piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape). An override can call the
/// shipped piece, a public function of this module with the same name. Not a stability
/// contract: the methods may change in a minor release, and the CHANGELOG says when.
pub trait OutputPromptParts {
    /// Every file: one formats crate per package with a responding prompt.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// A formats crate's `Cargo.toml`.
    fn manifest(&self, name: &str, c: &FormatsCrate) -> String {
        cargo_toml(name, c)
    }

    /// A formats crate's `src/lib.rs`: each module and the functions it exports.
    fn lib_file(&self, c: &FormatsCrate) -> String {
        lib_file(c)
    }

    /// One prompt's file: its imports, its fragment function and its spec.
    fn fragment_file(&self, f: &FragmentPlan) -> Result<String, GenError> {
        fragment_file(self, f)
    }

    /// The function that renders the fragment.
    fn render_fn(&self, w: &mut CodeWriter, f: &FragmentPlan) {
        render_fn(w, f);
    }

    /// The function that builds the fragment's spec.
    fn spec_fn(&self, w: &mut CodeWriter, f: &FragmentPlan) {
        spec_fn(w, f);
    }
}

/// The shipped [`OutputPromptParts::render`], through `parts`.
pub fn render<P: OutputPromptParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let templates = inbound_templates(ctx.tree, ctx.root);
    if templates.is_empty() {
        return Ok(Vec::new());
    }
    let plan = Plan::of(ctx)?;
    let selected = plan.selected_crates(ctx.entities)?;
    let index = ObjectIndex::build(ctx.tree, ctx.root);
    let mut crates: BTreeMap<String, FormatsCrate> = BTreeMap::new();
    for t in templates {
        // A reply shape that names no object gets no fragment (the loader reports it).
        let Some(fragment) = fragment_of(ctx.tree, &index, t) else {
            continue;
        };
        // A run limited to some entities writes the fragments of their crates only.
        let response_crate = plan
            .structs
            .iter()
            .find(|s| s.node == fragment.response)
            .map(|s| &s.crate_name);
        if let (Some(sel), Some(c)) = (selected.as_ref(), response_crate)
            && !sel.contains(c)
        {
            continue;
        }
        let package = ctx.tree.effective_package(t);
        let c = crates
            .entry(format!("{}{FORMATS_SUFFIX}", crate_name(&package)))
            .or_default();
        c.package = package;
        c.fragments.push(fragment);
    }
    let mut files = Vec::new();
    for (name, c) in &crates {
        formats_crate(parts, name, c, &mut files)?;
    }
    Ok(files)
}

/// What one prompt's fragment needs.
pub struct FragmentPlan {
    pub template: String,
    pub module: String,
    pub response: NodeId,
    pub response_name: String,
    pub spec: OutputFormatSpec,
}

fn fragment_of(tree: &Tree, index: &ObjectIndex, t: NodeId) -> Option<FragmentPlan> {
    let response = response_object(tree, index, t)?;
    let n = tree.node(t);
    Some(FragmentPlan {
        template: n.name.clone(),
        module: snake(&n.name),
        response,
        response_name: tree.node(response).name.clone(),
        spec: output_format_spec(tree, response, reply_format(tree, t), prompt_style(tree, t)),
    })
}

// ---- one formats crate -----------------------------------------------------------------

#[derive(Default)]
pub struct FormatsCrate {
    pub package: String,
    pub fragments: Vec<FragmentPlan>,
}

fn formats_crate<P: OutputPromptParts + ?Sized>(
    parts: &P,
    name: &str,
    c: &FormatsCrate,
    files: &mut Vec<EmittedFile>,
) -> Result<(), GenError> {
    for f in &c.fragments {
        files.push(EmittedFile::new(
            format!("{name}/src/{}.rs", f.module),
            parts.fragment_file(f)?,
        ));
    }
    files.push(EmittedFile::new(
        format!("{name}/Cargo.toml"),
        parts.manifest(name, c),
    ));
    files.push(EmittedFile::new(
        format!("{name}/rustfmt.toml"),
        RUSTFMT_TOML.to_string(),
    ));
    files.push(EmittedFile::new(
        format!("{name}/src/lib.rs"),
        parts.lib_file(c),
    ));
    Ok(())
}

/// The shipped [`OutputPromptParts::manifest`].
pub fn cargo_toml(name: &str, c: &FormatsCrate) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "Output-format prompt fragments for the prompts of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    m.entry(RENDER_CRATE, &toml_string(RENDER_VERSION));
    m.finish()
}

/// The shipped [`OutputPromptParts::lib_file`].
pub fn lib_file(c: &FormatsCrate) -> String {
    let mut w = CodeWriter::new();
    w.line(BANNER).blank();
    if c.package.is_empty() {
        w.line("//! Output-format prompt fragments for the prompts of the MetaObjects model that declares no package.");
    } else {
        w.line(format!(
            "//! Output-format prompt fragments for the prompts of the MetaObjects package `{}`.",
            c.package
        ));
    }
    w.line("//!");
    w.line("//! Each fragment tells a model how to shape its answer, in the shape the matching");
    w.line("//! response parser reads.");
    w.blank();
    let mut fragments: Vec<&FragmentPlan> = c.fragments.iter().collect();
    fragments.sort_by(|a, b| a.module.cmp(&b.module));
    for f in &fragments {
        w.line(format!("mod {};", f.module));
    }
    w.blank();
    w.line("pub use metaobjects_render::prompt::{PromptOverrides, PromptStyle};");
    for f in &fragments {
        let m = &f.module;
        w.line(format!(
            "pub use {m}::{{render_{m}_format, {m}_format_spec}};"
        ));
    }
    w.finish().expect("a lib.rs opens no block")
}

// ---- one fragment ----------------------------------------------------------------------

/// The shipped [`OutputPromptParts::fragment_file`], through `parts`.
pub fn fragment_file<P: OutputPromptParts + ?Sized>(
    parts: &P,
    f: &FragmentPlan,
) -> Result<String, GenError> {
    let s = &f.spec;
    let mut prompt = BTreeSet::from(["OutputFormatSpec", "PromptOverrides", "PromptStyle"]);
    prompt.insert("render_output_format");
    let mut extract = BTreeSet::from(["Format"]);
    if !s.fields.is_empty() {
        prompt.insert("PromptField");
        extract.insert("FieldKind");
    }
    let has_doc = s.fields.iter().any(|p| p.enum_doc.is_some());
    let sorted = |set: BTreeSet<&'static str>| {
        let mut v: Vec<&str> = set.into_iter().collect();
        v.sort_by_key(|s| (s.starts_with(char::is_lowercase), *s));
        v
    };
    let mut uses = CodeWriter::new();
    if has_doc {
        uses.use_list("std::collections", &["HashMap"]).blank();
    }
    uses.use_list("metaobjects_render::extract", &sorted(extract));
    uses.use_list("metaobjects_render::prompt", &sorted(prompt));
    let items = vec![
        uses.finish()?,
        item(|w| parts.render_fn(w, f))?,
        item(|w| parts.spec_fn(w, f))?,
    ];
    Ok(file(BANNER, &items))
}

/// The shipped [`OutputPromptParts::render_fn`].
pub fn render_fn(w: &mut CodeWriter, f: &FragmentPlan) {
    w.prose(&format!(
        "The output-format fragment of the `{}` prompt: how to shape an answer as a `{}`. \
         Pass `PromptOverrides::default()` for the model's style, examples and instructions, \
         or override any of them at render time.",
        f.template, f.response_name
    ));
    w.line("#[must_use]");
    w.open(vec![
        format!("pub fn render_{}_format", f.module).into(),
        list("(", ["overrides: &PromptOverrides"], ")"),
        " -> String {".into(),
    ]);
    w.line(vec![
        "render_output_format".into(),
        list(
            "(",
            [
                format!("&{}_format_spec()", f.module),
                "overrides".to_string(),
            ],
            ")",
        ),
    ]);
    w.close("}");
}

/// The shipped [`OutputPromptParts::spec_fn`].
pub fn spec_fn(w: &mut CodeWriter, f: &FragmentPlan) {
    let s = &f.spec;
    w.prose(&format!(
        "The output-format descriptor of the `{}` prompt: the fields of `{}`, as the model \
         declares them.",
        f.template, f.response_name
    ));
    w.line("#[must_use]");
    w.open(format!(
        "pub fn {}_format_spec() -> OutputFormatSpec {{",
        f.module
    ));
    let mut locals = Vec::new();
    for p in &s.fields {
        let local = field_ident(&p.name);
        let sets = field_sets(p);
        let binding = if sets.is_empty() {
            format!("let {local} =")
        } else {
            format!("let mut {local} =")
        };
        w.assign(
            &binding,
            vec![
                "PromptField::new".into(),
                list(
                    "(",
                    [
                        literal(&p.name),
                        format!("FieldKind::{:?}", p.kind),
                        p.required.to_string(),
                    ],
                    ");",
                ),
            ],
        );
        for (member, value) in sets {
            w.assign(&format!("{local}.{member} ="), value);
        }
        locals.push(local);
    }
    let format = match s.format {
        Format::Json => "Format::Json",
        Format::Xml => "Format::Xml",
    };
    let style = match s.style {
        PromptStyle::Guide => "PromptStyle::Guide",
        PromptStyle::Inline => "PromptStyle::Inline",
        PromptStyle::ExampleOnly => "PromptStyle::ExampleOnly",
    };
    w.line(vec![
        "OutputFormatSpec ".into(),
        padded(
            "{",
            vec![
                Piece::from(format!("format: {format}")),
                format!("root_name: {}.into()", literal(&s.root_name)).into(),
                format!("style: {style}").into(),
                vec!["fields: ".into(), list("vec![", locals, "]")].into(),
            ],
            "}",
        ),
    ]);
    w.close("}");
}

/// The members of `p` that differ from `PromptField::new(name, kind, required)`, each with
/// the right-hand side that sets it.
fn field_sets(p: &PromptField) -> Vec<(&'static str, Piece)> {
    let text = |s: &str| format!("{}.into()", literal(s));
    let mut out = Vec::new();
    if p.array {
        out.push(("array", "true;".into()));
    }
    if let Some(values) = &p.enum_values {
        out.push((
            "enum_values",
            list("Some(vec![", values.iter().map(|v| text(v)), "]);"),
        ));
    }
    if let Some(doc) = &p.enum_doc {
        // A HashMap has no order of its own: the source lists it by member.
        let sorted: BTreeMap<&String, &String> = doc.iter().collect();
        out.push((
            "enum_doc",
            list(
                "Some(HashMap::from([",
                sorted
                    .into_iter()
                    .map(|(k, v)| format!("({}, {})", text(k), text(v))),
                "]));",
            ),
        ));
    }
    if let Some(v) = &p.example {
        out.push(("example", format!("Some({});", text(v)).into()));
    }
    if let Some(v) = &p.instruction {
        out.push(("instruction", format!("Some({});", text(v)).into()));
    }
    out
}
