//! The language-neutral code writer core (ADR-0063; contract: `spec/code-writer.md`).
//!
//! A generator says WHAT a line contains; the writer decides WHERE it sits. It builds the
//! file in memory and returns a string, so nothing here touches the disk and no formatter
//! runs over the result: `rustfmt` is a test oracle for generated Rust, never a step of
//! generation. The writer never parses the text it is handed. It lays out the structure the
//! generator gave it: lines, blocks, blank-line requests and breakable lists.
//!
//! A line that does not fit the width breaks at its LAST non-empty list, one item per line.
//! With `use_small_heuristics = "Max"` in the generated crate's `rustfmt.toml` that is the
//! rule `rustfmt` applies to a call, a struct literal or a parameter list, which is why a
//! generator keeps one list on a line that may grow.
//!
//! Errors are kept and reported by [`CodeWriter::finish`], so emit code reads as a plain
//! sequence of calls. The first error wins and every later call is ignored.
//!
//! The Rust defaults are four spaces, 100 columns and a trailing comma; the shared
//! conformance cases (`fixtures/writer-conformance/`, dialect `core`) state all three.

use std::fmt;

/// `close()` with no block open.
pub const ERR_WRITER_UNBALANCED_CLOSE: &str = "ERR_WRITER_UNBALANCED_CLOSE";
/// The file was finished with a block still open; the message quotes the line that opened it.
pub const ERR_WRITER_UNCLOSED_BLOCK: &str = "ERR_WRITER_UNCLOSED_BLOCK";
/// `line()` was handed text containing a line break.
pub const ERR_WRITER_NEWLINE_IN_LINE: &str = "ERR_WRITER_NEWLINE_IN_LINE";

/// The width a generated Rust line may reach before its last list breaks.
pub const RUST_WIDTH: usize = 100;
/// One level of indentation in generated Rust.
pub const RUST_INDENT: &str = "    ";

/// The `rustfmt.toml` every generated crate carries. The generated files are written in
/// rustfmt's output form under exactly these settings, which is what makes `cargo fmt` over
/// the output a no-op; a generator that writes a crate writes this beside its manifest.
pub const RUSTFMT_TOML: &str = "# @generated by MetaObjects.\n\
# The generated files are written in rustfmt's output form under these settings; they pin\n\
# that form, so `cargo fmt` over the output changes nothing.\n\
max_width = 100\n\
use_small_heuristics = \"Max\"\n\
short_array_element_width_threshold = 0\n\
reorder_imports = false\n\
reorder_modules = false\n";

/// One top-level item, written on its own. An item with a code line wider than the limit is
/// one rustfmt would lay out in a form the writer does not reproduce (a long method chain,
/// a wide type), so it is marked `#[rustfmt::skip]` and left as written: the output stays
/// stable under `cargo fmt` whatever the model's names are.
pub fn item(build: impl FnOnce(&mut CodeWriter)) -> Result<String, WriterError> {
    let mut w = CodeWriter::new();
    build(&mut w);
    let body = w.finish()?;
    let too_wide = body.lines().any(|l| {
        let code = l.trim_start();
        !code.starts_with("//") && width_of(l) > RUST_WIDTH
    });
    Ok(if too_wide {
        format!("#[rustfmt::skip]\n{body}")
    } else {
        body
    })
}

/// A file: the banner line, then the items one blank line apart.
pub fn file(banner: &str, items: &[String]) -> String {
    let mut out = String::from(banner);
    out.push('\n');
    for i in items {
        out.push('\n');
        out.push_str(i);
    }
    out
}

/// A writer error: one of the shared codes and a message for people.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WriterError {
    pub code: &'static str,
    pub message: String,
}

impl fmt::Display for WriterError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.code, self.message)
    }
}

impl std::error::Error for WriterError {}

/// A bracketed, comma-separated list. Printed on one line when the line fits the width;
/// otherwise opener, one item per line (each followed by a comma) and closer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct List {
    pub open: String,
    pub items: Vec<Piece>,
    pub close: String,
    /// `{ a, b }` (true) versus `[a, b]` or `f(a, b)` (false) when printed on one line.
    pub pad: bool,
}

/// An expression fragment: text, a breakable list, or a concatenation of fragments.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Piece {
    Text(String),
    List(List),
    Seq(Vec<Piece>),
}

impl From<&str> for Piece {
    fn from(s: &str) -> Self {
        Piece::Text(s.to_string())
    }
}

impl From<String> for Piece {
    fn from(s: String) -> Self {
        Piece::Text(s)
    }
}

impl From<&String> for Piece {
    fn from(s: &String) -> Self {
        Piece::Text(s.clone())
    }
}

impl From<List> for Piece {
    fn from(l: List) -> Self {
        Piece::List(l)
    }
}

impl From<Vec<Piece>> for Piece {
    fn from(parts: Vec<Piece>) -> Self {
        Piece::Seq(parts)
    }
}

/// A list with no padding inside its brackets: `[a, b]`, `f(a, b)`, `<A, B>`.
pub fn list<I, P>(open: &str, items: I, close: &str) -> Piece
where
    I: IntoIterator<Item = P>,
    P: Into<Piece>,
{
    Piece::List(List {
        open: open.to_string(),
        items: items.into_iter().map(Into::into).collect(),
        close: close.to_string(),
        pad: false,
    })
}

/// A list padded inside its brackets when it stays on one line: `{ a, b }`.
pub fn padded<I, P>(open: &str, items: I, close: &str) -> Piece
where
    I: IntoIterator<Item = P>,
    P: Into<Piece>,
{
    Piece::List(List {
        open: open.to_string(),
        items: items.into_iter().map(Into::into).collect(),
        close: close.to_string(),
        pad: true,
    })
}

/// Several parts of one line, concatenated: `piece!["fn f", list("(", args, ")"), " {"]`.
#[macro_export]
macro_rules! piece {
    ($($part:expr),* $(,)?) => {
        $crate::writer::Piece::Seq(vec![$($crate::writer::Piece::from($part)),*])
    };
}

// The macro is exported at the crate root, as `macro_rules!` requires; this names it here
// too, so a generator reaches the whole writer through one module.
pub use crate::piece;

/// The three options of the core contract.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WriterOptions {
    /// One level of indentation.
    pub indent: String,
    /// The column a line may reach before its last list breaks, in Unicode code points.
    pub width: usize,
    /// Whether a broken list puts a comma after its last item too.
    pub trailing_comma: bool,
}

impl Default for WriterOptions {
    fn default() -> Self {
        Self {
            indent: RUST_INDENT.to_string(),
            width: RUST_WIDTH,
            trailing_comma: true,
        }
    }
}

/// The core writer.
#[derive(Debug)]
pub struct CodeWriter {
    options: WriterOptions,
    out: Vec<String>,
    /// The text of each line that opened a block still open, outermost first.
    openers: Vec<String>,
    want_blank: bool,
    /// True at the start of the file and right after a block opens: no blank line goes here.
    at_block_start: bool,
    error: Option<WriterError>,
}

impl Default for CodeWriter {
    fn default() -> Self {
        Self::new()
    }
}

fn width_of(s: &str) -> usize {
    if s.is_ascii() {
        s.len()
    } else {
        s.chars().count()
    }
}

/// A piece printed on one line.
pub fn flat(piece: &Piece) -> String {
    let mut out = String::new();
    flat_into(piece, &mut out);
    out
}

fn flat_into(piece: &Piece, out: &mut String) {
    match piece {
        Piece::Text(s) => out.push_str(s),
        Piece::List(l) => {
            out.push_str(&l.open);
            if !l.items.is_empty() {
                if l.pad {
                    out.push(' ');
                }
                for (n, item) in l.items.iter().enumerate() {
                    if n > 0 {
                        out.push_str(", ");
                    }
                    flat_into(item, out);
                }
                if l.pad {
                    out.push(' ');
                }
            }
            out.push_str(&l.close);
        }
        Piece::Seq(parts) => {
            for p in parts {
                flat_into(p, out);
            }
        }
    }
}

/// Split a piece around its LAST non-empty list: text before, the list, text after.
fn last_list(piece: &Piece) -> Option<(String, &List, String)> {
    match piece {
        Piece::Text(_) => None,
        Piece::List(l) => (!l.items.is_empty()).then(|| (String::new(), l, String::new())),
        Piece::Seq(parts) => {
            for i in (0..parts.len()).rev() {
                if let Some((before, l, after)) = last_list(&parts[i]) {
                    let mut head = String::new();
                    for p in &parts[..i] {
                        flat_into(p, &mut head);
                    }
                    head.push_str(&before);
                    let mut tail = after;
                    for p in &parts[i + 1..] {
                        flat_into(p, &mut tail);
                    }
                    return Some((head, l, tail));
                }
            }
            None
        }
    }
}

fn split_lines(snippet: &str) -> Vec<&str> {
    let mut lines = Vec::new();
    let mut rest = snippet;
    loop {
        match rest.find(['\n', '\r']) {
            None => {
                lines.push(rest);
                return lines;
            }
            Some(at) => {
                lines.push(&rest[..at]);
                let crlf = rest[at..].starts_with("\r\n");
                rest = &rest[at + if crlf { 2 } else { 1 }..];
            }
        }
    }
}

impl CodeWriter {
    /// A writer with the Rust defaults.
    pub fn new() -> Self {
        Self::with_options(WriterOptions::default())
    }

    pub fn with_options(options: WriterOptions) -> Self {
        Self {
            options,
            out: Vec::new(),
            openers: Vec::new(),
            want_blank: false,
            at_block_start: true,
            error: None,
        }
    }

    /// One line at the current indent. When the line does not fit the width, the LAST
    /// non-empty list in it is printed one item per line. A line whose text is empty is a
    /// blank-line request.
    pub fn line(&mut self, piece: impl Into<Piece>) -> &mut Self {
        let piece = piece.into();
        self.put(&piece);
        self
    }

    /// Ask for one blank line before whatever is written next. Requests never stack, and
    /// one at the start of the file, right after an opener, right before a closer or at the
    /// end of the file is dropped.
    pub fn blank(&mut self) -> &mut Self {
        self.want_blank = true;
        self
    }

    /// Write the line that opens a block, then indent.
    pub fn open(&mut self, piece: impl Into<Piece>) -> &mut Self {
        let piece = piece.into();
        self.open_piece(&piece);
        self
    }

    /// Dedent, then write the line that closes the block.
    pub fn close(&mut self, piece: impl Into<Piece>) -> &mut Self {
        let piece = piece.into();
        self.close_piece(&piece);
        self
    }

    /// `open(head)`, the body, then `close("}")`: the indent cannot be left unbalanced.
    pub fn block(&mut self, head: impl Into<Piece>, body: impl FnOnce(&mut Self)) -> &mut Self {
        self.block_with(head, "}", body)
    }

    /// [`CodeWriter::block`] with its own closing line.
    pub fn block_with(
        &mut self,
        head: impl Into<Piece>,
        tail: impl Into<Piece>,
        body: impl FnOnce(&mut Self),
    ) -> &mut Self {
        self.open(head);
        body(self);
        self.close(tail)
    }

    /// A multi-line snippet written as it should read. Its common left margin is removed
    /// and it is re-indented to the current level; a blank line in it is a blank-line
    /// request. Every line is re-indented, including lines inside a multi-line string
    /// literal.
    pub fn text(&mut self, snippet: &str) -> &mut Self {
        let mut lines = split_lines(snippet);
        if lines.len() > 1 && lines[0].trim().is_empty() {
            lines.remove(0);
        }
        if lines.last().is_some_and(|l| l.trim().is_empty()) {
            lines.pop();
        }
        let margin = lines
            .iter()
            .filter(|l| !l.trim().is_empty())
            .map(|l| l.len() - l.trim_start().len())
            .min()
            .unwrap_or(0);
        for l in lines {
            if l.trim().is_empty() {
                self.blank();
            } else {
                self.put(&Piece::Text(l[margin..].to_string()));
            }
        }
        self
    }

    /// Each line of `text` as a `///` doc comment (a bare `///` for an empty line).
    pub fn doc(&mut self, text: &str) -> &mut Self {
        for l in text.trim().lines() {
            let l = l.trim_end();
            if l.is_empty() {
                self.put(&Piece::Text("///".to_string()));
            } else {
                self.put(&Piece::Text(format!("/// {l}")));
            }
        }
        self
    }

    /// Generated prose as a `///` doc comment: each line of `text` is a paragraph line, wrapped
    /// at a word boundary so no comment line passes the width. For text the generator wrote;
    /// an author's own description goes through [`CodeWriter::doc`], which keeps their lines.
    pub fn prose(&mut self, text: &str) -> &mut Self {
        for paragraph in text.trim().lines() {
            let mut line = String::new();
            for word in paragraph.split_whitespace() {
                if !line.is_empty() && !self.fits(&format!("/// {line} {word}")) {
                    self.put(&Piece::Text(format!("/// {line}")));
                    line.clear();
                }
                if !line.is_empty() {
                    line.push(' ');
                }
                line.push_str(word);
            }
            if line.is_empty() {
                self.put(&Piece::Text("///".to_string()));
            } else {
                self.put(&Piece::Text(format!("/// {line}")));
            }
        }
        self
    }

    /// `head rhs` as rustfmt lays an assignment out (`let x = f(a, b);`, `const X: T = &[a];`):
    /// on one line when it fits; otherwise the right-hand side alone on the next line, one
    /// level in, when it fits there; otherwise on the first line with its last list broken.
    /// This is rustfmt's rule, not part of the shared core contract.
    pub fn assign(&mut self, head: &str, rhs: impl Into<Piece>) -> &mut Self {
        let rhs = rhs.into();
        let one_line = flat(&rhs);
        let next_line = format!("{}{one_line}", self.options.indent);
        if !self.fits(&format!("{head} {one_line}")) && self.fits(&next_line) {
            self.put(&Piece::Text(head.to_string()));
            self.put(&Piece::Text(next_line));
        } else {
            self.put(&Piece::Seq(vec![Piece::Text(format!("{head} ")), rhs]));
        }
        self
    }

    /// Whether `text` fits on one line at the current indent.
    pub fn fits(&self, text: &str) -> bool {
        width_of(&self.options.indent) * self.openers.len() + width_of(text) <= self.options.width
    }

    /// The finished file: `\n` line endings, no trailing whitespace, one final newline
    /// (none when the file is empty). Fails on the first error any call met, or when a
    /// block is still open.
    pub fn finish(self) -> Result<String, WriterError> {
        if let Some(e) = self.error {
            return Err(e);
        }
        if let Some(opener) = self.openers.last() {
            return Err(WriterError {
                code: ERR_WRITER_UNCLOSED_BLOCK,
                message: format!("unclosed block opened by: {opener}"),
            });
        }
        if self.out.is_empty() {
            return Ok(String::new());
        }
        let mut body = self.out.join("\n");
        body.push('\n');
        Ok(body)
    }

    fn fail(&mut self, code: &'static str, message: String) {
        if self.error.is_none() {
            self.error = Some(WriterError { code, message });
        }
    }

    fn open_piece(&mut self, piece: &Piece) {
        if self.error.is_some() {
            return;
        }
        self.put(piece);
        self.openers.push(flat(piece).trim().to_string());
        self.at_block_start = true;
    }

    fn close_piece(&mut self, piece: &Piece) {
        if self.error.is_some() {
            return;
        }
        if self.openers.pop().is_none() {
            self.fail(
                ERR_WRITER_UNBALANCED_CLOSE,
                format!("close({:?}) with no block open", flat(piece)),
            );
            return;
        }
        self.want_blank = false;
        self.put(piece);
    }

    fn put(&mut self, piece: &Piece) {
        if self.error.is_some() {
            return;
        }
        let raw = flat(piece);
        if raw.contains(['\n', '\r']) {
            self.fail(
                ERR_WRITER_NEWLINE_IN_LINE,
                format!(
                    "line text contains a line break; write each line separately or use text(): {raw:?}"
                ),
            );
            return;
        }
        let text = raw.trim_end();
        if text.is_empty() {
            self.want_blank = true;
            return;
        }
        if self.want_blank && !self.at_block_start {
            self.out.push(String::new());
        }
        self.want_blank = false;
        self.at_block_start = false;
        let split = if self.fits(text) {
            None
        } else {
            last_list(piece)
        };
        let Some((before, group, after)) = split else {
            let mut line = self.options.indent.repeat(self.openers.len());
            line.push_str(text);
            self.out.push(line);
            return;
        };
        self.open_piece(&Piece::Text(before + &group.open));
        let last = group.items.len() - 1;
        for (n, item) in group.items.iter().enumerate() {
            let comma = if n < last || self.options.trailing_comma {
                ","
            } else {
                ""
            };
            self.put(&Piece::Seq(vec![item.clone(), Piece::from(comma)]));
        }
        self.close_piece(&Piece::Text(format!("{}{after}", group.close)));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prose_wraps_at_a_word_boundary_inside_the_width() {
        let mut w = CodeWriter::with_options(WriterOptions {
            width: 24,
            ..WriterOptions::default()
        });
        w.block("mod m {", |w| {
            w.prose("one two three four five six\n\nseven");
        });
        assert_eq!(
            w.finish().unwrap(),
            "mod m {\n    /// one two three\n    /// four five six\n    ///\n    /// seven\n}\n"
        );
    }

    #[test]
    fn a_block_helper_keeps_the_indent_balanced() {
        let mut w = CodeWriter::new();
        w.block("impl A {", |w| {
            w.block("fn f() {", |w| {
                w.line("1");
            });
            w.blank();
        });
        assert_eq!(
            w.finish().unwrap(),
            "impl A {\n    fn f() {\n        1\n    }\n}\n"
        );
    }

    #[test]
    fn a_long_call_breaks_at_its_list_with_a_trailing_comma() {
        let mut w = CodeWriter::with_options(WriterOptions {
            width: 20,
            ..WriterOptions::default()
        });
        w.line(crate::piece![
            "let x = f",
            list("(", ["alpha", "beta", "gamma"], ")"),
            ";"
        ]);
        assert_eq!(
            w.finish().unwrap(),
            "let x = f(\n    alpha,\n    beta,\n    gamma,\n);\n"
        );
    }

    #[test]
    fn the_first_error_wins_and_later_calls_are_ignored() {
        let mut w = CodeWriter::new();
        w.close("}").line("a\nb").line("fine");
        let e = w.finish().unwrap_err();
        assert_eq!(e.code, ERR_WRITER_UNBALANCED_CLOSE);
    }

    #[test]
    fn doc_lines_are_trimmed() {
        let mut w = CodeWriter::new();
        w.doc("One.  \n\nTwo.");
        assert_eq!(w.finish().unwrap(), "/// One.\n///\n/// Two.\n");
    }
}
