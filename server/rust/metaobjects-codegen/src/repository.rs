//! The `repository` generator: data access over `sqlx` for every stored entity, one crate per
//! package, on Postgres and SQLite.
//!
//! For the package `acme::shop` it writes:
//!
//! ```text
//! <out>/acme_shop_store/Cargo.toml     the crate (the data-access crate, the model crates it names)
//! <out>/acme_shop_store/src/lib.rs     one `pub mod` per stored entity
//! <out>/acme_shop_store/src/<type>.rs  one entity: its table and its reads and writes
//! <out>/meta_store/                    the data access every store crate uses
//! ```
//!
//! Per stored entity (concrete, backed by a `source.rdb`), the module `<type>` holds:
//!
//! - `TABLE`, the table as data: its physical name and schema, the column of each field and
//!   how it is stored, its key, and for a subtype of a single-table hierarchy its
//!   discriminator;
//! - `list` (a `meta_store::Query`: the nine filter operators by field name, sort and page)
//!   and `count`;
//! - `get`, `update` and `delete` when it has a single key of text or a whole number, and
//!   `create`, unless its store is a view, which is read only;
//! - per lifecycle field (an enum with transitions, ADR-0066), `transition_<field>`: the
//!   guarded update that moves the row to a state only while it is in one of the states the
//!   transition leaves, in one statement, so two writers cannot both win.
//!
//! The types they take and return are the `entity` generator's (`<Name>`, `<Name>Create`,
//! `<Name>Patch`), so this generator runs with `entity`. A row is read into the JSON its
//! model type deserializes from and a body is serialized and bound column by column, which
//! keeps the model crates free of `sqlx`: the store crate is the only one that knows a
//! database is there. The functions take any `meta_store::Conn`: a `PgConnection`, a
//! `SqliteConnection`, or a transaction on either (`&mut *tx`).
//!
//! Not generated yet: stores for projections and reports, many-to-many traversal, and
//! `@storage: flattened` value objects (an entity with one is refused by name).

use std::collections::{BTreeMap, BTreeSet};

use metaobjects::naming::{
    NamingCtx, NamingRegistry, is_tph_subtype, resolve_column_name, resolve_table_name,
    resolve_table_schema,
};
use metaobjects::node::{NodeId, Tree};
use metaobjects::rules_names::rules_names_of;
use metaobjects::validate::util::ObjectIndex;
use metaobjects_codegen::emitted::STORE_RS;
use metaobjects_codegen::generator::{
    ERR_UNSUPPORTED, EmittedFile, GenContext, GenError, Generator,
};
use metaobjects_codegen::names::literal;
use metaobjects_codegen::plan::{
    CratePlan, FieldPlan, Kind, Plan, Route, STORE_CRATE, STORE_SUFFIX, SUPPORT_CRATE, StructPlan,
    Ty,
};
use metaobjects_codegen::writer::{
    CodeWriter, Manifest, RUSTFMT_TOML, file, fixed, item, list, padded, piece, sibling_dep,
    toml_string,
};

/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects repository generator. Do not edit: change the model and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects repository generator. Do not edit: change the model and run `cargo meta gen`.";

const ATTR_DISCRIMINATOR: &str = "discriminator";
const ATTR_DISCRIMINATOR_VALUE: &str = "discriminatorValue";
const ATTR_INT_VALUE_MAP: &str = "intValueMap";
const ATTR_STRING_VALUE_MAP: &str = "stringValueMap";
const ATTR_STORAGE: &str = "storage";
const STORAGE_FLATTENED: &str = "flattened";
const TYPE_ORIGIN: &str = "origin";

/// The `sqlx` the store crates are written for.
const SQLX: &str = r#"{ version = "0.8", default-features = false, features = ["runtime-tokio", "chrono", "json"] }"#;

/// The repository generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct RepositoryGenerator;

impl Generator for RepositoryGenerator {
    fn name(&self) -> &str {
        "repository"
    }

    fn identity(&self) -> String {
        format!("repository:{FORMAT}")
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl RepositoryParts for RepositoryGenerator {}

/// The pieces of the repository generator's output, one method each (ADR-0063 item 7). Each
/// default is the shipped piece: implement this for a generator of your own, override the
/// piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape). An override can call the
/// shipped piece, a public function of this module with the same name. Not a stability
/// contract: the methods may change in a minor release, and the CHANGELOG says when.
pub trait RepositoryParts {
    /// Every file: one store crate per package with a stored entity, and the shared
    /// data-access crate.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// The shared data-access crate's files.
    fn store_crate(&self) -> Vec<EmittedFile> {
        store_crate()
    }

    /// A store crate's `Cargo.toml`, with a dependency on each model crate it names.
    fn manifest(&self, name: &str, c: &CratePlan, deps: &BTreeSet<String>) -> String {
        cargo_toml(name, c, deps)
    }

    /// A store crate's `src/lib.rs`: a module per stored entity.
    fn lib_file(&self, package: &str, modules: &[String]) -> String {
        lib_file(package, modules)
    }

    /// One stored entity's file: its table, then its reads and writes.
    fn entity_file(&self, e: &StoredEntity) -> Result<String, GenError> {
        entity_file(e)
    }
}

// ---- the plan ------------------------------------------------------------------------------

/// One column of a stored entity, as `TABLE` describes it.
pub struct ColumnPlan {
    pub field: String,
    pub column: String,
    /// The `meta_store::Kind` expression.
    pub kind: String,
    pub array: bool,
    /// For an enum stored as other values, the const that holds its map: its name, its type
    /// and each `(member, stored)` pair as Rust text. `kind` names the const.
    pub map: Option<(String, &'static str, Vec<String>)>,
}

/// One lifecycle of a stored entity: the field and the path of its enum type.
pub struct LifecyclePlan {
    pub field: String,
    /// The function's name: `transition_<field in snake case>`.
    pub function: String,
    pub state_type: String,
}

/// One stored entity, with everything its file needs resolved.
pub struct StoredEntity {
    /// The object's name in the model.
    pub object: String,
    pub module: String,
    pub row: String,
    pub create: String,
    pub patch: String,
    pub schema: Option<String>,
    pub table: String,
    pub columns: Vec<ColumnPlan>,
    /// The key field and the type a call takes it as, when the entity has a single key of
    /// text or a whole number.
    pub key: Option<(String, String)>,
    /// Every field of the primary identity, for `TABLE.key` when it is a single one.
    pub key_field: Option<String>,
    pub read_only: bool,
    pub discriminator: Option<(String, String)>,
    pub lifecycles: Vec<LifecyclePlan>,
}

fn unsupported(message: String) -> GenError {
    GenError::new(ERR_UNSUPPORTED, message)
}

fn ty_path(ty: &Ty) -> String {
    match ty {
        Ty::Str => "String".to_string(),
        Ty::Prim(p) => (*p).to_string(),
        Ty::Ip => "std::net::IpAddr".to_string(),
        Ty::Decimal => format!("{SUPPORT_CRATE}::wire::Decimal"),
        Ty::Duration => format!("{SUPPORT_CRATE}::wire::Duration"),
        Ty::Ref(r) => format!("{}::{}", r.crate_name, r.type_name),
        Ty::Map(v) => format!("std::collections::BTreeMap<String, {}>", ty_path(v)),
    }
}

/// The `{member: stored}` pairs of an enum's `@intValueMap` or `@stringValueMap`.
fn value_map(tree: &Tree, field: NodeId, attr: &str) -> Option<Vec<(String, serde_json::Value)>> {
    // ADR-0039: resolving. A field may take the map from the enum it extends.
    let map = tree.attr(field, attr)?.as_object()?;
    Some(map.iter().map(|(k, v)| (k.clone(), v.clone())).collect())
}

type ColumnKind = (String, bool, Option<(String, &'static str, Vec<String>)>);

fn column_kind(tree: &Tree, f: &FieldPlan, what: &str) -> Result<ColumnKind, GenError> {
    let scalar = |k: &str| (format!("Kind::{k}"), f.array, None);
    let map_const = format!("{}_STORED", screaming(&f.wire));
    Ok(match f.kind {
        Kind::String | Kind::Uri => scalar("Text"),
        Kind::Int => scalar("Int"),
        Kind::Long | Kind::Currency => scalar("Long"),
        Kind::Double => scalar("Double"),
        Kind::Float => scalar("Float"),
        Kind::Boolean => scalar("Bool"),
        Kind::Decimal => scalar("Decimal"),
        Kind::Date => scalar("Date"),
        Kind::Time => scalar("Time"),
        Kind::Timestamp if f.local_time => scalar("Timestamp"),
        Kind::Timestamp => scalar("TimestampTz"),
        Kind::Uuid => scalar("Uuid"),
        Kind::Inet => scalar("Inet"),
        Kind::Duration => scalar("Duration"),
        Kind::Enum => {
            if let Some(map) = value_map(tree, f.node, ATTR_INT_VALUE_MAP) {
                let pairs = map
                    .iter()
                    .map(|(m, v)| {
                        v.as_i64()
                            .map(|i| format!("({}, {i})", literal(m)))
                            .ok_or_else(|| {
                                unsupported(format!(
                                    "{what}: @intValueMap maps {m} to a non-integer"
                                ))
                            })
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                (
                    format!("Kind::IntEnum({map_const})"),
                    f.array,
                    Some((map_const, "&[(&str, i64)]", pairs)),
                )
            } else if let Some(map) = value_map(tree, f.node, ATTR_STRING_VALUE_MAP) {
                let pairs = map
                    .iter()
                    .map(|(m, v)| {
                        v.as_str()
                            .map(|t| format!("({}, {})", literal(m), literal(t)))
                            .ok_or_else(|| {
                                unsupported(format!(
                                    "{what}: @stringValueMap maps {m} to a non-string"
                                ))
                            })
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                (
                    format!("Kind::StringEnum({map_const})"),
                    f.array,
                    Some((map_const, "&[(&str, &str)]", pairs)),
                )
            } else {
                scalar("Text")
            }
        }
        // A value object, a list of them and a map are each one JSON column.
        Kind::Object | Kind::Map => ("Kind::Json".to_string(), false, None),
    })
}

/// The base of `obj`'s single-table hierarchy's discriminator field, and `obj`'s own value.
fn discriminator(tree: &Tree, obj: NodeId) -> Option<(String, String)> {
    if !is_tph_subtype(tree, obj) {
        return None;
    }
    // ADR-0039 sanctioned own: `@discriminatorValue` is THIS subtype's value, and the field is
    // found by reading each ancestor's own `@discriminator`.
    let value = tree
        .own_attr(obj, ATTR_DISCRIMINATOR_VALUE)
        .and_then(|a| a.value.as_str())?
        .to_string();
    let mut seen = vec![obj];
    let mut cur = tree.node(obj).super_node;
    while let Some(n) = cur {
        if seen.contains(&n) {
            return None;
        }
        seen.push(n);
        // ADR-0039 sanctioned own: see above.
        if let Some(field) = tree
            .own_attr(n, ATTR_DISCRIMINATOR)
            .and_then(|a| a.value.as_str())
            .filter(|f| !f.is_empty())
        {
            return Some((field.to_string(), value));
        }
        cur = tree.node(n).super_node;
    }
    None
}

fn snake_ident(name: &str) -> String {
    metaobjects_codegen::names::snake(name)
}

/// `intEnumVal` as a const's name: `INT_ENUM_VAL`.
fn screaming(name: &str) -> String {
    snake_ident(name).trim_start_matches("r#").to_uppercase()
}

/// The stored entity of `s`.
fn stored_entity(
    tree: &Tree,
    naming: &NamingCtx<'_>,
    s: &StructPlan,
    route: &Route,
    lifecycles: &BTreeMap<NodeId, Vec<String>>,
) -> Result<StoredEntity, GenError> {
    let fail = |e: metaobjects::errors::MetaError| unsupported(e.to_string());
    let mut columns = Vec::new();
    for f in &s.fields {
        let what = format!("{}.{}", s.name, f.wire);
        // A derived field is computed on read by a projection; an entity stores none.
        if tree
            .children(f.node)
            .iter()
            .any(|&c| tree.node(c).type_name == TYPE_ORIGIN)
        {
            continue;
        }
        if f.kind == Kind::Object
            && tree.attr(f.node, ATTR_STORAGE).and_then(|v| v.as_str()) == Some(STORAGE_FLATTENED)
        {
            return Err(unsupported(format!(
                "{what} is stored flattened, which the Rust repository generator does not write yet"
            )));
        }
        let (kind, array, map) = column_kind(tree, f, &what)?;
        columns.push(ColumnPlan {
            field: f.wire.clone(),
            column: resolve_column_name(tree, f.node, naming).map_err(fail)?,
            kind,
            array,
            map,
        });
    }
    let primary: Vec<&FieldPlan> = s.fields.iter().filter(|f| f.primary).collect();
    let key_field = match primary.as_slice() {
        [only] => Some(only.wire.clone()),
        _ => None,
    };
    let key = route.key.map(|k| {
        let f = &s.fields[k];
        let ty = match &f.ty {
            Ty::Str => "&str".to_string(),
            other => ty_path(other),
        };
        (f.wire.clone(), ty)
    });
    let mut cycles = Vec::new();
    for field in lifecycles.get(&s.node).into_iter().flatten() {
        let Some(f) = s.fields.iter().find(|f| &f.wire == field) else {
            continue;
        };
        if f.array {
            continue;
        }
        cycles.push(LifecyclePlan {
            field: field.clone(),
            function: format!("transition_{}", snake_ident(field)),
            state_type: ty_path(&f.ty),
        });
    }
    let row = format!("{}::{}", s.crate_name, s.type_name);
    Ok(StoredEntity {
        object: s.name.clone(),
        module: s.module(),
        create: format!("{}::{}", s.crate_name, s.create_name()),
        patch: format!("{}::{}", s.crate_name, s.patch_name()),
        row,
        schema: resolve_table_schema(tree, s.node, naming).map_err(fail)?,
        table: resolve_table_name(tree, s.node, naming).map_err(fail)?,
        columns,
        key,
        key_field,
        read_only: route.read_only,
        discriminator: discriminator(tree, s.node),
        lifecycles: cycles,
    })
}

/// The shipped [`RepositoryParts::render`], through `parts`.
pub fn render<P: RepositoryParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let tree = ctx.tree;
    let plan = Plan::of(ctx)?;
    let selected = plan.selected_crates(ctx.entities)?;
    let registry = NamingRegistry::builtin();
    let naming = NamingCtx::new(&registry, &ctx.collection.physical_naming);

    // The lifecycle fields of each entity, from the engine walk the rules layers share.
    let index = ObjectIndex::build(tree, ctx.root);
    let mut lifecycles: BTreeMap<NodeId, Vec<String>> = BTreeMap::new();
    for p in rules_names_of(
        tree,
        ctx.root,
        &index,
        &ctx.collection.config.rules,
        &|_| true,
    ) {
        for e in p.entities {
            lifecycles
                .entry(e.node)
                .or_default()
                .extend(e.lifecycles.into_iter().map(|l| l.field));
        }
    }

    let mut files = Vec::new();
    for (cname, c) in &plan.crates {
        if selected.as_ref().is_some_and(|sel| !sel.contains(cname)) {
            continue;
        }
        let served: Vec<&StructPlan> = plan.served(c).collect();
        if served.is_empty() {
            continue;
        }
        let name = format!("{cname}{STORE_SUFFIX}");
        let mut deps: BTreeSet<String> = BTreeSet::from([cname.to_string()]);
        let mut modules = Vec::new();
        for s in served {
            let route = s.route.as_ref().expect("a served entity has a route");
            let e = stored_entity(tree, &naming, s, route, &lifecycles)?;
            for f in &s.fields {
                if let Some(t) = f.ty.type_ref() {
                    deps.insert(t.crate_name.clone());
                }
                if matches!(f.ty, Ty::Decimal | Ty::Duration) {
                    deps.insert(SUPPORT_CRATE.to_string());
                }
            }
            files.push(EmittedFile::new(
                format!("{name}/src/{}.rs", e.module),
                parts.entity_file(&e)?,
            ));
            modules.push(e.module);
        }
        modules.sort();
        files.push(EmittedFile::new(
            format!("{name}/Cargo.toml"),
            parts.manifest(&name, c, &deps),
        ));
        files.push(EmittedFile::new(
            format!("{name}/rustfmt.toml"),
            RUSTFMT_TOML.to_string(),
        ));
        files.push(EmittedFile::new(
            format!("{name}/src/lib.rs"),
            parts.lib_file(&c.package, &modules),
        ));
    }
    if !files.is_empty() {
        files.extend(parts.store_crate());
    }
    Ok(files)
}

// ---- the data-access crate ---------------------------------------------------------------

/// The shipped [`RepositoryParts::store_crate`]: `meta_store`, the data access every store
/// crate uses. It is generated, so the output depends on nothing from MetaObjects.
pub fn store_crate() -> Vec<EmittedFile> {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, STORE_CRATE);
    m.entry(
        "description",
        &toml_string("Data access over sqlx for the generated MetaObjects store crates."),
    );
    m.blank().table("features");
    m.entry("default", r#"["postgres", "sqlite"]"#);
    m.entry("postgres", r#"["sqlx/postgres"]"#);
    m.entry("sqlite", r#"["sqlx/sqlite"]"#);
    m.blank().table("dependencies");
    m.entry(SUPPORT_CRATE, &sibling_dep(SUPPORT_CRATE));
    m.entry(
        "chrono",
        r#"{ version = "0.4", default-features = false, features = ["std"] }"#,
    );
    m.entry("serde", &toml_string("1"));
    m.entry("serde_json", &toml_string("1"));
    m.entry("sqlx", SQLX);
    let file = |name: &str, text: String| EmittedFile::new(format!("{STORE_CRATE}/{name}"), text);
    vec![
        file("Cargo.toml", m.finish()),
        file("rustfmt.toml", RUSTFMT_TOML.to_string()),
        file("src/lib.rs", fixed(BANNER, STORE_RS)),
    ]
}

// ---- one store crate -----------------------------------------------------------------------

/// The shipped [`RepositoryParts::manifest`].
pub fn cargo_toml(name: &str, c: &CratePlan, deps: &BTreeSet<String>) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "Data access for the stored entities of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    m.entry(STORE_CRATE, &sibling_dep(STORE_CRATE));
    for dep in deps {
        m.entry(dep, &sibling_dep(dep));
    }
    m.finish()
}

/// The shipped [`RepositoryParts::lib_file`].
pub fn lib_file(package: &str, modules: &[String]) -> String {
    let mut w = CodeWriter::new();
    w.line(BANNER).blank();
    if package.is_empty() {
        w.line("//! Data access for the stored entities of the MetaObjects model that declares no package.");
    } else {
        w.line(format!(
            "//! Data access for the stored entities of the MetaObjects package `{package}`."
        ));
    }
    w.line("//!");
    w.line("//! One module per entity: its `TABLE` and its reads and writes, over any `meta_store::Conn`.");
    w.blank();
    for module in modules {
        w.line(format!("pub mod {module};"));
    }
    w.finish().expect("a lib.rs opens no block")
}

// ---- one entity ------------------------------------------------------------------------------

fn wrap(e: metaobjects_codegen::writer::WriterError) -> GenError {
    GenError::new(e.code, e.message)
}

const CONN: &str = "C: Conn + ?Sized";

/// `pub async fn <name><C>(c: &mut C, <params>) -> Result<<ret>, StoreError> { <body> }`.
fn function(w: &mut CodeWriter, doc: &str, name: &str, params: &[String], ret: &str, body: &str) {
    w.blank();
    w.prose(doc);
    let mut all = vec!["c: &mut C".to_string()];
    all.extend(params.iter().cloned());
    let head = piece![
        format!("pub async fn {name}<{CONN}>"),
        list("(", all, ")"),
        format!(" -> Result<{ret}, StoreError> {{")
    ];
    w.block(head, |w| {
        w.line(body);
    });
}

fn table_item(w: &mut CodeWriter, e: &StoredEntity) {
    let opt = |v: &Option<String>| {
        v.as_ref()
            .map_or("None".to_string(), |s| format!("Some({})", literal(s)))
    };
    for c in &e.columns {
        if let Some((name, ty, pairs)) = &c.map {
            w.prose(&format!("What `{}` stores for each member.", c.field));
            w.assign(
                &format!("const {name}: {ty} ="),
                list("&[", pairs.clone(), "];"),
            );
            w.blank();
        }
    }
    let columns: Vec<metaobjects_codegen::writer::Piece> = e
        .columns
        .iter()
        .map(|c| {
            let ctor = if c.array { "list" } else { "new" };
            piece![
                format!("Column::{ctor}"),
                list(
                    "(",
                    [literal(&c.field), literal(&c.column), c.kind.clone()],
                    ")"
                )
            ]
        })
        .collect();
    let discriminator = e
        .discriminator
        .as_ref()
        .map_or("None".to_string(), |(f, v)| {
            format!("Some(({}, {}))", literal(f), literal(v))
        });
    let fields: Vec<metaobjects_codegen::writer::Piece> = vec![
        format!("object: {}", literal(&e.object)).into(),
        format!("schema: {}", opt(&e.schema)).into(),
        format!("name: {}", literal(&e.table)).into(),
        format!("key: {}", opt(&e.key_field)).into(),
        piece!["columns: ", list("&[", columns, "]")],
        format!("writable: {}", !e.read_only).into(),
        format!("discriminator: {discriminator}").into(),
    ];
    let place = match &e.schema {
        Some(schema) => format!("`{schema}.{}`", e.table),
        None => format!("`{}`", e.table),
    };
    w.prose(&format!("Where `{}` rows are stored: {place}.", e.object));
    w.line(piece![
        "pub const TABLE: Table = ",
        padded("Table {", fields, "};")
    ]);
}

/// The shipped [`RepositoryParts::entity_file`].
pub fn entity_file(e: &StoredEntity) -> Result<String, GenError> {
    let mut items = Vec::new();
    let mut names = vec![
        "Conn",
        "Query",
        "Filter",
        "StoreError",
        "Table",
        "Column",
        "Kind",
    ];
    names.sort_unstable();
    items.push(
        item(|w| {
            w.use_list("meta_store", &names);
        })
        .map_err(wrap)?,
    );
    items.push(item(|w| table_item(w, e)).map_err(wrap)?);
    let row = &e.row;
    let body = item(|w| {
        w.prose(&format!("The `{}` rows the query selects, in its order and page.", e.object));
        let head = piece![
            format!("pub async fn list<{CONN}>"),
            list("(", ["c: &mut C".to_string(), "query: &Query".to_string()], ")"),
            format!(" -> Result<Vec<{row}>, StoreError> {{")
        ];
        w.block(head, |w| {
            w.line("meta_store::list(c, &TABLE, query).await");
        });
        function(
            w,
            "How many rows the filter selects.",
            "count",
            &["filter: Option<&Filter>".to_string()],
            "u64",
            "meta_store::count(c, &TABLE, filter).await",
        );
        if let Some((key, ty)) = &e.key {
            function(
                w,
                &format!("The row whose `{key}` is `id`, or `None`."),
                "get",
                &[format!("id: {ty}")],
                &format!("Option<{row}>"),
                "meta_store::get(c, &TABLE, id).await",
            );
        }
        if !e.read_only {
            function(
                w,
                "Inserts the row and reads it back as stored, with what the database filled in.",
                "create",
                &[format!("body: &{}", e.create)],
                row,
                "meta_store::create(c, &TABLE, body).await",
            );
            if let Some((key, ty)) = &e.key {
                function(
                    w,
                    &format!(
                        "Sets the members the patch carries on the row whose `{key}` is `id` and reads it back; `None` when there is no such row."
                    ),
                    "update",
                    &[format!("id: {ty}"), format!("patch: &{}", e.patch)],
                    &format!("Option<{row}>"),
                    "meta_store::update(c, &TABLE, id, patch).await",
                );
                function(
                    w,
                    &format!("Deletes the row whose `{key}` is `id`; `false` when there was none."),
                    "delete",
                    &[format!("id: {ty}")],
                    "bool",
                    "meta_store::delete(c, &TABLE, id).await",
                );
                for l in &e.lifecycles {
                    function(
                        w,
                        &format!(
                            "The guarded update of the lifecycle `{}`: moves the row whose `{key}` is `id` to `to` only while its state is one of `from`, in one statement. `false` when no row matched: it is gone, or another writer moved it first.",
                            l.field
                        ),
                        &l.function,
                        &[
                            format!("id: {ty}"),
                            format!("from: &[{}]", l.state_type),
                            format!("to: {}", l.state_type),
                        ],
                        "bool",
                        &format!("meta_store::transition(c, &TABLE, id, {}, from, &to).await", literal(&l.field)),
                    );
                }
            }
        }
    })
    .map_err(wrap)?;
    items.push(body);
    Ok(file(BANNER, &items))
}
