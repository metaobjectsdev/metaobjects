//! The `contract-types` generator: the shapes a caller and a service exchange through a
//! package's declared operations, one crate per package (ADR-0067 §1, layer 1).
//!
//! In Rust the entity generator's model crate already is the contract for an entity: its read
//! struct, `<Entity>Create` and `<Entity>Patch` with `validate()`, and its value objects, with
//! no persistence mapping in any of them. This generator builds on it (it needs `entity`, as
//! C#'s does) and adds what the model crate has no place for. For the package `acme::shop`
//! that declares operations it writes:
//!
//! ```text
//! <out>/acme_shop_contract/Cargo.toml          the crate (the model crates, meta_contract)
//! <out>/acme_shop_contract/src/lib.rs          its modules and exports
//! <out>/acme_shop_contract/src/<projection>.rs the read shape of a projection an operation returns
//! <out>/acme_shop_contract/src/operations.rs   each operation's input, output and errors
//! <out>/meta_contract/                         the wire error codes, statuses and bodies
//! ```
//!
//! Per operation (`placeOrder`): `PlaceOrderInput`, the `@inputRef` value object;
//! `PlaceOrderOutput`, the `@outputRef` object (a `Vec` of it when `@many`);
//! `PlaceOrderBusinessError`, the codes its body may return (`@errors`), serialized as the code;
//! and `PlaceOrderError`, the error body it answers with, whose code is a fixed one or a business
//! one. A projection's read shape is the struct the entity generator writes for an object: a
//! view-backed projection is a served read, which the model crate already holds, and any other is
//! written here. A model that declares no operation gets nothing from this generator.
//!
//! Which operations and what they resolve to come from the engine walk
//! ([`metaobjects::rules_names::rules_names_of`] and the model's own references), so an owned
//! copy changes the files' shape and keeps that walk.

use std::collections::{BTreeMap, BTreeSet, HashSet};

use metaobjects::node::{NodeId, Tree};
use metaobjects::rules_names::{OperationKind, rules_names_of};
use metaobjects::validate::util::ObjectIndex;
use metaobjects_codegen::emitted::CONTRACT_RS;
use metaobjects_codegen::generator::{
    ERR_NAME_COLLISION, ERR_UNSUPPORTED, EmittedFile, GenContext, GenError, Generator,
};
use metaobjects_codegen::names::{PRELUDE_TYPES, crate_name, literal, type_ident};
use metaobjects_codegen::plan::{
    CONTRACT_CRATE, EnumPlan, FieldPlan, NullMembers, Plan, SUPPORT_CRATE, StructPlan, Ty,
    is_served_read,
};
use metaobjects_codegen::writer::{
    CodeWriter, Manifest, RUSTFMT_TOML, file, fixed, item, list, sibling_dep, toml_string,
};

/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects contract-types generator. Do not edit: change the model and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects contract-types generator. Do not edit: change the model and run `cargo meta gen`.";

pub use metaobjects_codegen::plan::CONTRACT_SUFFIX;

const ATTR_INPUT_REF: &str = "inputRef";
const ATTR_OUTPUT_REF: &str = "outputRef";
const ATTR_MANY: &str = "many";
const SUB_PROJECTION: &str = "projection";
const OPERATIONS_MODULE: &str = "operations";

/// The contract-types generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct ContractTypesGenerator;

impl Generator for ContractTypesGenerator {
    fn name(&self) -> &str {
        "contract-types"
    }

    fn identity(&self) -> String {
        format!("contract-types:{FORMAT}")
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl ContractTypesParts for ContractTypesGenerator {}

/// The pieces of the contract-types generator's output, one method each (ADR-0063 item 7).
/// Each default is the shipped piece: implement this for a generator of your own, override the
/// piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape). An override can call the
/// shipped piece, a public function of this module with the same name. Not a stability
/// contract: the methods may change in a minor release, and the CHANGELOG says when.
pub trait ContractTypesParts {
    /// Every file: one contract crate per package with a declared operation, and the shared
    /// wire error crate.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// The wire error crate's files.
    fn errors_crate(&self) -> Vec<EmittedFile> {
        errors_crate()
    }

    /// A contract crate's `Cargo.toml`.
    fn manifest(&self, c: &ContractCrate) -> String {
        cargo_toml(c)
    }

    /// A contract crate's `src/lib.rs`: its modules and exports.
    fn lib_file(&self, c: &ContractCrate) -> String {
        lib_file(c)
    }

    /// A projection's file: its read shape and its enums.
    fn shape_file(
        &self,
        plan: &Plan,
        s: &StructPlan,
        current: &str,
        shadowed: &BTreeSet<String>,
    ) -> Result<String, GenError> {
        shape_file(plan, s, current, shadowed)
    }

    /// A contract crate's `src/operations.rs`.
    fn operations_file(&self, c: &ContractCrate) -> Result<String, GenError> {
        operations_file(self, c)
    }

    /// One operation's types.
    fn operation_item(&self, w: &mut CodeWriter, o: &OperationContract) {
        operation_item(w, o);
    }
}

// ---- the plan ----------------------------------------------------------------------------

/// One declared operation, with its references resolved to Rust paths.
pub struct OperationContract {
    pub name: String,
    pub kind: OperationKind,
    /// The type-name stem: the operation's name in pascal case (`placeOrder`: `PlaceOrder`).
    pub stem: String,
    /// The `@inputRef` value object's path, when declared.
    pub input: Option<String>,
    /// The `@outputRef` object's path, when declared.
    pub output: Option<String>,
    /// `@many`: the output is a list.
    pub many: bool,
    /// Each business error's code with its variant, in declaration order.
    pub errors: Vec<(String, String)>,
}

/// One package's contract crate.
pub struct ContractCrate {
    /// The crate's name (`acme_shop_contract`).
    pub name: String,
    /// The package (`acme::shop`), or `""` for a model with none.
    pub package: String,
    /// The projections whose read shape the crate holds: each one's module, file text and the
    /// types it exports.
    pub shapes: Vec<(String, String, Vec<String>)>,
    pub operations: Vec<OperationContract>,
    /// The generated crates it names.
    pub deps: BTreeSet<String>,
}

/// The Rust path of the planned object `node`, from the crate `current`.
fn type_path(
    plan: &Plan,
    node: NodeId,
    current: &str,
    deps: &mut BTreeSet<String>,
) -> Option<String> {
    let s = plan.structs.iter().find(|s| s.node == node)?;
    if s.crate_name == current {
        return Some(format!("crate::{}", s.type_name));
    }
    deps.insert(s.crate_name.clone());
    Some(format!("{}::{}", s.crate_name, s.type_name))
}

fn is_true(tree: &Tree, node: NodeId, attr: &str) -> bool {
    tree.attr(node, attr).and_then(serde_json::Value::as_bool) == Some(true)
}

/// The shipped [`ContractTypesParts::render`], through `parts`.
pub fn render<P: ContractTypesParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let tree = ctx.tree;
    let index = ObjectIndex::build(tree, ctx.root);
    let packages: Vec<_> = rules_names_of(
        tree,
        ctx.root,
        &index,
        &ctx.collection.config.rules,
        &|_| true,
    )
    .into_iter()
    .filter(|p| !p.operations.is_empty())
    .collect();
    if packages.is_empty() {
        return Ok(Vec::new());
    }

    // The projections an operation returns get a read shape; no other projection is planned,
    // so one the operations never reach cannot fail the run.
    let mut shapes: HashSet<NodeId> = HashSet::new();
    for p in &packages {
        for o in &p.operations {
            if let Some(out) = index.ref_target(tree, o.node, ATTR_OUTPUT_REF)
                && tree.node(out).sub_type == SUB_PROJECTION
                && !tree.node(out).is_abstract
                // A served projection's read shape is in its model crate already.
                && !is_served_read(tree, out)
            {
                shapes.insert(out);
            }
        }
    }
    let base = Plan::of(ctx)?;
    let plan = Plan::with_projections(ctx, CONTRACT_SUFFIX, &shapes)?;
    check_model_crates_unmoved(&base, &plan)?;
    let selected = base.selected_crates(ctx.entities)?;

    let mut crates: BTreeMap<String, ContractCrate> = BTreeMap::new();
    for p in packages {
        // A run limited to some entities writes the contract crates of their packages only.
        if selected
            .as_ref()
            .is_some_and(|sel| !sel.contains(&crate_name(&p.package)))
        {
            continue;
        }
        let name = format!("{}{CONTRACT_SUFFIX}", crate_name(&p.package));
        if base.crates.contains_key(&name) {
            return Err(GenError::new(
                ERR_NAME_COLLISION,
                format!(
                    "the contract crate of {:?} and a model crate are both {name}",
                    p.package
                ),
            ));
        }
        let mut stems: BTreeMap<String, String> = BTreeMap::new();
        let mut ops = Vec::new();
        let mut deps = BTreeSet::new();
        for o in p.operations {
            let stem = type_ident(&o.name);
            if let Some(other) = stems.insert(stem.clone(), o.name.clone()) {
                return Err(GenError::new(
                    ERR_NAME_COLLISION,
                    format!(
                        "the operations {other:?} and {:?} of {:?} would both be named {stem}",
                        o.name, p.package
                    ),
                ));
            }
            let resolve = |attr: &str, deps: &mut BTreeSet<String>| {
                match index
                .ref_target(tree, o.node, attr)
            {
                None => Ok(None),
                Some(target) => type_path(&plan, target, &name, deps).map(Some).ok_or_else(|| {
                    GenError::new(
                        ERR_UNSUPPORTED,
                        format!(
                            "the operation {} names {} in @{attr}, which is not a concrete entity, value object or projection the Rust generators write",
                            o.name,
                            tree.resolution_key(target)
                        ),
                    )
                }),
            }
            };
            let input = resolve(ATTR_INPUT_REF, &mut deps)?;
            let output = resolve(ATTR_OUTPUT_REF, &mut deps)?;
            let mut variants: BTreeMap<String, String> = BTreeMap::new();
            let mut errors = Vec::new();
            for code in &o.errors {
                let v = type_ident(code);
                if let Some(other) = variants.insert(v.clone(), code.clone()) {
                    return Err(GenError::new(
                        ERR_NAME_COLLISION,
                        format!(
                            "the business errors {other:?} and {code:?} of {} would both be the Rust variant {v}",
                            o.name
                        ),
                    ));
                }
                errors.push((code.clone(), v));
            }
            ops.push(OperationContract {
                many: is_true(tree, o.node, ATTR_MANY),
                kind: o.kind,
                stem,
                input,
                output,
                errors,
                name: o.name,
            });
        }
        crates.insert(
            name.clone(),
            ContractCrate {
                name,
                package: p.package,
                shapes: Vec::new(),
                operations: ops,
                deps,
            },
        );
    }

    // The read shapes, each in its package's contract crate.
    for (cname, cplan) in &plan.crates {
        if !cname.ends_with(CONTRACT_SUFFIX) || base.crates.contains_key(cname) {
            continue;
        }
        // A projection of a package the run did not select is not written.
        if selected
            .as_ref()
            .is_some_and(|sel| !sel.contains(&crate_name(&cplan.package)))
        {
            continue;
        }
        // A package that declares no operation still holds the read shape of a projection
        // another package's operation returns.
        let c = crates
            .entry(cname.clone())
            .or_insert_with(|| ContractCrate {
                name: cname.clone(),
                package: cplan.package.clone(),
                shapes: Vec::new(),
                operations: Vec::new(),
                deps: BTreeSet::new(),
            });
        // A std type the crate's own types shadow is spelled by its full path.
        let shadowed: BTreeSet<String> = cplan
            .structs
            .iter()
            .flat_map(|&i| {
                let s = &plan.structs[i];
                std::iter::once(s.type_name.clone())
                    .chain(s.enums.iter().map(|e| e.type_name.clone()))
            })
            .filter(|n| PRELUDE_TYPES.contains(&n.as_str()))
            .collect();
        let mut support = false;
        for &i in &cplan.structs {
            let s = &plan.structs[i];
            let mut exports = vec![s.type_name.clone()];
            exports.extend(s.enums.iter().map(|e| e.type_name.clone()));
            support |= s
                .fields
                .iter()
                .any(|f| matches!(f.ty, Ty::Decimal | Ty::Duration));
            let text = parts.shape_file(&plan, s, cname, &shadowed)?;
            c.shapes.push((s.module(), text, exports));
        }
        c.shapes.sort_by(|a, b| a.0.cmp(&b.0));
        c.deps.extend(cplan.deps.iter().cloned());
        if support {
            c.deps.insert(SUPPORT_CRATE.to_string());
        }
    }

    let mut files = Vec::new();
    if !crates.is_empty() {
        files.extend(parts.errors_crate());
    }
    for c in crates.values() {
        let name = &c.name;
        for (module, text, _) in &c.shapes {
            files.push(EmittedFile::new(
                format!("{name}/src/{module}.rs"),
                text.clone(),
            ));
        }
        if !c.operations.is_empty() {
            files.push(EmittedFile::new(
                format!("{name}/src/{OPERATIONS_MODULE}.rs"),
                parts.operations_file(c)?,
            ));
        }
        files.push(EmittedFile::new(
            format!("{name}/Cargo.toml"),
            parts.manifest(c),
        ));
        files.push(EmittedFile::new(
            format!("{name}/rustfmt.toml"),
            RUSTFMT_TOML.to_string(),
        ));
        files.push(EmittedFile::new(
            format!("{name}/src/lib.rs"),
            parts.lib_file(c),
        ));
    }
    Ok(files)
}

/// The model crates the entity generator writes must be the same with the projections planned:
/// a shared enum only a projection uses would otherwise be one the entity generator never
/// writes.
fn check_model_crates_unmoved(base: &Plan, plan: &Plan) -> Result<(), GenError> {
    for (cname, c) in &plan.crates {
        let Some(b) = base.crates.get(cname) else {
            continue;
        };
        for (_, e) in &c.shared_enums {
            if !b
                .shared_enums
                .iter()
                .any(|(_, x)| x.type_name == e.type_name)
            {
                return Err(GenError::new(
                    ERR_UNSUPPORTED,
                    format!(
                        "the shared enum {} is used only by a projection an operation returns, so the entity generator does not write it; give an entity or value object a field of it",
                        e.type_name
                    ),
                ));
            }
        }
    }
    Ok(())
}

