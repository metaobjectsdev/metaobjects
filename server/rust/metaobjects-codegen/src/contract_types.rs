/// The shipped [`ContractTypesParts::errors_crate`]: `meta_contract`, the wire error codes,
/// statuses and bodies every contract crate names.
pub fn errors_crate() -> Vec<EmittedFile> {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, CONTRACT_CRATE);
    m.entry(
        "description",
        &toml_string("The wire error contract of the generated MetaObjects REST API: codes, statuses and bodies."),
    );
    m.blank().table("dependencies");
    m.entry("serde", r#"{ version = "1", features = ["derive"] }"#);
    let file =
        |name: &str, text: String| EmittedFile::new(format!("{CONTRACT_CRATE}/{name}"), text);
    vec![
        file("Cargo.toml", m.finish()),
        file("rustfmt.toml", RUSTFMT_TOML.to_string()),
        file("src/lib.rs", fixed(BANNER, CONTRACT_RS)),
    ]
}

/// The shipped [`ContractTypesParts::manifest`].
pub fn cargo_toml(c: &ContractCrate) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, &c.name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "The contract types of the declared operations of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    m.entry("serde", r#"{ version = "1", features = ["derive"] }"#);
    let mut deps = c.deps.clone();
    deps.insert(CONTRACT_CRATE.to_string());
    for dep in &deps {
        m.entry(dep, &sibling_dep(dep));
    }
    m.finish()
}

/// The shipped [`ContractTypesParts::lib_file`].
pub fn lib_file(c: &ContractCrate) -> String {
    let mut w = CodeWriter::new();
    w.line(BANNER).blank();
    if c.package.is_empty() {
        w.line("//! The contract types of the operations of the MetaObjects model that declares no package.");
    } else {
        w.line(format!(
            "//! The contract types of the operations of the MetaObjects package `{}`.",
            c.package
        ));
    }
    w.line("//!");
    w.line(
        "//! `operations` holds what each operation takes, returns and answers an error with; an",
    );
    w.line("//! entity's own shapes are in its model crate. The wire error bodies are `meta_contract`'s.");
    w.blank();
    for (module, _, _) in &c.shapes {
        w.line(format!("mod {module};"));
    }
    if !c.operations.is_empty() {
        w.line(format!("pub mod {OPERATIONS_MODULE};"));
    }
    if !c.shapes.is_empty() {
        w.blank();
        for (module, _, exports) in &c.shapes {
            for e in exports {
                w.line(format!("pub use {module}::{e};"));
            }
        }
    }
    w.finish().expect("a lib.rs opens no block")
}

fn std_name(shadowed: &BTreeSet<String>, short: &str, full: &str) -> String {
    if shadowed.contains(short) {
        full.to_string()
    } else {
        short.to_string()
    }
}

fn ty_text(ty: &Ty, current: &str, shadowed: &BTreeSet<String>) -> String {
    match ty {
        Ty::Str => std_name(shadowed, "String", "std::string::String"),
        Ty::Prim(p) => (*p).to_string(),
        Ty::Ip => "std::net::IpAddr".to_string(),
        Ty::Decimal => format!("{SUPPORT_CRATE}::wire::Decimal"),
        Ty::Duration => format!("{SUPPORT_CRATE}::wire::Duration"),
        Ty::Ref(r) if r.crate_name == current => format!("crate::{}", r.type_name),
        Ty::Ref(r) => format!("{}::{}", r.crate_name, r.type_name),
        Ty::Map(v) => format!(
            "std::collections::BTreeMap<{}, {}>",
            std_name(shadowed, "String", "std::string::String"),
            ty_text(v, current, shadowed)
        ),
    }
}

/// A read member's type: optional when the model lets it be absent (a credential always is).
fn member_type(f: &FieldPlan, current: &str, shadowed: &BTreeSet<String>) -> String {
    let mut text = ty_text(&f.ty, current, shadowed);
    if f.boxed {
        text = format!("{}<{text}>", std_name(shadowed, "Box", "std::boxed::Box"));
    }
    if f.array {
        text = format!("{}<{text}>", std_name(shadowed, "Vec", "std::vec::Vec"));
    }
    if f.optional || f.credential {
        text = format!(
            "{}<{text}>",
            std_name(shadowed, "Option", "std::option::Option")
        );
    }
    text
}

/// The shipped [`ContractTypesParts::shape_file`]: a projection's read shape, a row as a
/// service returns it, read the way the entity generator reads one (the same names, member
/// types and `wire.nullMembers`), and the enums its fields declare. A projection is read-only,
/// so it has nothing a caller sends and no `validate()`.
pub fn shape_file(
    plan: &Plan,
    s: &StructPlan,
    current: &str,
    shadowed: &BTreeSet<String>,
) -> Result<String, GenError> {
    let mut items = vec![item(|w| read_struct(w, plan, s, current, shadowed)).map_err(wrap)?];
    for e in &s.enums {
        items.push(item(|w| enum_item(w, e)).map_err(wrap)?);
    }
    Ok(file(BANNER, &items))
}

fn read_struct(
    w: &mut CodeWriter,
    plan: &Plan,
    s: &StructPlan,
    current: &str,
    shadowed: &BTreeSet<String>,
) {
    if let Some(doc) = &s.doc {
        w.doc(doc);
    }
    w.line("#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]");
    if s.fields.is_empty() {
        w.line(format!("pub struct {} {{}}", s.type_name));
        return;
    }
    w.block(format!("pub struct {} {{", s.type_name), |w| {
        for f in &s.fields {
            if let Some(doc) = &f.doc {
                w.doc(doc);
            }
            let mut attrs: Vec<String> = Vec::new();
            if f.bare_ident() != f.wire {
                attrs.push(format!("rename = {}", literal(&f.wire)));
            }
            if f.optional || f.credential {
                // A row follows the project's `wire.nullMembers`; a credential is never part
                // of one.
                if f.credential {
                    attrs.push("default".to_string());
                }
                if f.credential || plan.null_members == NullMembers::Omit {
                    attrs.push("skip_serializing_if = \"Option::is_none\"".to_string());
                }
            }
            // rustfmt breaks an attribute's arguments without a trailing comma, so arguments
            // that do not fit one line are written as one attribute each.
            let joined = format!("#[serde({})]", attrs.join(", "));
            if attrs.is_empty() {
            } else if w.fits(&joined) {
                w.line(joined);
            } else {
                for a in attrs {
                    w.line(format!("#[serde({a})]"));
                }
            }
            w.line(format!(
                "pub {}: {},",
                f.ident,
                member_type(f, current, shadowed)
            ));
        }
    });
}

/// An enum a projection's field declares, written as the entity generator writes one: its
/// variants serialize as the member symbols.
fn enum_item(w: &mut CodeWriter, e: &EnumPlan) {
    if let Some(doc) = &e.doc {
        w.doc(doc);
    }
    w.line(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]",
    );
    w.block(format!("pub enum {} {{", e.type_name), |w| {
        for m in &e.members {
            if m.variant != m.wire {
                w.line(format!("#[serde(rename = {})]", literal(&m.wire)));
            }
            w.line(format!("{},", m.variant));
        }
    });
    w.blank();
    w.block(format!("impl {} {{", e.type_name), |w| {
        w.line("/// The wire spelling of the member.");
        w.block("pub const fn as_str(self) -> &'static str {", |w| {
            w.block("match self {", |w| {
                for m in &e.members {
                    w.line(format!(
                        "{}::{} => {},",
                        e.type_name,
                        m.variant,
                        literal(&m.wire)
                    ));
                }
            });
        });
    });
}

fn wrap(e: impl std::fmt::Display) -> GenError {
    GenError::new(ERR_UNSUPPORTED, e.to_string())
}

/// The shipped [`ContractTypesParts::operations_file`], through `parts`.
pub fn operations_file<P: ContractTypesParts + ?Sized>(
    parts: &P,
    c: &ContractCrate,
) -> Result<String, GenError> {
    let mut items = Vec::new();
    items.push(
        item(|w| {
            w.line("//! What each declared operation takes, returns and answers an error with.");
            w.blank();
            let mut names = vec!["ErrorBody", "OperationCode"];
            if c.operations.iter().any(|o| o.errors.is_empty()) {
                names.insert(1, "NoBusinessError");
            }
            w.use_list(CONTRACT_CRATE, &names);
        })
        .map_err(wrap)?,
    );
    for o in &c.operations {
        items.push(item(|w| parts.operation_item(w, o)).map_err(wrap)?);
    }
    Ok(file(BANNER, &items))
}

/// The shipped [`ContractTypesParts::operation_item`].
pub fn operation_item(w: &mut CodeWriter, o: &OperationContract) {
    let stem = &o.stem;
    let what = format!("`{}` (a {})", o.name, o.kind.as_str());
    if let Some(input) = &o.input {
        w.prose(&format!("What {what} takes: its `@inputRef`."));
        w.line(format!("pub type {stem}Input = {input};"));
        w.blank();
    }
    if let Some(output) = &o.output {
        let ty = if o.many {
            format!("Vec<{output}>")
        } else {
            output.clone()
        };
        w.prose(&format!(
            "What {what} returns: its `@outputRef`{}.",
            if o.many { ", a list (`@many`)" } else { "" }
        ));
        w.line(format!("pub type {stem}Output = {ty};"));
        w.blank();
    }
    let business = format!("{stem}BusinessError");
    if o.errors.is_empty() {
        w.prose(&format!("The business errors of {what}: it declares none."));
        w.line(format!("pub type {business} = NoBusinessError;"));
    } else {
        w.prose(&format!(
            "A business error the body of {what} may return (`@errors`), written as its code."
        ));
        w.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]");
        w.block(format!("pub enum {business} {{"), |w| {
            for (code, v) in &o.errors {
                w.line(format!("#[serde(rename = {})]", literal(code)));
                w.line(format!("{v},"));
            }
        });
        w.blank();
        w.block(format!("impl {business} {{"), |w| {
            w.doc("Every one, in declaration order.");
            w.assign(
                &format!("pub const ALL: &[{business}] ="),
                vec![
                    list(
                        "&[",
                        o.errors.iter().map(|(_, v)| format!("{business}::{v}")),
                        "]",
                    ),
                    ";".into(),
                ],
            );
            w.blank().doc("Its wire code.");
            w.line("#[must_use]");
            w.block("pub const fn code(self) -> &'static str {", |w| {
                w.block("match self {", |w| {
                    for (code, v) in &o.errors {
                        w.line(format!("{business}::{v} => {},", literal(code)));
                    }
                });
            });
        });
    }
    w.blank();
    w.prose(&format!(
        "The error body {what} answers with: a fixed code or one of its business errors."
    ));
    w.line(format!(
        "pub type {stem}Error = ErrorBody<OperationCode<{business}>>;"
    ));
}
