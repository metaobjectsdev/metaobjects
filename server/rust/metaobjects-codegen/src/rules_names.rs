/// The shipped [`RulesNamesParts::manifest`].
pub fn cargo_toml(name: &str, c: &RulesCrate) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "The rules names (states, transitions, commands, operations, permissions and errors) of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    if let Some(model) = &c.model_crate {
        m.entry(model, &sibling_dep(model));
    }
    m.finish()
}

fn wrap(e: impl std::fmt::Display) -> GenError {
    GenError::new(ERR_UNSUPPORTED, e.to_string())
}

/// The shipped [`RulesNamesParts::lib_file`], through `parts`.
pub fn lib_file<P: RulesNamesParts + ?Sized>(
    parts: &P,
    c: &RulesCrate,
) -> Result<String, GenError> {
    let mut items = Vec::new();
    let header = item(|w| {
        if c.package.is_empty() {
            w.line("//! The rules names of the MetaObjects model that declares no package.");
        } else {
            w.line(format!(
                "//! The rules names of the MetaObjects package `{}`.",
                c.package
            ));
        }
        w.line("//!");
        w.line("//! Name a state, a transition, a permission or an error code through these types, and");
        w.line("//! code that names one the model renamed or removed stops compiling.");
    })
    .map_err(wrap)?;
    items.push(header);
    items.push(item(|w| parts.shell_errors(w)).map_err(wrap)?);
    for e in &c.entities {
        items.push(item(|w| parts.entity_module(w, e)).map_err(wrap)?);
    }
    if !c.operations.is_empty() {
        items.push(item(|w| parts.operations(w, c)).map_err(wrap)?);
    }
    items.push(item(|w| parts.permissions(w, c)).map_err(wrap)?);
    items.push(item(|w| parts.business_errors(w, c)).map_err(wrap)?);
    Ok(file(BANNER, &items))
}

/// `pub enum <name> { A, B }` and the `impl` head with `ALL`; `body` adds the rest of the impl.
fn closed_enum(
    w: &mut CodeWriter,
    name: &str,
    variants: &[String],
    body: impl FnOnce(&mut CodeWriter),
) {
    w.line(DERIVES);
    if variants.is_empty() {
        w.line(format!("pub enum {name} {{}}"));
    } else {
        w.block(format!("pub enum {name} {{"), |w| {
            for v in variants {
                w.line(format!("{v},"));
            }
        });
    }
    w.blank();
    w.block(format!("impl {name} {{"), |w| {
        w.doc("Every one.");
        w.assign(
            &format!("pub const ALL: &[{name}] ="),
            vec![
                list("&[", variants.iter().map(|v| format!("{name}::{v}")), "]"),
                ";".into(),
            ],
        );
        body(w);
    });
}

/// `pub const fn <head> { match self { Name::V => value, ... } }`, one arm per variant. An arm
/// that does not fit on one line puts its value in a block, as rustfmt does.
fn match_fn<V: Into<Piece>>(
    w: &mut CodeWriter,
    doc: &str,
    head: &str,
    name: &str,
    arms: impl IntoIterator<Item = (String, V)>,
) {
    w.blank().doc(doc);
    w.line("#[must_use]");
    let arms: Vec<(String, Piece)> = arms.into_iter().map(|(v, p)| (v, p.into())).collect();
    w.block(format!("pub const fn {head} {{"), |w| {
        if arms.is_empty() {
            w.line("match self {}");
            return;
        }
        w.block("match self {", |w| {
            for (v, value) in arms {
                let head = format!("{name}::{v} =>");
                if w.fits(&format!("{head} {},", flat(&value))) {
                    w.line(vec![Piece::from(format!("{head} ")), value, ",".into()]);
                } else {
                    w.block(format!("{head} {{"), |w| {
                        w.line(value);
                    });
                }
            }
        });
    });
}

fn str_lit(s: &str) -> String {
    literal(s)
}

/// The shipped [`RulesNamesParts::shell_errors`].
pub fn shell_errors(w: &mut CodeWriter) {
    let codes = shell_error_codes();
    let variants: Vec<String> = codes.iter().map(|c| type_ident(c)).collect();
    w.doc("A wire code the enforcing shell answers with on its own (ADR-0066 §6).");
    closed_enum(w, "ShellError", &variants, |w| {
        match_fn(
            w,
            "Its wire code.",
            "code(self) -> &'static str",
            "ShellError",
            variants
                .iter()
                .cloned()
                .zip(codes.iter().map(|c| str_lit(c))),
        );
    });
}

fn states(l: &LifecycleNames, of: &[String]) -> Vec<String> {
    of.iter()
        .map(|s| {
            format!(
                "State::{}",
                l.variants.get(s).map_or(s.as_str(), String::as_str)
            )
        })
        .collect()
}

fn lifecycle_module(w: &mut CodeWriter, entity: &str, l: &LifecycleNames) {
    let n = &l.names;
    w.prose(&format!(
        "The lifecycle of `{entity}.{}`: its states, initial and terminal states, and transitions.",
        n.field
    ));
    w.block(format!("pub mod {} {{", l.module), |w| {
        w.doc("A state of the lifecycle: the model's own enum for the field.");
        w.line(format!("pub use {} as State;", l.state_type));
        w.blank().doc("The lifecycle's field.");
        w.line(format!("pub const FIELD: &str = {};", str_lit(&n.field)));
        w.blank().doc("Every state, in the model's order.");
        w.assign(
            "pub const STATES: &[State] =",
            vec![list("&[", states(l, &n.states), "]"), ";".into()],
        );
        w.blank()
            .doc("The state a new record starts in (the field's `@default`).");
        w.line(format!(
            "pub const INITIAL: State = {};",
            states(l, std::slice::from_ref(&n.initial))[0]
        ));
        w.blank().doc("The states no transition leaves.");
        w.assign(
            "pub const TERMINAL: &[State] =",
            vec![list("&[", states(l, &n.terminal), "]"), ";".into()],
        );
        w.blank().doc("A transition of the lifecycle.");
        closed_enum(w, "Transition", &l.transitions, |w| {
            match_fn(
                w,
                "Its name in the model.",
                "name(self) -> &'static str",
                "Transition",
                l.transitions
                    .iter()
                    .cloned()
                    .zip(n.transitions.iter().map(|t| str_lit(&t.name))),
            );
            match_fn(
                w,
                "The states it may start from (`@from`).",
                "from(self) -> &'static [State]",
                "Transition",
                l.transitions.iter().cloned().zip(
                    n.transitions
                        .iter()
                        .map(|t| list("&[", states(l, &t.from), "]")),
                ),
            );
            match_fn(
                w,
                "The state it ends in (`@to`).",
                "to(self) -> State",
                "Transition",
                l.transitions.iter().cloned().zip(
                    n.transitions
                        .iter()
                        .map(|t| states(l, std::slice::from_ref(&t.to))[0].clone()),
                ),
            );
        });
    });
}

fn permission_value(p: Option<&String>, c: &dyn Fn(&str) -> String) -> String {
    match p {
        Some(p) => format!("Some(crate::Permission::{})", c(p)),
        None => "None".to_string(),
    }
}

/// The shipped [`RulesNamesParts::entity_module`].
pub fn entity_module(w: &mut CodeWriter, e: &EntityNames) {
    let n = &e.names;
    w.prose(&format!("The rules names of `{}`.", n.name));
    w.block(format!("pub mod {} {{", e.module), |w| {
        for (i, l) in e.lifecycles.iter().enumerate() {
            if i > 0 {
                w.blank();
            }
            lifecycle_module(w, &n.name, l);
        }
        if n.commands.is_empty() {
            return;
        }
        w.blank().prose(&format!(
            "A command derived from a transition of `{}` (ADR-0066 §2): it takes the key and \
             makes its transition.",
            n.name
        ));
        let permission = |p: &str| permission_variant(p);
        closed_enum(w, "Command", &e.commands, |w| {
            match_fn(
                w,
                "Its name in the model: its transition's.",
                "name(self) -> &'static str",
                "Command",
                e.commands
                    .iter()
                    .cloned()
                    .zip(n.commands.iter().map(|c| str_lit(&c.name))),
            );
            match_fn(
                w,
                "The field of the lifecycle its transition belongs to.",
                "lifecycle(self) -> &'static str",
                "Command",
                e.commands
                    .iter()
                    .cloned()
                    .zip(n.commands.iter().map(|c| str_lit(&c.lifecycle))),
            );
            match_fn(
                w,
                "The permission the shell asks the policy about; `None` when it is `@public`.",
                "permission(self) -> Option<crate::Permission>",
                "Command",
                e.commands.iter().cloned().zip(
                    n.commands
                        .iter()
                        .map(|c| permission_value(c.permission.as_ref(), &permission)),
                ),
            );
        });
    });
}

/// The shipped [`RulesNamesParts::operations`].
pub fn operations(w: &mut CodeWriter, c: &RulesCrate) {
    let ops = &c.operations;
    let vs = &c.operation_variants;
    w.doc("Whether an operation changes state or only reads.");
    closed_enum(
        w,
        "OperationKind",
        &["Command".to_string(), "Query".to_string()],
        |w| {
            match_fn(
                w,
                "The word the model uses: the operation's subtype.",
                "as_str(self) -> &'static str",
                "OperationKind",
                [
                    ("Command".to_string(), str_lit("command")),
                    ("Query".to_string(), str_lit("query")),
                ],
            );
        },
    );
    w.blank().doc("A declared operation of the package.");
    closed_enum(w, "Operation", vs, |w| {
        match_fn(
            w,
            "Its name in the model.",
            "name(self) -> &'static str",
            "Operation",
            vs.iter().cloned().zip(ops.iter().map(|o| str_lit(&o.name))),
        );
        match_fn(
            w,
            "Whether it changes state or only reads.",
            "kind(self) -> OperationKind",
            "Operation",
            vs.iter().cloned().zip(
                ops.iter()
                    .map(|o| format!("OperationKind::{}", pascal(o.kind.as_str()))),
            ),
        );
        match_fn(
            w,
            "The permission the shell asks the policy about; `None` when it is `@public`.",
            "permission(self) -> Option<Permission>",
            "Operation",
            vs.iter()
                .cloned()
                .zip(ops.iter().map(|o| match &o.permission {
                    Some(p) => format!("Some(Permission::{})", c.permission(p)),
                    None => "None".to_string(),
                })),
        );
        match_fn(
            w,
            "The transitions a command may make (`@transitions`).",
            "transitions(self) -> &'static [&'static str]",
            "Operation",
            vs.iter().cloned().zip(
                ops.iter()
                    .map(|o| list("&[", o.transitions.iter().map(|t| str_lit(t)), "]")),
            ),
        );
        match_fn(
            w,
            "The business errors a command's body may return (`@errors`).",
            "errors(self) -> &'static [BusinessError]",
            "Operation",
            vs.iter().cloned().zip(ops.iter().map(|o| {
                list(
                    "&[",
                    o.errors
                        .iter()
                        .map(|e| format!("BusinessError::{}", c.error(e))),
                    "]",
                )
            })),
        );
    });
}

/// The shipped [`RulesNamesParts::permissions`].
pub fn permissions(w: &mut CodeWriter, c: &RulesCrate) {
    let vs: Vec<String> = c.permissions.iter().map(|(_, v)| v.clone()).collect();
    w.doc("A permission a point of the package asks about: what a grant table names.");
    closed_enum(w, "Permission", &vs, |w| {
        match_fn(
            w,
            "Its dotted name, as the policy is asked about it.",
            "name(self) -> &'static str",
            "Permission",
            c.permissions.iter().map(|(n, v)| (v.clone(), str_lit(n))),
        );
    });
}

/// The shipped [`RulesNamesParts::business_errors`].
pub fn business_errors(w: &mut CodeWriter, c: &RulesCrate) {
    let vs: Vec<String> = c.errors.iter().map(|(_, v)| v.clone()).collect();
    w.doc("A business error the package's commands declare (`@errors`).");
    closed_enum(w, "BusinessError", &vs, |w| {
        match_fn(
            w,
            "Its wire code.",
            "code(self) -> &'static str",
            "BusinessError",
            c.errors.iter().map(|(code, v)| (v.clone(), str_lit(code))),
        );
    });
}
