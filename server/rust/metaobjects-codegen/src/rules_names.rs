//! The `rules-names` generator: the rules names of each metadata package, one crate per package
//! (ADR-0067 §1, layer 0).
//!
//! The names layer is the tether between the model and hand-written code. A body, a policy or a
//! grant table that names a state, a transition, a permission or an error code through these
//! types stops compiling when the model renames it. For the package `acme::shop` the generator
//! writes:
//!
//! ```text
//! <out>/acme_shop_rules/Cargo.toml     the crate (the model crate, for the state enums)
//! <out>/acme_shop_rules/src/lib.rs     the package's names
//! ```
//!
//! `lib.rs` holds, as enums with `ALL` and a `const fn` per property:
//!
//! - `ShellError`: the wire codes the enforcing shell answers with on its own (ADR-0066 §6);
//! - a module per entity with a lifecycle (`order`), and in it a module per lifecycle field
//!   (`order::status`): `State` (the model's own enum for the field), `FIELD`, `STATES`,
//!   `INITIAL`, `TERMINAL`, and `Transition` with each transition's `from()` and `to()`;
//! - the entity's `Command`s, derived from its unclaimed transitions (ADR-0066 §2), each with
//!   its lifecycle and the `Permission` it asks the policy about (`None` when `@public`);
//! - `Operation`: the package's declared operations, with kind, permission, transitions and
//!   business errors;
//! - `Permission`: every permission a point of the package asks about, what a grant table
//!   names, with its dotted `name()`;
//! - `BusinessError`: the business errors the package's commands declare, with `code()`.
//!
//! What the names ARE comes from [`metaobjects::rules_names::rules_names_of`], the same
//! derivations `cargo meta verify`'s rules gate checks, so a generated name and a verify message
//! never name two different permissions. An owned copy of this generator changes the file's
//! shape and keeps calling that walk. A package that declares no lifecycle and no operation gets
//! no crate, so a model without the rules vocabulary generates nothing here.

use metaobjects::rules_names::{rules_names_of, shell_error_codes};
use metaobjects::validate::util::ObjectIndex;
use metaobjects_codegen::generator::{
    ERR_NAME_COLLISION, ERR_UNSUPPORTED, EmittedFile, GenContext, GenError, Generator,
};
use metaobjects_codegen::layers::rules::{
    EntityNames, LifecycleNames, RULES_SUFFIX, RulesCrate, crate_of, permission_variant,
};
use metaobjects_codegen::names::{crate_name, literal, pascal, type_ident};
use metaobjects_codegen::plan::Plan;
use metaobjects_codegen::writer::{
    CodeWriter, Manifest, Piece, RUSTFMT_TOML, file, flat, item, list, sibling_dep, toml_string,
};

/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects rules-names generator. Do not edit: change the model and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects rules-names generator. Do not edit: change the model and run `cargo meta gen`.";

const DERIVES: &str = "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]";

/// The rules-names generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct RulesNamesGenerator;

impl Generator for RulesNamesGenerator {
    fn name(&self) -> &str {
        "rules-names"
    }

    fn identity(&self) -> String {
        format!("rules-names:{FORMAT}")
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl RulesNamesParts for RulesNamesGenerator {}

/// The pieces of the rules-names generator's output, one method each (ADR-0063 item 7). Each
/// default is the shipped piece: implement this for a generator of your own, override the
/// piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape). An override can call the
/// shipped piece, a public function of this module with the same name. Not a stability
/// contract: the methods may change in a minor release, and the CHANGELOG says when.
pub trait RulesNamesParts {
    /// Every file: one rules crate per package that declares a lifecycle or an operation.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// A rules crate's `Cargo.toml`.
    fn manifest(&self, name: &str, c: &RulesCrate) -> String {
        cargo_toml(name, c)
    }

    /// A rules crate's `src/lib.rs`: every name of the package.
    fn lib_file(&self, c: &RulesCrate) -> Result<String, GenError> {
        lib_file(self, c)
    }

    /// The shell's error codes.
    fn shell_errors(&self, w: &mut CodeWriter) {
        shell_errors(w);
    }

    /// One entity's module: its lifecycles and its commands.
    fn entity_module(&self, w: &mut CodeWriter, e: &EntityNames) {
        entity_module(w, e);
    }

    /// The package's declared operations.
    fn operations(&self, w: &mut CodeWriter, c: &RulesCrate) {
        operations(w, c);
    }

    /// The package's permissions.
    fn permissions(&self, w: &mut CodeWriter, c: &RulesCrate) {
        permissions(w, c);
    }

    /// The package's business errors.
    fn business_errors(&self, w: &mut CodeWriter, c: &RulesCrate) {
        business_errors(w, c);
    }
}

/// The shipped [`RulesNamesParts::render`], through `parts`.
pub fn render<P: RulesNamesParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let index = ObjectIndex::build(ctx.tree, ctx.root);
    let packages = rules_names_of(
        ctx.tree,
        ctx.root,
        &index,
        &ctx.collection.config.rules,
        &|_| true,
    );
    if packages.is_empty() {
        return Ok(Vec::new());
    }
    let plan = Plan::of(ctx)?;
    let selected = plan.selected_crates(ctx.entities)?;
    let mut files = Vec::new();
    for pkg in packages {
        let base = crate_name(&pkg.package);
        // A run limited to some entities writes the rules crates of their packages only.
        if selected.as_ref().is_some_and(|sel| !sel.contains(&base)) {
            continue;
        }
        let name = format!("{base}{RULES_SUFFIX}");
        if plan.crates.contains_key(&name) {
            return Err(GenError::new(
                ERR_NAME_COLLISION,
                format!(
                    "the rules crate of {:?} and a model crate are both {name}",
                    pkg.package
                ),
            ));
        }
        let c = crate_of(&plan, pkg)?;
        files.push(EmittedFile::new(
            format!("{name}/Cargo.toml"),
            parts.manifest(&name, &c),
        ));
        files.push(EmittedFile::new(
            format!("{name}/rustfmt.toml"),
            RUSTFMT_TOML.to_string(),
        ));
        files.push(EmittedFile::new(
            format!("{name}/src/lib.rs"),
            parts.lib_file(&c)?,
        ));
    }
    Ok(files)
}

