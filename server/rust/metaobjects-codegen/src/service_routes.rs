//! The `service-routes` generator: a REST transport over the service layer (ADR-0067 layer 5),
//! one crate per package, written for `axum`.
//!
//! For the package `acme::purchasing` it writes:
//!
//! ```text
//! <out>/acme_purchasing_http/Cargo.toml        the crate
//! <out>/acme_purchasing_http/src/lib.rs        router(): every route of the package
//! <out>/acme_purchasing_http/src/<type>.rs     one entity's list and body rules
//! <out>/meta_http/                             the REST mechanics every one shares
//! ```
//!
//! `router(service, actor)` answers the shared REST contract
//! (`docs/features/api-contract.md`) at the paths the model serves, to be mounted under the
//! API root (`Router::new().nest("/api", acme_purchasing_http::router(service, actor))`). Each
//! route parses its request, calls one operation of the service and sends what it answered: it
//! holds no rules, which are the service's. Per served entity: `GET <path>` (the list, with the
//! REST standard's filter, `search`, sort, page and `withCount`), `GET <path>/{id}`,
//! `POST <path>` (201), `PATCH` and `PUT <path>/{id}`, `DELETE <path>/{id}` (204), and
//! `GET <path>/{id}/<relation>` per many-to-many relationship. A view-backed entity answers
//! its write verbs `405`. Per derived command `POST <path>/{id}/<transition>`; per declared
//! operation its `binding.rest` (`@method`, `@path`), else `GET` for a query and `POST` for a
//! command at `<path>/{id}/<operation>` when it is keyed, `<path>/<operation>` when not.
//!
//! `actor` is a `meta_http::ActorSource<A>`: the app's own reading of who a request runs for,
//! handed to the service untouched. `()` reads no one.
//!
//! It calls the `service` generator's crates, so it runs with that generator and the four it
//! builds on.

