//! The `output-parser` generator: a response parser per responding prompt, one crate per
//! package.
//!
//! A `template.prompt` that declares `@responseRef` names the value object its reply is read
//! into (ADR-0052). For the package `acme::ai` the generator writes:
//!
//! ```text
//! <out>/acme_ai_parsers/Cargo.toml         the crate (metaobjects-render, the response crates)
//! <out>/acme_ai_parsers/src/lib.rs         one `mod` per prompt and a `pub use` of its functions
//! <out>/acme_ai_parsers/src/<prompt>.rs    one prompt: its parsers and its extract descriptor
//! ```
//!
//! Each prompt gets two ways to read a reply into the response type, which is the value
//! object's own struct, written by the `entity` generator (ADR-0056):
//!
//! - `parse_<name>(text) -> Result<T, serde_json::Error>`, the strict parse: the reply must be
//!   exactly the JSON of a `T`. A prompt whose `@responseFormat` is `xml` has none (ADR-0053):
//!   all-or-nothing over a reader that repairs is not a contract anyone can reason about.
//! - `extract_<name>(text, opts) -> Extracted<T>`, the tolerant read of a raw model reply:
//!   fences, prose, comments, trailing commas, cut-off values and synonyms are tolerated, every
//!   field is classified in a report, and it never fails. The typed value is there when the
//!   extracted fields make a complete `T`.
//!
//! `<name>_schema()` returns the extract descriptor both rest on, derived from the response
//! object as every port derives it: nested value objects read to the shared depth, numeric
//! ranges and element counts from the field's validators, `@enumAlias`, `@coerceDefault`,
//! `@default`, `@normalize` and `@xmlText`. The parsers run on the `metaobjects-render`
//! crate, an ordinary Apache-2.0 library.

use std::collections::{BTreeMap, BTreeSet};

use metaobjects::node::{NodeId, Tree};
use metaobjects::validate::util::ObjectIndex;
use metaobjects_codegen::generator::{
    ERR_UNSUPPORTED, EmittedFile, GenContext, GenError, Generator,
};
use metaobjects_codegen::inbound::{
    extract_schema, inbound_templates, reply_format, response_object,
};
use metaobjects_codegen::names::{crate_name, field_ident, literal, snake};
use metaobjects_codegen::plan::Plan;
use metaobjects_codegen::render::extract::{ExtractSchema, FieldSpec, Format, normalize};
use metaobjects_codegen::writer::{
    CodeWriter, Manifest, Piece, RUSTFMT_TOML, file, item, list, padded, sibling_dep, toml_string,
};

/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects output-parser generator. Do not edit: change the model and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects output-parser generator. Do not edit: change the model and run `cargo meta gen`.";

/// The suffix of the parser crate of a package: `shop`'s replies are read by `shop_parsers`.
pub const PARSERS_SUFFIX: &str = "_parsers";

const RENDER_CRATE: &str = "metaobjects-render";
/// The version requirement the generated crate names `metaobjects-render` by.
const RENDER_VERSION: &str = metaobjects_codegen::render::REQUIREMENT;

/// The output-parser generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct OutputParserGenerator;

impl Generator for OutputParserGenerator {
    fn name(&self) -> &str {
        "output-parser"
    }

    fn identity(&self) -> String {
        format!("output-parser:{FORMAT}")
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl OutputParserParts for OutputParserGenerator {}

/// The pieces of the output-parser generator's output, one method each (ADR-0063 item 7). Each
/// default is the shipped piece: implement this for a generator of your own, override the
/// piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape). An override can call the
/// shipped piece, a public function of this module with the same name. Not a stability
/// contract: the methods may change in a minor release, and the CHANGELOG says when.
pub trait OutputParserParts {
    /// Every file: one parsers crate per package with a responding prompt.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// A parsers crate's `Cargo.toml`.
    fn manifest(&self, name: &str, c: &ParsersCrate) -> String {
        cargo_toml(name, c)
    }

    /// A parsers crate's `src/lib.rs`: each module and the parsers it exports.
    fn lib_file(&self, c: &ParsersCrate) -> String {
        lib_file(c)
    }

    /// One prompt's file: its imports, its parsers and its schemas.
    fn parser_file(&self, p: &ParserPlan) -> Result<String, GenError> {
        parser_file(self, p)
    }

    /// The strict `parse_*` of a prompt whose reply is exactly JSON.
    fn strict_fn(&self, w: &mut CodeWriter, p: &ParserPlan) {
        strict_fn(w, p);
    }

    /// The tolerant `extract_*`.
    fn extract_fn(&self, w: &mut CodeWriter, p: &ParserPlan) {
        extract_fn(w, p);
    }

    /// One schema function: the root's (`root`) or a nested object's.
    fn schema_fn(
        &self,
        w: &mut CodeWriter,
        p: &ParserPlan,
        root: bool,
        name: &str,
        s: &ExtractSchema,
    ) {
        schema_fn(w, p, root, name, s);
    }
}

/// The shipped [`OutputParserParts::render`], through `parts`.
pub fn render<P: OutputParserParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let templates = inbound_templates(ctx.tree, ctx.root);
    if templates.is_empty() {
        return Ok(Vec::new());
    }
    let plan = Plan::of(ctx)?;
    let selected = plan.selected_crates(ctx.entities)?;
    let index = ObjectIndex::build(ctx.tree, ctx.root);
    let mut crates: BTreeMap<String, ParsersCrate> = BTreeMap::new();
    for t in templates {
        let parser = parser_of(ctx.tree, &plan, &index, t)?;
        if selected
            .as_ref()
            .is_some_and(|sel| !sel.contains(&parser.response_crate))
        {
            continue;
        }
        let package = ctx.tree.effective_package(t);
        let c = crates
            .entry(format!("{}{PARSERS_SUFFIX}", crate_name(&package)))
            .or_default();
        c.package = package;
        c.deps.insert(parser.response_crate.clone());
        c.parsers.push(parser);
    }
    let mut files = Vec::new();
    for (name, c) in &crates {
        parsers_crate(parts, name, c, &mut files)?;
    }
    Ok(files)
}

/// What one prompt's parser needs.
pub struct ParserPlan {
    pub template: String,
    pub module: String,
    pub response_name: String,
    pub response_crate: String,
    pub response_type: String,
    pub strict: bool,
    pub schema: ExtractSchema,
}

fn parser_of(
    tree: &Tree,
    plan: &Plan,
    index: &ObjectIndex,
    t: NodeId,
) -> Result<ParserPlan, GenError> {
    let n = tree.node(t);
    let unsupported = |message: String| GenError::new(ERR_UNSUPPORTED, message);
    let response = response_object(tree, index, t).ok_or_else(|| {
        unsupported(format!(
            "template.prompt \"{}\": @responseRef resolves to no object",
            n.name
        ))
    })?;
    let s = plan
        .structs
        .iter()
        .find(|s| s.node == response)
        .ok_or_else(|| {
            unsupported(format!(
                "template.prompt \"{}\": the response \"{}\" is not a value object, and the \
                 Rust port generates a type only for value objects and entities",
                n.name,
                tree.node(response).name
            ))
        })?;
    let format = reply_format(tree, t);
    Ok(ParserPlan {
        template: n.name.clone(),
        module: snake(&n.name),
        response_name: tree.node(response).name.clone(),
        response_crate: s.crate_name.clone(),
        response_type: s.type_name.clone(),
        strict: format == Format::Json,
        schema: extract_schema(tree, index, response, format),
    })
}

// ---- one parsers crate -----------------------------------------------------------------

#[derive(Default)]
pub struct ParsersCrate {
    pub package: String,
    pub deps: BTreeSet<String>,
    pub parsers: Vec<ParserPlan>,
}

fn parsers_crate<P: OutputParserParts + ?Sized>(
    parts: &P,
    name: &str,
    c: &ParsersCrate,
    files: &mut Vec<EmittedFile>,
) -> Result<(), GenError> {
    for p in &c.parsers {
        files.push(EmittedFile::new(
            format!("{name}/src/{}.rs", p.module),
            parts.parser_file(p)?,
        ));
    }
    files.push(EmittedFile::new(
        format!("{name}/Cargo.toml"),
        parts.manifest(name, c),
    ));
    files.push(EmittedFile::new(
        format!("{name}/rustfmt.toml"),
        RUSTFMT_TOML.to_string(),
    ));
    files.push(EmittedFile::new(
        format!("{name}/src/lib.rs"),
        parts.lib_file(c),
    ));
    Ok(())
}

/// The shipped [`OutputParserParts::manifest`].
pub fn cargo_toml(name: &str, c: &ParsersCrate) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "Response parsers for the prompts of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    m.entry(RENDER_CRATE, &toml_string(RENDER_VERSION));
    if c.parsers.iter().any(|p| p.strict) {
        m.entry("serde_json", &toml_string("1"));
    }
    for dep in &c.deps {
        m.entry(dep, &sibling_dep(dep));
    }
    m.finish()
}

/// The shipped [`OutputParserParts::lib_file`].
pub fn lib_file(c: &ParsersCrate) -> String {
    let mut w = CodeWriter::new();
    w.line(BANNER).blank();
    if c.package.is_empty() {
        w.line("//! Response parsers for the prompts of the MetaObjects model that declares no package.");
    } else {
        w.line(format!(
            "//! Response parsers for the prompts of the MetaObjects package `{}`.",
            c.package
        ));
    }
    w.line("//!");
    w.line(
        "//! Each prompt's reply is read into its response type: `parse_*` exactly, `extract_*`",
    );
    w.line("//! tolerantly, with a report of every field.");
    w.blank();
    let mut parsers: Vec<&ParserPlan> = c.parsers.iter().collect();
    parsers.sort_by(|a, b| a.module.cmp(&b.module));
    for p in &parsers {
        w.line(format!("mod {};", p.module));
    }
    w.blank();
    w.line("pub use metaobjects_render::extract::{ExtractOptions, Extracted, FieldExtraction, Tolerance};");
    for p in &parsers {
        let m = &p.module;
        let mut names = Vec::new();
        if p.strict {
            names.push(format!("parse_{m}"));
        }
        names.push(format!("extract_{m}"));
        names.push(format!("{m}_schema"));
        w.line(format!("pub use {m}::{{{}}};", names.join(", ")));
    }
    w.finish().expect("a lib.rs opens no block")
}

