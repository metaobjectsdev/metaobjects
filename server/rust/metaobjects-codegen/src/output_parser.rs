/// The shipped [`OutputParserParts::parser_file`], through `parts`.
pub fn parser_file<P: OutputParserParts + ?Sized>(
    parts: &P,
    p: &ParserPlan,
) -> Result<String, GenError> {
    // The schemas, root first, then each nested object's in the order it is reached.
    let mut schemas = Vec::new();
    collect_schemas(&format!("{}_schema", p.module), &p.schema, &mut schemas);
    let mut used = BTreeSet::from(["ExtractOptions", "ExtractSchema", "Extracted", "Format"]);
    used.insert("extract_into");
    for (_, s) in &schemas {
        if !s.fields.is_empty() {
            used.insert("FieldKind");
            used.insert("FieldSpec");
        }
    }
    let mut imports: Vec<&str> = used.into_iter().collect();
    imports.sort_by_key(|s| (s.starts_with(char::is_lowercase), *s));
    let mut uses = CodeWriter::new();
    uses.use_list("metaobjects_render::extract", &imports);
    uses.use_list(&p.response_crate, &[&p.response_type]);
    let mut items = vec![uses.finish()?];
    if p.strict {
        items.push(item(|w| parts.strict_fn(w, p))?);
    }
    items.push(item(|w| parts.extract_fn(w, p))?);
    for (i, (name, schema)) in schemas.iter().enumerate() {
        items.push(item(|w| parts.schema_fn(w, p, i == 0, name, schema))?);
    }
    Ok(file(BANNER, &items))
}

/// Each schema in the tree with the name of the function that builds it: `<root>` for the
/// root, `<root>_<field>` for a nested one, and so on down.
fn collect_schemas<'s>(
    name: &str,
    schema: &'s ExtractSchema,
    out: &mut Vec<(String, &'s ExtractSchema)>,
) {
    out.push((name.to_string(), schema));
    for f in &schema.fields {
        if let Some(nested) = &f.nested {
            collect_schemas(&format!("{name}_{}", snake(&f.name)), nested, out);
        }
    }
}

/// The shipped [`OutputParserParts::strict_fn`].
pub fn strict_fn(w: &mut CodeWriter, p: &ParserPlan) {
    w.prose(&format!(
        "Parse a reply to the `{}` prompt that is exactly the JSON of a `{}`.",
        p.template, p.response_name
    ));
    w.doc_break();
    w.prose("# Errors");
    w.prose(&format!(
        "Anything that is not that JSON: prose around it, a fence, a member missing or of the \
         wrong type. Read a raw model reply with [`extract_{}`] instead.",
        p.module
    ));
    w.open(vec![
        format!("pub fn parse_{}", p.module).into(),
        list("(", ["text: &str"], ")"),
        format!(" -> Result<{}, serde_json::Error> {{", p.response_type).into(),
    ]);
    w.line("serde_json::from_str(text)");
    w.close("}");
}

/// The shipped [`OutputParserParts::extract_fn`].
pub fn extract_fn(w: &mut CodeWriter, p: &ParserPlan) {
    w.prose(&format!(
        "Read a raw model reply to the `{}` prompt into a `{}`, tolerantly: fences, prose, \
         comments, trailing commas, cut-off values and synonyms are read through. It never \
         fails: `value` is the answer when the extracted fields make a complete `{}`, and the \
         report classifies every field either way.",
        p.template, p.response_name, p.response_name
    ));
    w.line("#[must_use]");
    w.open(vec![
        format!("pub fn extract_{}", p.module).into(),
        list("(", ["text: &str", "opts: &ExtractOptions"], ")"),
        format!(" -> Extracted<{}> {{", p.response_type).into(),
    ]);
    w.line(vec![
        "extract_into".into(),
        list(
            "(",
            [
                "Some(text)".to_string(),
                format!("&{}_schema()", p.module),
                "opts".to_string(),
            ],
            ")",
        ),
    ]);
    w.close("}");
}

/// The shipped [`OutputParserParts::schema_fn`].
pub fn schema_fn(w: &mut CodeWriter, p: &ParserPlan, root: bool, name: &str, s: &ExtractSchema) {
    if root {
        w.prose(&format!(
            "The extract descriptor of a reply to the `{}` prompt: the fields of `{}`, as \
             the model declares them.",
            p.template, p.response_name
        ));
        w.line("#[must_use]");
        w.open(format!("pub fn {name}() -> ExtractSchema {{"));
    } else {
        w.open(format!("fn {name}() -> ExtractSchema {{"));
    }
    let mut locals = Vec::new();
    for f in &s.fields {
        let local = field_ident(&f.name);
        let sets = field_sets(name, f);
        let binding = if sets.is_empty() {
            format!("let {local} =")
        } else {
            format!("let mut {local} =")
        };
        w.assign(
            &binding,
            vec![
                "FieldSpec::scalar".into(),
                list(
                    "(",
                    [
                        literal(&f.name),
                        format!("FieldKind::{:?}", f.kind),
                        f.required.to_string(),
                    ],
                    ");",
                ),
            ],
        );
        for (member, value) in sets {
            w.assign(&format!("{local}.{member} ="), value);
        }
        locals.push(local);
    }
    let format = match s.format {
        Format::Json => "Format::Json",
        Format::Xml => "Format::Xml",
    };
    w.line(vec![
        "ExtractSchema ".into(),
        padded(
            "{",
            vec![
                Piece::from(format!("format: {format}")),
                format!("root_name: {}.into()", literal(&s.root_name)).into(),
                vec!["fields: ".into(), list("vec![", locals, "]")].into(),
            ],
            "}",
        ),
    ]);
    w.close("}");
}

/// The members of `f` that differ from `FieldSpec::scalar(name, kind, required)`, each with
/// the right-hand side that sets it.
fn field_sets(schema: &str, f: &FieldSpec) -> Vec<(&'static str, Piece)> {
    let text = |s: &str| format!("{}.into()", literal(s));
    let some_text = |s: &Option<String>| s.as_deref().map(|v| format!("Some({});", text(v)).into());
    let mut out = Vec::new();
    if f.array {
        out.push(("array", "true;".into()));
    }
    if let Some(values) = &f.enum_values {
        out.push((
            "enum_values",
            list("Some(vec![", values.iter().map(|v| text(v)), "]);"),
        ));
    }
    if !f.enum_alias.is_empty() {
        out.push((
            "enum_alias",
            list(
                "vec![",
                f.enum_alias
                    .iter()
                    .map(|(from, to)| format!("({}, {})", text(from), text(to))),
                "];",
            ),
        ));
    }
    if let Some(min) = f.min {
        out.push(("min", format!("Some({min:?});").into()));
    }
    if let Some(max) = f.max {
        out.push(("max", format!("Some({max:?});").into()));
    }
    if f.nested.is_some() {
        out.push((
            "nested",
            format!("Some(Box::new({schema}_{}()));", snake(&f.name)).into(),
        ));
    }
    if let Some(v) = some_text(&f.coerce_default) {
        out.push(("coerce_default", v));
    }
    if let Some(v) = some_text(&f.default_value) {
        out.push(("default_value", v));
    }
    if f.normalize != normalize::DEFAULT {
        out.push(("normalize", format!("{};", text(&f.normalize)).into()));
    }
    if f.text_content {
        out.push(("text_content", "true;".into()));
    }
    if let Some(n) = f.min_items {
        out.push(("min_items", format!("Some({n});").into()));
    }
    if let Some(n) = f.max_items {
        out.push(("max_items", format!("Some({n});").into()));
    }
    out
}
