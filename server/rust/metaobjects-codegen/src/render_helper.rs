//! The `render-helper` generator: a typed render function per renderable template, one crate
//! per package.
//!
//! A `template.output` or `template.prompt` names a payload value object (`@payloadRef`) and
//! the Mustache bodies it renders (`@textRef`, or the three parts of an email). For the
//! package `acme::ai` the generator writes:
//!
//! ```text
//! <out>/acme_ai_prompts/Cargo.toml         the crate (metaobjects-render, the payload crates)
//! <out>/acme_ai_prompts/src/lib.rs         one `mod` per template and a `pub use` of each helper
//! <out>/acme_ai_prompts/src/<template>.rs  one template: its payload field tree and its helper
//! ```
//!
//! What becomes what:
//!
//! - a `document` template (the default `@kind`, and every `template.prompt`) gets
//!   `render_<name>(payload, provider) -> Result<String, RenderError>`, escaped for its
//!   `@format` and held to its `@maxChars`;
//! - an `email` template gets `render_<name>(payload, provider) -> Result<EmailDocument, _>`:
//!   the subject and the text body as text, the HTML body as HTML.
//!
//! The payload type is the value object's own struct, written by the `entity` generator
//! (ADR-0056), so this generator runs with `entity`.
//!
//! **The drift gate runs at build time.** Each body the template names is read from the
//! project's template directory (`prompts/` when it exists, else `templates/`) and checked
//! against the payload's field tree, nested value objects included (each `@objectRef`
//! resolved on its exact package-qualified name, ADR-0041). A variable the payload does not
//! have fails `cargo meta gen` with `ERR_VAR_NOT_ON_PAYLOAD`, naming the template, the
//! reference and the variable. The field tree is also written into the helper, and every
//! render checks the body again: a template edited, or served by another provider, after the
//! helper was generated fails the render instead of rendering a blank.
//!
//! The helpers render through the `metaobjects-render` crate, an ordinary Apache-2.0
//! library. Its `FilesystemProvider` reads the same directory layout the gate reads.
//!
//! Not generated yet: helpers over a sourceless `object.projection` payload, which has no
//! Rust type in this port, and Jinja bodies (ADR-0061), which this port does not render.

