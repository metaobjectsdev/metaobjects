/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects render-helper generator. Do not edit: change the model or the template and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects render-helper generator. Do not edit: change the model and run `cargo meta gen`.";

/// The suffix of the render-helper crate of a package: `shop` is rendered by `shop_prompts`.
pub const PROMPTS_SUFFIX: &str = "_prompts";

/// The template directory the drift gate reads, when the project has it.
pub const PROMPTS_DIR: &str = "prompts";
/// The template directory the drift gate reads otherwise.
pub const TEMPLATES_DIR: &str = "templates";

