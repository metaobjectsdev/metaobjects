/// The render-helper generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct RenderHelperGenerator;

impl Generator for RenderHelperGenerator {
    fn name(&self) -> &str {
        "render-helper"
    }

    fn identity(&self) -> String {
        format!("render-helper:{FORMAT}")
    }

    /// Both directories the gate may read: the one that exists decides, and adding the
    /// other changes which, so each is part of the skip key.
    fn extra_inputs(&self) -> Vec<String> {
        vec![PROMPTS_DIR.to_string(), TEMPLATES_DIR.to_string()]
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl RenderHelperParts for RenderHelperGenerator {}

/// The pieces of the render-helper generator's output, one method each (ADR-0063 item 7).
/// Each default is the shipped piece: implement this for a generator of your own, override
/// the piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape; keep this generator's
/// [`Generator::extra_inputs`], since the drift gate reads the template directories). An
/// override can call the shipped piece, a public function of this module with the same name.
/// Not a stability contract: the methods may change in a minor release, and the CHANGELOG
/// says when.
pub trait RenderHelperParts {
    /// Every file: one prompts crate per package with a renderable template, after each
    /// template passes the drift gate.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// A prompts crate's `Cargo.toml`.
    fn manifest(&self, name: &str, c: &PromptsCrate<'_>) -> String {
        cargo_toml(name, c)
    }

    /// A prompts crate's `src/lib.rs`: each module (with the helper it exports) and the
    /// render types a caller needs.
    fn lib_file(&self, package: &str, modules: &[(&str, &str)]) -> String {
        lib_file(package, modules)
    }

    /// One template's file: its imports, its field statics and its helper.
    fn helper_file(&self, h: &HelperPlan<'_>) -> Result<String, GenError> {
        helper_file(self, h)
    }

    /// One template's helper function.
    fn helper_fn(&self, w: &mut CodeWriter, h: &HelperPlan<'_>) {
        helper_fn(w, h);
    }
}

/// The shipped [`RenderHelperParts::render`], through `parts`.
pub fn render<P: RenderHelperParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let templates = renderable(ctx.tree, ctx.root);
    if templates.is_empty() {
        return Ok(Vec::new());
    }
    let plan = Plan::of(ctx)?;
    let selected = plan.selected_crates(ctx.entities)?;
    let index = ObjectIndex::build(ctx.tree, ctx.root);
    let provider = FilesystemProvider::new(template_root(&ctx.collection.config_dir));
    let mut crates: BTreeMap<String, PromptsCrate> = BTreeMap::new();
    for t in templates {
        let helper = helper_of(ctx.tree, &plan, &index, t)?;
        if selected
            .as_ref()
            .is_some_and(|sel| !sel.contains(&helper.payload_crate))
        {
            continue;
        }
        for part in &helper.parts {
            gate(&provider, &helper.template, part.reference, &helper.fields)?;
        }
        let package = ctx.tree.effective_package(t);
        let c = crates
            .entry(format!("{}{PROMPTS_SUFFIX}", crate_name(&package)))
            .or_default();
        c.package = package;
        c.deps.insert(helper.payload_crate.clone());
        c.helpers.push(helper);
    }
    let mut files = Vec::new();
    for (name, c) in &crates {
        prompts_crate(parts, name, c, &mut files)?;
    }
    Ok(files)
}

/// The directory the drift gate reads templates from: `prompts/` when it exists, else
/// `templates/`, as the Python and C# ports default.
pub fn template_root(project_root: &Path) -> std::path::PathBuf {
    let prompts = project_root.join(PROMPTS_DIR);
    if prompts.is_dir() {
        prompts
    } else {
        project_root.join(TEMPLATES_DIR)
    }
}

// ---- the template gate (`cargo meta verify --templates`) -------------------------------

/// What `verify --templates` found: how many bodies it checked, and one line per drift.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TemplateCheck {
    /// The template bodies that resolved and were checked.
    pub checked: usize,
    /// Every finding that fails the gate, as `[Template] ...` lines.
    pub errors: Vec<String>,
}

/// The template gate: every `template.*` body (a tool-call template has none) checked
/// against its payload's field tree, read from [`template_root`]. A `template.prompt` is
/// also held to its `@requiredTags` (and an unused `@requiredSlots` entry is a warning,
/// which never fails). The derivation is the generator's, so the gate and `gen` agree.
pub fn check_templates(tree: &Tree, root: NodeId, project_root: &Path) -> TemplateCheck {
    let root_dir = template_root(project_root);
    let provider = FilesystemProvider::new(&root_dir);
    let index = ObjectIndex::build(tree, root);
    let mut report = TemplateCheck::default();
    // ADR-0039 own: the root's top-level nodes are its declared children.
    let mut templates: Vec<NodeId> = tree
        .own_children(root)
        .iter()
        .copied()
        .filter(|&c| {
            let n = tree.node(c);
            n.type_name == TYPE_TEMPLATE && n.sub_type != TEMPLATE_TOOLCALL && !n.is_abstract
        })
        .collect();
    templates.sort_by(|a, b| tree.node(*a).name.cmp(&tree.node(*b).name));
    for t in templates {
        let name = &tree.node(t).name;
        let Some(payload_ref) = str_attr(tree, t, ATTR_PAYLOAD_REF) else {
            report.errors.push(format!("[{name}] missing @payloadRef."));
            continue;
        };
        let Some(payload) = index
            .ref_target(tree, t, ATTR_PAYLOAD_REF)
            .filter(|&p| tree.node(p).type_name == TYPE_OBJECT)
        else {
            report.errors.push(format!(
                "[{name}] @payloadRef '{payload_ref}' did not resolve to an object."
            ));
            continue;
        };
        let fields = field_tree(tree, &index, payload, &HashSet::new());
        let refs: Vec<&str> = [
            ATTR_TEXT_REF,
            ATTR_SUBJECT_REF,
            ATTR_HTML_BODY_REF,
            ATTR_TEXT_BODY_REF,
        ]
        .iter()
        .filter_map(|a| str_attr(tree, t, a))
        .collect();
        if refs.is_empty() {
            report.errors.push(format!(
                "[{name}] declares no text reference (@textRef / @subjectRef / @htmlBodyRef / @textBodyRef)."
            ));
            continue;
        }
        let is_prompt = tree.node(t).sub_type == TEMPLATE_PROMPT;
        let strings = |attr: &str| -> Vec<String> {
            if !is_prompt {
                return Vec::new();
            }
            tree.attr(t, attr)
                .and_then(Value::as_array)
                .map(|a| {
                    a.iter()
                        .filter_map(Value::as_str)
                        .map(str::to_string)
                        .collect()
                })
                .unwrap_or_default()
        };
        let required_slots = strings(ATTR_REQUIRED_SLOTS);
        let required_tags = strings(ATTR_REQUIRED_TAGS);
        let options = VerifyOptions {
            provider: Some(&provider),
            required_slots: &required_slots,
            required_tags: &required_tags,
        };
        for reference in refs {
            let Some(text) = provider.resolve(reference) else {
                report.errors.push(format!(
                    "[{name}] ref '{reference}' did not resolve under {} (missing template).",
                    root_dir.display()
                ));
                continue;
            };
            report.checked += 1;
            for e in verify::verify(&text, &fields, &options) {
                if e.code != verify::ERR_REQUIRED_SLOT_UNUSED {
                    report.errors.push(format!(
                        "[{name}] ref '{reference}' — {}: {}",
                        e.code, e.path
                    ));
                }
            }
        }
    }
    report
}

// ---- the model read --------------------------------------------------------------------

/// Every renderable template at the root, by name: both subtypes render (ADR-0052).
fn renderable(tree: &Tree, root: NodeId) -> Vec<NodeId> {
    // ADR-0039 own: the root's top-level nodes are its declared children; a root extends
    // nothing, so own and effective agree.
    let mut out: Vec<NodeId> = tree
        .own_children(root)
        .iter()
        .copied()
        .filter(|&c| {
            let n = tree.node(c);
            n.type_name == TYPE_TEMPLATE
                && matches!(n.sub_type.as_str(), TEMPLATE_OUTPUT | TEMPLATE_PROMPT)
                && !n.is_abstract
        })
        .collect();
    out.sort_by(|a, b| tree.node(*a).name.cmp(&tree.node(*b).name));
    out
}

fn str_attr<'t>(tree: &'t Tree, id: NodeId, name: &str) -> Option<&'t str> {
    tree.attr(id, name)
        .and_then(Value::as_str)
        .filter(|s| !s.is_empty())
}

/// One part a helper renders: the body it names and the format it is escaped for.
pub struct PartPlan<'t> {
    /// The member of an [`EmailDocument`] it fills, or `None` for a document.
    pub member: Option<&'static str>,
    pub reference: &'t str,
    pub format: &'t str,
    pub max_chars: Option<u64>,
}

/// What one template's helper needs.
pub struct HelperPlan<'t> {
    pub template: String,
    pub function: String,
    pub module: String,
    pub is_email: bool,
    pub payload_name: String,
    pub payload_crate: String,
    pub payload_type: String,
    pub parts: Vec<PartPlan<'t>>,
    pub fields: Vec<PayloadField>,
}

fn helper_of<'t>(
    tree: &'t Tree,
    plan: &Plan,
    index: &ObjectIndex,
    t: NodeId,
) -> Result<HelperPlan<'t>, GenError> {
    let n = tree.node(t);
    let what = format!("template.{} \"{}\"", n.sub_type, n.name);
    let unsupported = |message: String| GenError::new(ERR_UNSUPPORTED, message);
    let payload_ref = str_attr(tree, t, ATTR_PAYLOAD_REF)
        .ok_or_else(|| unsupported(format!("{what} declares no @payloadRef")))?;
    let payload = index.ref_target(tree, t, ATTR_PAYLOAD_REF).ok_or_else(|| {
        unsupported(format!(
            "{what}: @payloadRef \"{payload_ref}\" resolves to no object"
        ))
    })?;
    let s = plan
        .structs
        .iter()
        .find(|s| s.node == payload)
        .ok_or_else(|| {
            unsupported(format!(
                "{what}: the payload \"{payload_ref}\" is not a value object, and the Rust port \
             generates a type only for value objects and entities"
            ))
        })?;
    let required = |attr: &str| {
        str_attr(tree, t, attr).ok_or_else(|| unsupported(format!("{what} declares no @{attr}")))
    };
    let is_email = str_attr(tree, t, ATTR_KIND) == Some(KIND_EMAIL);
    let parts = if is_email {
        let mut parts = vec![
            PartPlan {
                member: Some("subject"),
                reference: required(ATTR_SUBJECT_REF)?,
                format: FORMAT_TEXT,
                max_chars: None,
            },
            PartPlan {
                member: Some("html_body"),
                reference: required(ATTR_HTML_BODY_REF)?,
                format: FORMAT_HTML,
                max_chars: None,
            },
        ];
        if let Some(reference) = str_attr(tree, t, ATTR_TEXT_BODY_REF) {
            parts.push(PartPlan {
                member: Some("text_body"),
                reference,
                format: FORMAT_TEXT,
                max_chars: None,
            });
        }
        parts
    } else {
        vec![PartPlan {
            member: None,
            reference: required(ATTR_TEXT_REF)?,
            format: str_attr(tree, t, ATTR_FORMAT).unwrap_or(FORMAT_TEXT),
            max_chars: tree.attr(t, ATTR_MAX_CHARS).and_then(Value::as_u64),
        }]
    };
    let module = snake(&n.name);
    Ok(HelperPlan {
        template: n.name.clone(),
        function: format!("render_{module}"),
        module,
        is_email,
        payload_name: tree.node(payload).name.clone(),
        payload_crate: s.crate_name.clone(),
        payload_type: s.type_name.clone(),
        parts,
        fields: field_tree(tree, index, payload, &HashSet::new()),
    })
}

/// The payload's field tree. A `field.object` whose `@objectRef` resolves to a value object
/// pushes that object's fields; a reference cycle stops at an object already on the path.
fn field_tree(
    tree: &Tree,
    index: &ObjectIndex,
    object: NodeId,
    seen: &HashSet<NodeId>,
) -> Vec<PayloadField> {
    if seen.contains(&object) {
        return Vec::new();
    }
    let mut path = seen.clone();
    path.insert(object);
    let mut out = Vec::new();
    for &f in tree.children(object).iter() {
        let node = tree.node(f);
        if node.type_name != TYPE_FIELD {
            continue;
        }
        let is_array = tree.resolved_is_array(f);
        let nested = (node.sub_type == FIELD_OBJECT)
            .then(|| index.ref_target(tree, f, ATTR_OBJECT_REF))
            .flatten()
            .filter(|&target| {
                let t = tree.node(target);
                t.type_name == TYPE_OBJECT && t.sub_type == OBJECT_VALUE
            })
            .map(|target| field_tree(tree, index, target, &path));
        out.push(PayloadField::owned(node.name.clone(), nested, is_array));
    }
    out
}

/// The build-time drift gate for one body: it must resolve, and every finding but an unused
/// required slot (a warning) fails the run.
fn gate(
    provider: &FilesystemProvider,
    template: &str,
    reference: &str,
    fields: &[PayloadField],
) -> Result<(), GenError> {
    let Some(text) = provider.resolve(reference) else {
        return Err(GenError::new(
            ERR_TEMPLATE_REF_UNRESOLVED,
            format!(
                "render-helper drift: template \"{template}\" ref \"{reference}\" — unresolved \
                 (no {}.mustache under {})",
                reference,
                provider.root().display()
            ),
        ));
    };
    let options = VerifyOptions {
        provider: Some(provider),
        ..VerifyOptions::default()
    };
    for e in verify::verify(&text, fields, &options) {
        if e.code == verify::ERR_REQUIRED_SLOT_UNUSED {
            continue;
        }
        let detail = if e.code == verify::ERR_VAR_NOT_ON_PAYLOAD {
            format!("{{{{{}}}}} not on payload VO", e.path)
        } else {
            e.path.clone()
        };
        return Err(GenError::new(
            code_of(&e.code),
            format!(
                "render-helper drift: template \"{template}\" ref \"{reference}\" — {}: {detail}",
                e.code
            ),
        ));
    }
    Ok(())
}

/// A verify code as the `'static` code a [`GenError`] carries.
fn code_of(code: &str) -> &'static str {
    [
        verify::ERR_VAR_NOT_ON_PAYLOAD,
        verify::ERR_PARTIAL_UNRESOLVED,
        verify::ERR_REQUIRED_SLOT_UNUSED,
        verify::ERR_OUTPUT_TAG_MISSING,
        verify::ERR_TEMPLATE_SYNTAX,
        verify::ERR_TEMPLATE_ENGINE_UNSUPPORTED,
    ]
    .into_iter()
    .find(|c| *c == code)
    .unwrap_or(verify::ERR_TEMPLATE_SYNTAX)
}

// ---- one prompts crate -----------------------------------------------------------------

#[derive(Default)]
pub struct PromptsCrate<'t> {
    pub package: String,
    pub deps: BTreeSet<String>,
    pub helpers: Vec<HelperPlan<'t>>,
}

fn prompts_crate<P: RenderHelperParts + ?Sized>(
    parts: &P,
    name: &str,
    c: &PromptsCrate<'_>,
    files: &mut Vec<EmittedFile>,
) -> Result<(), GenError> {
    let mut modules: Vec<(&str, &str)> = Vec::new();
    for h in &c.helpers {
        files.push(EmittedFile::new(
            format!("{name}/src/{}.rs", h.module),
            parts.helper_file(h)?,
        ));
        modules.push((&h.module, &h.function));
    }
    modules.sort();
    files.push(EmittedFile::new(
        format!("{name}/Cargo.toml"),
        parts.manifest(name, c),
    ));
    files.push(EmittedFile::new(
        format!("{name}/rustfmt.toml"),
        RUSTFMT_TOML.to_string(),
    ));
    files.push(EmittedFile::new(
        format!("{name}/src/lib.rs"),
        parts.lib_file(&c.package, &modules),
    ));
    Ok(())
}

/// The shipped [`RenderHelperParts::manifest`].
pub fn cargo_toml(name: &str, c: &PromptsCrate<'_>) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "Typed render helpers for the templates of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    m.entry(RENDER_CRATE, &toml_string(RENDER_VERSION));
    for dep in &c.deps {
        m.entry(dep, &sibling_dep(dep));
    }
    m.finish()
}

/// The shipped [`RenderHelperParts::lib_file`].
pub fn lib_file(package: &str, modules: &[(&str, &str)]) -> String {
    let mut w = CodeWriter::new();
    w.line(BANNER).blank();
    if package.is_empty() {
        w.line("//! Typed render helpers for the templates of the MetaObjects model that declares no package.");
    } else {
        w.line(format!(
            "//! Typed render helpers for the templates of the MetaObjects package `{package}`."
        ));
    }
    w.line("//!");
    w.line(
        "//! Each helper checks its template against the payload's fields before it renders, so a",
    );
    w.line("//! variable the payload does not have fails instead of rendering blank.");
    w.blank();
    for (module, _) in modules {
        w.line(format!("mod {module};"));
    }
    w.blank();
    w.line(
        "pub use metaobjects_render::{EmailDocument, FilesystemProvider, Provider, RenderError};",
    );
    for (module, function) in modules {
        w.line(format!("pub use {module}::{function};"));
    }
    w.finish().expect("a lib.rs opens no block")
}

// ---- one helper ------------------------------------------------------------------------

/// The shipped [`RenderHelperParts::helper_file`], through `parts`.
pub fn helper_file<P: RenderHelperParts + ?Sized>(
    parts: &P,
    h: &HelperPlan<'_>,
) -> Result<String, GenError> {
    let mut imports = vec![
        "Part",
        "PayloadField",
        "Provider",
        "RenderError",
        "render_part",
    ];
    if h.is_email {
        imports.insert(0, "EmailDocument");
    }
    let mut uses = CodeWriter::new();
    uses.use_list("metaobjects_render", &imports);
    uses.use_list(&h.payload_crate, &[&h.payload_type]);
    let mut items = vec![uses.finish()?];
    let mut statics = Vec::new();
    field_statics("FIELDS", &h.fields, &mut statics);
    for (i, (name, fields)) in statics.iter().enumerate() {
        let is_root = i + 1 == statics.len();
        items.push(item(|w| {
            if is_root {
                w.prose(&format!(
                    "The fields of `{}`: the template is checked against them on every render.",
                    h.payload_name
                ));
            }
            w.assign(
                &format!("static {name}: &[PayloadField] ="),
                list("&[", fields.iter().map(String::as_str), "];"),
            );
        })?);
    }
    items.push(item(|w| parts.helper_fn(w, h))?);
    Ok(file(BANNER, &items))
}

/// One `static` per object in the tree, innermost first, so each names only statics above
/// it: a nested `&[...]` would be a temporary a `static` cannot keep.
fn field_statics(name: &str, fields: &[PayloadField], out: &mut Vec<(String, Vec<String>)>) {
    let mut entries = Vec::new();
    for f in fields {
        let field = literal(&f.name);
        entries.push(match (f.fields.as_deref(), f.is_array) {
            (None, false) => format!("PayloadField::scalar({field})"),
            (None, true) => format!("PayloadField::scalar_array({field})"),
            (Some(inner), array) => {
                let nested = format!("{name}_{}", snake(&f.name).to_uppercase());
                field_statics(&nested, inner, out);
                let ctor = if array { "object_array" } else { "object" };
                format!("PayloadField::{ctor}({field}, {nested})")
            }
        });
    }
    out.push((name.to_string(), entries));
}

fn part_literal(p: &PartPlan<'_>) -> Vec<String> {
    let max_chars = p
        .max_chars
        .map_or("None".to_string(), |n| format!("Some({n})"));
    vec![
        format!("reference: {}", literal(p.reference)),
        format!("format: {}", literal(p.format)),
        format!("max_chars: {max_chars}"),
        "fields: FIELDS".to_string(),
    ]
}

/// The shipped [`RenderHelperParts::helper_fn`].
pub fn helper_fn(w: &mut CodeWriter, h: &HelperPlan<'_>) {
    let returns = if h.is_email {
        "EmailDocument"
    } else {
        "String"
    };
    let summary = if h.is_email {
        let parts = if h.parts.len() == 3 {
            "subject, HTML body and text body"
        } else {
            "subject and HTML body"
        };
        format!(
            "Render the `{}` email ({parts}) from a typed `{}` payload.",
            h.template, h.payload_name
        )
    } else {
        format!(
            "Render the `{}` template from a typed `{}` payload.",
            h.template, h.payload_name
        )
    };
    w.prose(&summary);
    w.doc_break();
    w.prose(
        "The template was checked against the payload when this file was generated, and is \
         checked again on every render: a variable the payload does not have fails, it never \
         renders blank.",
    );
    w.doc_break();
    w.prose("# Errors");
    w.prose(
        "A body the provider does not hold, a variable not on the payload, or a render the engine \
         refuses (a budget exceeded, a template that does not parse).",
    );
    let signature = vec![
        format!("pub fn {}", h.function).into(),
        list(
            "(",
            [
                format!("payload: &{}", h.payload_type),
                "provider: &dyn Provider".to_string(),
            ],
            ")",
        ),
        format!(" -> Result<{returns}, RenderError> {{").into(),
    ];
    w.open(signature);
    if h.is_email {
        for p in &h.parts {
            let member = p.member.expect("an email part fills a member");
            w.assign(
                &format!("let {member} ="),
                vec!["Part ".into(), padded("{", part_literal(p), "};")],
            );
        }
        let mut members = Vec::new();
        for p in &h.parts {
            let member = p.member.expect("an email part fills a member");
            let call = format!("render_part(payload, provider, &{member})?");
            members.push(if member == "text_body" {
                format!("{member}: Some({call})")
            } else {
                format!("{member}: {call}")
            });
        }
        if h.parts.len() == 2 {
            members.push("text_body: None".to_string());
        }
        w.line(vec!["Ok(EmailDocument ".into(), padded("{", members, "})")]);
    } else {
        let p = &h.parts[0];
        w.assign(
            "let part =",
            vec!["Part ".into(), padded("{", part_literal(p), "};")],
        );
        w.line("render_part(payload, provider, &part)");
    }
    w.close("}");
}
