//! The `client` generator: a typed HTTP client for the REST API the model implies, one crate
//! per package.
//!
//! Every port's server generators serve the same routes for the same model
//! (`docs/features/api-contract.md`), so a client for them is derivable from the model alone.
//! For the package `acme::billing` the generator writes:
//!
//! ```text
//! <out>/acme_billing_client/Cargo.toml     the crate (the transport crate, the model crates it names)
//! <out>/acme_billing_client/src/lib.rs     one `mod` per served entity and a `pub use` of each type
//! <out>/acme_billing_client/src/<type>.rs  one entity: its client and its list query
//! <out>/meta_client/                       the transport every client crate uses
//! ```
//!
//! What becomes what:
//!
//! - an entity that is served (concrete, backed by a store) gets `<Name>Client`, with `list`
//!   and `page`; `get` when it has a single key of text or a whole number; and `create`,
//!   `update` and `delete` unless its store is a view, which answers reads only;
//! - a subtype of a single-table hierarchy is served under its base, at its discriminator
//!   value: `accounts/member`;
//! - a many-to-many relationship gets `<relation>_of(id)`, the rows on its far side;
//! - `<Name>Query` has one method per field and operator the model's `@filterable` allows,
//!   taking a value of the field's own type, and `sort` over the `@sortable` fields. A
//!   request the server would refuse for its filter or its sort does not compile.
//!
//! The types a call takes and returns are the `entity` generator's: a row is `<Name>`, a
//! create body `<Name>Create`, a change `<Name>Patch`. This generator therefore runs with
//! `entity`; on its own it writes crates that name types nothing declared.
//!
//! The transport is `reqwest` with its default features (asynchronous, TLS through `rustls`),
//! written out as a crate of its own, so a project that wants another HTTP stack or another
//! TLS backend changes one file it owns.
//!
//! Not generated yet: clients for `object.projection` and `object.report` routes, and the
//! report export.

use std::collections::BTreeSet;

use metaobjects_codegen::emitted::CLIENT_TRANSPORT_RS;
use metaobjects_codegen::generator::{EmittedFile, GenContext, GenError, Generator};
use metaobjects_codegen::names::{literal, pascal, snake};
use metaobjects_codegen::plan::{
    CLIENT_CRATE, CLIENT_SUFFIX, CratePlan, FieldPlan, Plan, Route, SUPPORT_CRATE, StructPlan, Ty,
};
use metaobjects_codegen::writer::{
    CodeWriter, Manifest, RUSTFMT_TOML, file, fixed, item, list, piece, sibling_dep, toml_string,
};

/// Bump when the emitted text changes shape, so a stored skip key never survives it.
const FORMAT: u32 = 1;

/// The line every generated Rust file starts with.
pub const BANNER: &str = "// @generated by the MetaObjects client generator. Do not edit: change the model and run `cargo meta gen`.";

const MANIFEST_BANNER: &str = "@generated by the MetaObjects client generator. Do not edit: change the model and run `cargo meta gen`.";

/// The client generator.
#[derive(Debug, Clone, Copy, Default)]
pub struct ClientGenerator;

impl Generator for ClientGenerator {
    fn name(&self) -> &str {
        "client"
    }

    fn identity(&self) -> String {
        format!("client:{FORMAT}")
    }

    fn generate(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        self.render(ctx)
    }
}

impl ClientParts for ClientGenerator {}

/// The pieces of the client generator's output, one method each (ADR-0063 item 7). Each
/// default is the shipped piece: implement this for a generator of your own, override the
/// piece you want changed, and have its [`Generator::generate`] return `self.render(ctx)`
/// (the [`crate::entity::EntityParts`] example shows the shape). An override can call the
/// shipped piece, a public function of this module with the same name. Not a stability
/// contract: the methods may change in a minor release, and the CHANGELOG says when.
pub trait ClientParts {
    /// Every file: one client crate per package with a served entity, then the transport
    /// crate when there is any.
    fn render(&self, ctx: &GenContext<'_>) -> Result<Vec<EmittedFile>, GenError> {
        render(self, ctx)
    }

    /// The transport crate's files.
    fn transport_crate(&self) -> Vec<EmittedFile> {
        transport_crate()
    }

    /// A client crate's `Cargo.toml`, with a dependency on each model crate it names.
    fn manifest(&self, name: &str, c: &CratePlan, deps: &BTreeSet<String>) -> String {
        cargo_toml(name, c, deps)
    }

    /// A client crate's `src/lib.rs`: each module and what it exports.
    fn lib_file(&self, package: &str, items: &[(String, Vec<String>)]) -> String {
        lib_file(package, items)
    }

    /// One served entity's file: its client, then its query and sort types.
    fn entity_file(
        &self,
        plan: &Plan,
        s: &StructPlan,
        route: &Route,
        deps: &mut BTreeSet<String>,
    ) -> Result<String, GenError> {
        entity_file(self, plan, s, route, deps)
    }

    /// One entity's client: the struct and a method per route.
    fn client_item(
        &self,
        plan: &Plan,
        s: &StructPlan,
        route: &Route,
        deps: &mut BTreeSet<String>,
    ) -> Result<String, GenError> {
        client_item(plan, s, route, deps)
    }

    /// One entity's list query and, when it sorts, its sort type.
    fn query_items(
        &self,
        s: &StructPlan,
        route: &Route,
        deps: &mut BTreeSet<String>,
    ) -> Result<Vec<String>, GenError> {
        query_items(s, route, deps)
    }
}

/// The shipped [`ClientParts::render`], through `parts`.
pub fn render<P: ClientParts + ?Sized>(
    parts: &P,
    ctx: &GenContext<'_>,
) -> Result<Vec<EmittedFile>, GenError> {
    let plan = Plan::of(ctx)?;
    let selected = plan.selected_crates(ctx.entities)?;
    let mut files = Vec::new();
    for (cname, c) in &plan.crates {
        if selected.as_ref().is_some_and(|sel| !sel.contains(cname)) {
            continue;
        }
        client_crate(parts, &plan, cname, c, &mut files)?;
    }
    if !files.is_empty() {
        files.extend(parts.transport_crate());
    }
    Ok(files)
}

// ---- the transport crate ---------------------------------------------------------------

/// The crate of HTTP plumbing the client crates share. It is generated, so the output
/// depends on nothing from MetaObjects.
pub fn transport_crate() -> Vec<EmittedFile> {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, CLIENT_CRATE);
    m.entry(
        "description",
        &toml_string("The HTTP transport of the generated MetaObjects client crates."),
    );
    m.blank().table("dependencies");
    m.entry(
        "reqwest",
        r#"{ version = "0.13", features = ["json", "query"] }"#,
    );
    m.entry("serde", r#"{ version = "1", features = ["derive"] }"#);
    m.entry("serde_json", &toml_string("1"));
    let manifest = m.finish();
    let file = |name: &str, text: String| EmittedFile::new(format!("{CLIENT_CRATE}/{name}"), text);
    vec![
        file("Cargo.toml", manifest),
        file("rustfmt.toml", RUSTFMT_TOML.to_string()),
        file("src/lib.rs", fixed(BANNER, CLIENT_TRANSPORT_RS)),
    ]
}

// ---- one client crate ------------------------------------------------------------------

fn client_crate<P: ClientParts + ?Sized>(
    parts: &P,
    plan: &Plan,
    cname: &str,
    c: &CratePlan,
    files: &mut Vec<EmittedFile>,
) -> Result<(), GenError> {
    let served: Vec<&StructPlan> = plan.served(c).collect();
    if served.is_empty() {
        return Ok(());
    }
    let name = format!("{cname}{CLIENT_SUFFIX}");
    let mut deps: BTreeSet<String> = BTreeSet::from([cname.to_string()]);
    let mut lib_items: Vec<(String, Vec<String>)> = Vec::new();
    for s in served {
        let route = s.route.as_ref().expect("a served entity has a route");
        let mut exports = vec![s.client_name(), s.query_name()];
        if s.has_sort() {
            exports.push(s.sort_name());
        }
        lib_items.push((s.module(), exports));
        let text = parts.entity_file(plan, s, route, &mut deps)?;
        files.push(EmittedFile::new(
            format!("{name}/src/{}.rs", s.module()),
            text,
        ));
    }
    lib_items.sort();
    files.push(EmittedFile::new(
        format!("{name}/Cargo.toml"),
        parts.manifest(&name, c, &deps),
    ));
    files.push(EmittedFile::new(
        format!("{name}/rustfmt.toml"),
        RUSTFMT_TOML.to_string(),
    ));
    files.push(EmittedFile::new(
        format!("{name}/src/lib.rs"),
        parts.lib_file(&c.package, &lib_items),
    ));
    Ok(())
}

/// The shipped [`ClientParts::manifest`].
pub fn cargo_toml(name: &str, c: &CratePlan, deps: &BTreeSet<String>) -> String {
    let mut m = Manifest::generated_crate(MANIFEST_BANNER, name);
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    m.entry(
        "description",
        &toml_string(&format!(
            "A client for the REST API of the MetaObjects package {package}."
        )),
    );
    m.blank().table("dependencies");
    m.entry(CLIENT_CRATE, &sibling_dep(CLIENT_CRATE));
    for dep in deps {
        m.entry(dep, &sibling_dep(dep));
    }
    m.finish()
}

/// The shipped [`ClientParts::lib_file`].
pub fn lib_file(package: &str, items: &[(String, Vec<String>)]) -> String {
    let mut w = CodeWriter::new();
    w.line(BANNER).blank();
    if package.is_empty() {
        w.line("//! A client for the REST API of the MetaObjects model that declares no package.");
    } else {
        w.line(format!(
            "//! A client for the REST API of the MetaObjects package `{package}`."
        ));
    }
    w.blank();
    for (module, _) in items {
        w.line(format!("mod {module};"));
    }
    w.blank();
    for (module, exports) in items {
        for e in exports {
            w.line(format!("pub use {module}::{e};"));
        }
    }
    w.finish().expect("a lib.rs opens no block")
}

// ---- one entity ------------------------------------------------------------------------

/// A type of a model crate, by its path from another crate.
fn model_type(crate_name: &str, type_name: &str, deps: &mut BTreeSet<String>) -> String {
    deps.insert(crate_name.to_string());
    format!("{crate_name}::{type_name}")
}

/// How a value of a field is passed to a call, and how it is written into a URL.
struct Param {
    /// The parameter's type.
    ty: String,
    /// The type of one element of an `in` list.
    element: String,
    /// The expression that writes the parameter `value`.
    one: &'static str,
    /// The expression that writes the list `values`.
    many: &'static str,
}

fn param(f: &FieldPlan, deps: &mut BTreeSet<String>) -> Param {
    let by_value = |ty: String| Param {
        element: ty.clone(),
        ty,
        one: "value",
        many: "values",
    };
    match &f.ty {
        Ty::Str | Ty::Map(_) => Param {
            ty: "&str".into(),
            element: "&str".into(),
            one: "value",
            many: "values",
        },
        Ty::Prim(p) => by_value((*p).to_string()),
        Ty::Ip => by_value("std::net::IpAddr".to_string()),
        Ty::Duration => {
            deps.insert(SUPPORT_CRATE.to_string());
            by_value(format!("{SUPPORT_CRATE}::wire::Duration"))
        }
        Ty::Decimal => {
            deps.insert(SUPPORT_CRATE.to_string());
            let decimal = format!("{SUPPORT_CRATE}::wire::Decimal");
            Param {
                ty: format!("&{decimal}"),
                element: decimal,
                one: "value",
                many: "values",
            }
        }
        // An enum is written as its member's wire spelling.
        Ty::Ref(r) => {
            let ty = model_type(&r.crate_name, &r.type_name, deps);
            Param {
                element: ty.clone(),
                ty,
                one: "value.as_str()",
                many: "values.iter().map(|value| value.as_str())",
            }
        }
    }
}

/// The method of a query for one field and one operator: its name suffix, its parameter,
/// and the statement that records it.
fn filter_method(w: &mut CodeWriter, f: &FieldPlan, op: &str, p: &Param) {
    let field = literal(&f.wire);
    let bare = f.bare_ident();
    let (suffix, arg, doc, statement) = match op {
        "in" => (
            "in".to_string(),
            format!("values: &[{}]", p.element),
            format!("Rows whose `{}` is one of `values`.", f.wire),
            format!("self.query.filter_in({field}, {});", p.many),
        ),
        "like" => (
            "like".to_string(),
            "pattern: &str".to_string(),
            format!(
                "Rows whose `{}` matches the SQL `LIKE` pattern (`%` any run, `_` any one character; case-sensitive).",
                f.wire
            ),
            format!("self.query.filter({field}, \"like\", pattern);"),
        ),
        "isNull" => (
            "is_null".to_string(),
            "is_null: bool".to_string(),
            format!(
                "Rows whose `{}` is null (`true`) or is not (`false`).",
                f.wire
            ),
            format!("self.query.filter({field}, \"isNull\", is_null);"),
        ),
        other => {
            let test = match other {
                "eq" => "equals",
                "ne" => "does not equal",
                "gt" => "is greater than",
                "gte" => "is at least",
                "lt" => "is less than",
                _ => "is at most",
            };
            (
                snake(other),
                format!("value: {}", p.ty),
                format!("Rows whose `{}` {test} `value`.", f.wire),
                format!("self.query.filter({field}, {}, {});", literal(other), p.one),
            )
        }
    };
    w.blank();
    w.prose(&doc);
    let head = piece![
        format!("pub fn {bare}_{suffix}"),
        list("(", ["mut self".to_string(), arg], ")"),
        " -> Self {"
    ];
    w.block(head, |w| {
        w.line(statement);
        w.line("self");
    });
}

/// The shipped [`ClientParts::query_items`].
pub fn query_items(
    s: &StructPlan,
    route: &Route,
    deps: &mut BTreeSet<String>,
) -> Result<Vec<String>, GenError> {
    let query = s.query_name();
    let mut items = Vec::new();
    items.push(item(|w| {
        w.prose(&format!(
            "Which rows of `{}` to list, and in what order.",
            route.path
        ));
        w.line("#[derive(Debug, Clone, Default)]");
        w.block(format!("pub struct {query} {{"), |w| {
            w.line(format!("query: {CLIENT_CRATE}::Query,"));
        });
    })?);
    let filters: Vec<String> = s
        .filterable()
        .map(|f| {
            let ops: Vec<String> = f.filter_ops.iter().map(|op| literal(op)).collect();
            format!("({}, &[{}])", literal(&f.wire), ops.join(", "))
        })
        .collect();
    let sorts: Vec<String> = s.sortable().map(|f| literal(&f.wire)).collect();
    let params: Vec<(&FieldPlan, Param)> = s.filterable().map(|f| (f, param(f, deps))).collect();
    items.push(item(|w| {
        w.block(format!("impl {query} {{"), |w| {
            w.prose("The fields a list request may filter on, each with the operators it takes.");
            w.assign("pub const FILTERS: &[(&str, &[&str])] =", list("&[", filters, "];"));
            w.blank();
            w.prose("The fields a list request may sort on.");
            w.assign("pub const SORTS: &[&str] =", list("&[", sorts, "];"));
            w.blank();
            w.prose("Every row, in the server's order.");
            w.block("pub fn new() -> Self {", |w| {
                w.line("Self::default()");
            });
            w.blank();
            w.prose(
                "A query written by hand. Nothing here checks it; the server holds it to the same fields and operators.",
            );
            w.block(format!("pub fn raw(query: {CLIENT_CRATE}::Query) -> Self {{"), |w| {
                w.line("Self { query }");
            });
            w.blank();
            w.prose("The query as the transport sends it.");
            w.block(format!("pub fn as_query(&self) -> &{CLIENT_CRATE}::Query {{"), |w| {
                w.line("&self.query");
            });
            for (f, p) in &params {
                for op in &f.filter_ops {
                    filter_method(w, f, op, p);
                }
            }
            if s.has_sort() {
                w.blank();
                w.prose("Sort by one field. A later sort replaces an earlier one.");
                let head = piece![
                    "pub fn sort",
                    list(
                        "(",
                        [
                            "mut self".to_string(),
                            format!("by: {}", s.sort_name()),
                            format!("direction: {CLIENT_CRATE}::Direction"),
                        ],
                        ")"
                    ),
                    " -> Self {"
                ];
                w.block(head, |w| {
                    w.line("self.query.sort(by.as_str(), direction);");
                    w.line("self");
                });
            }
            for (name, doc) in
                [("limit", "Return at most `rows` rows."), ("offset", "Skip the first `rows` rows.")]
            {
                w.blank();
                w.prose(doc);
                w.block(format!("pub fn {name}(mut self, rows: u64) -> Self {{"), |w| {
                    w.line(format!("self.query.{name}(rows);"));
                    w.line("self");
                });
            }
        });
    })?);
    if s.has_sort() {
        let sort = s.sort_name();
        // Two fields that differ only in case would be one variant; the wire name decides.
        let mut seen = BTreeSet::new();
        let variants: Vec<(String, &FieldPlan)> = s
            .sortable()
            .map(|f| (pascal(&f.wire), f))
            .filter(|(variant, _)| seen.insert(variant.clone()))
            .collect();
        items.push(item(|w| {
            w.prose(&format!(
                "The fields of `{}` a list can be sorted on.",
                route.path
            ));
            w.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
            w.block(format!("pub enum {sort} {{"), |w| {
                for (variant, _) in &variants {
                    w.line(format!("{variant},"));
                }
            });
            w.blank();
            w.block(format!("impl {sort} {{"), |w| {
                w.prose("The field's name on the wire.");
                w.block("pub const fn as_str(self) -> &'static str {", |w| {
                    w.block("match self {", |w| {
                        for (variant, f) in &variants {
                            w.line(format!("{sort}::{variant} => {},", literal(&f.wire)));
                        }
                    });
                });
            });
        })?);
    }
    Ok(items)
}

/// One asynchronous method of a client.
fn call(w: &mut CodeWriter, doc: &str, name: &str, args: Vec<String>, returns: &str, body: &str) {
    w.blank();
    w.prose(doc);
    let args = std::iter::once("&self".to_string()).chain(args);
    let head = piece![
        format!("pub async fn {name}"),
        list("(", args, ")"),
        format!(" -> {CLIENT_CRATE}::Result<{returns}> {{")
    ];
    w.block(head, |w| {
        w.line(body);
    });
}

/// The shipped [`ClientParts::client_item`].
pub fn client_item(
    plan: &Plan,
    s: &StructPlan,
    route: &Route,
    deps: &mut BTreeSet<String>,
) -> Result<String, GenError> {
    let client = s.client_name();
    let query = s.query_name();
    let row = model_type(&s.crate_name, &s.type_name, deps);
    let create = model_type(&s.crate_name, &s.create_name(), deps);
    let patch = model_type(&s.crate_name, &s.patch_name(), deps);
    let key = route.key.map(|k| {
        let f = &s.fields[k];
        (f.wire.clone(), param(f, deps).ty)
    });
    let traversals: Vec<(String, String, String)> = route
        .traversals
        .iter()
        .map(|t| {
            let target = &plan.structs[t.target];
            (
                t.name.clone(),
                format!("{}_of", snake(&t.name)),
                model_type(&target.crate_name, &target.type_name, deps),
            )
        })
        .collect();
    Ok(item(|w| {
        w.prose(&format!("The `{}` collection of the API.", route.path));
        w.line("#[derive(Debug, Clone, Copy)]");
        w.block(format!("pub struct {client}<'a> {{"), |w| {
            w.line(format!("client: &'a {CLIENT_CRATE}::Client,"));
        });
        w.blank();
        w.block(format!("impl<'a> {client}<'a> {{"), |w| {
            w.prose("The collection's path under the API's base address.");
            w.line(format!("pub const PATH: &'static str = {};", literal(&route.path)));
            w.blank();
            w.block(format!("pub fn new(client: &'a {CLIENT_CRATE}::Client) -> Self {{"), |w| {
                w.line("Self { client }");
            });
            call(
                w,
                "The rows the query selects.",
                "list",
                vec![format!("query: &{query}")],
                &format!("Vec<{row}>"),
                "self.client.list(Self::PATH, query.as_query()).await",
            );
            w.blank();
            w.prose("The rows the query selects, and how many rows its filters match in all.");
            let head = piece![
                "pub async fn page",
                list("(", ["&self".to_string(), format!("query: &{query}")], ")"),
                format!(" -> {CLIENT_CRATE}::Result<{CLIENT_CRATE}::Page<{row}>> {{")
            ];
            w.block(head, |w| {
                w.line("let mut counted = query.as_query().clone();");
                w.line("counted.with_count();");
                w.line("self.client.list(Self::PATH, &counted).await");
            });
            let id = key.as_ref().map(|(_, key_ty)| format!("id: {key_ty}"));
            if let (Some((key_name, _)), Some(id)) = (&key, &id) {
                call(
                    w,
                    &format!("The row whose `{key_name}` is `id`."),
                    "get",
                    vec![id.clone()],
                    &row,
                    &format!("self.client.get(&{CLIENT_CRATE}::row(Self::PATH, id)).await"),
                );
            }
            if !route.read_only {
                call(
                    w,
                    "Create a row. Returns the row as the server stored it.",
                    "create",
                    vec![format!("body: &{create}")],
                    &row,
                    "self.client.post(Self::PATH, body).await",
                );
            }
            if let (Some((key_name, _)), Some(id)) = (&key, &id) {
                if !route.read_only {
                    call(
                        w,
                        &format!(
                            "Change the row whose `{key_name}` is `id`: only the members `body` sets. Returns the row as it now is."
                        ),
                        "update",
                        vec![id.clone(), format!("body: &{patch}")],
                        &row,
                        &format!("self.client.patch(&{CLIENT_CRATE}::row(Self::PATH, id), body).await"),
                    );
                    call(
                        w,
                        &format!("Delete the row whose `{key_name}` is `id`."),
                        "delete",
                        vec![id.clone()],
                        "()",
                        &format!("self.client.delete(&{CLIENT_CRATE}::row(Self::PATH, id)).await"),
                    );
                }
                for (relation, method, target) in &traversals {
                    call(
                        w,
                        &format!("The `{relation}` of the row whose `{key_name}` is `id`."),
                        method,
                        vec![id.clone()],
                        &format!("Vec<{target}>"),
                        &format!(
                            "self.client.get(&{CLIENT_CRATE}::related(Self::PATH, id, {})).await",
                            literal(relation)
                        ),
                    );
                }
            }
        });
    })?)
}

/// The shipped [`ClientParts::entity_file`], through `parts`.
pub fn entity_file<P: ClientParts + ?Sized>(
    parts: &P,
    plan: &Plan,
    s: &StructPlan,
    route: &Route,
    deps: &mut BTreeSet<String>,
) -> Result<String, GenError> {
    let mut items = vec![parts.client_item(plan, s, route, deps)?];
    items.extend(parts.query_items(s, route, deps)?);
    Ok(file(BANNER, &items))
}
