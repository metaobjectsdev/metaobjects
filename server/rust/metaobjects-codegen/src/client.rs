// ---- one client crate ------------------------------------------------------------------

fn client_crate(
    plan: &Plan,
    cname: &str,
    c: &CratePlan,
    files: &mut Vec<EmittedFile>,
) -> Result<(), GenError> {
    let served: Vec<&StructPlan> = plan.served(c).collect();
    if served.is_empty() {
        return Ok(());
    }
    let name = format!("{cname}{CLIENT_SUFFIX}");
    let mut deps: BTreeSet<String> = BTreeSet::from([cname.to_string()]);
    let mut lib_items: Vec<(String, Vec<String>)> = Vec::new();
    for s in served {
        let route = s.route.as_ref().expect("a served entity has a route");
        let mut exports = vec![s.client_name(), s.query_name()];
        if s.has_sort() {
            exports.push(s.sort_name());
        }
        lib_items.push((s.module(), exports));
        let text = entity_file(plan, s, route, &mut deps)?;
        files.push(EmittedFile::new(
            format!("{name}/src/{}.rs", s.module()),
            text,
        ));
    }
    lib_items.sort();
    files.push(EmittedFile::new(
        format!("{name}/Cargo.toml"),
        cargo_toml(&name, c, &deps),
    ));
    files.push(EmittedFile::new(
        format!("{name}/rustfmt.toml"),
        RUSTFMT_TOML.to_string(),
    ));
    files.push(EmittedFile::new(
        format!("{name}/src/lib.rs"),
        lib_file(&c.package, &lib_items),
    ));
    Ok(())
}

fn cargo_toml(name: &str, c: &CratePlan, deps: &BTreeSet<String>) -> String {
    let mut out = String::from(MANIFEST_BANNER);
    out.push_str("[package]\n");
    out.push_str(&format!("name = {}\n", literal(name)));
    out.push_str("version = \"0.1.0\"\n");
    out.push_str("edition = \"2021\"\n");
    out.push_str("publish = false\n");
    let package = if c.package.is_empty() {
        "the model's"
    } else {
        c.package.as_str()
    };
    out.push_str(&format!(
        "description = {}\n",
        literal(&format!(
            "A client for the REST API of the MetaObjects package {package}."
        ))
    ));
    out.push_str("\n[dependencies]\n");
    out.push_str(&format!(
        "{CLIENT_CRATE} = {{ path = \"../{CLIENT_CRATE}\" }}\n"
    ));
    for dep in deps {
        out.push_str(&format!("{dep} = {{ path = \"../{dep}\" }}\n"));
    }
    out
}

fn lib_file(package: &str, items: &[(String, Vec<String>)]) -> String {
    let mut out = format!("{BANNER}\n\n");
    if package.is_empty() {
        out.push_str(
            "//! A client for the REST API of the MetaObjects model that declares no package.\n",
        );
    } else {
        out.push_str(&format!(
            "//! A client for the REST API of the MetaObjects package `{package}`.\n"
        ));
    }
    out.push('\n');
    for (module, _) in items {
        out.push_str(&format!("mod {module};\n"));
    }
    out.push('\n');
    for (module, exports) in items {
        for e in exports {
            out.push_str(&format!("pub use {module}::{e};\n"));
        }
    }
    out
}

